### T019 线性变奏法

**核心原理**：完全按时间顺序写是最基础的叙事。改变线性结构，读者会产生"探索感"。

**适用症候**：P007 句式节奏单一

**技法描述**：
五种结构变奏：
1. **倒叙**：从高潮或结局开始，再回到起点——悬念驱动
2. **双线交替**：两条时间线/空间线交替推进——对比效果
3. **单元拼接**：每个单元独立但共同指向同一主题——网状效果
4. **环形**：结尾回到开头——闭合的宿命感
5. **嵌套**：故事里的故事——层次感

**示范对比**：
- ❌ 线性：他早上起床，出门，遇见朋友，吃饭，回家
- ✅ 环形：他早上起床的时候，不知道今天晚上会回到同一张床上——带着一身伤。门在身后关上的时候，他想，早上出门的时候，门关上的声音也是这样。

**练习模板**：
> 把你当前段落改写成倒叙结构：先写结局，再写过程。对比效果。

**关联教学动作**：A009 节奏变速

