### T013 潜台词法

**核心原理**：好对话不是"信息交换"，是"意图博弈"。角色说的话和他真正想表达的内容之间有一个"缝隙"，这个缝隙就是潜台词。

**适用症候**：P011 对话疲劳症

**技法描述**：
在写每段对话之前，先问：角色真正的意图是什么？然后让角色说和这个意图相关但**不完全一致**的话。三级递进：
1. **信息层**：角色嘴上说的字面意思
2. **意图层**：角色真正想达成的目的（请求/拒绝/试探/掩饰/攻击）
3. **关系层**：这段对话在改变角色之间的关系（拉近/疏远/确认/挑战）

**示范对比**：
- ❌ 无潜台词："你爱我吗？" "爱。"
- ✅ 有潜台词："你爱我吗？" "今天怎么突然问这个。"（意图层：回避正面回答；关系层：感到不安）

**练习模板**：
> 写一段两个人的对话，要求：A 想借钱、B 不想借。但不允许出现"借钱""没钱""还"这几个词。让读者从潜台词里读出真实意图。

**关联教学动作**：A008 对话瘦身

