### T012 视角锚定法

**核心原理**：视角漂移的本质是写的时候"忘了谁在看"。建立一个固定的视角锚点，所有信息都经过这个锚点过滤。

**适用症候**：P005 视角漂移

**技法描述**：
开写前确定当前段落的"视角锚点"——正在看故事的人：
1. **锚定标记**：用一个触发器（"他看见""他听见""他注意到"）锁定视角
2. **信息过滤**：只写视角角色能看到、听到、知道、感受到的信息
3. **越界检测**：写完通读一遍，标出所有"视角角色不可能知道"的信息——删掉或改写

**示范对比**：
- ❌ 漂移：林远推开门，屋里坐着三个人。他不知道的是，最左边那个人口袋里有一把刀
- ✅ 锚定：林远推开门，屋里坐着三个人。最左边那个人的手放在口袋里，口袋里鼓起一块

**练习模板**：
> 找出你文本中视角角色不知道的信息。全部改写成"他看见/听见/注意到..."。如果改写后信息不再成立，删掉。

**关联教学动作**：A002 回归主角

