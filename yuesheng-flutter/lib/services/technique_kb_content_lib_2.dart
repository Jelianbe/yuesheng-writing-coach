### T014 声线分立法

**核心原理**：如果去掉对话标记（"XX说"），读者还能分清谁在说话吗？不能，说明角色的说话方式没有区分度。

**适用症候**：P011 对话疲劳症

**技法描述**：
为每个角色在三个维度上设定"声线特征"：
1. **词汇**：角色爱用什么词？学术词多还是口语多？喜欢用"但是"还是"不过"？
2. **句长**：角色说话长还是短？紧张时变长还是变短？
3. **语气**：角色爱反问、爱陈述、爱省略还是爱感叹？

三个角色一组对话，每个角色至少有两个维度不同。

**示范对比**：
- ❌ 无区分："你来了。""嗯。""坐。""好。""喝水？""不用。"
- ✅ 有区分："哟，舍得来了？我还以为你忘了我住哪儿。"他靠在门框上，没让路。"堵车。"林远侧身挤进门，熟门熟路地找到了冰箱。

**练习模板**：
> 写三个角色关于"要不要吃火锅"的讨论，每人最多说两句话。去掉引号和人名后，读者必须能分出来谁是谁。

**关联教学动作**：A010 角色盲写

