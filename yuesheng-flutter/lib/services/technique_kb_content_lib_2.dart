### T017 悬念伏笔法

**核心原理**：读者"想知道接下来会发生什么"的欲望，来自作者在前面埋下的"未解决的问题"。一个悬念就是一个"未结的债"。

**适用症候**：P006 节奏停滞

**技法描述**：
在场景中制造"未回答的问题"：
1. **前期埋设**：安插一个不合常理的细节、一句没说完的话、一个不该出现的东西
2. **中期延迟**：不要立刻解释，让读者在下一段/下一章才等到答案
3. **后期兑现**：揭示真相，同时让读者感到"原来如此"的满足

**示范对比**：
- ❌ 无悬念：他走进书房，看见桌上有一封信。
- ✅ 有悬念：他走进书房。桌上有一封信，信封上没有寄件人。但他认得这个字迹——十年前就该消失的人。

**练习模板**：
> 写一段 100 字场景，在其中安插一个悬念点——一个"让读者觉得不对劲"的细节。不在同一段解释它。

**关联教学动作**：A007 一句话冲突

