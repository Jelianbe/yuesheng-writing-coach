### T020 借景抒情法

**核心原理**：不写"我很难过"，写"窗外的雨一直下"。景物是情绪的影子——景物的状态和角色心境同步时，读者不需要被"告知"情绪，而是自己"读出来"。

**适用症候**：P003 情绪标签化

**技法描述**：
四种常见对应模式：
1. **同步**：快乐→明亮/温暖；悲伤→阴雨/寒冷；愤怒→暴风雨/嘈杂
2. **反差（高级）**：以乐景写哀情——越是热闹的环境，越显孤独
3. **过渡**：景随情变——情绪变化时，景物也在变化
4. **定格**：在情绪最高/最低点，写一个静景——让读者的情绪停留

**示范对比**：
- ❌ 标签：她很难过
- ✅ 借景：窗外的雨一直下着，打在玻璃上，汇成一道道细细的水痕。她把额头贴在玻璃上，看着水痕慢慢往下淌。

**练习模板**：
> 取一个你的情绪场景。不写情绪词，只写窗外/房间里的景物。景物的状态和角色的心境同步。

**关联教学动作**：A006 感官全开

