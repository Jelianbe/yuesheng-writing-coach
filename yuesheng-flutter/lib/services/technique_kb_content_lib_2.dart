### T021 动静烘托法

**核心原理**：静态写环境，动态写事件。动静交替时，读者的注意力被动态捕捉，又被静态沉淀——阅读节奏就有了呼吸感。

**适用症候**：P008 语言堆砌、P006 节奏停滞

**技法描述**：
1. **静→动**：先铺环境（静），再引入动作/事件（动）——动被静放大
2. **动→静**：动作结束后，写一段静景——给读者和角色一起沉淀的时间
3. **动静交织**：静态环境中出现一个动态细节——这只"动"会被读者注意到

**示范对比**：
- ❌ 纯动：他冲进房间，翻箱子，找钥匙，打开抽屉，翻了一遍
- ✅ 动静交织：房间里很安静，只有老钟在滴答。他站在门口，喘着气，目光扫过书架、茶几、窗帘——然后停在床头柜第二个抽屉上。

**练习模板**：
> 写一个 100 字场景：前 30 字写静的景物，中间 40 字写一个事件，后 30 字回归静止。不允许使用情绪词。

**关联教学动作**：A005 动作链

