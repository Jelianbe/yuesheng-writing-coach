### T022 场景概述交替法

**核心原理**：小说只有两种叙事模式——"场景"（实时发生的事件）和"概述"（压缩时间的叙述）。只用场景会太慢，只用概述会太干。交替使用，节奏就有了。

**适用症候**：P006 节奏停滞
