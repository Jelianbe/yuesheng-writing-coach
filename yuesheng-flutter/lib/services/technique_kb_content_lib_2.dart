### T018 欲扬先抑法

**核心原理**：读者的满足感来自"反差"。先写低点，高点才有冲击力。先抑后扬，比全程高能更打动读者。

**适用症候**：P006 节奏停滞

**技法描述**：
1. **抑**：写失败、写低谷、写不可能——让读者和角色一起绝望
2. **转**：一个意外事件改变了形势——但不是"奇迹"，而是之前埋下的伏笔的兑现
3. **扬**：释放被压制的情绪——越抑,扬的力道越大

**示范对比**：
- ❌ 平铺：他冲进了决赛，最后赢了比赛
- ✅ 欲扬先抑：他输了前两局，第三局被对手踩断了球拍。他在场边坐了三十秒，然后换了一把备用拍——这把拍子，是他父亲十年前送他的。

**练习模板**：
> 写一个"先抑后扬"的 150 字场景。前 100 字写失败，后 50 字写转机。转机必须有之前的铺垫。

**关联教学动作**：A007 一句话冲突

