### P024 期待感断裂症

> **position_sensitivity**: serial

**核心问题**：悬念与承诺管理失衡——章末设的钩子下一章不兑现、关键信息提前剧透、吊胃口过度悬而不决，读者期待一次次落空后情绪耗散。与 P017（伏笔失效）区分——P017 是伏笔"埋/收"的技术问题（埋了不收/收了太生硬），P024 是"期待-兑现"的节奏管理（承诺何时兑现、信息何时释放）。

**触发信号**：章末抛悬念后长时间不接；下一章直接换线把钩子悬置；对话/内心提前说破后续结果；同一悬念反复拉长无推进；关键信息在无铺垫处提前揭晓。

**判断原则**（基于上下文，非硬性标准）：
- 抛出的悬念有没有在合理章数内获得回应或推进？
- 信息释放的时机是"吊胃口"还是"拖延症"？
- 读者当前的"已知"与"未知"配比是否健康（全知=无期待，全不知=无代入）？
- 承诺的冲突/揭秘是否兑现，还是被无限推延？

**严重度判断**（结合三维标定表综合评估）：
- L1：单处悬念拖沓，读者仍有其他看点
- L2：多次悬而不决/提前剧透，追读动力明显受损
- L3：全书承诺失信，读者"不再相信作者会兑现"而弃书

**例外情况**（以下场景通常不是期待感断裂）：
- 开放式结尾/留白——有意不回收是风格
- 长线悬念中期——只要在持续推进，跨度长不算断裂
- 反转叙事——"伪剧透"本身是误导设计

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（钩子悬置）**：
> 原文：章末"门后传来熟悉的脚步声……"；下一章却完全转入另一条支线，此后五章未提及门后是谁。
> 判定：P024 L2
> 理由：章末钩子被悬置五章，承诺未兑现，读者期待落空。

**❌ 未命中（及时兑现）**：
> 原文：章末"她推开门，愣住了。" 下一章开头即揭晓门后之人。
> 判定：不触发
> 理由：钩子在下章开头兑现，期待-满足循环闭合。

**推荐教学动作**：首选 A012 伏笔追踪，备选 A003 五问法

