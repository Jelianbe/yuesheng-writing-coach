**核心问题**：段落组织失衡——要么一屏一段无呼吸感（读者在移动端被"文字墙"劝退），要么碎片化断行（一句话一段、节奏被切碎）。阅读节奏由段落结构主导，段落失控直接破坏沉浸。与 P007（句子层面结构重复）不同，P029 是**段落层面**的组织问题。

