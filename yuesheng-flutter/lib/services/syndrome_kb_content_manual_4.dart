### P026 章节钩子缺失症

> **position_sensitivity**: chapter

**核心问题**：章末缺乏悬念/反转/情绪冲击——信息在章内完全交代清楚，情绪落地即收束，读者没有"再看一章"的翻页动力。网文以章为消费单位，章末钩子是连载的节拍器。与 P013（开篇平庸）区分——P013 关注作品整体开篇，P026 关注每一章结尾的翻页设计。

**触发信号**：章末停留在"事情办完、安然入睡"等收束态；章末无未解问题；章末无情绪高点后的余波；连续多章钩子缺失导致整体追读下降。

**判断原则**（基于上下文，非硬性标准）：
- 章末是否有至少一个"未闭合"的问题/情绪/信息？
- 本章完成的目标是否留了一个"下一步期待"？
- 章末是否只剩句号，没有省略号或惊叹号？
- 读者的"再读一章"冲动来自什么——如果答案是没有，即为缺失

**严重度判断**（结合三维标定表综合评估）：
- L1：单章结尾平淡，靠章节内容本身可维持
- L2：多章结尾无钩子，追读节拍断裂
- L3：每章都无钩子，读者随手停在任何一章

**例外情况**（以下场景通常不是章节钩子缺失）：
- 卷末/全书收官章——收束本身是设计
- 高密度信息章——信息量本身就是阅读奖励
- 读者黏性强的中后期——钩子需求相对降低

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（章末收束态）**：
> 原文：章末"解决了问题，大家各自休息。窗外月色正好。"
> 判定：P026 L2
> 理由：一切闭合、无悬念、无余波，读者无翻页动力。

**❌ 未命中（钩子收尾）**：
> 原文：章末"他答应下来，转身时，腰间那枚令牌上刻着的字，他却看不清。"
> 判定：不触发
> 理由：章末留有未解之问，制造翻页动力。

**推荐教学动作**：首选 A012 伏笔追踪，备选 A009 节奏变速

