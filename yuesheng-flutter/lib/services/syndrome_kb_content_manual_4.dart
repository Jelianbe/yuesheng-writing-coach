### P021 画面感缺失症

> **position_sensitivity**: chapter

**核心问题**：通篇停留在抽象概述层——"他很悲伤地走了""他们激烈地争吵""场面十分混乱"，全程无场景化、无感官细节，读者无法脑内成像。与 P001（有描写但用情绪词替代细节）、P017（特定情节点被一笔带过）不同，P021 是**整体表达方式**问题：作者习惯用"总结"代替"呈现"。

**触发信号**：连续多段以概括句推进；关键词为"很/非常/十分 + 情绪或状态词"；读者读完一页回忆不出任何画面。

**判断原则**（基于上下文，非硬性标准）：
- 抽掉人物对话后，剩余叙述是否还能让读者"看见"场景？
- 事件的呈现是"细节化的"还是"新闻摘要式的"？
- 是否存在至少一处具体的感官锚点（视觉/听觉/触觉/气味）？
- **合情合理细节原则**（外部资料佐证·血红讲课实录）：细节刻画的前提是"合情合理"——人物的行为、语言、反应必须与其社会地位/性格/阅历/教育层次匹配。大场面（超过 100 人）只能泛泛而谈，应从小场景/小队伍入手，仔细刻画每个人的动作、语言、表情、作息习惯。细节太多同样不耐烦看——关键场景要具体到"一杯马丁尼"而非"一杯饮料"，过渡段落则收。
- **描写四忌参考**（外部资料佐证）：①不中断叙述——描写不能使故事停下来；②不浪费非重要环境——不要花大量笔墨写与主线无关的背景；③不浪费读者注意力——不要在无关紧要的事情上停留；④要具体——不要概括，"一只长卷毛狗"而非"一只狗"。

**严重度判断**（结合三维标定表综合评估）：
- L1：个别段落抽象概述，主体部分仍有场景化描写
- L2：整章以概述推进，关键场景也只写"结果"不写"过程"
- L3：全文几乎无场景，像剧情大纲而非小说，读者完全无法代入

**例外情况**（以下场景通常不是画面感缺失）：
- 快速过渡段/时间跳跃段（为效率刻意压缩，P017 场景）——是 P017 而非 P021
- 角色内心独白/议论性段落（本就无需具象化）
- 语言本身精炼但信息完整（P006 反向——描写密度不足但叙事完整）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（整体概述）**：
> 原文：她很难过，觉得自己被世界抛弃了。生活失去了意义。她决定离开这个城市。
> 判定：P021 L2
> 理由：全程抽象词（难过/失去意义），无任何场景与感官细节，读者无法成像。

**❌ 未命中（有具体画面）**：
> 原文：她很难过，把那张机票折了又折，直到折痕处泛白，才终于丢进垃圾桶。
> 判定：不触发
> 理由：情绪虽仍抽象（难过），但有具体动作与画面，非 P021（若仅此一处，可作 P001 备查）。

**推荐教学动作**：首选 A006 感官全开，备选 A004 现实锚点

