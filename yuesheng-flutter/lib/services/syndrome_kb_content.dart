### P023 爽点乏力症

> **position_sensitivity**: chapter

**核心问题**：情节推进缺乏情绪回报——主角的胜利、成长、打脸、收获被平淡带过，优势展示不足或收益兑现无快感累积，读者情绪没有起落、追读动力弱。与 P015（高潮疲软）区分——P015 是"高潮段落执行不到位"（单点冲击力），P023 是"爽感设计机制缺失"（情绪回报节奏，含优势展示/收益兑现/反差打脸）。

**触发信号**：关键胜利一两句带过；主角优势存在但从不展示；收获无过程（升级/得宝/赢局无铺垫）；打脸环节无反差累积；连续多章无一次"情绪高点"。

**判断原则**（基于上下文，非硬性标准）：
- 读者期待的关键时刻有没有得到"足够的篇幅与细节"去感受？
- 主角的强项有没有被展示的机会，还是只在设定里存在？
- 收益/成长是否"给了但没感觉"——缺少过程、反差或仪式感？
- 爽感是否只靠单点爆发，缺乏铺垫-释放的节奏循环？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别关键场景处理平淡，整体追读未受明显影响
- L2：整章缺少情绪回报点，读者读完无"爽"感，追读意愿下降
- L3：全篇爽点机制缺失，主角无优势展示/无收获感，读者中途弃书

**例外情况**（以下场景通常不是爽点乏力）：
- 压抑流/虐主流——刻意的情绪压榨是题材策略
- 悬疑推理——信息本身是回报，不需要打脸式快感
- 慢热日常文——以情感细腻为卖点，不以爽点为节奏单位

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（关键胜利被带过）**：
> 原文："经过一番苦战，主角终于赢了。他回到了客栈，休整一晚后继续上路。"
> 判定：P023 L2
> 理由：关键胜利只有一句话，无过程、无收益展示、无情绪释放。

**❌ 未命中（反差到位）**：
> 原文："所有人都以为他会输。他起身，只说了三个字：'我押自己。'"
> 判定：不触发
> 理由：铺垫-反差-释放的爽感循环完整。

**推荐教学动作**：首选 A005 动作链，备选 A013 情节复盘

