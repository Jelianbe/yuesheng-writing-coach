### P030 节奏比例失衡症

> **position_sensitivity**: serial

**核心问题**：铺垫/冲突/收束的比例失衡——铺垫无限拉长该收不收，或高潮一笔带过该放不放，文戏武戏、日常与事件分配失调。与 P006（整体无推进）不同，P030 是**有推进但分配不当**：读者能感受到"节奏不对"，但每个段落单独看都成立。与 P015（高潮段执行不到位）不同，P030 是段落之间的**比例**问题。

**触发信号**：读者抱怨"前面太拖"或"高潮太快"；铺垫章节远多于兑现；文戏/武戏占比悬殊且与故事类型不匹配。

**判断原则**（基于上下文，非硬性标准）：
- 铺垫与兑现的篇幅比例是否符合该情节线的重要性？
- 关键冲突前是否铺垫过长（读者已猜到、失去新鲜感）？
- 高潮后是否立刻转入下一事件、没有给读者留情绪停留？

**严重度判断**（结合三维标定表综合评估）：
- L1：单一线索的铺垫略拖，整体可读
- L2：多条线索节奏错配，读者在多处产生"不耐烦"或"被骗感"
- L3：全文节奏结构失衡，关键情节被压缩、日常被无限拉长，读者流失

**例外情况**（以下场景通常不是节奏比例失衡）：
- 慢热型故事的整体节奏设定（类型使然，且读者预期匹配）
- 单段落内的节奏问题（属 P006/P007）
- 高潮段落本身执行差（属 P015——先修高潮，再看整体比例）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（兑现不足）**：
> 原文：前十五章都在铺垫主角的宿敌。双方终于对决，一章之内就分出了胜负，然后主角立刻赶往下一座城。读者期待的多年恩怨清算，三页草草结束。
> 判定：P030 L2
> 理由：铺垫/对决比例约 15:1，兑现严重不足，节奏比例失衡。

**❌ 未命中（段落内停滞）**：
> 原文：主角与宿敌的战斗写了三章，但每章都在写环境、写回忆，冲突始终没有推进。
> 判定：不触发
> 理由：是段落内无推进（P006）而非比例失衡。

**推荐教学动作**：首选 A009 节奏变速，备选 A013 情节复盘

