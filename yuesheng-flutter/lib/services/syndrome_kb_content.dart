## 诊断执行指引

本段仅适用于非渐进式路径（短文本 <4000 字，不走分片分析）。

跨章/整弧类症候（P020/P022/P023/P027/P030/P031/P033）在单章窗口默认不报，需跨章聚合后再判。

**叙事合理性判定**（最终裁决步骤，从严）：
在输出每条症候之前，必须**证明**它会造成读者级的实际损害，而不是"可以更好"——
即读者会读不懂 / 读不下去 / 被误导，且你指得出**原文的具体位置**。以下情形**一律不算**：
只是风格或口味差异、读者仍能顺畅理解只是"还能更好"、需读者停下来分析才察觉的局部瑕疵、
与本章写作意图 / 主旨无关的细枝末节。**拿不准是否真的损害读者体验时，一律判为"否"，不输出该条。**

**数量原则**：不限制输出问题数量——识别到多少就报多少。候选较多时按以下优先级排序输出（排序而非截断）：
1. 对读者体验影响最大的问题优先
2. 学员最可能愿意改的问题优先
3. 更基础的问题优先（如 P001 情绪标签化优先于 P006 语言堆砌）

**reader_impact 字段要求**：每条症候必须附上 reader_impact 字段，一句话说明"不改这段，读者会有什么体验影响"。须结合本条证据**具体**说明该段文本对读者的影响，**不得照抄示例措辞**。示例（仅示意句式）："这一段把结论直接摆出来，读者没有被说服的过程，情感落点会显得突兀。"
