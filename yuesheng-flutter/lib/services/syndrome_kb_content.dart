### P007 句式节奏单一

> **position_sensitivity**: global

**核心问题**：表达手段重复，缺乏句式节奏的变化。

**触发信号**：句式结构和叙事模式缺乏变化，通篇以同一段落节奏推进，造成阅读疲劳

**判断原则**（基于上下文，非硬性标准）：
- 连续 3 句以上是否都是相同的结构（"X 做了 Y" / "X 是 Z"）？
- 段落的长短和句子的长短是否有变化？短句是加速还是冲击，长句是铺垫还是解释？
- 如果给段落标上"主语+谓语"模式，前几句和后几句是否在重复同一模式？

**严重度判断**（结合三维标定表综合评估）：
- L1：部分段落结构趋同，但不影响整体阅读体验，适当穿插长短句即可
- L2：整段/整章句式单调，阅读产生持续疲劳感，需要结构调整
- L3：全文结构单一，缺乏任何节奏变化，读者在句法层面产生审美疲劳

**例外情况**（以下场景通常不是结构单一）：
- 极简风格的刻意选择——海明威式的短句叙事是风格而非缺陷
- 信息密集段落中的句式趋同——当核心目标是传递信息而非阅读体验时，句式一致可以接受
- 限制视角下的心理描写——角色思维本身的重复性反映在句式上

**诊断锚点示例**（few-shot 参考）：
- **L2 命中**："他冲进房间。他看见桌上有一封信。他打开信。他读完了。他没有表情。他把信折好放进口袋。他走出房间。" → 连续 7 句"他+动词"句式，无任何变化。P007 L2
- **❌ 未命中（刻意节奏）**："他推开门。风灌进来。桌上的信被吹起一角。他忽然不想读了。" → 判定：不触发。理由：短句是极简风格的刻意选择，且末句信息转折打破单调——短句推进伴随信息变化，不是机械重复。

**推荐教学动作**：首选 A009 节奏变速，备选 A003 五问法

