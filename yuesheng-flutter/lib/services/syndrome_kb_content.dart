### P012 张力不足症

> **position_sensitivity**: global

**核心问题**：冲突没有分量、没有代价、没有后果。读者知道主角一定会赢，所以遇到天大的危机也激不起心跳。读者翻两页就犯困，不是因为节奏慢，而是因为"没有让读者紧张的东西"。

**触发信号**：冲突没有代价，悬念没有分量，读者无法紧张

**判断原则**（基于上下文，非硬性标准）：
- 这场冲突如果主角输了，会失去什么？失去的东西对读者来说重要吗？
- 读者真的相信主角可能输吗？——如果答案是否定的，说明张力不足
- 冲突只有表面对抗（打斗/吵架/竞争）还是也包含了情绪层面的对抗？
- 解决冲突的方式是否让读者感到"有代价"？还是"轻松解决"？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别场景冲突力度偏弱，但整体故事有驱动力，加强一个关键冲突即可
- L2：多章节冲突沦为走过场，读者失去紧张感，主角的成功读者不觉得"来之不易"
- L3：全文缺乏有分量的冲突，主角顺风顺水，读者完全不会为角色担心

**例外情况**（以下场景通常不是张力不足）：
- 日常向/温馨向作品——微弱的冲突本身就是类型特征
- 悬疑中"一切平稳"的铺垫章节——平稳是为后面的爆发蓄力
- 角色处于绝对优势时的"碾压式"场景——如果"碾压"本身就是爽点

**诊断锚点示例**（few-shot 参考）：
- **L2 命中**："主角轻松打败了对手，拿到了宝物，继续上路。下一个副本里，他再次轻松取胜。每个敌人都像纸糊的一样。" → 读者没有紧张感，因为知道主角不会输。P012 L2
- **❌ 未命中（日常向微冲突）**："他们没有吵架，只是沉默着把碗洗了。他递给她毛巾，她没接，但也没有走开。窗外的雨停了。" → 判定：不触发。理由：日常向作品的微冲突本身就是类型特征——张力藏在细节里（毛巾没接、人没走开），非"无张力"。

**推荐教学动作**：首选 A007 一句话冲突，备选 A003 五问法

