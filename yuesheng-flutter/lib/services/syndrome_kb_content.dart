### P028 画面感缺失症

> **position_sensitivity**: chapter

**核心问题**：通篇停留在抽象概述层——"他很悲伤地走了""他们激烈地争吵""场面十分混乱"，全程无场景化、无感官细节，读者无法脑内成像。与 P003（有描写但用情绪词替代细节）、P021（特定情节点被一笔带过）不同，P028 是**整体表达方式**问题：作者习惯用"总结"代替"呈现"。

**触发信号**：连续多段以概括句推进；关键词为"很/非常/十分 + 情绪或状态词"；读者读完一页回忆不出任何画面。

**判断原则**（基于上下文，非硬性标准）：
- 抽掉人物对话后，剩余叙述是否还能让读者"看见"场景？
- 事件的呈现是"细节化的"还是"新闻摘要式的"？
- 是否存在至少一处具体的感官锚点（视觉/听觉/触觉/气味）？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别段落抽象概述，主体部分仍有场景化描写
- L2：整章以概述推进，关键场景也只写"结果"不写"过程"
- L3：全文几乎无场景，像剧情大纲而非小说，读者完全无法代入

**例外情况**（以下场景通常不是画面感缺失）：
- 快速过渡段/时间跳跃段（为效率刻意压缩，P021 场景）——是 P021 而非 P028
- 角色内心独白/议论性段落（本就无需具象化）
- 语言本身精炼但信息完整（P008 反向——描写密度不足但叙事完整）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（整体概述）**：
> 原文：她很难过，觉得自己被世界抛弃了。生活失去了意义。她决定离开这个城市。
> 判定：P028 L2
> 理由：全程抽象词（难过/失去意义），无任何场景与感官细节，读者无法成像。

**❌ 未命中（有具体画面）**：
> 原文：她很难过，把那张机票折了又折，直到折痕处泛白，才终于丢进垃圾桶。
> 判定：不触发
> 理由：情绪虽仍抽象（难过），但有具体动作与画面，非 P028（若仅此一处，可作 P003 备查）。

**推荐教学动作**：首选 A006 感官全开，备选 A004 现实锚点

