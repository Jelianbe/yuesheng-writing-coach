### P013 开篇平庸症

> **position_sensitivity**: beginning

**核心问题**：开篇前 300 字没有冲突、没有悬念、没有反常事件，读者在碎片化阅读场景中直接滑走了。开篇的冷启动失败——读者在决定是否继续读的 3 秒内没有得到"必须看下去"的理由。

**触发信号**：开篇无钩子，前 300 字无冲突无反常，开局平淡

**判断原则**（基于上下文，非硬性标准）：
- 读者读到前 300 字的时候，是否已经产生了一个"为什么？"或"然后呢？"？
- 开篇是在"介绍背景"还是"开启故事"？——介绍背景的都在科普，开启故事的已经在冲突中
- 去掉开篇前 200 字，故事是否依然成立？——如果成立，说明这 200 字是无效的

**严重度判断**（结合三维标定表综合评估）：
- L1：开篇稍显平淡，但有一段情绪铺垫或氛围描写，前 500 字内进入了故事
- L2：开篇前 300 字纯日常/纯背景，读者需要撑过一段"空白期"才能进入故事
- L3：开篇前 1000 字都在介绍背景或展示日常，读者大概率在前 3 段就关掉了

**例外情况**（以下场景通常不是开篇平庸）：
- 文学性作品的缓慢开场——文学读者和网文读者的阅读习惯不同
- 第一人称内心独白式开篇——如果内心独白本身就是冲突的载体
- 诗化/氛围型开篇——氛围本身就是"钩子"

**诊断锚点示例**（few-shot 参考）：
- **L2 命中**："李明是一个普通的上班族，每天早上九点准时到公司。今天和往常一样，他打卡、泡咖啡、打开电脑……" → 前 200 字没有任何冲突、悬念或反常事件。P013 L2
- **❌ 未命中（氛围型开篇）**："雾把整个城市泡软了。路灯在雾里化成一团光晕，远处的钟楼只剩轮廓。他站在雾里，手里的伞没有打开。" → 判定：不触发。理由：氛围型开篇——雾的意象本身就是钩子（他为什么不打伞？），是诗化开场而非无效背景介绍。

**推荐教学动作**：首选 A007 一句话冲突，备选 A001 缩小范围

