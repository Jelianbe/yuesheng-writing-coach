### P036 流水账叙述症

> **position_sensitivity**: chapter

**核心问题**：事件按时间顺序平均罗列，无冲突聚焦与轻重缓急，像流水账。与 P006（无新事件、原地打转）不同，P036 是**有事件但平铺**——事件一个接一个但平均用力；与 P021（关键事件被概括、太快）不同，P036 是展开太平均、没有详略，两者是同一问题的两端。

**触发信号**：起床—洗漱—吃饭—上班式逐项交代；一天之内每个事件占用相似篇幅；事件与事件之间无因果/冲突连接；读完整段说不出"重点是哪件事"。

**判断原则**（基于上下文，非硬性标准）：
- 段落中事件是否有轻重？（重点场景展开、过渡一句话带过？）
- 事件之间是否有因果/冲突连接？（还是只是时间先后罗列？）
- 读者能说出这一段的核心事件/冲突吗？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别段落平铺，不影响理解
- L2：整章以流水账组织，重点事件与日常等重
- L3：多章流水账，冲突被稀释，读者找不到追读点

**例外情况**（以下场景通常不是流水账）：
- 日常琐事本身在塑造生活质感（有情绪价值的日常不等于平铺）
- 时间线快进式的概述（几十年的变迁本就该一笔带过）
- 悬疑铺垫中"看似平淡"的章节（平淡本身是设计）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（时间平铺无轻重）**：
> 原文：他起床，洗漱，出门，路过包子铺买了两个包子，坐地铁，到公司打卡，打开电脑，开始回邮件，中午吃外卖，下午开会，晚上加班，十点回家睡觉。
> 判定：P036 L2
> 理由：事件按时间顺序等重罗列，无冲突聚焦与详略分配，读者读不出重点。

**❌ 未命中（有详略有冲突）**：
> 原文：早上一切照旧。直到午休时，手机屏幕亮起——是十年前那个号码。"还活着？"那头的声音沙哑。他攥紧了杯子，纸杯捏出一道折痕。
> 判定：不触发
> 理由：日常一笔带过，重点事件展开且有冲突聚焦，不算流水账。

**✅ L3 命中（冲突被稀释）**：
> 原文：主角正在被追杀，作者却用一整章流水账写了他在小镇上买菜、修鞋、吃饭、闲逛的日常。
> 判定：P036 L3
> 理由：冲突紧迫时用多章流水账稀释，读者找不到追读点。

**推荐教学动作**：首选 A009 节奏变速，备选 A011 场景裁剪

