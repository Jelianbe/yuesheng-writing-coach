| **对读者体验的影响** | 不影响理解，仅质感下降 | 打断阅读节奏，影响沉浸 | 直接导致读不下去 |
| **修复成本** | 改几句话即可 | 需要调整段落结构 | 要重写整段/重构叙事 |
| **教学优先级** | 顺带提一下即可 | 锁定为主线症候 | 立即介入训练 |

