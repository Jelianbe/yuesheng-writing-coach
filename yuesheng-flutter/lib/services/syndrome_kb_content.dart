### P008 语言堆砌

> **position_sensitivity**: global

**核心问题**：描写的密度超过了叙事所需，信息被华丽辞藻稀释，读者需要费力才能抓到核心内容。

**触发信号**：修饰词过多，有效信息密度低

**判断原则**（基于上下文，非硬性标准）：
- 这段描写的"投入产出比"是否合理？如果删掉一半修饰，核心信息是否不变？
- 这段描写在故事中的功能是什么？高潮场景的浓墨重彩，还是过渡段落的无意义铺陈？
- 描写是否服务于叙事目的？（推进情节/塑造角色/营造氛围/埋设伏笔）
- 读者读这段的经验是什么？是被画面感染，还是被文字淹没？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别段落用词偏华丽，但核心内容可抓取，精简修饰语即可
- L2：描写明显超过叙事所需，读者开始感到阅读疲劳，需要修剪部分段落
- L3：全文依赖堆砌维持文本量，几乎无有效信息传递，读者费力才能抓到核心

**例外情况**（以下场景通常不是堆砌）：
- 关键情感爆发点或高潮场景，适当的浓墨重彩是合理的叙事手段
- 作者刻意营造的特定风格（如诗化小说、意识流）
- 悬疑氛围铺垫——环境描写的冗余有时是故意制造的压迫感

**诊断锚点示例**（few-shot 参考）：
- **L2 命中**："黄昏的光线透过百叶窗的缝隙，在实木地板上画出一道道平行的金色条纹。窗台上那盆绿萝的叶子微微颤动，似乎在呼吸着窗外吹进来的微风。空气中漂浮着细小的尘埃，在光柱中上下翻飞，像是被困在琥珀里的时间碎片。" → 300 字环境描写只服务于"门开了"这一个事件，投入产出比失衡。P008 L2
- **❌ 未命中（情感爆发点的浓墨重彩）**："她终于见到他。多年积攒的话堵在喉咙，她张了张嘴，什么都说不出来。窗外的雨突然大了起来，砸在玻璃上，像是替她哭。" → 判定：不触发。理由：描写集中在情感爆发点，意象（雨）承载情绪而非堆砌辞藻——投入产出比合理。

**推荐教学动作**：首选 A006 感官全开，备选 A008 对话瘦身 或 A011 场景裁剪 / A016 高频词清扫

