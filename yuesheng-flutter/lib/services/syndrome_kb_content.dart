### P022 重复用词/基础语病

> **position_sensitivity**: local

**核心问题**：词汇或标点重复、基础文法瑕疵——同一字/词紧邻重复、连续标点、多句同一起头、高频连接词反复出现，读者注意力被细碎瑕疵分散，语言显得粗糙。与 P007（句式结构重复）互补——P007 是"句式骨架"雷同，P022 是"用词/标点"层面的基础问题。

**触发信号**：同一字紧邻重复（"的了了""他他"）；连续重复标点（"。。""，，"）；连续多句以同一词起头；短篇幅内同一连接词/副词反复出现（"然后""但是""忽然"）

**判断原则**（基于上下文，非硬性标准）：
- 有没有紧邻的重复字/词，属于打字错误或措辞未打磨？
- 有没有连续的重复标点？
- 连续句子是否以同一词/字起头，造成机械感？
- 高频词是"口语习惯"还是"刻意节奏"？——刻意排比不算问题

**严重度判断**（结合三维标定表综合评估）：
- L1：单处重复/个别标点瑕疵，不影响理解，改几个字即可
- L2：多处重复，打断阅读节奏，需通读润色
- L3：全文通病（高频词/起头全篇雷同），需系统性修改

**例外情况**（以下场景通常不是基础语病）：
- 刻意排比/顶真——重复是有意为之的修辞
- 口语对话——人物口头禅是塑造手段
- 文言/仿古文体——用词重复是文体特征

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（重复用词）**：
> 原文："他忽然站起来。忽然又坐下。忽然把桌上的信揉成一团。"
> 判定：P022 L2
> 理由：连续三句以"忽然"起头，机械重复。

**❌ 未命中（刻意排比）**：
> 原文："我等你，等风停，等雨歇，等你说一句喜欢。"
> 判定：不触发
> 理由：重复是刻意修辞，节奏上服务于情感推进。

**推荐教学动作**：首选 A016 高频词清扫，备选 A011 场景裁剪

