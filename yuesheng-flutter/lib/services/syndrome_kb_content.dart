### P027 追读动力不足症

> **position_sensitivity**: serial

**核心问题**：长线追读设计缺失——更新期待、长线悬念、情感绑定与主线牵引弱，爽点分散无主轴，读者在连载中逐渐弃书。与 P024（期待感断裂）区分——P024 是"单点期待兑现"的节奏问题，P027 是"长线留存结构"的架构问题（主线牵引/情感绑定/成长弧光）。

**触发信号**：连载中期开始掉粉；主线被支线淹没/遗忘；无跨章的情感/关系绑定；主角成长无阶段感；更新依赖读者惯性而非内容吸引力。

**判断原则**（基于上下文，非硬性标准）：
- 是否存在一条跨多卷的"主线目标"，每章都在推进它？
- 读者与角色之间是否有可积累的情感绑定（关系/羁绊/遗憾）？
- 主角的成长是否有清晰的阶段弧光，而非原地打转？
- 长线悬念是否被定期"充值"（推进/加深），而不是抛完就忘？

**严重度判断**（结合三维标定表综合评估）：
- L1：局部章节游离主线，总体仍被主线牵引
- L2：主线淡化，支线喧宾夺主，追读动力下滑
- L3：主线消失，无情感绑定、无成长弧光，读者批量弃书

**例外情况**（以下场景通常不是追读动力不足）：
- 单元剧/副本流——以单元本身的吸引力为长线
- 日常/治愈流——情感陪伴本身就是留存
- 短篇完结型——不适用连载留存

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（主线淡化）**：
> 原文：连载中期的五章分别写五个互不相干的小事件，主角初始目标已三个月未提及。
> 判定：P027 L2
> 理由：主线牵引缺失，无长线悬念充值，读者靠惯性追读。

**❌ 未命中（主线持续推进）**：
> 原文：每章解决一个支线危机，但主线"寻找失踪的师父"始终在推进，且每五章有阶段收获。
> 判定：不触发
> 理由：支线服务主线，长线悬念持续充值。

**推荐教学动作**：首选 A013 情节复盘，备选 A012 伏笔追踪

