### P029 段落失控症

> **position_sensitivity**: chapter

**核心问题**：段落组织失衡——要么一屏一段无呼吸感（读者在移动端被"文字墙"劝退），要么碎片化断行（一句话一段、节奏被切碎）。阅读节奏由段落结构主导，段落失控直接破坏沉浸。与 P007（句子层面结构重复）不同，P029 是**段落层面**的组织问题。

**触发信号**：连续段落 ≥5 行无分段；或连续 5+ 段为单句段；场景切换处段落长短无起伏。

**判断原则**（基于上下文，非硬性标准）：
- 在手机屏幕上，最长的段落是否超过约一屏？
- 段落切分是否服务于语义节奏（一个场景/一个动作/一次情绪转折一段），还是随意断行？
- 动作序列、对话往来、情绪起伏是否在段落层面有呼吸感？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别长段可读但偏闷，或个别单句段略显碎片
- L2：整章出现"文字墙"或密集碎行，读者在段落层面产生疲劳
- L3：段落结构完全失控，阅读体验在段落层面直接断裂

**例外情况**（以下场景通常不是段落失控）：
- 对话为主的场景中短段密集（对话本身驱动节奏，P011 场景）
- 有意为之的节奏实验（如高潮段落的短句短段堆叠）——若服务于情绪则不算
- 列表式/条目式内容（设定说明，P004 场景）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（文字墙）**：
> 原文：他推开门的瞬间，屋子里的一切都在这一刻凝固。陈旧的木地板在脚底发出细碎的呻吟。窗外的雨声、桌上没喝完的茶、墙上那张泛黄的照片，还有照片里那个笑得很开心的女人。他站在门口，久久没有动。时间像被拉长了一样。他想起很多年前……（350 字无分段）
> 判定：P029 L2
> 理由：移动端一屏文字墙，段落层面无呼吸感。

**❌ 未命中（段落服务节奏）**：
> 原文：她打开门。外面下着雨。她撑开伞，走进雨里。
> 判定：不触发
> 理由：单句段服务于雨夜氛围的克制节奏，段落结构与语义一致。

**推荐教学动作**：首选 A011 场景裁剪，备选 A009 节奏变速

