### P005 视角漂移

> **position_sensitivity**: global

**核心问题**：叙事视角不统一，写入了当前视角角色不可能知道的信息。

**触发信号**：写了主角看不到/听不到的信息

**判断原则**（基于上下文，非硬性标准）：
- 当前段落是从谁的视角看的？这个角色能看到/听到/知道这条信息吗？
- 如果信息超出了当前视角的感知范围，是否有视角切换的明确标记？
- 无意识的全知视角插入（"实际上...""他不知道..."）是否在破坏沉浸感？

**严重度判断**（结合三维标定表综合评估）：
- L1：偶尔出现视角越界，但整体叙事主体清晰，改一两句话即可
- L2：频繁视角漂移，读者有时不确定是谁在看，阅读沉浸被打断
- L3：整段叙事视角混乱，完全无法确定叙述主体，读者必须反复回读确认"这是谁在看"

**例外情况**（以下场景通常不是视角漂移）：
- 有明确标记的视角切换（章节标题、段落分隔、视角人物明确切换）
- 第三人称全知视角作为叙事风格——只要一致性保持
- 第三人称限制视角中偶尔的"客观叙述"（描述环境而非角色的内心活动）
- 角色对自己所处环境的评价——"那是出了名的死地""这地方邪门"——角色在自己的视角内对一个地点做判断，不构成视角越界
- 角色对自己的过去的回忆或反思——"他曾在这里待过三年"——只要不包含他人内心，角色回忆自身经历是视角内的

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（典型）**：
> 原文："林远推开门，看到屋里坐着三个人。他不知道的是，最左边那个男人刚刚在口袋里攥紧了刀。林远觉得很紧张。那个男人心里想：今晚必须动手。"
> 判定：P005 L2
> 理由："他不知道的是"是全知视角侵入，"那个男人心里想"切换到他人内心。一段文本两次越界。

**❌ 未命中（明确标记的视角切换）**：
> 原文："林远推开门。（视角切换）李梅坐在屋里，心里想着今晚的计划。"
> 判定：不触发
> 理由：有明确标记的视角切换，不是无意识的视角越界。

**推荐教学动作**：首选 A002 回归主角，备选 —

