### P025 黄金三章失效症

> **position_sensitivity**: global

**核心问题**：开局前三章未完成网文"阅读契约"——读者需在约 3000 字内建立代入（主角处境可感）、获得立足点（身份/能力/金手指）、看到第一个冲突与目标牵引。前三章若主角平淡、无优势、无冲突、无目标，读者无法"入坑"即流失。与 P013（开篇平庸）区分——P013 是"前 300 字无钩子"（单点开篇），P025 是"前三章整体结构"（人设/金手指/冲突/目标四件套）。

**触发信号**：前三章无主角明显优势或金手指；主角被动无目标；第一个冲突迟迟不来或强度不足；开局大量设定铺陈无行动；前三章无一次"让读者记住主角"的时刻。

**判断原则**（基于上下文，非硬性标准）：
- 前三章内读者能否说清"主角是谁、要干什么、凭什么"？
- 主角有没有可感知的成长预期（金手指/天赋/上升通道）？
- 第一个冲突是否发生在主角身上且需要主角主动应对？
- 开局是否用"行动+冲突"而非"设定+旁白"建立代入？

**严重度判断**（结合三维标定表综合评估）：
- L1：前两章合格，第三章开始乏力（仍有挽回）
- L2：前三章未建立阅读契约，读者在免费章节末流失
- L3：开局即劝退，代入/金手指/冲突/目标四件套全缺

**例外情况**（以下场景通常不是黄金三章失效）：
- 已成名作者/系列续作——读者自带信任与期待
- 纯文学/短篇——不适用网文商业节奏
- 慢热但开局有强钩子的文——钩子已拉住读者

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（开局无立足点）**：
> 原文：前三章全为背景介绍与日常描写，主角是普通店员，无任何特殊之处，无冲突，无目标。
> 判定：P025 L2
> 理由：前三章主角无优势、无冲突、无目标，读者无法建立阅读契约。

**❌ 未命中（四件套齐全）**：
> 原文：第一章被裁员（处境）+ 觉醒天赋（金手指）+ 前东家打压（冲突）+ 复仇目标（目标）。
> 判定：不触发
> 理由：代入/立足点/冲突/目标在开局即建立。

**推荐教学动作**：首选 A007 一句话冲突，备选 A001 缩小范围

