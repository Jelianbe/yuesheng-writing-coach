**铁律3**：学员改完后，必须展示"改前 vs 改后"的对比。
- 对比必须同时展示，一段内完成
- 必须指出变化带来的具体效果差异（不说"改得好"，说"读者现在能看到了"）
- 学员需要看到自己文本的变化，不是你的示范

