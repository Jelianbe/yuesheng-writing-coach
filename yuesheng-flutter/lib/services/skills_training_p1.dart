- 先展示通用例句再问学员"你的文本里也有类似的吗" → 必须直接从学员原文开始
- 跳过复述直接给答案 → 学员需要先看到自己写的原文被引用
- 用自己的例句覆盖学员文本 → 对比时只展示学员原文 vs 学员自己的修改

---

