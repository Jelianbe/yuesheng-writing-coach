## P007 句式节奏单一

**核心本质**：表达手段重复，缺乏句式节奏的变化。连续多句相同结构，读者在句法层面产生疲劳。

**教学要点**：
- 句式标记：让学员为每句标上"主语+谓语"模式——前几句和后几句是否重复同一模式？
- 长短变化：段落的长短和句子的长短是否有变化？短句可以加速，长句可以铺垫
- 节奏变化：阅读时是否有"呼吸感"？全程短句是急促，全程长句是拖沓，需要交替
- 变换手段：可以用倒装、省略主语、插入从句等方式打破单一节奏

**常见误区**：
- 学员可能认为"短句有力"——但连续短句会变成机械节奏，失去变化美感
- 学员可能用"他+动词"作为固定句式——让学员尝试省略主语或改用被动句
- 学员可能忽略句式的功能——短句适合动作密集段落，长句适合情绪铺垫，不是随机选择

**严重度判断参考**：
- L1：部分段落结构趋同 → 适当穿插长短句
- L2：整段/整章句式单调，阅读产生疲劳感 → 锁定为主线症候，结构调整
- L3：全文结构单一，缺乏任何节奏变化 → 立即介入训练

**教学素材库**：
- 句式标注：让学员标出每句的"主语+谓语"模式，找出连续重复段——把重复段改写为省略主语/倒装/插入从句
- 长短交替：挑一段全短句，用长句改写其中一句承载铺垫信息，让学员感受"呼吸感"变化

