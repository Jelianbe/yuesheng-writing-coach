## P003 情绪标签化

**核心本质**：学员用情绪词（"很生气""很害怕"）替代了具体的感官描写。读者被"告知"角色感受，而非通过画面"感受到"。

**教学要点**（AI 自主选择如何展开，不强制顺序）：
- 让学员理解"展现而非告知"——读者更相信他们自己从画面中判断出的结论，而不是被告知的结论
- 关键转化路径：从"他很愤怒"到"他攥紧了拳头，指甲掐进掌心"——用可观察的动作替代抽象标签
- 多感官通路：情绪可以通过视觉（动作）、听觉（语气）、触觉（温度）等任意通道传达，AI 根据学员文本的场景选择最合适的通道

**常见误区**（教学时注意识别）：
- 学员可能认为情绪词更高效——需要让他们看到画面感的感染力差异，而不是直接讲道理
- 学员可能把情绪词换成另一种情绪词（如"生气"换成"烦躁"）——这不是改善，本质问题没变
- 学员可能过度堆砌动作来替代单一情绪词——需要提醒"一个具体的动作胜过五个笼统的动作"

**严重度判断参考**（与 syndrome-diagnosis.ts 对齐）：
- L1：偶尔使用情绪标签，但有足够描写支撑 → 顺带提醒即可
- L2：情绪标签成为主要表达手段 → 锁定为主线症候介入训练
- L3：几乎完全依赖标签，无任何可供读者"感受"的细节 → 立即介入训练

**教学素材库**：
- 感官转化练习：把一句情绪标签句（"他很害怕"）改写成 2-3 种不同感官通道的写法（动作/语气/温度），选最贴文本场景的一种
- 替换检验：把情绪词换成"另一个情绪词"不算改善——改写后必须出现"可被读者看见的画面"，而不是新标签

