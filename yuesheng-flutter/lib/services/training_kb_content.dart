## P029 段落失控症

**核心本质**：段落组织失衡——要么一屏一段无呼吸感（"文字墙"），要么碎片化断行（节奏被切碎）。阅读节奏由段落结构主导，段落失控直接破坏沉浸。不是句子层面的问题（那是 P007），而是段落层面缺乏与语义节奏匹配的切分。

**教学要点**：
- 段落服务语义：一个场景/一个动作/一次情绪转折一段，让学员标注每段的"功能"再重切
- 呼吸感训练：长段必拆——以手机一屏为参考，超长段落按动作/感官/情绪转折点断开
- 防碎片化：单句段须有理由（强调/节奏加速），连续碎行合并回语义单元
- 长短起伏：让学员观察场景切换处的段落长短变化，长段铺陈、短段推进

**常见误区**：
- 以为分段越多越易读——过度碎行反而切断阅读节奏
- 只看长度不看语义——为拆而拆，打断动作连贯性
- 对话段落一刀切——对话驱动的短段密集是正常的（P011 场景）

**严重度判断参考**：
- L1：个别长段偏闷/个别单句段碎片 → 挑 1-2 处重切
- L2：整章文字墙或密集碎行 → 整章段落重排（先大段拆小、再碎行归并）
- L3：段落结构完全失控 → 按场景逐段重切，段落长短重新设计

**教学素材库**：
- 文字墙改写练习：给 300 字无分段原文，让学员按语义节奏切分并说明理由
- 碎行归并练习：给 8 个单句段，让学员归并为 2-3 个语义单元
- 屏幕自检：学员把段落长度对照手机屏幕，超一屏即标记

