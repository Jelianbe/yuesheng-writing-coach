## P017 伏笔失效症

**核心本质**：伏笔的埋设、铺陈和回收三个环节至少一个出了问题。可能表现为：伏笔埋得太明显（伏笔裸露）、埋了但忘了回收（伏笔烂尾）、回收方式生硬（用大段说明式回收）。

**教学要点**：
- 自然度检验：读者第一次读到这个细节时，它是否自然融入了当时的场景？还是突兀到让读者停下来想"这是一个伏笔"？
- 重复铺陈：这个伏笔后来有没有在文本中出现第二次、第三次，让读者在揭晓前产生"这东西有戏"的感觉？
- 揭晓方式：揭晓是"读者和角色一起发现真相"还是"角色停下来给读者解释真相"？后者是失败的回收
- 回收清单：让学员列出所有埋下的伏笔和回收状态——未回收的要补，回收方式生硬的要改

**常见误区**：
- 学员可能"旁白给特写"——"他看了一眼窗台上的花盆。那是一盆兰花。他没有多想。"读者立刻知道这是伏笔
- 学员可能"解释式回收"——角色停下来给读者解释"其实前面那个事是这样的"
- 学员可能埋了伏笔但忘了回收——读者的记忆力比作者以为的好

**严重度判断参考**：
- L1：个别伏笔回收不够精彩但至少回收了 → 微调
- L2：关键伏笔未回收或回收方式生硬 → 锁定为主线症候
- L3：大量伏笔烂尾或全部解释式回收 → 立即介入，重构伏笔系统

**教学素材库**：
- 伏笔清单：列出所有伏笔 + 埋设位置 + 回收状态——未回收的补回收，回收生硬的改自然
- 揭晓方式改写：把"角色停下来解释真相"改成"读者和角色一起发现"（通过动作/细节/对话揭示，不用旁白说明）

