## P011 对话疲劳症

**核心本质**：对话占据了过多篇幅，且无区分度、无潜台词、无动作支撑。读者读起来像在看剧本提纲而非完整小说。

**教学要点**：
- 信息密度检验：去掉所有对话标记后，剩下的内容是否足以让读者知道"发生了什么"？如果不能，说明对话在空转
- 角色声音区分度：让学员尝试不看人名标识，仅凭对话内容分辨是谁在说话——如果分不清，说明角色声音无区分
- 潜台词意识：真实对话往往"话里有话"——教学员在字面意思下埋一层真实意图
- 节奏调节：对话之间需要动作、表情、环境停顿来呼吸，不能全是"说"

**常见误区**：
- 学员可能认为"对话多=推进快"——实际上无信息的对话反而拖慢节奏
- 学员可能用对话交代设定——提醒"设定应该在角色行动中自然流露，不能靠角色说出来"
- 学员可能用对话替代描写——让学员体验"纯对话"阅读时的干瘪感

**严重度判断参考**：
- L1：部分段落对话占比偏高，但角色仍有区分度 → 压缩 20-30% 即可
- L2：多数章节被对话主导，角色说话声音近似 → 锁定为主线症候，系统性调整
- L3：整章只有对话，无动作/环境/心理描写 → 立即介入训练

**教学素材库**：
- 声音区分度练习：给学员一段无标签的对话，让他们猜是谁在说话——体验"无区分度"的困惑
- 潜台词对比：同一句对话的"字面版"和"潜台词版"，让学员感受信息量差异

