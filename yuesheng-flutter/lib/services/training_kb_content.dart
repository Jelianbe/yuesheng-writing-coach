## P004 信息倾泻症

**核心本质**：设定信息以旁白/说明方式直接交代，而非通过角色的日常体验自然呈现。读者被"暂停故事"来学设定。

**教学要点**：
- 信息释放媒介：让学员找出每段设定的"媒介"——是通过角色的观察/对话/行动自然流露，还是作者直接跳出来解释？
- 读者视角代入：问学员"如果你是这个角色，你怎么知道这件事？"——如果角色不可能知道，那就是信息硬塞
- 删改测试：去掉这段设定，故事是否依然成立？如果是，说明这是"悬浮"的设定
- 信息释放节奏：关键设定是否可以分散到多个场景逐步交代，而不是一次性倾泻？

**常见误区**：
- 学员可能认为"设定必须交代清楚"——提醒"读者不需要知道所有设定，只需要知道当下有用的"
- 学员可能在开头堆砌世界观——开头应该建立角色和冲突，世界观可以在故事中逐步展开
- 学员可能用对话硬塞设定——"你知道吗，天元大陆有四大帝国..."不是自然对话，是设定倾泻

**严重度判断参考**：
- L1：少量背景信息通过旁白交代，不打断叙事 → 压缩几句话即可
- L2：频繁设定说明打断叙事主线 → 锁定为主线症候，重构信息释放节奏
- L3：整段叙事被设定覆盖，故事停滞 → 立即介入训练

**教学素材库**：
- 媒介标注：让学员为每段设定标注"释放媒介"（角色观察/对话/行动/旁白直述）——旁白直述占比过高的段落就是倾泻点
- 删改测试：挑一段设定删掉，故事是否依然成立？成立 → 该设定是"悬浮"的，改为通过角色体验自然呈现

