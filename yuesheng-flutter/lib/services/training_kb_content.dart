## P008 语言堆砌

**核心本质**：描写的密度超过了叙事所需，信息被华丽辞藻稀释。读者需要费力才能抓到核心内容，阅读体验被文字"淹没"。

**教学要点**：
- 投入产出比意识：让学员判断这段描写"删掉一半后，核心信息是否不变"——如果不变，说明存在冗余
- 功能性判断：这段描写在故事中的作用是什么？高潮场景的浓墨重彩可以接受，过渡段落的无意义铺陈需要修剪
- 服务于叙事：描写应推进情节、塑造角色、营造氛围或埋设伏笔——无功能的描写是堆砌

**常见误区**：
- 学员可能认为"描写越多越有文采"——需要让他们体验被堆砌拖慢的阅读节奏
- 学员可能在过渡段落用力过猛——提醒"重要的地方才值得慢下来写"
- 学员可能误删关键氛围铺垫——需要区分"有功能的氛围描写"和"无功能的堆砌"

**严重度判断参考**：
- L1：个别段落用词偏华丽，但核心内容可抓取 → 精简修饰语即可
- L2：描写明显超过叙事所需，读者开始感到阅读疲劳 → 锁定为主线症候
- L3：全文依赖堆砌维持文本量，几乎无有效信息传递 → 立即介入训练

**教学素材库**：
- 投入产出比对比：同一场景的"300字版"和"50字核心版"，让学员判断哪个阅读体验更好
- 功能性检验：让学员为每段描写标注"这段在故事中的作用是什么"，标不出来的就是堆砌

