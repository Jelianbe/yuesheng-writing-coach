## P034 配角工具人症

**核心本质**：配角群像工具化——无独立性格/动机/记忆点，仅承担传话、推剧情、喊口号的功能。不是核心角色问题（那是 P009 无动机 / P010 无辨识度），而是**配角群像的功能性过强**：把配角名字换成"路人甲"剧情依然成立，读者记不住他们。

**教学要点**：
- 动机补位：每个重要配角问一句"他想要什么？"——配角有独立欲望，行为才有个性
- 辨识度塑造：给配角一个特征性行为/口头禅/癖好（T006 特征性对话），不靠名字辨认
- 功能剥离：传话/送情报的功能改由"带性格的方式"完成——同一功能，不同的性格表达
- 独立小场景：让配角做一件与主线无关但展现性格的事（T007 意外测试）

**常见误区**：
- 以为配角戏份多是浪费——戏份少≠工具人，一句有性格的台词胜过三章功能戏
- 以为功能角色可以完全扁平——报信/跑腿可以一次性，但重要配角必须独立
- 以为配角跟主角绑定就有存在感——贴身跟班/兄弟/搭档最容易被写成工具人（滑向 P009 空心化）

**严重度判断参考**：
- L1：个别配角平面化 → 补一个辨识特征/独立动机
- L2：多个配角工具化 → 逐配角补动机与特征性行为，剥离纯功能戏
- L3：全员配角工具人 → 群像重设计（配角动机网+辨识度档案重建）

**教学素材库**：
- 配角档案模板：姓名 / 欲望 / 恐惧 / 特征性行为 / 与主线的非功能关联
- 换名测试卡：把配角名字换成"路人甲"，剧情是否依然成立？成立则工具化
- 特征性对话练习：给五个配角同一句话（如"路上小心"），让学员写出五种性格版本
- 群像对比案例：同题材"工具人配角 vs 有独立动机的配角"两组互动，学员对比体验

