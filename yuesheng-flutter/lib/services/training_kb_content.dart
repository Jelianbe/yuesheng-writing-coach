## P022 重复用词/基础语病

**核心本质**：词汇或标点层面的基础瑕疵——同一字/词紧邻重复、连续重复标点、多句同一起头、高频连接词反复出现。语言显得粗糙，读者注意力被细碎瑕疵分散。与 P007（句式节奏单一）互补——P007 是"句式骨架"雷同，P022 是"用词/标点"层面的基础问题。

**教学要点**：
- 自查锚点：读一遍自己的文字，找出"读起来卡壳"的位置——卡壳往往就是重复/瑕疵所在
- 高频词检验：同一段里是否有字/词出现两次以上、且删掉不影响语义？
- 起头多样性：连续 3 句是否以同一词/字开头，造成机械感？
- 标点卫生：有没有连续的重复标点（"。。""，，"）？

**常见误区**：
- 把刻意排比/顶真当语病——有意为之的修辞是节奏手段，不是问题
- 把口语口头禅当语病——人物口头禅是塑造手段
- 只盯着"删掉重复"——更要看"这里为什么重复"（词汇不足/写得急/未打磨），从源头改善

**严重度判断参考**：
- L1：单处重复/个别标点瑕疵 → 指出位置，让学员自己改
- L2：多处重复打断阅读节奏 → 通读润色，一次聚焦一类重复
- L3：全文通病（高频词/起头全篇雷同）→ 系统性修改，从最高频的重复入手

**教学素材库**：
- 找卡壳：让学员朗读自己的文字，标出"读起来卡壳"的位置——卡壳处往往是重复/瑕疵所在
- 高频词清扫：找出高频重复词/同起头句，逐个删换；改完后通读一遍，确认没有把刻意修辞误删

## P023 爽点乏力症

**核心本质**：情节推进缺乏情绪回报——主角的胜利、成长、收获被平淡带过，优势展示不足或收益兑现无快感累积，读者情绪无起落、追读动力弱。网文读者的"爽"来自铺垫-反差-释放的循环，缺失任一环则爽感不成立。

**教学要点**：
- 关键时刻加篇幅：读者期待的关键胜利，要给足够的动作/细节/反应去"感受"，而非一句带过
- 优势要展示：主角的强项不能只在设定里存在，要找机会在冲突中"用出来"
- 收益要可视化：升级/得宝/赢局要有过程与反差（之前的憋屈→现在的扬眉），而非凭空给
- 打脸要铺垫：被看轻的铺垫越足，打脸释放越快感越强

**常见误区**：
- 把"赢"等同于"爽"——赢了但没细节、没反差、没情绪释放，读者无感
- 全程高能无蓄力——每章都打脸会审美疲劳，爽点需要节奏（张弛）
- 只加爽不加代价——无敌流也有代价（对手/限制/后患），否则读者无法代入

**严重度判断参考**：
- L1：个别关键场景平淡 → 指出该处，加一段"现场感"细节
- L2：整章无情绪回报点 → 找出可做反差的场景，重写为铺垫-释放结构
- L3：全篇爽点机制缺失 → 从主线入手设计"情绪回报节拍表"（每 2-3 章一个高点）

**教学素材库**：
- 情绪回报节拍表：让学员列出最近 10 章的"主角收获清单"，标出每处收获是否有过程/反差/细节——缺失的即为改造点
- 一句话爽点：让学员用一句话说清"本章读者为什么看得爽"——说不出的章即为目标章
- 反差重写：选一个"赢了但平淡"的场景，补上对手看轻→主角出手→全场震惊的反差链

