## P018 人设崩塌症

**核心本质**：角色在连载过程中行为模式发生了未经铺垫的变化。与 P009（一开始就没建立动机）不同，P018 是角色在连载中途"写崩了"。

**教学要点**：
- 合理性检验：这个角色在本章的行为——如果让只读过前十章的读者来判断，他们会觉得"合理"吗？
- 动机检验：角色行为的改变是因为"情节需要他这样做"还是因为"这个角色在某种特定压力下会这样做"？前者是崩塌，后者是成长
- 过渡检验：角色改变有没有过渡？是从 A 突然跳到 Z，还是经过了 B→C→D……Y 的渐变？
- 一致性档案：让学员为角色建立"行为档案"——记录角色的核心性格特征，后续写作时对照

**常见误区**：
- 学员可能让角色"剧情需要什么就做什么"——这是崩塌，不是成长
- 学员可能忽略"渐变"的重要性——角色的重大改变需要足够的铺垫和过渡
- 学员可能把"极端情境下的例外反应"当成崩塌——善良的人在保护孩子时可以做出残忍的事，这是合理的

**严重度判断参考**：
- L1：个别场景中角色行为略有不一致 → 加一个过渡
- L2：角色关键行为与前期形象严重矛盾 → 锁定为主线症候
- L3：角色完全不像同一个人 → 立即介入，重构角色一致性

**教学素材库**：
- 前史检验：让只读过前几章的读者判断"这个行为合理吗"——不合理，就是崩塌
- 行为档案：列出角色 3 个核心特质，为本章行为找"档案内"的动机——找不到，说明这个行为不该发生或需要铺垫

