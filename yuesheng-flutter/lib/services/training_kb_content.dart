## P036 流水账叙述症

**核心本质**：事件按时间顺序平均罗列，无冲突聚焦与轻重缓急，像流水账。不是没有事件（那是 P006 停滞），也不是事件被概括（那是 P021 过快），而是**有事件但平铺**——每个事件等重展开，读者读不出重点与张力。

**教学要点**：
- 详略分配（T022）：重点事件展开写，过渡事件一句话带过；先问"哪件事改变了主角处境"，那就是展开点
- 冲突聚焦：让每个事件与主角目标/冲突挂钩（T008 因果动作链），无事因的事件概述化或删掉
- 节奏变速（A009）：平淡处快进、关键时刻慢写；让读者感知"时间的权重"
- 场景裁剪（A011）：删掉不改变剧情/情绪/信息的日常事件

**常见误区**：
- 以为平铺是"忠实记录生活"——小说记录的是戏剧性，不是日程表
- 以为事件越多节奏越快——等重罗列反而拖慢节奏，读者抓不住重点
- 以为概述就冷场——过渡句的"快"正是为了衬托重点场景的"慢"

**严重度判断参考**：
- L1：个别段落平铺 → 调详略
- L2：整章流水账 → 找核心事件展开，其余概述/删减
- L3：多章流水账冲突稀释 → 重建章节结构，事件重组为冲突单元

**教学素材库**：
- 事件权重表：列出章节所有事件，标「主角目标关联/冲突关联」，无关联的概述化
- 详略改写练习：同一段流水账改写两版——「全展开版 vs 一详多略版」，对比节奏
- 冲突聚焦练习：给流水账段加一个贯穿矛盾，让事件围绕矛盾组织
- 快进/慢写对照：同一天日常写两版——「时间快进版 vs 关键时刻慢写版」

