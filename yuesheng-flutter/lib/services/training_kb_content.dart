## P005 视角漂移

**核心本质**：叙事视角不统一，写入了当前视角角色不可能知道的信息。读者失去"是谁在看"的确定感。

**教学要点**：
- 视角锚点识别：让学员标出每段的视角人物——"这段是从谁的眼睛看的？"
- 越界检测：当前视角人物能否看到/听到/知道这条信息？如果不能，就是越界
- 全知标记：如果确实需要视角切换，是否有明确标记（章节标题、段落分隔、视角人物切换）？
- 一致性原则：同一段落内不应跳跃视角，如果切换必须明确告知读者

**常见误区**：
- 学员可能用"实际上..."引入全知信息——这破坏了限制视角的沉浸感
- 学员可能写"他不知道的是..."——这是在提醒读者"我在用全知视角"，打断代入
- 学员可能混淆"角色判断"和"全知信息"——角色说"那是死地"是角色判断，写"那里曾经发生过大战"是全知信息

**严重度判断参考**：
- L1：偶尔视角越界，但整体叙事主体清晰 → 改一两句话
- L2：频繁视角漂移，读者有时不确定是谁在看 → 锁定为主线症候
- L3：整段叙事视角混乱，无法确定叙述主体 → 立即介入训练

**教学素材库**：
- 视角标段：让学员给每段标"这段是谁在看"，再逐段检查"这段信息 ta 可能知道吗"——标不出视角或信息越界的段落就是漂移点
- 越界改写：找出越界信息，改写成"角色通过某种方式发现"（听到/看到/别人告诉），而不是直接告诉读者

