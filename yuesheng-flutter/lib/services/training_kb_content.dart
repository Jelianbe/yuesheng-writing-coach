## P030 节奏比例失衡症

**核心本质**：铺垫/冲突/收束的比例失衡——铺垫无限拉长该收不收，或高潮一笔带过该放不放，文戏武戏、日常与事件分配失调。不是整体无推进（那是 P006），不是冲突无分量（那是 P012），而是**有推进但分配不当**：读者感受到"节奏不对"，每个段落单独看却都成立。

**教学要点**：
- 节拍图复盘：让学员画出情节线（铺垫/冲突/兑现各占多少篇幅），一眼看比例
- 比例校准：按情节线重要性分配篇幅——主线兑现 > 支线铺垫，高潮处给足情绪停留
- 铺垫体检：读者已能猜到结果的地方就是铺垫过长，果断前移兑现或砍铺垫
- 收束练习：高潮后留白一段（读者消化情绪），不立刻转入下一事件

**常见误区**：
- 以为节奏问题都要改段落——比例问题是跨章节的，要先看节拍图
- 以为铺垫越多越有张力——过长的铺垫会提前耗尽读者耐心（滑向 P013 开篇冷启动）
- 高潮后立刻推进——不给情绪停留，读者体验"被骗"（易滑向 P024 期待落空）

**严重度判断参考**：
- L1：单一线索铺垫略拖 → 节拍图标记超长段，压缩 1-2 处
- L2：多条线索节奏错配 → 重排章节大纲，兑现点前移、铺垫减量
- L3：全文结构失衡 → 整卷节拍重设计（铺垫/高潮/收束比例重建）

**教学素材库**：
- 节拍图模板：横轴章节/纵轴冲突强度，让学员画出全文节奏曲线
- 比例自检卡：主线兑现章节数 / 总章节数 ≥ 1/3，低于则预警
- 情绪停留练习：给一段高潮后紧接转场的原文，让学员补"读者呼吸段"

