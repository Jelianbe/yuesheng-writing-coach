## P006 节奏停滞

**核心本质**：事件推进密度低，叙事陷入静止状态，缺乏冲突或悬念驱动读者前进。读者在想"然后呢？"

**教学要点**：
- 事件检验：去掉这一段，故事是否少了一件事？如果是，说明有推进；如果不是，可能在打转
- 悬念驱动：读者在读完这段时，是否想知道"接下来会发生什么"？如果没有，说明缺乏驱动力
- 冲突累积：这段是否引入了新信息/新冲突/新悬念？三者都没有就是在原地打转
- 功能判断：这段是"累积情绪/铺垫"，还是"纯静态描写"？静态描写需要压缩或删减

**常见误区**：
- 学员可能认为"描写可以调节节奏"——但没有事件推进的描写是停滞，不是调节
- 学员可能用对话填补空白——如果对话没有推进关系或揭示信息，同样在打转
- 学员可能把"气氛营造"当成推进——气氛必须服务于即将发生的事件，否则是停滞

**严重度判断参考**：
- L1：个别段落节奏偏慢 → 压缩几段即可
- L2：整段/整章节奏停滞，读者容易走神 → 锁定为主线症候
- L3：连续多章无有效事件推进 → 立即介入训练，重做章节结构

**教学素材库**：
- 事件贴标：让学员为每个段落贴"推进/打转"标签——统计打转段落，逐个问"去掉它故事少了一件事吗"
- 加一件小事：在停滞段落里加一个"角色主动做的小事"（看了一眼窗外/想起一件事），看叙事是否动起来

