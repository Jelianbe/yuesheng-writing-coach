## P015 高潮疲软症

**核心本质**：冲突写到了最高点但没有执行到位。铺垫做好了、冲突设定了、读者蓄势待发了——但高潮段落本身没有给读者期待的震撼/感动/热血。

**教学要点**：
- 情绪释放比：高潮之前读者积累了多少情绪？高潮之后释放了多少？两者是否匹配？
- 转折点：高潮是否有明确的"转折点"——一个让故事从此不同的事件/决定/揭示？
- 改变检验：如果删掉这个高潮场景，故事的走向会变吗？如果不会，说明这个高潮没有改变任何东西
- 执行力：高潮中的动作/对话/情绪是否有足够的"画面感"和"冲击力"？

**常见误区**：
- 学员可能"铺垫太长，高潮太短"——十章的期待换来几行字的释放
- 学员可能让高潮"顺理成章"——没有转折、没有意外、没有让读者"哇"的时刻
- 学员可能忽略高潮中的"角色选择"——高潮应该是角色做出最困难的决定，而不是最容易的

**严重度判断参考**：
- L1：高潮缺乏一个"最高点"的冲击力 → 加一两处情绪爆发
- L2：读者积累的期待没有被充分满足 → 锁定为主线症候，重写高潮
- L3：高潮段落几乎不成立 → 立即介入，重构高潮设计

**教学素材库**：
- 情绪收支表：列"高潮前读者积累了多少情绪" vs "高潮释放了多少"——释放远小于积累，就是疲软
- 改变检验：删掉这个高潮，故事走向会变吗？不会 → 高潮没有改变任何东西，需要加一个"转折点"

