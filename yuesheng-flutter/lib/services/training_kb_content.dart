## P033 升级节奏失衡症

**核心本质**：升级/成长节奏失衡——过快导致力量通货膨胀（数值爆炸，读者对成长失去感知），过慢导致读者期待流失（成长弧线拖沓）。不是段落比例问题（那是 P030），不是金手指机制问题（那是 P032），而是**成长弧线的推进速度本身失衡**：升级不再伴随新冲突/新代价，成长沦为数据堆砌。

**教学要点**：
- 升级伴随原则：每次升级必须带来新冲突或新代价——新敌人、新代价、新限制，成长才推进叙事
- 升级间隔校准：让学员画出升级时间线，检查"每次升级是否改变了读者的期待"
- 成长弧线服务主线：升级是否只是为了爽点，还是推动了主线冲突？
- 期待管理：升级前给足预兆与延迟（读者期待被拉满再兑现），避免随手升级

**常见误区**：
- 以为升级越多越爽——无代价升级导致力量通货膨胀，读者对数值麻木
- 以为升级要快读者才追——过快的升级消灭后续成长空间（滑向 P032 金手指过强）
- 以为升级是奖励与主线无关——游离于主线的升级只是数据堆砌（滑向 P016 巧合过多）

**严重度判断参考**：
- L1：单处升级过快/过慢 → 校准该次升级的间隔与代价
- L2：力量通货膨胀或成长停滞可感知 → 补代价与新冲突，重新设计升级阶梯
- L3：升级体系整体崩塌 → 重设成长体系（升级曲线+代价机制重建）

**教学素材库**：
- 升级时间线模板：章节 / 等级 / 新能力 / 新代价四栏，让学员画出成长弧线
- 代价绑定检查卡：每次升级检查"这次升级带来了什么新冲突/新代价？"
- 期待管理练习：给一段"该升级而未升级"的原文，让学员设计预兆与延迟
- 成长弧线对比案例：同题材"升级伴随代价 vs 升级纯数值"两组弧线，学员对比体验

