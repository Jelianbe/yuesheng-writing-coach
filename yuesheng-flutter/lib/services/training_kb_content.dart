## P009 角色空心化

**核心本质**：角色（尤其是主角）缺乏清晰的行为驱动力。动机不足是病根，工具化是症状——读者不知道"这个角色现在最想要什么"。

**教学要点**：
- 欲望检验：让学员用一句话回答"这个角色现在最想要什么"——如果回答不出来，说明动机缺失
- 角色替换测试：把当前角色换成另一个角色，这段剧情是否还能成立？如果成立，说明角色被工具化了
- 决定前置：角色的重大决定之前，是否有"为什么去"的铺垫？不是"剧情需要他去"，而是"这个角色真的会去"
- 内在目标：角色在故事中是否有自己的目标、恐惧、执念——还是只为主角服务？

**常见误区**：
- 学员可能给角色一个"伟大的目标"但缺乏具体步骤——"拯救世界"不是动机，"为了保护妹妹不被带走"才是
- 学员可能让角色"剧情需要什么就做什么"——提醒"角色不配合的时候，剧情就要改"
- 学员可能混淆"角色迷茫"和"角色空心"——迷茫是"我不知道要什么"，空心是"读者不知道这个角色有任何想要的能力"

**严重度判断参考**：
- L1：个别配角行为逻辑略生硬 → 补几句提示或改几句台词
- L2：主角关键行为缺乏动机 → 锁定为主线症候
- L3：主角缺乏清晰目标，大部分角色像提线木偶 → 立即介入，重构角色动机

**教学素材库**：
- 欲望一句话：让学员用一句话写"这个角色现在最想要什么"——写不出或太笼统（"拯救世界"），就是动机缺失
- 换人测试：把当前角色换成另一个角色，剧情是否仍成立？成立 → 角色被工具化，需要给 ta 自己的目标/恐惧/执念

