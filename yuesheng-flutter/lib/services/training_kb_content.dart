## P013 开篇平庸症

**核心本质**：开篇前 300 字没有冲突、没有悬念、没有反常事件。读者在决定是否继续读的 3 秒内没有得到"必须看下去"的理由。

**教学要点**：
- 钩子检验：读者读到前 300 字时，是否已经产生了一个"为什么？"或"然后呢？"？
- 功能判断：开篇是在"介绍背景"还是"开启故事"？介绍背景的都在科普，开启故事的已经在冲突中
- 删改测试：去掉开篇前 200 字，故事是否依然成立？如果成立，说明这 200 字无效
- 角色优先：开头应该建立角色和冲突，世界观可以在故事中逐步展开

**常见误区**：
- 学员可能用"天气/环境描写"开头——除非天气本身就是冲突的一部分
- 学员可能用"角色起床/吃饭"开头——日常不是钩子，反常才是
- 学员可能用"大段世界观设定"开头——读者还没关心这个世界，先让读者关心一个人

**严重度判断参考**：
- L1：开篇稍显平淡但前 500 字内进入故事 → 微调开头
- L2：开篇前 300 字纯日常/纯背景 → 锁定为主线症候，重写开头
- L3：开篇前 1000 字都在介绍背景 → 立即介入，彻底重构开篇

**教学素材库**：
- 钩子检验：读完学员开篇前 300 字，写下一个"读者此刻想问的问题"——写不出，说明没有钩子
- 删改测试：删掉开篇前 200 字，故事是否依然成立？成立 → 这 200 字是无效铺垫，换成一个"正在发生"的场景

