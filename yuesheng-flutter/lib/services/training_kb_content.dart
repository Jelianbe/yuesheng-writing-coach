## P041 降智反派症

**核心本质**：反派为坏而坏、降智送人头，无利益动机，冲突失真张力崩坏。不是冲突无分量（那是 P012 的结果），而是**对手角色被工具化**——高手博弈只为利益与活路，利益冲突到位矛盾自然爆发。

**教学要点**：
- 利益动机审计（A003 五问法）：追问每个反派"他图什么"——资源、活路、欲望，至少占一个
- 利益冲突到位：反派与主角的对抗建立在真实利益冲突上，冲突自然爆发（A007 一句话冲突）
- 意外测试法（T007）：反派也会做"意外但合理"的事——身居高位就有身居高位的算计与筹码
- 人味三问法（T005）：给反派正常的欲望与顾虑，不是"坏"而是"想要的和我不同"

**常见误区**：
- 以为降智才能让主角赢——主角赢在智慧而非对手愚蠢，读者要的是势均力敌
- 以为写惨反派就有动机——动机要具体到利益：夺舍、抢机缘、保命
- 以为反派必须坏——反派可以是立场不同、利益相悖的正常人

**严重度判断参考**：
- L1：个别反派单薄 → 补利益动机
- L2：核心反派降智 → 利益冲突重构 + 五问法
- L3：全篇对手工具化 → 对手体系复盘（A013）+ 利益链重构（A003）

**教学素材库**：
- 反派利益表：每个反派填「他想要什么 / 他怕失去什么 / 他为什么不肯让」
- 利益冲突练习：把"反派无脑找茬"改写成"利益冲突导致的必然对抗"
- 聪明反派对照：同一冲突写两版——降智版 vs 势均力敌版，对比张力
- 立场白描卡：一句话说清反派立场（立场不同而非人品坏）

