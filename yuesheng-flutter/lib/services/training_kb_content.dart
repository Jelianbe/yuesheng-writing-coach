## P025 黄金三章失效症

**核心本质**：开局前三章未完成网文"阅读契约"——读者在约 3000 字内需要建立代入（主角处境可感）、立足点（身份/能力/金手指）、第一个冲突与目标牵引。四件套缺一，读者"入坑"失败即流失。

**教学要点**：
- 代入：开局让主角陷入一个读者能感同身受的处境（失业/屈辱/危机），而非从平静日常开始
- 立足点：前三章内给主角可感知的优势/金手指/上升通道——读者需要相信"这个主角有戏"
- 冲突：第一个冲突必须发生在主角身上、需要主角主动应对，强度要能让读者紧张
- 目标：前三章立起一个读者也想知道答案的疑问/目标（复仇/寻人/求生）

**常见误区**：
- 设定先行——前三章全在铺世界观，主角无行动，读者看说明书
- 主角被动——一切靠他人推动，读者无法"代入"一个没有能动性的主角
- 平淡开局——从"普通的一天"开始，没有反常/危机/悬念，读者 3 秒流失

**严重度判断参考**：
- L1：前两章合格、第三章乏力 → 检查第三章是否丢了钩子/冲突
- L2：前三章未建立契约 → 重排开局，先冲突后设定，金手指前置
- L3：四件套全缺 → 整体重写开局，从"危机+优势+冲突+目标"四点重新设计

**教学素材库**：
- 四件套自查表：前三章逐章核对"代入/立足点/冲突/目标"是否各就各位，缺位章即为重写目标
- 金手指前置练习：把主角最大优势提前到第一章展示一次，观察阅读黏性变化
- 冲突前置练习：把第一个冲突提前到第一章（从"设定章"改为"冲突章"）

