## P039 目标模糊症

**核心本质**：主角目标抽象模糊（想变强/要复仇），无数量/期限/代价，读者找不到可「替他着急」的点。不是行为没动机（那是 P009），而是**动机方向有但目标不可追踪**——读者对"主角现在最想要什么"说不出一句话，就无法替他担心、期待、着急。

**教学要点**：
- 目标四要素（A003 五问法追问）：具体目标 + 明确数量 + 截止时间 + 失败代价，至少补齐缺失项
- 一句话冲突（A007）：逼学员用一句话说清"主角现在要什么、拦路的是谁、做不到会怎样"
- 欲望三层法（T009）：把抽象欲望拆成底层欲望/表层欲望/行动目标三层，让目标可执行
- 阶段目标承接：长线目标 + 每 30-50 章一个清晰短目标，上一目标有反馈再开新目标

**常见误区**：
- 以为"具体化等于写惨"——"妹妹快死了"不是必须选项，"38 万是首付，错过就要回老家"同样具体
- 以为目标是开篇的事——中段阶段目标断档同样是 P039（serial 表现）
- 以为给目标就是一句话——目标必须可追踪、可期待、有截止感，否则仍是空话

**严重度判断参考**：
- L1：目标稍显空泛 → 补目标四要素
- L2：目标模糊代入感下降 → 一句话冲突 + 四要素改写
- L3：全书无主心骨 → 主线目标重构（A003 深挖 + 情节复盘）

**教学素材库**：
- 目标四要素填空：给出抽象目标，填数量/期限/代价三栏
- 一句话冲突练习：把"想变强"改写成"三天后的大比前，他必须拿到最后一枚淬体丹，否则废脉无法修复"
- 阶段目标承接表：列出长线目标与每卷短目标，检查断档
- 欲望三层拆解卡：底层欲望→表层欲望→行动目标逐层写

