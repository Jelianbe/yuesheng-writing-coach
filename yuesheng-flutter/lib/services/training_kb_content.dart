## P035 对话注水症

**核心本质**：对话段落信息增量低——寒暄、客套、重复确认、明知故问，看似推进实则灌水。不是对话本身写得不好（那是 P011 表现力问题），而是**对话不承担叙事功能**：每句对话既不推进剧情、不升级矛盾、不暴露人设，也不抛出线索。

**教学要点**：
- 信息增量检查：每句对话过四问——推进剧情？升级矛盾？暴露人设？抛出线索？四者皆无即候选注水
- 对话瘦身（A008）：砍寒暄客套、重复确认、废话解释；一句能推进的对话胜过十句客套
- 潜台词改写（T013）：把直白交代改成带潜台词的对话，信息密度与人物张力同时提升
- 叙事功能转移：设定交代改由冲突场景自然带出（T008 因果动作链），不用对话硬灌

**常见误区**：
- 以为对话多是"人物互动丰富"——互动要有效，无效互动是灌水
- 以为寒暄能显真实——无潜台词的寒暄只显啰嗦，带情绪的客套才是戏
- 以为删对话会冷场——删掉水话后留下的对话更抓人，节奏不降反升

**严重度判断参考**：
- L1：个别对白注水 → 删客套、改潜台词
- L2：整段对话以寒暄为主 → 对话瘦身 + 信息增量改造
- L3：长对话章节靠水话撑字数 → 整章对话重写，叙事功能重新分配

**教学素材库**：
- 四问检查卡：每句对话过「推进剧情/升级矛盾/暴露人设/抛出线索」四问
- 寒暄压缩练习：把三段寒暄对话压缩成一句带潜台词的对话
- 对话功能标注：给一段对话逐句标注叙事功能，标不出功能的即注水
- 水话改写对比：同场景"注水版 vs 信息版"两组对话，学员对比阅读体验

