## P040 被动主角症

**核心本质**：剧情需要主角去哪主角就去哪——无理由、无顾虑、无权衡，角色被作者硬拖着走。不是目标模糊（那是 P039），不是情节靠巧合（那是 P016），而是**主角的主动性缺失**——角色所有动作必须有动机（内心渴望或外部逼迫），否则读者一眼出戏。

**教学要点**：
- 动作动机审计（A002 回归主角）：给主角的每个动作追一句"他为什么这么做"，答不出即重写
- 主动性三问：这次选择是他自己要的，还是剧情让他做的？他权衡过代价吗？他有没有反制的余地？
- 欲望三层法（T009）：先立动机再写剧情——主角的每个行动都由渴望/逼迫驱动
- 人味三问法（T005）：让主角像正常人一样有顾虑、有犹豫、有舍不得

**常见误区**：
- 以为写惨就有主动性——被虐不等于主动，主角要"要来不及了"而不是"又出事了"
- 以为主动就是无脑冲——主动含权衡与代价评估，权衡本身也是主动
- 以为被动可以靠配角弥补——配角有主意而主角没主意，主角会变成配角

**严重度判断参考**：
- L1：个别段落被动 → 补动作动机
- L2：长期被推着走 → 主动性三问 + 决策重写
- L3：完全木偶化 → 主线复盘（A013 情节复盘）+ 动机重构（A003）

**教学素材库**：
- 动作动机审计表：列出本章主角所有行动，逐个追问"为什么"
- 被动段落改写练习：把"剧情推着他走"改成"他自己选择去"
- 抉择时刻对照：同一场景写两版——被动版 vs 主动权衡版
- 主动性自检清单：主动决策 / 权衡代价 / 反制余地 / 内心渴望四栏打钩

