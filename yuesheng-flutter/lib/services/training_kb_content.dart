## P019 情感失真症

**核心本质**：角色做出了不符合正常人情感逻辑的反应。不是描写方式的问题（那是 P003），不是动机的问题（那是 P009），而是**情感本身不真实**——角色遭遇的事情和ta的反应之间出现了人类不理解的断层。

**教学要点**：
- 真人对照检验：让学员想象"如果一个真人在同样情境下经历了同样的事，第一反应会是什么"——和角色的反应一致吗？
- 情感过渡原则：情绪从 A 切换到 B，至少需要一个过渡步骤（沉默/犹豫/反复/挣扎），不能像开关一样瞬间切换
- 服务于叙事 vs 服务于角色：问学员"这个情感反应是因为'角色真的会有这种感觉'，还是因为'作者需要他看起来有这种感觉'？"

**常见误区**：
- 学员可能为了让剧情推进，让角色"强制"产生某种情感——提醒"角色不配合的时候，剧情就要改"
- 学员可能忽略情感的时间维度——重大事件的情感冲击需要时间消化，不能"刚发生就恢复"
- 学员可能把"压抑情感"写成"没有情感"——压抑是"表面平静但手指在发抖"，不是"看了一眼就走了"

**严重度判断参考**：
- L1：个别情感反应可被接受但略有不真实感 → 不影响共情，顺带提醒
- L2：某处关键情感反应明显不真实，读者无法和角色共情 → 锁定为主线症候
- L3：全文多处情感失真，读者完全无法代入任何角色 → 立即介入训练

**教学素材库**：
- 真人对照练习：给学员一个情境（如"亲妈去世"），让他们写出"一个正常人会有什么反应"，对比角色反应
- 过渡步骤补全：给出一个"瞬间切换"的情感转折，让学员补充中间的过渡步骤

