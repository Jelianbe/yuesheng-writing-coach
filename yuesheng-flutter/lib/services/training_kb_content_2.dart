## P021 跳跃叙事/过度概括症

**核心本质**：故事推进过快，关键情节、情绪转折、重要细节被过度概括。读者还没来得及"看见"和"感受"就跳到了下一个事件。与 P006（节奏停滞）互补——P006 是车轮陷进泥里，P021 是踩油门冲过去、该停的地方没停。

**教学要点**：
- 感受空间检验：这段文本中，有没有读者"需要停下来感受"的时刻——但作者没有给读者这个空间？
- 场景 vs 概述：给每个段落贴上"场景"（实时发生）或"概述"（压缩时间）标签——场景比例是否过低？
- 情绪落地：情绪转折是否有"落地"？角色从愤怒到平静，中间有没有至少一个过渡？
- 关键事件检验：重大事件（死亡/背叛/重大决定）是否被概述呈现？读者本该"在场"见证的时刻不能省略

**常见误区**：
- 学员可能认为"快节奏=好看"——快节奏不等于跳跃，跳跃是该写的没写
- 学员可能用概述替代场景——"他很伤心。三个月后他离开了。"读者失去了"在场"的体验
- 学员可能忽略"时间标记"——概述后需要有明确的场景落地，否则读者会迷失

**严重度判断参考**：
- L1：个别过渡段落略快 → 加一两段场景描写
- L2：关键事件被概括呈现 → 锁定为主线症候
- L3：全文以概述推进 → 立即介入，将概述转化为场景

**教学素材库**：
- 场景贴标：给段落贴"场景（实时发生）/概述（压缩时间）"标签——概述占比过高的段落，挑关键事件展开成场景
- 情绪落地：找一处被概括的情绪转折，补一个"落地"的过渡（角色此刻看见什么/做了什么/听见什么）

