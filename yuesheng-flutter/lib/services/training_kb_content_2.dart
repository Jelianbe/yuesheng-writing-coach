## P022 重复用词/基础语病

**核心本质**：词汇或标点层面的基础瑕疵——同一字/词紧邻重复、连续重复标点、多句同一起头、高频连接词反复出现。语言显得粗糙，读者注意力被细碎瑕疵分散。与 P007（句式节奏单一）互补——P007 是"句式骨架"雷同，P022 是"用词/标点"层面的基础问题。

**教学要点**：
- 自查锚点：读一遍自己的文字，找出"读起来卡壳"的位置——卡壳往往就是重复/瑕疵所在
- 高频词检验：同一段里是否有字/词出现两次以上、且删掉不影响语义？
- 起头多样性：连续 3 句是否以同一词/字开头，造成机械感？
- 标点卫生：有没有连续的重复标点（"。。""，，"）？

**常见误区**：
- 把刻意排比/顶真当语病——有意为之的修辞是节奏手段，不是问题
- 把口语口头禅当语病——人物口头禅是塑造手段
- 只盯着"删掉重复"——更要看"这里为什么重复"（词汇不足/写得急/未打磨），从源头改善

**严重度判断参考**：
- L1：单处重复/个别标点瑕疵 → 指出位置，让学员自己改
- L2：多处重复打断阅读节奏 → 通读润色，一次聚焦一类重复
- L3：全文通病（高频词/起头全篇雷同）→ 系统性修改，从最高频的重复入手

