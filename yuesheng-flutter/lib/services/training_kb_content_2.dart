## P016 情节巧合过多症

**核心本质**：情节的推动大量依赖巧合而非角色的主动选择。删掉巧合后，情节链断裂——不是角色在推动故事，是作者在操控。

**教学要点**：
- 因果检验：删掉这个偶然事件，角色有没有其他方式达到同样的结果？如果没有，说明过度依赖巧合
- 作者操控检验：这个事件之所以发生，是因为"角色做了某个决定导致了它"还是因为"作者需要它发生"？
- 选择检验：如果角色做一个不同的选择，这件事还会发生吗？如果无论如何都会发生，说明和角色选择无关
- 主动驱动：让学员为每个关键转折标注"是角色主动选择导致"还是"外部巧合导致"——后者比例不应过高

**常见误区**：
- 学员可能用"刚好/恰好"推动情节——"刚好遇到商人""刚好有解药"不是叙事，是偷懒
- 学员可能认为"巧合增加戏剧性"——真正的戏剧性来自角色的两难选择，不是运气
- 学员可能忽略"巧合的累积效应"——单个巧合可以接受，连续巧合让读者失去代入感

**严重度判断参考**：
- L1：个别事件巧合但整体有因果逻辑 → 微调
- L2：多个关键转折依赖外部事件 → 锁定为主线症候
- L3：全文情节由不相关的巧合串联 → 立即介入，重构情节驱动

**教学素材库**：
- 因果标注：给每个关键转折标注"角色主动选择导致"或"外部巧合导致"——后者比例过高，逐个改写成主动选择
- 巧合改写：挑一个"刚好"事件（刚好遇到/刚好有解药），改写成"角色主动制造或促成"

