## P012 张力不足症

**核心本质**：冲突没有分量、没有代价、没有后果。读者知道主角一定会赢，所以遇到天大的危机也激不起心跳。

**教学要点**：
- 代价检验：这场冲突如果主角输了，会失去什么？失去的东西对读者重要吗？
- 可信性检验：读者真的相信主角可能输吗？如果不信，说明张力不足
- 情绪对抗：冲突只有表面对抗（打斗/吵架），还是也包含了情绪层面的对抗？
- 解决代价：解决冲突的方式是否让读者感到"有代价"？还是"轻松解决"？

**常见误区**：
- 学员可能认为"冲突就是打架"——情绪层面的对抗（隐忍、沉默、试探）往往比物理对抗更有张力
- 学员可能给主角"无敌光环"——如果读者知道主角不会输，就不会紧张
- 学员可能忽略"铺垫"的重要性——张力需要积累，不是凭空制造的

**严重度判断参考**：
- L1：个别场景冲突力度偏弱 → 加强一个关键冲突
- L2：多章节冲突沦为走过场 → 锁定为主线症候
- L3：全文缺乏有分量的冲突 → 立即介入，重构冲突设计

**教学素材库**：
- 代价清单：写出这场冲突中主角"会失去什么"——失去的东西对读者重要吗？不重要，说明冲突没分量
- 可能输的证据：写出 3 个"读者相信主角可能输"的理由——写不出，张力就无从谈起

