## P014 结尾乏力症

**核心本质**：故事收束没有给读者满足感。结尾要么太仓促（没有余韵），要么靠机械降神（外部力量突然解决所有问题），要么埋了大量伏笔却不回收。

**教学要点**：
- 完成感检验：读完最后一段，读者是否产生了"完成了"的感觉？还是觉得"是不是少了一段"？
- 解决方式：主角的困境是以"主角自己的选择/行动"解决的，还是以"外部力量突然介入"解决的？
- 伏笔回收：前文埋下的伏笔线在结尾处是否都有交代？哪怕只是"留白"式的交代？
- 余韵空间：结尾是否给读者留下了"回味"的空间？还是像急刹车一样戛然而止？

**常见误区**：
- 学员可能"解释式结尾"——角色停下来给读者解释"其实前面那些事是这样的"，这很枯燥
- 学员可能让"好人帮主角"解决所有问题——主角自己的成长在哪里？
- 学员可能忽略"情绪释放"——高潮中的情绪需要在结尾有释放的空间

**严重度判断参考**：
- L1：结尾稍显仓促但核心冲突已解决 → 补一段余韵收束
- L2：关键伏笔未回收 → 锁定为主线症候
- L3：烂尾——机械降神、伏笔全烂 → 立即介入，重写结尾

**教学素材库**：
- 完成感检验：读最后一段，写下一个词描述"读者此刻的心情"——是"完成了"还是"少了什么"？
- 伏笔清单：列出所有伏笔与回收状态——未回收的补收尾，机械降神的改为"主角自己的选择解决"

