## P020 过渡生硬症

**核心本质**：场景之间的衔接缺乏流畅感。读者从场景 A 切换到场景 B 时产生断裂感——没有空间/时间的锚点。

**教学要点**：
- 滑入检验：从上一段到下一段，读者能否自然地"滑入"新场景？还是需要停下来重建空间感？
- 连接线检验：上一个场景的最后一个画面/情绪/声音，和下一个场景的第一个画面/情绪/声音之间——有没有一根"线"？
- 过渡词检验：如果删掉"与此同时""镜头一转"这样的词，两个场景之间还有什么在连接它们？
- 感官桥梁：用声音/气味/情绪等感官元素作为场景之间的桥梁，比时间/地点说明更自然

**常见误区**：
- 学员可能用"机械过渡词"频繁切换——"镜头一转""与此同时"让读者反复被推出叙事
- 学员可能忽略"情绪连续性"——场景切换时情绪应该有过渡，不是瞬间切换
- 学员可能认为"章节分隔就是过渡"——章节分隔提供的是"许可"，不是"桥梁"

**严重度判断参考**：
- L1：个别切换生硬但不影响整体 → 微调
- L2：多场景频繁使用机械过渡 → 锁定为主线症候
- L3：全文场景切换全靠过渡词维持 → 立即介入，重构场景衔接

**教学素材库**：
- 桥梁检验：删掉"与此同时/镜头一转"等过渡词，两个场景之间还有没有"线"在连接？没有 → 缺桥梁
- 感官桥梁：用一个感官元素（某个声音/气味/情绪残留）连接两个场景，比时间地点说明更自然

