### P015 人设崩塌症

> **position_sensitivity**: global

**核心问题**：角色在连载过程中行为模式发生了未经铺垫的变化，读者从"这个角色会这么做"变成了"这个角色怎么会这么做？"。与P007（一开始就没建立动机）不同，P015指角色在连载中途"写崩了"。

**触发信号**：前期建立的角色性格在中后期被打破；冷静型角色突然暴怒；善良型角色做出残忍决定——且这些转折缺乏足够的触发铺垫
> **区分 P007**：P015 以"读者预期断裂"为判断依据——前期铺垫了明确行为方向（可提取 3 个关键选择锚定其价值观/底线），后期未经预警转向且渐变不足；若角色从头到尾就没有建立过一致行为模式（无"前期的 A 方向"可依附），归入 P007 而非 P015。

**判断原则**（基于上下文，非硬性标准）：
- 这个角色在本章的行为——如果让只读过前十章的读者来判断，他们会觉得"合理"吗？
- 角色行为的改变是因为"情节需要他这样做"还是因为"这个角色在某种特定压力下会这样做"？——前者是崩塌，后者是成长
- 角色改变有没有过渡？是从A突然跳到Z，还是经过了B→C→D……Y的渐变？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别场景中角色行为略有不一致但可被读者接受，加一个过渡就可以
- L2：角色的某些关键行为的动机和前期建立的形象严重矛盾，读者会注意到并困惑
- L3：角色已经完全不像同一个人——前后判若两人，读者失去对角色的信任

**例外情况**（以下场景通常不是人设崩塌）：
- 角色成长弧——角色的改变是铺垫好的、渐进式的、有迹可循的
- 重大创伤后的性格改变——足够的创伤事件可以做为人设改变的触发
- 伪装/人设套娃——角色前期展现的性格本身就是假象，揭示真相是设计好的叙事策略
- 极端情境下的"例外反应"——一个善良的人在保护孩子时可以做出残忍的事

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（典型）**：
> 原文：前50章建立的主角形象：冷静、机智、从不主动伤人。
> 第51章："他疯了似地冲进人群，一拳打在路人甲脸上。"（没有任何前文铺垫——路人甲只是一个挡了他路的人）
> 判定：P015 L2
> 理由：角色行为大幅偏离了50章建立起来的行为模式，且没有任何触发铺垫。

**❌ 未命中（创伤转折）**：
> 原文：善良的主角目睹全家被杀后变得冷酷无情。前文详细写了目睹过程——他连续七天没说话，第八天开始变了。
> 判定：不触发
> 理由：足够的创伤事件+过渡描写——这是角色弧线而非崩塌。

**推荐教学动作**：首选 A015 人设审查，备选 A010 角色盲写

