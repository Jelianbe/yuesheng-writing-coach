### P017 伏笔失效症

> **position_sensitivity**: global

**核心问题**：伏笔的埋设、铺陈和回收三个环节中至少一个出了问题。可能表现为：伏笔埋得太明显（伏笔裸露）、埋了但忘了回收（伏笔烂尾）、回收方式生硬（用大段说明式回收而非让读者"发现"）。

**触发信号**：看到"伏笔"就知道是伏笔；重要前文细节在结尾消失；回收伏笔时角色停下来解释"其实前面那个事是这样的"

**判断原则**（基于上下文，非硬性标准）：
- 读者第一次读到这个细节时，它是否自然融入了当时的场景——还是突兀到让读者停下来想"这是一个伏笔"？
- 这个伏笔后来有没有在文本中出现第二次、第三次，让读者在揭晓前产生"这东西有戏"的感觉？
- 揭晓的方式是"读者和角色一起发现真相"还是"角色停下来给读者解释真相"？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别伏笔回收不够精彩但至少回收了，读者不至于不满
- L2：关键伏笔未回收或回收方式生硬，读者读到结局时会产生"那个呢？"的疑问
- L3：大量伏笔烂尾，或所有伏笔的回收方式都是"解释式"，阅读体验如作者在补作业

**例外情况**（以下场景通常不是伏笔失效）：
- 故意不回收的伏笔——开放式悬疑中留下的"永远的谜"
- 系列作品——伏笔预定在后几部回收
- "伏笔"本身就是红鲱鱼——故意制造误导，不是所有暗示都需要"回收"

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（伏笔裸露）**：
> 原文：日常场景中突然插入——"他看了一眼窗台上的花盆。那是一盆兰花。他没有多想。"（旁白突然给这个花盆一个特写——读者立刻知道"这是伏笔"但不知道为什么要知道）
> 判定：P017 L2
> 理由：旁白给了不该给的注意力——一个普通物品被赋予了超过场景所需的关注，读者被"剧透"了"这里有线索"。

**❌ 未命中（自然回收）**：
> 原文：前文埋了"他右手腕有个疤"。后文一个场景：他伸手接住落下的杯子，袖子滑上去——露出手腕上的疤。对面的老医生看了一眼就变了脸色。"那个疤——你在哪里弄的？"
> 判定：不触发
> 理由：伏笔通过场景中的动作自然露出，回收通过角色的即时反应——读者和角色同时"发现"。

**推荐教学动作**：首选 A012 伏笔追踪，备选 A003 五问法

