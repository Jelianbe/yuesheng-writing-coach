### P018 重复用词/基础语病

> **position_sensitivity**: local

**核心问题**：词汇或标点重复、基础文法瑕疵——同一字/词紧邻重复、连续标点、多句同一起头、高频连接词反复出现，读者注意力被细碎瑕疵分散，语言显得粗糙。与 P005（句式结构重复）互补——P005 是"句式骨架"雷同，P018 是"用词/标点"层面的基础问题。

**触发信号**：同一字紧邻重复（"的了了""他他"）；连续重复标点（"。。""，，"）；连续多句以同一词起头；短篇幅内同一连接词/副词反复出现（"然后""但是""忽然"）

**判断原则**（基于上下文，非硬性标准）：
- 有没有紧邻的重复字/词，属于打字错误或措辞未打磨？
- 有没有连续的重复标点？
- 连续句子是否以同一词/字起头，造成机械感？
- 高频词是"口语习惯"还是"刻意节奏"？——刻意排比不算问题

**边界纪律**：
- 禁止把逗号/句号/破折号的密度直接读作"节奏快/慢/紧张/舒缓"——标点/句读密度≠节奏好坏。
- 禁止把任何标点一对一映射为固定停顿或情绪（标点-停顿无中文网文读者实验证据；逗号分类证据仅来自新闻语料）。
- 触发：学员问"这里是不是该多断句/少断句才对节奏"时——节奏判断须回到句法/语义/话题层面。

**严重度判断**（结合三维标定表综合评估）：
- L1：单处重复/个别标点瑕疵，不影响理解，改几个字即可
- L2：多处重复，打断阅读节奏，需通读润色
- L3：全文通病（高频词/起头全篇雷同），需系统性修改

**例外情况**（以下场景通常不是基础语病）：

**外部佐证（中文写作规范三来源）**：用词层基础问题获独立规范印证——A-15（冷僻词）、B-8（生造词/文言词）指向「非常规词挤占阅读注意力、语言显得粗糙」，与 P018 同轴；但 P018 判据不含「生造/文言」，仅部分覆盖（详见报告 ④ 4.1、④ 4.2）。

