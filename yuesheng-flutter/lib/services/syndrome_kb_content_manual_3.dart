### P019 情感失真症

> **position_sensitivity**: global

**核心问题**：角色做出了不符合正常人情感逻辑的反应。不是描写方式的问题（那是P003情绪标签化），不是角色动机的问题（那是P009角色空心化），而是**情感本身不真实**——角色遭遇的事情和ta的反应之间出现了人类不理解的断层。

**触发信号**：重大事件后角色反应不对等；情感转折没有过渡；角色的情感像开关一样可以瞬间切换

**判断原则**（基于上下文，非硬性标准）：
- 如果一个真人在同样的情境下经历了同样的事——ta的第一反应会是什么？这个反应和当前角色的反应一致吗？
- 角色从一种情绪切换到另一种情绪，有没有经过至少一个"过渡步骤"（哪怕是一句话：沉默/犹豫/反复/挣扎）？
- 这个情感反应是否服务于叙事的需要而非角色的需要？——如果某个场景里角色"不应该"有某个情感，但作者需要他"看起来""感到"那个情感。

**严重度判断**（结合三维标定表综合评估）：
- L1：个别情感反应可被读者接受但略有不真实感，不影响共情
- L2：某处关键情感反应明显不真实，读者无法和角色共情——会影响后续情节的认同感
- L3：全文多处情感失真，读者完全无法代入任何角色

**例外情况**（以下场景通常不是情感失真）：
- 角色的设定就是"情感异于常人"——如反社会人格、AI觉醒、异族（需要提前建立）
- 喜剧/荒诞风格——夸张的情感反应是风格的一部分
- 角色在刻意压抑情感——"表面平静但手指在发抖"是合理的矛盾反应
- 角色情感延迟——有些人需要时间才能反应过来自己的感受

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（典型）**：
> 原文：亲妈死了。主角的反应："他看了一眼，走了。"
> 判定：P019 L2
> 理由：巨大的情感事件没有产生对应量级的情感反应——除非角色是反社会人格（需要提前建立），否则不真实。

**❌ 未命中（压抑情感）**：
> 原文："他站在母亲床前，面无表情。'走吧。'他转身。手在口袋里握成了拳头，指甲陷进了掌心。"
> 判定：不触发
> 理由：表面平静但身体出卖了真实感受——"压抑"本身就是一种真实的情感反应。

**推荐教学动作**：首选 A014 情感校准，备选 A004 现实锚点

