### P016 情节巧合过多症

> **position_sensitivity**: global

**核心问题**：情节的推动大量依赖巧合而非角色的主动选择，故事被"外部事件"推着走而非由"角色的决定"驱动。删掉巧合后，情节链断裂——说明不是角色在推动故事，是作者在操控。

**触发信号**：角色走到哪都能碰到关键NPC；多条线索恰好同时汇聚；敌人总在主角刚好够级的时候出现

**判断原则**（基于上下文，非硬性标准）：
- 删掉这个偶然事件——角色有没有其他方式达到同样的结果？如果没有，说明情节过度依赖巧合
- 这个事件之所以发生，是因为"角色做了某个决定导致了它"还是因为"作者需要它发生"？
- 如果角色做一个不同的选择，这件事还会发生吗？——如果无论如何都会发生，说明这件事和角色选择无关

**严重度判断**（结合三维标定表综合评估）：
- L1：个别事件巧合但整体情节链有因果逻辑，不影响连续性
- L2：多个关键转折依赖外部事件而非角色决定，读者开始感觉"这也太巧了吧"
- L3：全文情节由一系列不相关的巧合串联，角色只是"恰好路过"所有关键场景

**例外情况**（以下场景通常不是巧合过多）：
- 开篇的"幸运事件"——这是一个故事开始的方式，很多经典作品的第一推动力就是偶然
- 悬疑作品中所有线索确实指向同一处——前提是每个线索的角色获得方式不同且合理
- 系统/穿越设定中的"提前布局"——如果角色做了准备，主动造成多个条件同时满足，不是巧合

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（典型）**：
> 原文："他刚逃出城，就遇到一个商人愿意载他。商人的车上刚好有他需要的药。药铺的老板恰好认识他要找的人。找到那个人时，那个人刚好准备离开——晚一步就见不到了。"
> 判定：P016 L2
> 理由：全文情节由连续4个"刚好/恰好"串联——删掉任何一个巧合，情节链断裂。角色没有任何主动选择推动故事。

**❌ 未命中（角色主动）**：
> 原文："他知道商人每周二会经过这条路。他在路边等了三天。第四天，商人的车出现了。"
> 判定：不触发
> 理由：看似"巧遇"实为角色主动等待——是角色的选择导致了相遇。

**推荐教学动作**：首选 A013 情节复盘，备选 A003 五问法

