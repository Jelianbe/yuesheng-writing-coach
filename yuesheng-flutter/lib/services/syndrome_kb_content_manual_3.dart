### P020 过渡生硬症

> **position_sensitivity**: global

**核心问题**：场景之间的衔接缺乏流畅感，读者从场景A切换到场景B时产生断裂感——像电影剪辑中的"跳切"，但小说中的跳切如果没有设计好，读者会失去空间/时间的锚点。

**触发信号**："镜头一转""与此同时""画面切换到"等机械过渡词频繁出现；两个场景之间没有任何感官/情绪/因果的连接；读者在切换到新场景时需要"重新适应"

**判断原则**（基于上下文，非硬性标准）：
- 从上一段到下一段，读者能否自然地"滑入"新场景？还是需要停下来重建空间感？
- 如果删掉"与此同时""镜头一转"这样的过渡词，两个场景之间还有什么在连接它们？
- 上一个场景的最后一个画面/情绪/声音，和下一个场景的第一个画面/情绪/声音之间——有没有一根"线"？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别切换生硬但不影响整体阅读流畅度
- L2：多场景频繁使用机械过渡，读者每次切换都感到被"踢出"叙事
- L3：全文场景切换全靠过渡词维持，无任何有机连接

**例外情况**（以下场景通常不是过渡生硬）：
- 有意制造的跳跃感——快速切镜是节奏控制的一部分
- 章节分隔——新的一章自然提供了一个"硬切"的许可，读者预期就是从头开始
- 蒙太奇——用碎片画面拼接传递信息，跳跃本身就是表达方式
- 时间跳跃标记——"三年后""第二天早上"等明确的时间标记本身就是一个过渡

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（典型）**：
> 原文："他们在废墟中找到了那封信。镜头一转。城市的另一端，一个黑衣人正在敲一扇门。与此同时，在遥远的北方，一场暴风雪正在酝酿。"
> 判定：P020 L2
> 理由：连续三个"镜头一转/与此同时"切换——读者被反复推出叙事，没有空间锚点。

**❌ 未命中（章节分隔）**：
> 原文：第一章结尾："他关上门。" 第二章开头："三个月后，他站在另一座城市的火车站前。"
> 判定：不触发
> 理由：章节分隔本身就是一个"硬切换许可"——读者在新章开头会自然重建空间。

**推荐教学动作**：首选 A009 节奏变速，备选 A006 感官全开

