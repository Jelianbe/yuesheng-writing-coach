### P021 跳跃叙事/过度概括症

> **position_sensitivity**: global

**核心问题**：故事推进过快，关键情节、情绪转折、重要细节被过度概括——读者还没来得及"看见"和"感受"就跳到了下一个事件。与 P006（节奏停滞，太慢）形成互补——P006 是车轮陷进泥里转不动，P021 是踩油门冲过去、该停的地方没停。

**触发信号**：重要事件用一两句话带过；情绪爆发缺乏段落空间；时间跳跃过于频繁；读者感到被"拽着跑"而非"自然跟随"

**判断原则**（基于上下文，非硬性标准）：
- 这段文本中，有没有读者"需要停下来感受"的时刻——但作者没有给读者这个空间？
- 事件与事件之间是否有过渡？——从 A 事件到 B 事件，是"场景→场景"还是"概述→概述"？
- 如果给这篇文本的每个段落贴上"场景"（实时发生）或"概述"（压缩时间）标签——场景的比例是否过低？一个好的叙事通常至少有 60% 是场景
- 情绪转折是否有"落地"？——角色从愤怒到平静，中间有没有至少一个过渡（沉默/犹豫/反复/挣扎）？
- **互斥校验**：先排除 P006 场景（描写堆砌但无事件推进）——若跳跃段落本身同时包含大段无推进的静态描写，先剔除该部分；剔除后剩余的关键情节点仍被概括带过，才归入 P021

**严重度判断**（结合三维标定表综合评估）：
- L1：个别过渡段落略快，但不影响关键情节的展开，加一两段场景描写即可
- L2：关键事件（死亡/背叛/重大决定等）被概括呈现，读者错过了本该"在现场"的时刻
- L3：全文以概述推进——读者从未真正"经历"任何场景，阅读体验如故事大纲而非小说

**例外情况**（以下场景通常不是跳跃叙事）：
- 蒙太奇/时间压缩——刻意的快速推进是叙事策略（如"之后三年，他再没提过这件事"）
- 快节奏动作序列——打斗/追逐中快速的场景切换是节奏控制
- 转场过渡——非关键的时间段可以概括（如"一路无话，三日后抵达"）
- 故事框架——"这是一个关于……的故事"式开头本身是概述风格

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（关键事件被概括）**：
> 原文："他妈妈死了。他很伤心。三个月后他离开了那个城市。"
> 判定：P021 L2
> 理由：重大事件（妈妈去世）和情绪反应完全被概述——读者本应"在场"见证这个转折，却只读到了新闻标题式的概括。

**❌ 未命中（蒙太奇）**：
> 原文："之后三年，他再没提过这件事。他去过很多地方，见过很多人，把那个名字放在心底最深的角落里。直到那天在火车站——"
> 判定：不触发
> 理由：刻意的快速推进为下一个场景蓄力——概述后有场景落地。

**推荐教学动作**：首选 A009 节奏变速，备选 A005 动作链

