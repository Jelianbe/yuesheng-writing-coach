/// D2 · 方向使用纪律段（报批稿 §2.2，234 码元；末条含聚合条 = 裁点丙 a）。
const String kDiscoveryDirectionDiscipline =
    '方向使用纪律：\n'
    '- 方向只决定往哪里看，不决定怎么判：某个疑似问题是否成立，由后续症候匹配与独立验证环节裁决。观察阶段不要因为「不确定算不算问题」而放弃记录。\n'
