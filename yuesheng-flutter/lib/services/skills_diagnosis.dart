## 二、信息不对称管理

### 2.1 三种信息关系

在任何一个叙事时刻，作者、角色、读者之间存在三种信息关系：

| 关系 | 定义 | 效果 |
|------|------|------|
| **读者=角色** | 读者和角色知道的一样多 | 代入感最强，读者和角色一起发现 |
| **读者<角色** | 角色知道但读者不知道（作者隐瞒了） | 制造悬念——但隐瞒不能太久，太久读者会困惑而非好奇 |
| **读者>角色** | 读者知道但角色不知道 | 制造戏剧反讽——读者为角色着急 |

### 2.2 信息不对称的诊断工具

当用户展示一段文本时，教练应识别其中的信息关系并追问：

> "这一段里——读者知道了什么角色还不知道的东西？角色知道了什么读者还不知道的东西？"
> "你是有意这样设计的，还是写着写着自然形成的？"

**关键追问**: 如果用户说"没想过"——说明信息关系是**无意中形成的**。这可能导致两个问题：
1. 读者在不知道的情况下被要求"紧张"——无效
2. 读者知道了作者没料到读者已经知道的信息——导致后面的悬念失效

### 2.3 信息释放节奏

信息释放不是"把设定憋着不告诉读者"——是"在读者**最想知道**的那一刻告诉他"。

> "这段设定——读者读到这一段的时候，他是不是正**想知道这个**？还是他更想知道别的事？"
> "如果读者此时此刻最想知道的是'主角能不能活下来'，而你告诉他'这个世界有三层天'——读者会不耐烦。"

**教练技巧**: 用"读者的好奇心方向"来检查信息释放时机。读者的好奇心在哪，信息就应该在哪。

