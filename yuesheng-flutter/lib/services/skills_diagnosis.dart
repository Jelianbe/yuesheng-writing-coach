## 一、五维风格坐标

### 维度 1：感官偏好

学员在无意识状态下最常激活的感官通道：

| 类型 | 标志 | 优势 | 盲区风险 |
|------|------|------|---------|
| **视觉型** | 文本中颜色/光影/形状/空间关系占主导 | 场景感强，画面清晰 | 可能忽略声音/气味/触感 |
| **听觉型** | 大量对话/声音描写/节奏感强 | 对话自然，叙事有韵律 | 可能缺少视觉锚点 |
| **体感型** | 温度/重量/触觉/身体感受优先 | 代入感极强，读者能"感觉"到 | 可能过度依赖身体感受 |
| **均衡型** | 多种感官自然轮换，无明显偏好 | 全方位沉浸 | 无突出优势 |

**识别方法**：取学员最近 3 段场景描写，统计各感官描写的比例。如果某种感官 >50%，即为其偏好。

### 维度 2：节奏偏好

学员的句子和段落自然节奏：

| 类型 | 标志 | 优势 | 盲区风险 |
|------|------|------|---------|
| **长句型** | 平均句长 >25 字，多从句嵌套 | 氛围营造好，思考深度够 | 可能节奏拖沓 |
| **短句型** | 平均句长 <15 字，多用句号分隔 | 节奏爽利，冲击力强 | 可能缺乏韵律变化 |
| **错落型** | 长句短句有意交替 | 节奏丰富 | — |
| **重复型** | 排比/对仗/重复结构频繁出现 | 有仪式感/韵律感 | 可能显得单调 |

**识别方法**：取一段 500 字的叙述段落，数句子数和总字数，计算平均句长。同时观察长短句的交替模式。

### 维度 3：叙事距离

学员在叙述时与角色/事件的自然距离：

| 类型 | 标志 | 优势 | 盲区风险 |
|------|------|------|---------|
| **贴身型** | 大量内心独白/自由间接引语，读者仿佛在角色脑子里 | 共情极强 | 可能缺少外部世界 |
| **观察型** | 保持一定距离，像摄影机客观记录 | 信息清晰，不煽情 | 可能缺乏情感温度 |
| **评述型** | 叙述者有自己的声音，会评价/感叹/插话 | 有个性，风格鲜明 | 可能打断沉浸感 |
| **游移型** | 距离灵活切换，根据场景需要 | 适应性强 | 可能导致视角漂移 |

**识别方法**：找一段角色经历重要事件时的叙事——叙述者离角色有多近？读者能"听到"角色的内心声音吗？叙述者有没有自己的"评论"？

### 维度 4：语气质地

学员文字的语言质感：

| 类型 | 标志 | 优势 | 盲区风险 |
|------|------|------|---------|
| **诗意型** | 修辞丰富，意象密集，语言本身即是美学 | 文字美感强 | 可能信息密度不足 |
| **冷峻型** | 简洁、克制、不修饰，"让事实自己说话" | 信息效率高，有力量 | 可能缺乏温度 |
| **口语型** | 大量口语化表达，贴近日常生活语言 | 亲切、生动、有烟火气 | 可能在正式场景中出戏 |
| **文雅型** | 语言规范、用词考究、有一定"书卷气" | 庄重、有质感 | 可能不够接地气 |

**识别方法**：找一段纯粹的叙述段落（非对话）——遮住作者名字读一遍，你会用什么形容词描述这段文字给人的"感觉"？

### 维度 5：结构本能

学员组织故事的自然方式：

| 类型 | 标志 | 优势 | 盲区风险 |
|------|------|------|---------|
| **线性型** | 按时间顺序，从头到尾 | 清晰、不易混乱 | 可能缺乏悬念 |
| **碎片型** | 跳跃、碎片化、多时间线 | 有张力、便于埋悬念 | 可能让读者困惑 |
| **回环型** | 喜欢首尾呼应、反复回到某个核心意象 | 结构精巧、有仪式感 | 可能过于刻意 |
| **发散型** | 从一个点发散出去，联想丰富 | 自由、有创造力 | 可能缺乏控制 |

**识别方法**：看学员作品的整体结构——如果是短篇，看开头和结尾的关系。如果是长篇，看时间线的处理方式。

