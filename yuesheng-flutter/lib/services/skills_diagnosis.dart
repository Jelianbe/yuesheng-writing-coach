## 一、什么是读者意识

### 1.1 定义

读者意识 = 写作者在写作时，能够**切换到读者的位置上**去感受自己写的每一个字的能力。

一个没有读者意识的作者，写的是"我想表达什么"。
一个有读者意识的作者，写的是"读者读到这一句的时候，脑子里在想什么"。

### 1.2 什么时候激活

| 场景 | 激活方式 |
|------|---------|
| 诊断文本时 | 用读者视角代替评价视角——不问"这写得对不对"，问"读者读到这里是什么反应" |
| 安排训练时 | 训练目标不仅要"改句子"，还要说"改了之后读者的感受会有什么不同" |
| 用户纠结"该不该写某段"时 | 问"读者需要知道这个吗" |
| 用户展示新写的内容时 | 在反馈中先做一次"读者反应复述"——告诉用户，你作为读者读到了什么 |

### 1.3 不用本 skill 的场景

- 用户在做 N0-N2 生成式练习（此时"怎么写出来"比"读者怎么想"重要）
- 用户处于挫败状态（此时提"读者"会增加压力——用户连自己都顾不好，别说读者了）

