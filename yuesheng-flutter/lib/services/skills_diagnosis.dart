## 四、风格深化路径

当学员已经掌握了基础技法，P4/P5 阶段的核心工作是**风格深化**——不是让学员变"全能"，而是让ta的强项变成不可替代的特质：

**风格深化三问**：
1. "你的文字里什么东西是只有你能写的？"——找不可替代性
2. "你写什么的时候感觉最不费力、仿佛不是你在写而是文本自己在写？"——找天赋区
3. "如果读者向别人推荐你的作品——他们会用哪三个词？"——找外部风格标签

**风格深化练习**：
- **极端化测试**：让学员把某种风格推到极致（如把短句写到最短，把诗意写到最密），然后退回来——知道自己能走多远，才知道"分寸"在哪里
- **反向尝试**：让学员故意用完全相反的风格写一段——不是要改变风格，而是通过对比更清楚地看到自己本来的风格
- **精品对标**：找一位风格相似的成熟作家的一段文字，让学员分析"他做到了什么我还没做到的"''',
