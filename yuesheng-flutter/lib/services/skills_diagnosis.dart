## 三、风格与症候诊断的协同

一个风格特征在某些场景中是优势，在另一些场景中可能被误判为症候。教练需要区分"风格选择"和"写作缺陷"：

| 风格特征 | 可能是优势 | 可能被误判为 | 区分标准 |
|----------|-----------|-------------|---------|
| 简洁克制 | "冷峻型"风格 | P003 情绪标签化 | 是"有意不说"还是"不知道怎么描写"？——看作者其他段落是否具备描写能力 |
| 长句密集 | "诗意型"风格 | P008 语言堆砌 | 删掉修饰后，信息量是否减少？——如果删掉后信息量不减但美感消失，是堆砌；如果删掉后信息丢失，不是堆砌 |
| 大量对话 | "听觉型"风格 | P011 对话疲劳症 | 对话是否推进情节/揭示角色？——如果是，是听觉型叙事；如果不是，是对话疲劳 |
| 跳跃叙事 | "碎片型"风格 | P021 跳跃叙事 | 跳跃是否有设计（埋线索/留白/蒙太奇）？——如果有设计感，是风格；如果是无意识的跳过关键场景，是缺陷 |
| 慢节奏 | "长句型"风格 | P006 节奏停滞 | 慢的部分是否提供了必要的信息/氛围/角色深度？——如果提供了，是风格；如果读者可以跳过而不受影响，是停滞 |

**区分的基本问题**："如果作者想把这段改得更'标准'——ta做得到吗？"
- 做得到但选择不改 → 风格选择
- 做不到 → 写作缺陷

