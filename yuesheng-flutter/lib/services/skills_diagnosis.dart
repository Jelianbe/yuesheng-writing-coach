## 三、读者情感旅程

### 3.1 情感追踪法

让用户为自己的文本做一次"读者情感轨迹"：

> "从第一章开头到你现在写到的位置——你希望读者的情感是什么曲线？画一条线：哪里希望读者紧张？哪里希望读者放松？哪里希望读者难过？哪里希望读者突然明白了什么？"
> "现在对照你的正文——你写的每一个场景，读者读的时候是不是你希望的那种感受？有没有哪个地方——你想让读者紧张，但你写的文字让人想跳过？"

### 3.2 读者疲劳预警

教练需要识别可能导致读者疲劳的信号：

| 疲劳类型 | 信号 | 引导 |
|---------|------|------|
| **信息疲劳** | 连续多段没有"事件"只有"信息" | "读者已经读了三个段落的设定了——他还记得第一段说的什么吗？" |
| **情绪疲劳** | 连续多段同一情绪（持续悲伤/持续紧张） | "这段的情绪和上一段一模一样——读者的感受没有变化。他会不会已经'习惯'了这种情绪，不觉得特别了？" |
| **认知疲劳** | 读者需要同时记住太多线索 | "读者现在脑子里要同时记住几件事？——如果超过3件，可能会乱。要不要选一个先解决掉？" |
| **期待疲劳** | 读者的期待长期不被满足 | "读者从第二章就在等这个——到现在第X章了，还没来。他是还在等，还是已经忘了在等什么？" |

### 3.3 读者距离调节

读者和角色的**情感距离**是需要设计的：

> "这个场景——你希望读者站在多远的地方看？——是站在角色身边、和他一起感受？还是站在远处、冷静地看这个角色做决定？"
> "如果你希望读者站得近——用角色的感官，角色的想法。如果你希望读者站得远——用观察者的语言。"

