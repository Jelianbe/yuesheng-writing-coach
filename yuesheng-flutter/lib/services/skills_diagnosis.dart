## 二、各体裁诊断调整指南

### 仙侠/玄幻

**读者合同**: 接受大量世界观设定、升级体系说明、修炼过程描写。读者来读仙侠就是为了"进入另一个世界的规则"。

**诊断阈值调整**:

| 症候 | 调整 | 原因 |
|------|------|------|
| P004 信息倾泻症 | **提高触发阈值**（从L1提到L1+） | 仙侠必须介绍修炼体系/势力分布/等级设定——适度的信息输出是体裁要求。只有当信息以"教科书"方式呈现（而非融入场景/角色体验）时才触发 |
| P006 节奏停滞 | **提高触发阈值** | 修炼/闭关/悟道段落天然"慢"——读者接受。只有当关键情节也被拖慢时才触发 |
| P008 语言堆砌 | **标准** | 仙侠的华丽描写是风格的一部分，但堆砌仍然是堆砌——"紫金色的灵气如瀑布般倾泻而下，璀璨夺目，绚丽无比"仍然可以精简 |
| P015 高潮疲软 | **降低触发阈值**（更敏感） | 仙侠的核心爽点就是高潮——如果高潮疲软，读者流失极快 |
| P017 伏笔失效症 | **降低触发阈值** | 仙侠篇幅通常极长（百万字+），伏笔管理是刚需。断掉的伏笔在后期会被无限放大 |

**该体裁特有陷阱**:
- **修炼可读性陷阱**: "灵力从丹田涌出，沿经脉运行了三十六个周天，每一个穴位都在发出微光……"——修炼过程写得太细太重复，读者开始跳过。解决：第一次详细写，后续用"他又运行了三个周天"一笔带过。
- **等级熵增陷阱**: 等级/境界越来越多，前期强大的境界后期变成白菜。解决：每个等级引入时明确其"不可替代性"——不是更强，而是不同。

