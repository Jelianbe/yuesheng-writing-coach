### 悬疑/推理

**读者合同**: 接受作者保留关键信息，接受叙事视角的局限，接受"误导"。但要求**最终所有线索必须对得上**——悬疑读者的信任建立在"作者比读者聪明但公平"的基础上。

**诊断阈值调整**:

| 症候 | 调整 | 原因 |
|------|------|------|
| P004 信息倾泻症 | **降低触发阈值**（更敏感） | 悬疑的信息释放需要精确计算——什么时候读者知道什么。过早泄露 = 破坏悬念 |
| P005 视角漂移 | **视情况** | 多视角是悬疑常见手法，但切换必须标记清晰——混乱的视角切换会让线索失效 |
| P006 节奏停滞 | **降低触发阈值** | 悬疑需要节奏——两个线索之间不能有大段空转 |
| P016 情节巧合 | **降低触发阈值** | 悬疑读者对巧合的容忍度极低——"刚好发现了关键证据"是悬疑的大忌 |
| P017 伏笔失效症 | **极大降低触发阈值** | 悬疑就是伏笔+回收。一个未回收的线索 = 读者认为作者在耍ta |
| P021 跳跃叙事 | **视情况** | 时间跳跃是悬疑常用手法，但跳跃不能跳过关键推理过程 |

**该体裁特有陷阱**:
- **"上帝视角漏洞"陷阱**: 叙述者知道真相但故意不告诉读者——不是通过角色视角自然避免，而是直接"省略"关键信息。读者会感到被欺骗。解决：确保"读者不知道某信息"是因为"当前POV角色不知道"而非"作者故意藏着"。
- **红鲱鱼疲劳陷阱**: 放太多误导线索，最后揭露真相时读者已经忘了核心线索。解决：主要红鲱鱼不超过3条。
- **"作者下降头"陷阱**: 关键推理步骤由角色"灵光一闪"完成——读者无法跟随推理过程。解决：每一个推理步骤都必须有前文线索支撑。

---

### 言情/都市

**读者合同**: 接受对情感关系的细致描写，接受一定程度的内省和内心独白。核心要求是**情感真实**——角色为什么要爱/不爱/恨/原谅，必须有说服力。

**诊断阈值调整**:

| 症候 | 调整 | 原因 |
|------|------|------|
| P003 情绪标签化 | **降低触发阈值** | 言情以情感为核心——"他很伤心"这种写法直接破坏共情基础 |
| P006 节奏停滞 | **提高触发阈值** | 读者接受情感互动需要"空间"——两人慢慢相处的段落不是停滞 |
| P009 角色空心化 | **降低触发阈值** | 言情的角色动机必须清晰——读者需要理解"ta为什么会爱上ta" |
| P019 情感失真 | **降低触发阈值** | 言情的核心就是情感——情感失真 = 地基塌了 |
| P011 对话疲劳症 | **降低触发阈值** | 言情依赖对话推进关系——无效对话比别的体裁更致命 |

**该体裁特有陷阱**:
- **"工业糖精"陷阱**: 情感进展完全依赖外部事件推动（意外同居/被迫合作/英雄救美），角色之间没有真正的化学反应。检测：如果删掉所有外部事件，这两个人还有理由在一起吗？
- **"工具人恋人"陷阱**: 恋爱对象只有"对主角好"这一个特征，没有独立的欲望、弱点和故事。解决：恋人必须有一章完全是ta自己的视角——ta在没有主角的时候在做什么？
- **"误会驱动"陷阱**: 整篇的情感冲突全靠"不说清楚"来维持——只要角色开口解释一句，故事就结束了。解决：至少有一个冲突不能靠"沟通"解决——那是真正的情感冲突。

