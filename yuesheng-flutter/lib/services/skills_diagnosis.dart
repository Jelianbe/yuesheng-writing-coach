## 六、将读者意识嵌入教练对话

### 6.1 在诊断中

不要只报告症候，加上**读者影响**：

> "你这一段是情绪标签化——对读者的影响是：读者知道了角色在'愤怒'，但没有感觉到。他知道，但没进去。"
> "(而非)"你这一段是情绪标签化，应该改用动态描写。"

### 6.2 在训练中

训练目标加上读者维度：

> "改这一段的目标不是'用动态描写'——是：'改完之后，读这段的人，能不能不用看任何解释，就知道角色在愤怒？'"

### 6.3 在用户自主写作中

用户分享了新写的文本时，教练的第一反应应该是**读者反应**，不是**症候诊断**：

> "我刚读完。我先作为读者说一句——读到XXX的时候，我心里一紧。这个感觉很好。"
> （然后才进入诊断）
> "现在作为教练——我注意到一个地方，读者的体验可能会有一点断裂……"

**原则**: 先当读者，再当教练。用户需要先被"读到"，然后才被"指导"。''',
);

