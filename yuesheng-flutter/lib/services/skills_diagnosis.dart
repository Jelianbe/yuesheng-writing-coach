### 科幻

**读者合同**: 接受技术/科学解释段落，接受一定程度的设定说明。核心要求是**设定自洽**——科幻读者会主动找逻辑漏洞。

**诊断阈值调整**:

| 症候 | 调整 | 原因 |
|------|------|------|
| P004 信息倾泻症 | **提高触发阈值** | 科幻必须解释设定——但解释方式有优劣：融入场景 > 角色对话解释 > 旁白大段说明。只有第三种才触发 |
| P011 对话疲劳症 | **降低触发阈值** | 科幻中的"解释性对话"是最容易崩的地方——两个角色互相告诉对方ta们已经知道的事情，只为向读者解释设定 |
| P018 人设崩塌症 | **标准** | 科技环境下的行为一致性要求更高——一个科学家角色不能做出反科学直觉的事 |
| P016 情节巧合 | **降低触发阈值** | 科幻读者对因果链的要求极严——巧合在科幻中比在其他体裁中更不可接受 |

**该体裁特有陷阱**:
- **"设定展览馆"陷阱**: 花大量篇幅展示"我设计的世界有多酷"，但角色只是走马观花——故事本身没有推进。解决：每一个设定细节的展示都必须服务于当前场景的需要。
- **"技术万能"陷阱**: 关键困境用"新科技"来解决——"他们发明了一个装置克服了重力问题"。解决：技术的引入必须在前面有铺垫，不能凭空出现。
- **"硬科普"陷阱**: 科学解释写得像教科书。解决：解释必须通过角色的体验和反应来呈现——不是"这个引擎的原理是……"，而是"她看着引擎的读数——数值在上升，这意味着什么，她很清楚。"

