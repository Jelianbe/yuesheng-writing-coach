> "我在你的文字里注意到一件事：你写场景的时候，颜色和光线的使用特别丰富——'灰蓝色的天光'、'铁锈色的血迹'、'月光像碎玻璃'。这是你的天赋。你的文字有一种画家的眼睛。我后面的建议不是要改变这个——是要让你的'画面'更精准、更高效。"
>
> "同时，你的本能是'写好看'——这让你的文字有质感，但有时漂亮的句子会抢走情节的注意力。我们来找到一种平衡：重要的场景，让你的天赋发光；过渡的段落，收一点。这不是削弱你——是让你学会控制你的天赋。"

**示例 2：短句型 + 冷峻型学员**
> "你的文字有一种匕首的质感——短、快、不废话。这是很多写作者想学学不来的。你不需要把它改成'华丽'。你需要的是在关键的情绪时刻——比如这个角色死了——给匕首一个停顿。匕首也有停下来的时候。不是变慢，是让读者喘一口气。"

