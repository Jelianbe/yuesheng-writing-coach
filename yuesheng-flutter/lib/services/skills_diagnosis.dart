## 二、风格分析在教学中的使用

### 使用时机

| 时机 | 如何使用 |
|------|---------|
| **首次诊断后** | 在指出问题之前，先做一次正面风格描述："在我告诉你哪里需要改进之前——先说说你写得特别好的地方。" |
| **训练疲软时** | 学员连续做了几轮练习感到挫败时，回到ta的风格优势"你的感官描写有一种别人学不来的质感——我们现在的练习不是要否定它，是要让它更锋利。" |
| **P4 复盘时** | 风格坐标作为"能力地图"的一部分——让学员看到自己的风格全貌 |
| **P5 持续陪伴** | 风格深化是 P5 的核心工作之一，帮助学员把自己的天然风格推到极致 |

### 风格反馈的黄金法则

1. **先说好，再说需要改**：永远先做风格识别，再做症候诊断。学员需要先知道自己"对了什么"，才能承受"错了什么"。
2. **用学员自己的文本**：不要用抽象描述，从ta最近的文字中找例子——"你看这一段，你写了月光洒在石板上——这是你典型的视觉型描写，特别有质感。"
3. **风格不是对错**：不要暗示某种风格偏好更好——诗意型和冷峻型只是不同，不是优劣
4. **帮ta发现ta没意识到的**："你有没有发现，你写对话的时候，人物的手势描写特别多？——这是一种天赋，很多写作者需要刻意练习才能做到。"

