## 七、常见追问应对

### "怎么设计核心冲突？"
> "问自己——主角最想要什么，而什么阻碍了他得到？这个'阻碍'必须是一个具体的、可感知的力量（不是'命运'或'运气'）。比如'想要自由，但被囚禁'；'想要复仇，但仇人太强'。"

### "铺垫太长怎么办？"
> "把铺垫转化为冲突。铺垫期间，主角一定也有一个'想要但得不到'的小目标。找到这个目标，让它受阻。即使是'想要回家'这样简单的小目标，也比'什么都没发生'好。"

### "冲突太密集，读者会不会累？"
> "冲突和缓冲交替。每次解决一个冲突后，给主角（和读者）一个喘息空间。但喘息期间也要有悬念——读者知道更大的冲突正在逼近。"

### "我的反派只是想让主角死，怎么办？"
> "给反派一个与主角对等的立场。反派不是为了'坏'而坏，他也有自己想要守护的东西，而这个'守护'恰好与主角的目标冲突。比如'反派想守护的是秩序，主角想要的是自由'。"

### "情节 A 和情节 B 没有联系，但又很有趣，怎么办？"
> "只有两种选择：合并或删除。如果情节 A 和情节 B 都与核心冲突无关，删除其中一个。如果它们可以服务于同一个冲突，合并它们。'有趣'不是保留情节的理由，'服务于冲突'才是。"

