> **定位**: 正向识别——发现学员已经"对"的东西
> **与诊断体系的关系**: 诊断体系找"哪里不对"，风格分析找"哪里特别对"——两者互补

## 核心哲学

每一位写作者都有一种**天然的写作本能**——在不假思索的时候，ta会自然地使用某种感官、某种节奏、某种距离来讲述故事。这种本能不是"技巧"，而是"天赋"。

教练的工作不是改变一个人的本能，而是：
1. **先找到它**——学员自己可能都没意识到
2. **告诉ta**——"你注意到没有，你写 X 的时候特别好"
3. **帮ta打磨它**——把天赋变成武器

---

## 五维风格坐标

分析学员风格时，从以下五个维度切入：

| 维度 | 核心问题 |
|------|---------|
| **感官偏好** | 学员最常激活哪种感官通道？（视觉/听觉/体感/均衡） |
| **节奏偏好** | 句子和段落的自然节奏？（长句/短句/错落/重复） |
| **叙事距离** | 叙述者离角色有多近？（贴身/观察/评述/游移） |
| **语气质地** | 文字的语言质感？（诗意/冷峻/口语/文雅） |
| **结构本能** | 组织故事的自然方式？（线性/碎片/回环/发散） |

**识别方法**：从学员最近 3 段文本中，统计各维度的倾向。某种倾向占比 >50% 即为其偏好。

> 示例：学员写场景时大量使用"灰蓝色的天光""铁锈色的血迹"等颜色描写 → 视觉型偏好。

---

## 黄金法则

1. **先说好，再说需要改**：永远先做风格识别，再做症候诊断。学员需要先知道自己"对了什么"，才能承受"错了什么"。
2. **用学员自己的文本**：不要用抽象描述，从ta最近的文字中找例子。
3. **风格不是对错**：不要暗示某种风格偏好更好——诗意型和冷峻型只是不同，不是优劣。
4. **帮ta发现ta没意识到的**：指出学员自己没注意到的天赋。

---

## 风格 vs 缺陷的区分

**基本问题**："如果作者想把这段改得更'标准'——ta做得到吗？"
- 做得到但选择不改 → 风格选择
- 做不到 → 写作缺陷

**常见误判对照**：

| 风格特征 | 可能被误判为 | 区分关键 |
|----------|-------------|---------|
| 简洁克制 | P003 情绪标签化 | 是"有意不说"还是"不知道怎么描写"？ |
| 长句密集 | P008 语言堆砌 | 删掉修饰后信息量是否减少？ |
| 大量对话 | P011 对话疲劳症 | 对话是否推进情节/揭示角色？ |
| 跳跃叙事 | P021 跳跃叙事 | 跳跃是否有设计（埋线索/留白）？ |
| 慢节奏 | P006 节奏停滞 | 慢的部分是否提供必要信息/氛围？ |''',
