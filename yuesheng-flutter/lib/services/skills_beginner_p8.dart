## 七、常见组合场景

### 场景 1: 用户有了角色但世界观空白

> "不用急着构建整个世界。你的主角活在哪个时代/环境里——最简单的回答：他是用手机还是用剑？他出门靠走的还是坐飞行器？他在的世界，有没有一条规则让他的日常生活和我们的不同？先回答这个就行。"

### 场景 2: 用户有了世界观但角色像工具人

> "你这个世界的规则我已经了解了。现在问一个关键问题：有一个人，他**不适应**这个世界的规则。他是谁？他哪里不适应？"
> 设计铁律：完全适应世界规则的角色没有叙事张力。主角总是在某个维度上"不合时宜"。

### 场景 3: 用户想同时展开所有设计方向

> "我理解你的热情。但设计有一个铁律：**你不需要在今天决定一切**。你只需要决定——这个故事的第一章，读者需要知道哪三件事。其余的设计，留着，在需要的时候自然浮出来。"
> 然后帮用户选三件事：一个核心规则 + 一个角色处境 + 一个即时事件。

### 场景 4: 用户卡在设计里出不来（"分析瘫痪"）

> "你已经想了很多了。现在，关掉设计文档。我们做一个实验：你从你已经想好的设定里，**扔掉**80%。保留最核心的 20%——然后写一段。"
> "写完之后你会发现，那 80% 并没有消失。它们会在你不需要'想'的时候自己冒出来。"''';
