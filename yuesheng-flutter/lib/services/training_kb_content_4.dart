## P030 声线漂移症

**核心本质**：文风随段落漂移、前后声线不统一，读者辨不出"这是谁写的"。声线=稳定的句式节奏+词汇偏好+叙述视角选择；漂移=情绪带动文风突变、模仿腔与本色腔混用、对话与叙述声线打架。不是单段写不好，而是整本书没有一条连贯的"作者的声音"。

**教学要点**：
- 声线分立（T014）：先分两套声线——叙述者的与角色的；对话可用角色腔，叙述必须守住叙述者腔，两套各自稳定
- 句速控制（T023）：情绪高点不换腔，只变速——同一套句式节奏下把句子拉短/拉长，而不是突然换成另一种文风
- 用词浓度审计（A016）：列出全书高频词与情感浓度词，情绪段落不堆感叹词，靠节奏与细节传递情绪
- 潜台词法（T013）：情绪升级时让动作和留白承接，叙述声线不跟着情绪"喊"

**常见误区**：
- 以为声线=文笔好坏——声线是"稳定"问题不是"水平"问题，写得好也会漂移
- 以为换题材就该换声线——题材影响用词浓度，不影响叙述者腔调
- 以为情绪戏就要澎湃文风——澎湃靠节奏与细节密度，不靠句式突变
- 以为对话活泼叙述就必须活泼——对话与叙述是两套声线，各自稳定即可

**严重度判断参考**：
- L1：个别段落起伏 → 用词浓度审计 + 句速控制
- L2：章节间漂移 → 声线分立 + 情绪段变速练习
- L3：整书分裂 → 声线基准文重写（定叙述者腔调）+ 全书用词浓度扫描（A016）

**教学素材库**：
- 声线基准文：从全书抽 300 字稳定的段落做"声线锚"，训练时对照
- 情绪变速练习：同一段情绪戏写两版——原样 vs 只变速不换腔，对比差异
- 声线二分卡：一句话说清"叙述者怎么说话 / 角色怎么说话"
- 用词浓度扫描：标出情绪高点的感叹词/程度副词，改由节奏与细节承接

