## P026 心理内耗症

**核心本质**：角色内心反复纠结、自我怀疑、复盘过往，大段独白无进展。不是情绪不真实（那是 P001 失真），也不是直接告知情绪（那是 P001 标签），而是**内心戏篇幅失控**——情绪真实但反复拉扯，没有收敛与推进，读者看独白时"进度条不动"。

**教学要点**：
- 独白收敛：让纠结在 1-3 句内给出决策（"纠结后决策"是标准动作，无决策的纠结即内耗）
- 心理转动作（T001）：把"反复想"改写为动作/选择——手攥紧、起身、拨电话，行动替代独白
- 场景裁剪（A011）：删掉不推进决策的复盘段；一段纠结两三句可表达，就砍掉三页
- 动机推进（T009）：用欲望/恐惧驱动决策替代反复权衡——角色"要什么"比"怕什么"更快推剧情

**常见误区**：
- 以为内心戏多=人物有深度——深度在于独白有洞察/决策，不在于篇幅
- 以为纠结真实就该保留——真实但无进展的纠结，两三句点到即止
- 以为删独白丢情绪——情绪可以移进动作和对话，读者依然感受得到

**严重度判断参考**：
- L1：个别段落拉扯偏长 → 收 1-3 句，转动作
- L2：每章固定大段独白 → 场景裁剪 + 心理转动作
- L3：行动被内心戏淹没 → 重写冲突段，独白让位给行动

**教学素材库**：
- 独白收敛模板：纠结 → 关键一问（"我要什么"）→ 决策 → 动作
- 心理转动作练习：把一段内心戏改写成"零独白版"（全用动作/对话/选择表达）
- 决策驱动练习：给内耗主角一个明确的欲望，让欲望推着他走出纠结
- 内耗删减对照：同段冲突写两版——「内心戏版 vs 行动版」，对比节奏与情绪强度

