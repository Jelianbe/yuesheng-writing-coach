## P031 题材边界感缺失症

**核心本质**：写作者不清楚自己写的是哪个题材赛道、目标读者是谁，题材内部混搭失焦，读者找不到类型预期，平台也推不动。不是开篇契约问题（那是 P011），而是更前置的**赛道定位**缺失。

**教学要点**：
- 类型一句话测试（A007 一句话冲突）：让学员用一句话说清"这是本什么书、给谁看"，说不出即边界缺失
- 题材内核审计（A003 五问法）：追问每个看似混搭的元素"它服务什么统一内核"，无内核即蹭元素
- 读者画像锚定：明确"给谁爽/给谁哭"，题材选择围绕核心读者而非作者兴趣漂移

**常见误区**：
- 以为元素多=内容丰富——混搭无纲领只是噪音
- 以为蹭热点题材就能火——没有自己的赛道积累，读者不沉淀
- 以为"类型融合"天然高级——融合要有审美纲领，否则是失焦

**严重度判断参考**：
- L1：个别章节跑题 → 指出并收窄
- L2：主线题材模糊 → 类型一句话重构 + 内核审计
- L3：全书赛道混乱 → 重做选题定位（A007）+ 读者画像（A003）

**教学素材库**：
- 类型一句话卡：写出"本书类型 + 核心读者 + 一句话卖点"
- 混搭审计表：列出书中所有题材元素，逐一标注服务的内核
- 对标书单：找 3 本同类畅销书，归纳它们的稳定赛道特征
- 读者画像模板：年龄/爽点/泪点/阅读场景四栏

## P032 翻译腔/外来语干扰症

**核心本质**：句子带着翻译腔——长定语前置、名词化堆叠、被动框式滥用、It is…式抽象，或被生硬音译词打断中文语流，读起来像机翻不像人写。不是字句堆砌（P006），而是**句式结构被外语语序带跑**。

**教学要点**：
- 感官全开（A006 感官全开）：用五感具体细节替代抽象名词主语句，打破"值得注意的是…"式框式
- 核心信息提取（T003）：三稿删减法剥离翻译腔的冗余包装，留下主干
- 线性变奏（T019）：把长定语拆成中文习惯的短句链，恢复主谓骨架

**常见误区**：
- 以为长句=高级——中文以短句链为美，长定语是机翻痕迹
- 以为被动显客观——中文主动更直接，被动框式多为翻译残留
- 以为音译词显专业——没有中文锚点的外来语只是噪音

**严重度判断参考**：
- L1：个别句子翻译腔 → 重排语序即可
- L2：段落级语感断裂 → 拆长定语（T019）+ 转主动（A006）
- L3：通篇机翻腔 → 全文语序重构（T019）+ 抽象名词落地（T003）

**教学素材库**：
- 语序体检：把一句长定语中文重排成 2-3 个短句，对比语感
- 被动转主动练习：列出"被…所/对于…来说"句，逐句改主动
- 音译词落地卡：每个外来语配一句中文语境缓冲

## P033 冲突未升级/模式重复症

**核心本质**：同一冲突模式被重复多次，但威胁程度、信息量、情绪强度没有逐级递增。读者第二次就摸清套路，之后只是音量调大。不是单次冲突没分量（P010 张力不足），也不是段落无推进（P004 节奏停滞），而是**重复的冲突没有进化**——模式可识别、强度不爬坡。

**教学要点**：
- 一句话冲突（A007 一句话冲突）：每场冲突用一句话写清"这一局比上一局难在哪"，写不出差异＝未升级
- 五问法（A003 五问法）：对重复模式追问"换了什么维度/代价/ stakes"，逼出每轮的增量
- 节奏变速（A009 节奏变速）：同构场景之间插入变奏轮次，用节奏与信息密度制造升级曲线

**常见误区**：
- 以为冲突多=紧张——重复同强度的冲突只会让读者疲劳
- 以为"写得更急"就是升级——音量调大不是局势变难
- 以为读者不会发现重复——读者第二次就能预判套路

**严重度判断参考**：
- L1：个别段落结构近似 → 标出两轮差异点
- L2：连续多场同构、强度不涨 → 一句话冲突（A007）逐场补增量
- L3：全篇套路可预测 → 五问法（A003）重构升级曲线 + 节奏变速（A009）插变奏

**教学素材库**：
- 冲突爬坡表：逐场列"威胁/信息量/情绪强度"三轴，检查是否单调递增
