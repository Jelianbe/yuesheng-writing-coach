## P034 代词指代不清/零回指过载症

**核心本质**：中文允许零形回指，但过度省略使指称解歧负担转嫁读者——连续小句主语/宾语均省略且就近可及候选≥2，读者需回看上段才能确认指谁。

**教学要点**：
- 数连续零主语句数。
- 标每处零成分的就近候选数。
- 若候选≥2 且无话题锚，记为疑似过载——不自动补出代词。

**常见误区**：
- 以为标出就近候选就该替学员补出代词——判断原则只诊断过载，不代写指称。

**严重度判断参考**：
- L1：偶发一两处零回指、话题锚明显 → 标出位置让学员自查
- L2：连续多处零回指无话题锚 → 示范"有话题锚 vs 无话题锚"两种零回指
- L3：整段指称链断裂 → 逐处标注就近候选数，重排指称链

**教学素材库**：
- 话题锚 vs 无话题锚对照：展示两种零回指段落，让学员自己判断哪处读者会卡住。

