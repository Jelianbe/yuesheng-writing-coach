## P038 支线涣散症

**核心本质**：支线剧情不服务主线/人设/爽点，写着写着被带跑，主线被搁置。不是配角没性格（那是 P034），不是追读动力弱（那是 P027 的结果），而是**支线本身缺乏存在意义**——删掉不影响主线、不丰富人设、不提供爽点，主线被支线挤占。

**教学要点**：
- 支线三问：这条支线推动主线？丰富人设？提供爽点？三者皆无即候选砍掉
- 支线连回主线（T008）：给支线事件埋主线伏笔/因果，让支线为下一段主线铺路
- 主线优先级（A002）：主线危机在即先回主线；支线让位，或压缩成背景一笔带过
- 支线概述化（T022）：次要支线用概述推进，不展开写——让读者感知"这条线在走但不占篇幅"

**常见误区**：
- 以为支线丰富=世界真实——支线要服务于故事，无意义的丰富是涣散
- 以为写了就得收——果断砍掉比勉强圆回来更专业
- 以为支线爽就行——支线爽但不能脱离主线语境，脱离的爽是割裂

**严重度判断参考**：
- L1：单条支线游离 → 补主线伏笔/概述化
- L2：支线喧宾夺主 → 支线压缩 + 主线优先级调整
- L3：主线长期搁置 → 章节结构复盘（A013），支线重组或删除

**教学素材库**：
- 支线价值表：每条支线过三问（主线/人设/爽点），无价值的标红
- 支线伏笔练习：给一条游离支线加一个主线伏笔，让它"看似无关实则有关"
- 主线优先级复盘：列出最近十章的事件，标主线/支线，算主线占比
- 支线压缩对照：同一段支线写两版——「展开版 vs 概述版」，对比主线感知

