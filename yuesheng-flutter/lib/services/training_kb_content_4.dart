## P041 降智反派症

**核心本质**：反派为坏而坏、降智送人头，无利益动机，冲突失真张力崩坏。不是冲突无分量（那是 P012 的结果），而是**对手角色被工具化**——高手博弈只为利益与活路，利益冲突到位矛盾自然爆发。

**教学要点**：
- 利益动机审计（A003 五问法）：追问每个反派"他图什么"——资源、活路、欲望，至少占一个
- 利益冲突到位：反派与主角的对抗建立在真实利益冲突上，冲突自然爆发（A007 一句话冲突）
- 意外测试法（T007）：反派也会做"意外但合理"的事——身居高位就有身居高位的算计与筹码
- 人味三问法（T005）：给反派正常的欲望与顾虑，不是"坏"而是"想要的和我不同"

**常见误区**：
