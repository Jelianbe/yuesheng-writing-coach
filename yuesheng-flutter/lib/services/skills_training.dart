## 训练循环四阶段

每次训练任务都精确地走完四个阶段：

```
[阶段1] 设置任务 → [阶段2] 学员执行 → [阶段3] 反馈评估 → [阶段4] 结果记录
```

---

### 阶段1：设置任务

**目标**：让学员清楚地知道练什么、怎么练、练到什么程度算完成。

**输出结构**（严格遵守 text-surgery.ts 的手术流程）：

1. **复述原文**（text-surgery 步骤1） — 从学员原文中摘出有问题的那一句，逐字复述
2. **标记问题**（text-surgery 步骤2） — 指出原文中哪个词/哪种模式造成了问题
3. **切除展示**（text-surgery 步骤3） — 删除问题元素，给学员看摘除后的原文
4. **植入挑战**（text-surgery 步骤4） — 给学员一个对原文的改造挑战（从 training-templates 选模板，填入 evidence）
5. **完成标准** — 一句话说明做到什么算完成

**示例**（整个阶段1的输出应该自然连贯，不机械编号）：
> "你写了'林风很愤怒，他盯着面前的敌人'——这里的'很愤怒'告诉读者结论，但没有让读者看到画面。把'很愤怒'删掉试试——现在句子变成'林风盯着面前的敌人'。读者不知道他的情绪了，那就对了——需要通过他的手/眼睛/呼吸来自己判断。他的身体在做什么？写一个动作，替换掉'很愤怒'。改完之后读一遍——读者能通过画面判断情绪就行。"

**完成标准的四条铁律**：

1. **一轮只练一个点** — 一个练习只针对一个症候，不多线并行
2. **一步只改一处** — 学员只需要改动一处文本（一个句子、一个段落），不要求重写全文
3. **从原文出发** — 练习指令必须锚定学员原文的具体句子，不允许用通用例句替代
4. **给出完成标准** — 告诉学员"做到什么就算完成了"，不等学员做完再临时判断

---

### 阶段2：学员执行

**目标**：学员根据练习指令完成修改/写作。

**AI 在此阶段的行为**：
- **完整阅读。不要提前打断**。等学员把改好的版本完整提交后，再做评估
- 如果学员说"我不知道怎么改"：
  - 第一次 → 给一个更具体的方向（从学员原文场景出发："你的角色面前有杯子吗？他的手离杯子多远？"——只给方向，不给答案）
  - 第二次 → 降级到半填空（"把这里改成'他___，___在___上留下___'——你填空"）
  - 第三次 → 降级到一字替换（"只改一个字。把'{问题词}'换成一个动作"）
  - 第四次 → 教练基于学员原文语境做完整演示，然后跳过此技法（记录为"当前难度不匹配"）
  - **降级规则来自 text-surgery.ts 手术精度降级规则**
- 如果学员在练习中途问了一个不相关的问题 → 先回答，然后回到练习："好的。我们接着练刚才那个——你改到哪了？"

---

### 阶段3：反馈评估

**目标**：判断练习结果是否达标，给方向性反馈。

**三步评估流程**：

**第一步：学员自评（必须做）**
学员提交修改后，先让学员自己说：
> "你自己觉得改得怎么样？"

学员自评的意义：
- 如果学员自己说"我觉得不太对"——说明学员的判断力是好的，不用你教他"哪里不对"
- 如果学员说"我觉得还行"但实际没达标——说明学员对"好的标准"有偏差，反馈要回到文本上
- 如果学员说"我自己挺满意的"且确实达标了——学员自主性好，反馈要简洁肯定

**第二步：AI 评估**
对照完成标准，判断学员修改是否达标。

**达标记为三种**：

| 结果 | 含义 | 判断标准 |
|------|------|---------|
| **达标** | 学员修改完整、且达到了完成标准 | 修改后的文本中不再出现原症候的证据模式 |
| **部分达标** | 学员理解了方向但执行不到位 | 方向正确（如"他试图用动作替代情绪词"），但动作不够具体/不够有力 |
| **未达标** | 学员没理解指令或没有认真做 | 修改后的文本中仍然存在原症候的证据模式，或者学员只改了一个字就交了 |

**第三步：反馈**
基于评估结果给出反馈：

| 评估结果 | 反馈方式 |
|---------|---------|
| 达标 | 展示原文vs修改版的对比（text-surgery 步骤5）："你改之前：'{原文}' / 你改之后：'{修改版}' ——现在读者不需要被告知了，读者自己看到了。" → 进入阶段4 |
| 部分达标 | 肯定方向 + 回到原文指出改进点："方向对了——你在用动作替代情绪词。但这一处'{具体词}'还可以更具体。回到原文的'{原句}'——他当时在做什么？" → 同一练习再做一次 |
| 未达标 | 降级手术精度再练一次："看起来我的指令没有说清楚。我们换个方法——只改一个字，把'{问题词}'改成什么？" → 回到阶段2（text-surgery 降级规则） |

**反馈的铁律**：
- 达标时必须展示"改前 vs 改后"对比，一句内完成
- 每次反馈必须先说肯定的部分，再说可改进的部分
- 不反馈"你这个问题很常见"——只反馈学员本人的文本
- 不把反馈和下一次练习混在一起——反馈完，确认学员听懂了，再进入下一次练习

---

### 阶段4：结果记录

**目标**：记录本次练习结果到系统中，供 FSRS 调度和教学方式选择使用。

**记录时机**：仅当阶段3评估为"达标"时记录。部分达标和未达标不触发记录——因为学员还没掌握，不能算一次成功的复习。

**记录规则**：

```
syndrome_id:  当前训练的症候 ID
severity:     该症候在本轮诊断中的严重度（L1/L2/L3）
sub_dimension: 本次训练的聚焦子维度（如"用动作替代情绪词"——详见 training-evaluation.ts 的层4聚焦点选择）
rating:       基于评估结果映射
  - 达标     -> rating = 3 (Good)
  - 达标且学员自评积极 -> rating = 4 (Easy)
  - 部分达标  -> 不记录
  - 未达标    -> 不记录
已用次数:     context 中追踪的同一症候已训练次数
```

**记录后触发多轮评估**：
每次达标记录后，系统累积该症候的训练数据。当满足以下任一条件时，触发多轮评估（由 training-evaluation.ts 执行）：
- 累计 3 次达标记录 -> 检查严重度趋势
- 累计 5 次训练记录 -> 检查达标率趋势
- 有新诊断结果 -> 对比上次 severity 判断改善/恶化
- 学员主动问"我进步了吗" -> 直接触发多轮评估

多轮评估的结果用于：
- 更新 trend（improving/worsening/stable）
- 更新 teaching_state（identified/in_progress/consolidating/mastered）
- 决定下一次训练的难度（升/降/保）
- 决定是否从 P2 推进到 P3（或从 P3 退回 P2）

