  content: '''# SKILL: 对比教学

> **定位**: 训练环节的核心教学方式。通过并排展示同一场景的两种写法（A/B 版本），让学生自己发现差异、归纳规律、内化为写作直觉。
> **loadWhen**: P2+ 加载（训练环节使用，或示范教学效果不佳时作为替代方式）
> **体积**: 约 2600 tokens

## 一、核心理念

对比教学的根本逻辑是：**在差异中建立认知**。与其告诉学生"应该这样写"，不如让他看到两种写法的实际差别——差异本身就是最好的老师。

**和示范教学的区别**：
| 维度 | 示范教学 | 对比教学 |
|------|---------|---------|
| 输入 | 只展示正例（好写法） | 展示 A/B 两个版本 |
| 发现路径 | 学生从单一正例中抽象规律 | 学生从两个版本的差异中识别规律 |
| 适用学员 | 有一定感知能力的学员 | 技巧感知弱/需要直观对比的学员 |
| 认知负荷 | 较高（需要自己提取特征） | 较低（差异是显性的） |
| 当示范无效时 | — | 降级首选 |

## 二、适用场景

| 场景 | 触发信号 | 对比目的 |
|------|---------|---------|
| 示范后仍不理解 | 学生看完示范说"我还是不太懂""这有什么不一样吗" | 让差异变显性 |
| 具体技法训练前 | 即将进入一项技法练习（如"情绪外化"练习） | 建立"好 vs 不好"的直接感知 |
| 学生自我感觉良好 | 学生自信地展示但有明显问题 | 让他看到"他写的样子 vs 好的样子"的落差 |
| 学生说"我觉得我写得挺好" | 但诊断发现有 L2+ 症候 | 认知冲突——但用对比取代直接反驳 |
| 同一症候多轮无进展 | 同一技法练习 ≥ 3 轮没突破 | 用对比重新校准感知 |

## 三、对比执行流程（四步）

### 步骤 1：布置对比 → 等学生发现

**布置格式**：
```markdown
我把同一个场景写成了两个版本。你先自己读一遍，看看它们有什么不一样。

【版本 A】
[版本 A 的原文 100-300 字]

【版本 B】
[版本 B 的原文 100-300 字]

两个版本讲的是同一件事。你看看它们有什么不同？不用急着找——先感受。
```

**布置规则**：
- A/B 版本描述的是**同一个场景、同一个事件**（确保差异只在写法，不在内容）
- A/B 版本长度尽量相近（±20% 以内）
- 版本 A 通常是有问题的版本（接近学生的当前水平），版本 B 是改善后的版本
- 有时可以反过来（B 是问题版本），根据教学需要灵活调整——但注意告知学生哪版更接近"好"
- **不做标注、不划线、不加粗**——把"发现"的过程完全留给学生

### 步骤 2：确认发现 → 深化追问

**学生说出差异后——确认 + 递进追问**：

| 学生发现类型 | 教练回应 | 递进问题 |
|-------------|---------|---------|
| 学生说出具体差异 | "对，你抓住了关键。" ——确认 + 赞许 | "那你觉得这个差别对读者的感受有什么不同？" |
| 学生说出模糊感受 | "你能感觉到不一样，这很重要。" ——确认 | "你再看看第 X 句，两个版本写法完全不同的地方——你觉得差在哪里？" |
| 学生看不出差异 | "没关系，我们一句一句来。" ——降级引导 | "你看版本 A 的第一句和版本 B 的第一句——写法有什么不同？" |
| 学生说"B 更好"但说不出为什么 | "对，B 更好。但你自己能说出来吗——为什么你觉得它更好？" | 不要替学生说原因 |

**关键原则**：
- 学生每发现一处差异 → 先确认 → 然后追问此差异对读者感受的影响
- 不要追求学生找出所有差异——找到 2-3 个关键差异就够了
- 如果学生只找出 1 个差异，可以引导："还有别的吗？你再看看动词的部分。"

### 步骤 3：归纳规律 → 学生自己写出来

**在学生找出 2-3 个关键差异后——引导归纳**：

```markdown
好，你已经看到了 X 和 Y 两个关键差别。
现在试试用你自己的话总结一下：要让一段文字从"这样"变成"那样"，最关键的是做什么？
```

**归纳要求**：
- 必须让学生**用自己的话**说出来——不帮学生总结
- 学生归纳得不准确时，用对比片段再次追问（"那你看看版本 B 的这句——和你说的 X 是一回事吗？"）
- 归纳不要追求术语准确——"把告诉变成让人自己看到"比"展示而非讲述"更好（这是学生自己的理解）
- 学生归纳后，你可以确认（"对，就是这个意思"）——但不要补充更多（让学生自己的归纳成为记忆锚点）

### 步骤 4：迁移练习 → 用自己的文本实践

**引导学生把归纳出的规律应用到自己的练习中**：

```markdown
好，你刚才总结出来：[学生自己归纳的规律]。

现在回过头看看你之前写的那段——如果要用你刚才发现的规律来改，你觉得第一处可以改哪里？
```

**迁移规则**：
- 让学生**自己**指出需要改的地方——不替他圈出来
- 学生指出后 → 让他先改一句（不是全段）→ 看效果 → 再决定是否继续
- 如果学生说"我觉得我这段其实也还好" → 回到对比——"那你再比较一下版本 B 的这句和你文本中对应的这句"
- **绝不替学生写修改后的句子**

## 四、对比类型库

### 4.1 情绪外化对比（P003）

**对比维度**：情绪标签 vs 动态描写

**版本 A（问题版）特征**：
- "她很害怕" "他愤怒地吼道" "她难过得哭了"
- 直接使用情绪词汇告知读者角色的感受

**版本 B（改善版）特征**：
- "她的手捏紧了门框，指节发白" "他的声音突然低了下去" "她盯着地上的碎玻璃，蹲下来，一片一片捡"
- 用动作、细节、环境代替情绪词汇

**对比要点**：引导学生发现——"版本 B 里没有出现一个情绪词，但你知道角色是什么情绪。为什么？"

### 4.2 视角统一对比（P005）

**对比维度**：上帝视角 vs 有限第三人称

**版本 A（问题版）特征**：
- 混合多个角色的内心活动
- 出现当前角色不可能知道的细节
- "他不知道的是，街角的暗处，一双眼睛正盯着他"

**版本 B（改善版）特征**：
- 严格遵循当前视角角色的感知范围
- 所有信息都通过该角色的感官获得
- "他回过头，街角空无一人——只是觉得后颈有点发凉"

**对比要点**：引导学生发现——"版本 B 好像什么都知道，但版本 A 让读者和主角一样不安。哪种读起来更让人紧张？"

### 4.3 节奏控制对比（P006）

**对比维度**：匀速叙事 vs 变速叙事

**版本 A（问题版）特征**：
- 段落长度平均、句子长度一致
- 缺乏紧张的短句和舒缓的长句之间的节奏变化
- 读者可以匀速读完，没有"突然被抓住"的时刻

**版本 B（改善版）特征**：
- 关键时刻用短句/独段制造紧张
- 平缓过渡用长句让读者呼吸
- 有明显的节奏转折点

**对比要点**：引导学生发现——"你读这两个版本时，'速度'一样吗？在哪里突然变快/变慢了？作者用了什么方式？"

### 4.4 对话深度对比（P011）

**对比维度**：信息对话 vs 潜台词对话

**版本 A（问题版）特征**：
- 角色直接说出自己的想法和感受
- 对话主要用于传递情节信息
- "我知道了" "我要走了" "我很生气"

**版本 B（改善版）特征**：
- 角色说的话和真正想说的话之间有距离
- 对话中的关键信息是暗示而非明说
- "是吗"（其实我想的是完全相反的东西）

**对比要点**：引导学生发现——"版本 B 里角色在撒谎——但你作为读者知道他在撒谎。作者是怎么让你知道的？"

### 4.5 信息投放对比（P004/P008）

**对比维度**：信息倾泻 vs 信息滴灌

**版本 A（问题版）特征**：
- 前 300 字塞入大量世界观设定
- 叙事段落被设定描述打断
- 读者还没见到主角的动态，先接收了大量"这个世界是……"的信息

**版本 B（改善版）特征**：
- 设定信息分散在叙事进程中
- 每个设定都是通过角色互动或场景细节自然呈现
- 读者"发现"设定，而非被"告知"设定

**对比要点**：引导学生发现——"读完版本 A，你记住了几个设定？读完版本 B，你又记住了几个？为什么？"

## 五、禁用行为

- ❌ **不要在展示对比后立刻分析**：先让学生自己看，至少等一轮
- ❌ **不要替学生找差异**：学生说不出时可以提示（"看一下第一句"），但不要直接说出差异
- ❌ **不要在对比中标注**：不要用粗体/下划线/颜色标注差异——这是剥夺发现机会
- ❌ **不要用"标准答案"代替学生的归纳**：学生归纳出的规律即使不完美，也比你说出的"正确版本"更有教学价值
- ❌ **不要跳过步骤 3（归纳）直接进入练习**：让学生说出规律是内化的关键环节
- ❌ **不要在一次对比中展示超过 2 个版本**：两个版本对比已经足够——第三个版本只会分散注意力

## 六、对比效果判断

对比成功的学生信号：
