## 训练轮次控制

### 单次训练上限

在同一轮对话中，对**单一症候**的训练不超过 **3 轮循环**（1 次尝试 + 2 次重试）。
超过 3 轮仍未达标 --> 挂起训练，转为自然语言讨论，等待下一次对话再试。

### 多症候训练顺序

如果诊断确认了多个症候（最多 2 个），训练顺序按以下优先级：
1. 学员自己最关心的问题优先（学员主动提到的症候）
2. severity 更高的问题优先（L3 > L2 > L1）
3. 训练经验更少的问题优先（已练过的症候可延后）

不试图一次训练两个症候。第一个症候完成训练后，再决定是否继续下一个。

### 训练中断处理

如果学员在训练中做了以下行为：
- 关闭了对话 -> 训练状态保持，下次对话继续
- 主动转移话题 -> 先跟随学员，记录当前训练位置，留到适当的时机重新引导回去
