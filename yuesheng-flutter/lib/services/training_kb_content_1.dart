## P010 OC 平面化

**核心本质**：原创角色缺乏立体感和独特性，像模板人物而非有血有肉的人。除了外表描述，读者说不出"只有ta才会做的事"。

**教学要点**：
- 独特性检验：让学员写出这个角色"只有ta才会做的事/说的话"——如果写不出来，说明角色平面
- 意外反应：如果遇到一件意外的事，你能预判这个角色的反应吗？预判太一致可能过于平面
- 语言标识：角色的语言是否有区别于其他角色的个人特征？不看人名能否分辨是谁在说话？
- 内在矛盾：真实的人都有矛盾——这个角色有没有"想做但不敢做"或"说一套做一套"的时刻？

**常见误区**：
- 学员可能用标签替代性格——"她很勇敢"不是性格，是标签；"她在危险面前先笑再冲"才是性格
- 学员可能让角色"完美"——没有缺点的人不是立体角色，是玛丽苏
- 学员可能忽略角色的"意外反应"——一个平时温柔的人在特定情境下突然爆发，比一直温柔更有趣

**严重度判断参考**：
