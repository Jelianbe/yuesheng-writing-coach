### P014 结尾乏力症

> **position_sensitivity**: end

**核心问题**：故事收束没有给读者满足感。结尾要么太仓促（没有余韵），要么靠机械降神（外部力量突然解决所有问题），要么埋了大量伏笔却不回收。

**触发信号**：结尾缺少情绪停留；关键伏笔未回收；冲突解决方式让读者感到"就这？"

**判断原则**（基于上下文，非硬性标准）：
- 读完最后一段，读者是否产生了一种"完成了"的感觉——还是觉得"是不是少了一段"？
- 结尾是"故事自然走到了终点"还是"作者强行画了句号"？
- 主角的困境是以"主角自己的选择/行动"解决的，还是以"外部力量突然介入"解决的？
- 前文埋下的伏笔线在结尾处是否都有交代？哪怕只是"留白"式的交代？

**严重度判断**（结合三维标定表综合评估）：
- L1：结尾稍显仓促但核心冲突已解决，读者不至于不满，补一段余韵收束即可
- L2：结尾给人"读到一半被砍了"的感觉，关键伏笔未回收，读者会在书评区表达不满
- L3：烂尾——机械降神、伏笔全烂、情绪断裂，读者觉得前面积累的所有期待都被辜负了

**例外情况**（以下场景通常不是结尾乏力）：
- 开放结尾——有意让故事停在"未完"的状态（如"他推开门，门外是雪"），关键在于这个"未完"是有意为之还是无心之失
- 系列作品第一部结尾——为续集留钩子是合理设计
- 悲剧收束——悲壮的宿命感本身就是一种满足

