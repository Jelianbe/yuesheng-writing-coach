### P010 OC 平面化

> **position_sensitivity**: global

**核心问题**：原创角色缺乏立体感和独特性，像模板人物而非有血有肉的人。

**触发信号**：原创角色缺乏立体感和独特性

**判断原则**（基于上下文，非硬性标准）：
- 除了外表描述，这个角色有没有"只有ta才会做的事/说的话"？
- 如果遇到一件意外的事，你能预判这个角色的反应吗？——如果预判太一致，可能过于平面
- 角色的语言和行为是否有区别于其他角色的个人特征？

**严重度判断**（结合三维标定表综合评估）：
- L1：次要角色比较平面，但不影响主线，补充个别特征性对话即可
- L2：主角缺乏独特的性格标识，容易被混淆或记不住
- L3：所有角色都是模板，读者无法区分，需要为每个核心角色重建个性特征

**例外情况**（以下场景通常不是平面化）：
- 功能性配角（保安、收银员、路人）——扁平本身就是合理的设计
- 喜剧中的"类型角色"——某些喜剧类型需要夸张的类型化角色
- 扁平化作为叙事策略——刻意制造"符号化"角色服务于寓言/讽刺类作品

**诊断锚点示例**（few-shot 参考）：
- **L2 命中**："她叫小美，是一个普通的女孩，有着普通的长相、普通的性格、普通的爱好。她喜欢看书，也喜欢听音乐。她的梦想是找一个普通人过普通的一生。" → 连续 5 个"普通"，角色完全没有任何区分度。P010 L2
- **❌ 未命中（功能性配角/符号化）**："他叫老周，是这条街的邮差。每天同一时间出现，把信塞进门缝，从不和任何人多说一句话。谁也不知道他是什么时候来的，就像这条街本身。" → 判定：不触发。理由：配角扁平是功能性设计，且"像这条街本身"的符号化承载氛围意义——不是主角式平面化。

**推荐教学动作**：首选 A003 五问法，备选 A010 角色盲写

