### P015 高潮疲软症

> **position_sensitivity**: middle

**核心问题**：冲突写到了最高点但没有执行到位。铺垫做好了、冲突设定了、读者蓄势待发了——但高潮段落本身没有给读者期待的震撼/感动/热血。

**触发信号**：关键对决/揭示/爆发场景缺乏冲击力；情绪在最高点回落太快；读者预期管理失败

**判断原则**（基于上下文，非硬性标准）：
- 高潮场景之前，读者积累了多大的情绪？高潮场景之后，读者的情绪被释放了多少？——释放的比例与积累的比例是否匹配？
- 高潮是否有明确的"转折点"——一个让故事从此不同的事件/决定/揭示？
- 如果删掉这个高潮场景，故事的走向会变吗？——如果不会变，说明这个高潮没有改变任何东西
- **铺垫质量前置校验**：先校验铺垫段是否已建立"代价预期"——若铺垫本身未让读者产生"主角可能输"的恐惧，则无论高潮如何执行，优先诊断为 P012 张力不足症，而非 P015

**严重度判断**（结合三维标定表综合评估）：
- L1：高潮场景整体成立但缺乏一个"最高点"的冲击力，加一两处情绪爆发即可
- L2：高潮场景推进但读者没有被"击中"——读者之前积累的期待没有被充分满足
- L3：高潮场景几乎不成立——读者翻完高潮段落没有任何情绪波动，甚至跳过直接看结局

**例外情况**（以下场景通常不是高潮疲软）：
- 有意设计的"反高潮"——如冷静完成复仇而非宣泄式爆发
- 日常向/温馨向作品——高潮本身就是内敛的
- 角色性格决定的"压抑"——一个永不爆发的人，他的"沉默"本身就是高潮

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（典型）**：
> 原文：铺垫了十章：主角练剑、调查、潜入。决战场景：主角走进大殿。对手说："你终于来了。"两人打了一架，主角赢了。走人。
> 判定：P015 L2
> 理由：十章的期待换来几行字的释放——读者积累的情绪完全没有被引爆。

