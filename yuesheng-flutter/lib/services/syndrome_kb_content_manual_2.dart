### P009 角色空心化（含原 P002 角色工具化症状）

> **position_sensitivity**: global

**核心问题**：角色（尤其是主角）缺乏清晰的行为驱动力。可能是动机不足（不知道"为什么"要做某件事），也可能是角色行为完全服务于剧情需要而非内在逻辑（换一个角色剧情依然成立）。两者互为因果——动机缺失是病根，工具化是症状。

**触发信号**：角色行为缺乏内在驱动力的表现；角色行为缺乏动机或前后不一致
> **区分 P018**：P009 是"从未建立"——角色自始至终缺乏可解释其行为的一致动机，行为可被任意同类型角色替代；P018 是"已建立后断裂"——前期有明确行为模式，后期在无铺垫下偏离。若片段无法判断"从未建立"还是"建立后断裂"，看行为是否具备个体化指纹（只有 ta 才会做的事）——无指纹倾向 P009。

**判断原则**（基于上下文，非硬性标准）：
- 读者能否回答"这个角色现在最想要什么？"——如果不能，动机可能缺失了
- 把当前角色换成另一个角色，这段剧情是否还能成立？（如果成立，说明角色被工具化了）
- 角色的重大决定是否有前置积累？（决定去京城之前，是否有"为什么去"的铺垫）
- 角色的行为是否和ta被建立的性格/背景一致？如果不一致，是否有合理的解释？
- 角色在故事中是否有自己的目标、恐惧、执念——还是只为主角服务？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别配角行为逻辑略生硬，或次要角色动机不明确，不影响主线理解，补几句提示或改几句台词即可
- L2：主角的某些关键行为缺乏动机构成，或重要角色多次依赖剧情需要行动，读者开始困惑"ta为什么这么做"
- L3：主角缺乏清晰的目标和欲望，或大部分角色像提线木偶，全程服务于情节推进，读者无法与任何角色建立情感连接

**例外情况**（以下场景通常不是角色空心化）：
- 悬疑叙事中的角色——动机在揭示前故意模糊是叙事策略，读者知道"有事"但不一定需要知道"什么事"
- 日常场景中的功能性行为——"起床/吃饭/出门"不需要每个动作都有深刻动机
- 角色本身的设定就是"迷茫/随机"——这本身就是动机（迷茫是很多角色的合理状态）
- 功能性配角（店员、路人、报信者）——他们的"工具性"本身就是合理的
- 喜剧/荒诞风格中刻意制造的角色机械化——这是风格选择

**诊断锚点示例**（few-shot 参考）：
- **L2 命中（动机缺失）**："他决定去京城。收拾好行李，上了马车，一路向东。三个月后到了京城，找了家客栈住下。" → 读者困惑"他为什么要去京城？""在路上三个月他在想什么？"完全没有前置积累。P009 L2
- **❌ 未命中（动机刻意留白）**："他决定去京城。没有人知道他为什么去，连他自己也说不清。马车一路向东，他在路上反复回想那封只有两行字的信。" → 判定：不触发。理由：动机留白是叙事悬念——那封只有两行字的信牵引着角色，角色有内在的困惑与追问，非工具化行为。

**推荐教学动作**：首选 A003 五问法，备选 A007 一句话冲突

