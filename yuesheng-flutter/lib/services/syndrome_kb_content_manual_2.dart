### P011 对话疲劳症

> **position_sensitivity**: global

**核心问题**：对话占据了过多篇幅，且无区分度、无潜台词、无动作支撑，读者读起来像在看剧本提纲而非完整小说。

**触发信号**：章节被对话填充，角色说话声音无区分，对话无动作环境兜底

**判断原则**（基于上下文，非硬性标准）：
- 去掉所有对话标记和引号后，剩下的文本是否足以让读者知道"发生了什么"？
- 角色的对话——如果不看前面的人名标识——是否还能分清谁在说话？
- 每段对话是否有明确的潜台词（话里有话），还是所有对话都是字面意思？
- 对话之间是否有动作、表情、环境停顿来调节节奏？
- 对话标签是否依赖修饰性副词（「低声说」「呢喃道」）而非动作/表情/语境支撑？同一修饰标签是否反复出现？

**严重度判断**（结合三维标定表综合评估）：
- L1：部分段落对话占比偏高，但角色仍有区分度，压缩 20-30% 对话量即可
- L1：同一修饰性对话标签（如「低声说」）重复出现 ≥2 次，情感全靠标签标注、无动作表情支撑（F02 对话标签过度维度）
- L2：多数章节被对话主导，角色说话声音近似，读者依靠标签才能分辨谁在说话，需要系统性调整
- L3：整章只有对话，无动作描写、无环境描述、无心理活动，阅读体验如剧本纯文字版

**例外情况**（以下场景通常不是对话疲劳症）：
- 剧本/对白主导的文体风格（如话剧剧本）——这是文体选择，不是写作问题
- 法庭剧/审讯场景中的密集对话——功能性需要
- 喜剧中的连珠炮式对话——风格选择
- 叙事中刻意制造的"对话疲惫感"——如果"疲劳"本身就是叙事效果
- 低声密语/耳语场景的功能性需要（偷听、密室、病榻）——密集使用修饰标签合理
- 人物固定的口头式说话方式（如某人永远"冷冷地说"）——若为人物特征而非偷懒，需结合角色塑造判断

**诊断锚点示例**（few-shot 参考）：
- **L2 命中**："'吃饭了吗？''吃了。''去哪？''街上。''和谁？''自己。''几点回来？''不知道。'" → 连续 6 句无意义对话，无名无动作无情绪，读者无法获得任何有效信息。P011 L2
- **L1 命中（F02 对话标签过度）**："'我等你很久了。'她低声说。'我也是。'他低声说。'那就好。'她低声说。" → 3 处「低声说」标签重复，情感全靠标签标注，无动作/表情/停顿支撑。P011 L1
- **❌ 未命中（功能性密集对话）**："'你昨晚在哪？''在家。''有人能证明吗？''没有人。''那你怎么证明你不在现场？''我不需要证明——因为我没有杀人。'" → 判定：不触发。理由：审讯场景的密集对话是功能性需要，且末句带转折冲突（新信息），非无信息量的疲劳堆砌。

**推荐教学动作**：首选 A008 对话瘦身，备选 A006 感官全开

