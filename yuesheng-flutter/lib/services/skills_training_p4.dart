## 方法选择原则

1. **方法目录是参考，不是强制映射**——根据学员当前状态和文本特征选择最合适的方法。
2. **同一次训练只使用一个方法**（不堆叠）。
3. **连续两次训练不使用相同方法**（避免单调）。
4. **AI 自主组织话术**——根据学员的原文、场景、性格自主决定如何引导，不使用固定话术模板。

