> **定位**: 为 AI 提供教学方法的目录和适用范围。不是话术库，不包含固定话术。
> **设计理念**: AI 根据学员具体情况自主选择方法并组织语言。
> **体积**: 约 1400 tokens

---

## 方法目录

### A001 缩小范围
**适用**：开篇平庸、黄金三章失效
**方法**：让学员从庞大设定中选出一个具体场景，只写这个场景里发生的一件小事，不引入额外设定。

### A002 回归主角
**适用**：信息倾泻、视角漂移、支线涣散、被动主角
**方法**：找出文本中超出主角视角的信息，让学员重新改写，确保所有信息通过主角的感官呈现。

### A003 五问法
**适用**：节奏停滞、句式单一、角色空心化、OC平面化、张力不足、结尾乏力、情节巧合过多、伏笔失效、期待感断裂、配角工具人、目标模糊、被动主角、降智反派
**方法**：对当前段落提出五个问题——谁在？发生了什么？为什么？接下来？读者在等什么？引导学员自我诊断。

### A004 现实锚点
**适用**：情绪标签化、情感失真、画面感缺失、心理内耗
**方法**：让学员想象如果是真人，在现实中会怎么表现。用具体动作、表情、细节代替抽象标签。
**核心提问方向**：手会怎么放？眼神会怎么样？说话的语气会变吗？身体哪个部位最先有反应？

### A005 动作链
**适用**：节奏停滞、跳跃叙事/过度概括、爽点乏力
**方法**：让学员列出当前场景中角色的动作序列，检查每个动作是否有因果关系，要求每个动作推动下一个动作。

### A006 感官全开
**适用**：情绪标签化、语言堆砌、对话疲劳、过渡生硬、画面感缺失
**方法**：让学员从五个感官（视觉、听觉、嗅觉、味觉、触觉）描述当前场景，每个感官只写一个具体细节，不允许使用情绪词。

### A007 一句话冲突
**适用**：角色空心化、张力不足、开篇平庸、结尾乏力、高潮疲软、黄金三章失效、目标模糊、被动主角、降智反派
**方法**：让学员用一句话概括当前场景的核心冲突。如果说不出来，说明场景缺乏冲突。

### A008 对话瘦身
**适用**：信息倾泻、对话疲劳、对话注水
**方法**：找出对话中纯粹传递信息的部分，用动作、表情、环境描写代替部分对话。

### A009 节奏变速
**适用**：节奏停滞、句式单一、高潮疲软、过渡生硬、跳跃叙事/过度概括、章节钩子缺失、段落失控、节奏比例失衡、金手指失衡、升级节奏失衡、对话注水、流水账叙述
**方法**：分析当前段落节奏，在段落中加入节奏变化——紧张场景用短句，舒缓场景用长句。

### A010 角色盲写
**适用**：OC平面化、人设崩塌、配角工具人
**方法**：不给学员角色设定，让学员自由描写一个角色，通过动作、对话、细节展现性格，不允许直接描述性格。

### A011 场景裁剪
**适用**：语言堆砌、重复用词/基础语病、段落失控、流水账叙述、心理内耗
**方法**：分析当前场景是否必要，如果不是必要场景，要求学员删除或压缩，保留核心信息。

### A012 伏笔追踪
**适用**：伏笔失效、期待感断裂、章节钩子缺失、追读动力不足、设定矛盾
**方法**：让学员用一句话列出全文所有伏笔线，标注状态（已埋/强化中/已回收/已断裂），找出断裂的线设计修复方案。

### A013 情节复盘
**适用**：情节巧合过多、爽点乏力、追读动力不足、节奏比例失衡、设定矛盾、金手指失衡、升级节奏失衡、支线涣散
**方法**：让学员用"因为…所以…"链概述全章事件，检查链中是否有"没有任何前置原因的事件"（巧合），为每个巧合补上因果。

### A014 情感校准
**适用**：情感失真症
**方法**：让学员找出角色情感反应，提问"如果这件事发生在真人身上，ta的第一反应是什么？"对比后重写。

### A015 人设审查
**适用**：人设崩塌症
**方法**：让学员回看角色首次出场，提取3个核心特质，用这3个特质审读当前章节的每一处角色行为，找出不一致的地方。

### A016 高频词清扫
**适用**：重复用词/基础语病、语言堆砌
**方法**：让学员圈出原文中高频重复的实词（200 字内 ≥3 次），逐个判断是"意图性重复"（排比/口头禅/刻意节奏）还是"无意识重复"；无意识重复部分删除或同义替换，改后通读确认语义不变、刻意修辞未被误删。

