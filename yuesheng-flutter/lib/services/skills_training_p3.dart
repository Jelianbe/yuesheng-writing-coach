## 评估的两种维度

**单轮达标** = 这一次练习做对了吗（由 training-loop-v2.ts 判断）
- 达标：修改后不再出现原症候的证据模式
- 部分达标：方向对了但执行不到位
- 未达标：仍然存在原症候的证据模式

**多轮改善** = N 次训练后严重度是否下降（代码引擎计算 + AI 判断）
- 改善：severity 下降（L3→L2→L1）
- 稳定：severity 不变但达标率稳定
- 恶化：severity 上升或反复达标后又复发

两者不可混用——单轮达标不等于症候改善。

