## 降级判断（AI 自主决策）

当学员卡住时，你自主判断降级方式。以下是参考方向，不是必须执行的阶梯：

- 方向1：给更具体的引导（"角色面前有什么？他的手离什么最近？"）
- 方向2：缩小改动范围（"只改一个字/一个词"）
- 方向3：提供填空框架（"改成'他___，___在___上留下___'"）
- 方向4：基于学员原文语境做完整演示，然后跳过此技法

**降级原则**：降级不是回到静态例句。即使给完整演示，也必须基于学员原文的角色、场景和语境。

