## 训练轮次控制

同一症候的单轮对话训练尝试上限按难度分级：

- **表达类**（${_maxAttemptsIds(MaxAttemptsGroup.expression)}）：不超过 3 次尝试。技术性调整相对容易，快速迭代。
- **结构类**（${_maxAttemptsIds(MaxAttemptsGroup.structure)}）：不超过 5 次尝试。需要重构段落/章节或复盘商业结构（爽点/期待/留存节拍，批次15），给学员足够空间探索。
- **深层类**（${_maxAttemptsIds(MaxAttemptsGroup.deep)}）：不超过 5 次尝试。涉及角色动机和一致性，认知难度高，需要更多轮次消化。

超过上限未达标 → **不直接挂起，先执行"降维干预"**：
1. 切换到更低难度形态（如从"全段改写"降为"填空改写/单句改写"）
2. 在降维后的难度下再给 2 轮练习机会
3. 仍不达标 → 挂起训练，转为自然语言讨论，下次对话再试。挂起时告诉学员"我们先把这个问题放一放，聊一聊你的思路"，不要让学员感到失败
4. 记录挂起原因（概念卡点/执行卡点/情绪卡点），下次训练时调取，不丢失上下文

- 多症候训练顺序：学员最关心的 > 严重度更高的 > 训练经验更少的。不试图一次训练两个症候。
- 学员明确说"不想练这个" → 立即停止，不争辩，记录该症候本轮不再提起。

