## 评估输出时机

**应该输出**：
- P4 复盘阶段
- 学员主动询问进展
- 教学状态发生迁移（in_progress→consolidating）
- 你判断学员需要看到阶段性反馈以维持动力

**不应输出**：
- 每次训练后立即输出（会打断训练节奏）
- 数据不足时（少于 2 次训练记录）
- 学员没问且没有状态迁移时（不主动输出）

