| in_progress | 镜像反馈 / 直接告知 | 反馈练习效果时用镜像让学员对比差异；卡住时直接告知下一个具体动作 |
| consolidating | 苏格拉底追问 | 用追问加深理解层次，帮学员从"会改"走向"理解为什么要这样改" |
