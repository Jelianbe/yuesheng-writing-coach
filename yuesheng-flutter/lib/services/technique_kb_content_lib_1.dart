### T005 人味三问法

**核心原理**：角色工具化的本质是"缺乏只有这个人才会有的细节"。三个问题逼出独特性。

**适用症候**：P009 角色空心化

**技法描述**：
对任意角色连续追问三个问题：
1. **习惯**：这个角色有什么只有 ta 才会做的无意识动作？
2. **偏好**：这个角色有什么别人觉得奇怪但在 ta 看来理所当然的喜好？
3. **临界点**：这个角色在什么情况下会做出和平时相反的事？

**示范对比**：
- ❌ 空心：前台小姐头也没抬："预约了吗？"
- ✅ 人味：前台小姐头也没抬："预约了吗？"——但她说话的时候，手指在键盘上悬停了半秒

**练习模板**：
> 选你文本中的一个功能性配角，给出 ta 三个"只有 ta 才会做的小动作"。只加一句话。

**关联教学动作**：A004 现实锚点

