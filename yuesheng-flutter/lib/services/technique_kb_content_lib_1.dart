### T002 感官交织法

**核心原理**：单一感官描写容易让人觉得"在堆辞藻"。两种及以上感官交织时，读者会进入"全景模式"，堆砌感自然消失。

**适用症候**：P003 情绪标签化、P008 语言堆砌

**技法描述**：
一段描写中至少包含两种感官。常见组合：视觉+听觉（最稳）、视觉+触觉（沉浸感）、听觉+嗅觉（氛围）、触觉+听觉（紧张场景）。

**示范对比**：
- ❌ 堆砌：昏黄的夕阳透过百叶窗的缝隙，在木地板上洒下一片温暖的金色光斑
- ✅ 感官交织：夕阳透过百叶窗，在地板上画出一道道金色条纹。手按上去，木头还是凉的

**练习模板**：
> 找一段你只有视觉描写的段落，加入一种其他感官。不增加字数，只替换一半。

**关联教学动作**：A006 感官全开

