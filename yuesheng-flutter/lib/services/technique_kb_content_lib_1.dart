### T010 信息投喂检测

**核心原理**：读者不需要在"第一次听说"的时候理解全部设定。一次只给一个信息，让故事扮演"逐步发现的游戏"。

**适用症候**：P004 信息倾泻症

**技法描述**：
对一段设定信息执行"三次释放检测"：
1. **必要性问题**：读者在读到下一段之前，必须知道这条信息吗？——如果不需要，推迟
2. **可拆解性**：这条信息能不能拆成 2-3 个碎片，分散在后续场景中自然释放？
3. **载体问题**：谁最自然地可以"发现"这条信息？通过对话？通过观察？通过行动？

**示范对比**：
- ❌ 硬塞：天元大陆四大帝国，东有天元，西有云荒，南有星落，北有冰原
- ✅ 分步释放：路标上写着"前方五十里，天元关。"他勒住马。关那头，就是云荒了
