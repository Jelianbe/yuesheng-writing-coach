### T004 角色独白检测

**核心原理**：角色是否工具化，把他扔进一个与主线无关的场景就知道了。

**适用症候**：P009 角色空心化

**技法描述**：
把当前角色放进一个与故事主线无关的独立场景（如"超市排队"/"等公交"/"下雨没带伞"），然后问三个问题：
1. 他会做什么？
2. 他有什么反应和其他人不一样？
3. 他的反应和主角在这个场景的反应是否不同？

如果三个答案都是"普通人的正常反应"，角色就太工具化了。

**示范对比**：
- ❌ 无差异："被雨淋了，他会赶紧找地方躲雨"
- ✅ 有差异："被雨淋了，他就在雨里慢慢走，不躲。他喜欢雨打在皮肤上的感觉"

**练习模板**：
> 把你的角色放进一个与主线无关的场景（下雨没带伞/排队结账/电梯坏了），写 50 字。如果反应和"任何人"都一样，重新想。

**关联教学动作**：A004 现实锚点、A010 角色盲写

