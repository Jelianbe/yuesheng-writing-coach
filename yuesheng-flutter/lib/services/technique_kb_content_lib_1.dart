### T009 欲望三层法（含场景动机锚定应用）

**核心原理**：角色的动机是分层的。表面动机不够驱动读者，深层动机才是一个角色的"为什么"。

**适用症候**：P009 角色空心化

**技法描述**：
为角色挖掘三层欲望：
- **表面层**：角色说自己想要什么
- **中间层**：角色真正想要什么（可能自己都没意识到）
- **深层层**：角色害怕什么（恐惧比欲望更驱动人）

逐级推入：角色说"我要去京城"（表面）→ 因为他想离开这个地方（中间）→ 因为他害怕被困在父亲的人生里（深层）。

**示范对比**：
- ❌ 无动机：他决定去京城
- ✅ 三层驱动：他决定去京城。不是因为那里有什么，而是因为这个城市已经让他喘不过气来了

**练习模板**：
> 为你主角当前的选择写下三层欲望。如果第三层（恐惧）写不出来，说明角色的动机还不够深。

**关联教学动作**：A003 五问法、A007 一句话冲突

