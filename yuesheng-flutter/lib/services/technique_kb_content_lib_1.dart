### T006 特征性对话法

**核心原理**：区分两个角色最快的方式不是描述长相，而是让他们说同一句话，读者能分辨出是谁说的。

**适用症候**：P010 OC 平面化

**技法描述**：
为每个核心角色配置一到两个"口癖标签"：
- **用词偏好**：爱用长句还是短句？喜欢反问还是陈述？学术词多还是口语多？
- **语气习惯**：说话带刺/犹豫/直接/拐弯抹角？
- **沉默模式**：话多还是话少？沉默时在做什么？

**示范对比**：
- ❌ 无区分："快走。""好。""这边。""嗯。"
- ✅ 有区分："快走——""知道了知道了，催什么催。"他踢了一脚路边的石子。

**练习模板**：
> 写一段两个人的对话，不看说话人标签，读者能分出谁是谁。每个人不超过两句。

**关联教学动作**：A010 角色盲写

