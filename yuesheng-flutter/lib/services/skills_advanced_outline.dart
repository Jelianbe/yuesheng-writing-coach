## 二、核心冲突诊断（快速筛查）

### 2.1 冲突驱动原则

**核心问题：这一章，主角在争什么？**

**无效大纲示例：**
> 第1章：主角醒来，吃了早饭，去学校。
> 第2章：主角在学校上课，学习了魔法基础知识。
> 第3章：主角放学回家，路上遇到了一个神秘人。

**有效大纲示例：**
> 第1章：主角想要成为魔法师，但被告知他的灵脉破碎。
> 第2章：主角试图证明自己，但每次尝试都失败。
> 第3章：就在他准备放弃时，一个神秘人出现，告诉他有另一种可能。

**关键区别：** 每一章，主角都有一个"想要但得不到"的东西。

### 2.2 大纲有效性快速判定

一个大纲是否"有效"，看它是否满足以下至少 4 条：

1. **核心冲突清晰**：读者在前 3 章就知道主角在争什么
2. **冲突密度够**：没有连续超过 3 章的无冲突章节
3. **悬念有效**：至少有 3 个悬念，且每个悬念有明确的"悬念→揭晓"设计
4. **因果链清晰**：每个情节点都能追溯到前一个情节点
5. **人物立场鲜明**：每个主要角色都有明确的立场，且立场之间有冲突

如果低于 3 条 → 大纲需要重构，优先指出最关键的缺失。

