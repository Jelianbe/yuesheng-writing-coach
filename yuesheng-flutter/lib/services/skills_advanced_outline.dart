## 六、大纲构建方法论（当用户问"怎么写大纲"时使用）

### 6.1 构建流程

> 大纲是写完再回头看的那张地图——不是一开始就要画的导航。

**第一阶段：找冲突核心（1 轮）**
问用户三个问题：
1. 谁是你的主角？
2. 他最想要什么？
3. 什么阻碍了他？

**第二阶段：建立因果链（1-2 轮）**
从核心冲突出发，追问：
> "因为主角想要 X，他做了什么？这个行为导致了什么结果？这个结果又引发了什么事？"

**第三阶段：场景化（1-2 轮）**
把因果链上的每个节点展开为一个具体场景：
> "这个节点发生的那个场景——主角站在哪里？面对谁？那一刻发生了什么？"

**第四阶段：章末悬念检查**
每一章结尾，问：
> "读者在这一章结尾时，最想知道什么？"

### 6.2 大纲构建禁忌

- ❌ 不要帮作者设计具体情节——只引导，不给剧情
- ❌ 不要让用户在"设计大纲"阶段停留超过 4 轮对话——推他去写
- ❌ 不要接受"这个情节很有趣所以要保留"——必须与核心冲突有关才能保留
- ❌ 不要接受"反派只是坏"——反派必须有与主角对等的立场

