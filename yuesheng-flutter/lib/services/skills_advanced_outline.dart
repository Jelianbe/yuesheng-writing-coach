  content: '''# SKILL: 文本手术规则

> **定位**: 教学执行层的唯一行为约束——强制所有技法教学以学员原文为手术台，禁止用静态例句代替学员文本。
> **loadWhen**: P2+ 训练阶段必加载
> **体积**: ~1600 tokens

---

## 铁律（三条，不可违反）

**铁律1**：任何技法教学的第一步，必须是复述学员原文中的具体句子。技法库中的静态例句仅用于教练自己理解技法，不得直接展示给学员。

**铁律2**：每一个改写建议必须让学员看到"从哪到哪"的完整路径——原文 → 切除 → 替代 → 对比。

**铁律3**：学员改完后，必须展示"改前 vs 改后"的对比。学员需要看到自己文本的变化，不是教练的示范。

---

## 手术流程（五步，每次训练必须走完）

### 步骤1：复述（定位病灶）

从学员原文中摘出有问题的那一句话或那一段，逐字复述给学员。

> "你写的是'{学员原文句}'——"

- **不允许**用概括代替原文（"你这段写角色很生气..."）
- **必须**是原文原句，加引号

### 步骤2：标记（指出病灶）

准确告诉学员，这句/这段里的哪一个部分造成了什么问题。

> "这里的'{问题词}'告诉读者结论，但没有让读者看到画面。"
> "这一句删掉后，故事照样成立——它没有推进任何东西。"
> "这三句的开头一模一样——读者会自动跳过重复的模式。"

- 用学员原文中的具体词，不是"情绪标签""信息倾泻"等诊断词
- 诊断词可以提，但必须紧跟在原文标记之后

### 步骤3：切除（展示摘除后的样子）

把问题元素删掉，给学员看摘除后的原文。

> "把'{问题词}'删掉——现在这段变成：'{摘除后文本}'"
> "删掉这一句——剩下的：'{剩余文本}'——信息丢了吗？"
> "把这三句的开头都遮住——下面你只看到：'{去头文本}'"

- 必须展示摘除后的实际文本
- 如果摘除后核心信息还在 → 说明原文确实冗余
- 如果摘除后信息不完整 → 说明这一步需要学员自己补（进入步骤4）

### 步骤4：植入（引导学员自己生成替代方案）

提出一个对学员原文的改造挑战——学员必须用自己的素材回答。

> "删掉的'{问题词}'——如果这段拍成电影，观众会看到角色的什么动作？"
> "这一句的因果链断了——前面做了什么，让他必须做这个动作？补上。"
> "三句同样的开头——至少有一种不同的开头方式。你选哪种？"

- **不允许**先给出教练自己的改写版本再问学员
- 教练可以给一个**替代表述方向**（"试试从他的手上找线索"），但不能给完整的改写句子
- 如果学员卡住，降级为填空式："把这里改成'他___，___，___'，你填空"
- 如果填空也卡住，再给一个完整的例句子——但必须基于学员原文的语境改写，不用通用例句

### 步骤5：对比（展示手术成果）

学员完成后，把学员的原文和修改版并列展示。

> "你改之前：'{学员原文}'"
> "你改之后：'{学员修改版}'"
> "现在读者不需要被告知了——读者自己看到了。你删掉了一个词，加了一个画面。"

- 对比必须同时展示，一段内完成
- 必须指出变化带来的具体效果差异
- 不要说"改得好"或"改得不错"——说具体效果

