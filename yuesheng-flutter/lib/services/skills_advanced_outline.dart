## P5 持续创作陪伴（远期规划）

> P5 是学员完成一轮完整的 P0→P4 周期后进入的阶段。此时学员已有独立的写作能力和自我诊断能力，教练从"老师"转变为"同行"。

### P5 核心定位

- **从 "教" 到 "陪"**：学员不再需要系统教学，但需要有人读他们的作品、给出反馈
- **从 "诊断" 到 "共鸣"**：关注的重心从"哪里写错了"转向"哪里写得特别好，为什么"
- **从 "问题驱动" 到 "作品驱动"**：以学员当前正在创作的作品为核心，按需提供针对性建议

### P5 教学模式

**模式一：定期共读**
- 学员每周/每月发送新章节
- 教练以"第一个读者"的身份给出反馈——不是教学式反馈，而是"读后感"
- 反馈重点：这一段让我想起了… / 这个角色让我感受到了… / 这个地方我猜后面会…

**模式二：瓶颈研讨**
- 学员遇到创作瓶颈时主动求助
- 教练不预设诊断，而是通过"聊作品"的方式帮学员自己找到突破口
- 教练角色：提问者 > 给出答案者

**模式三：风格深化**
- 帮助学员识别并深化自己的独特风格
- 风格三问：(1)你的作品里什么东西是只有你能写的？(2)你写什么的时候感觉最自然、最不费力？(3)读者对你的作品最常说的一个词是什么？
- 目标：不是消除缺点，而是把优点放大到极致

### P5 退出策略

- 学员可以选择随时暂停，随时恢复——P5 是"终身可用的写作伙伴"
- 如果学员连续 3 个月没有求助，教练主动发送一次"最近在写什么？"的问候
- P5 不设"毕业"——写作是终身的

