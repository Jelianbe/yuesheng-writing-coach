## 四、诊断维度详解

### 维度 1：核心冲突清晰度（最重要，权重 30%）

**判断问题：**
- 读者在前 3 章就知道主角在争什么吗？
- 核心冲突是什么？对抗力量是什么？
- 主角的目标和阻碍是什么？

**病灶表现：** 核心冲突太晚出现（前 5 章还在铺垫）、冲突太模糊、冲突太简单没有"不得不"的张力

### 维度 2：冲突密度（权重 25%）

**判断问题：**
- 连续无冲突章节最多有多少章？
- 每个冲突的解决是否带来局面变化？
- 是否有过长铺垫（>3 章）？

**病灶表现：** 连续 3 章以上无有效冲突、冲突解决后没有新冲突接上、铺垫与冲突比例失衡

### 维度 3：因果链清晰度（权重 20%）

**判断问题：**
- 每个情节点能追溯到核心冲突吗？
- 角色决定有充分动机吗？
- 情节之间有必然联系吗？

**有效因果示例：** 因为 A 所以 B → 因为 B 所以 C → 因为 C 所以 D

**无效因果：** B 在 A 之后发生，但 A 不是 B 的原因。

**因果链检测法：** 从最后一个情节点往前推，问"为什么"，如果能追溯到核心冲突 → 有效。

### 维度 4：悬念有效性（权重 15%）

**判断问题：**
- 每章结尾的悬念是什么？
- 悬念与核心冲突有关吗？
- 揭晓悬念后是否有新悬念接上？

**悬念类型：** 核心悬念（贯穿全书）、章节悬念（每章结尾）、小悬念（具体情节疑问）

**规则：** 每章最多 1 个主要悬念、悬念必须与核心冲突有关、揭晓后必须有新悬念接上、不要在一个悬念还没揭晓时引入太多新悬念

### 维度 5：节奏设计（权重 10%）

**核心公式：** 好节奏 = 冲突密度 × 变化幅度

**节奏类型：** 快节奏（冲突密集变化大，适合爽文/冒险）、慢节奏（冲突稀疏但深刻，适合文学/情感）、张弛有度（冲突-缓冲交替，适合大多数类型）

**禁忌：** 超过 3 章的纯粹铺垫、全程高能（没有低谷 = 没有高潮）、没有变化的重复冲突

