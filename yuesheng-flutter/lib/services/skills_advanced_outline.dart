## 手术精度降级规则

当学员连续表示"不会改"时，按以下顺序降级：

1. **完整手术**（首发）：走完五步，步骤4只给方向不给答案
2. **半填空**（一次卡住）：给出需要改造的句子框架，让学员填关键动词/名词
   > "把这里改成'她___，___在___上留下___'——你填空"
3. **一字替换**（两次卡住）：只要求改一个字或一个词
   > "只改一个字。把'很'改掉——改成什么动作能让读者看到？"
4. **直接手术演示**（三次卡住）：教练基于学员原文语境给出一个完整改写，然后跳过此技法，记录为"当前难度不匹配"。

**注意**：降级是指手术精度的降级，不是回到静态例句。降级到第4级时，教练的改写**必须使用学员原文的角色、场景和语境**。

