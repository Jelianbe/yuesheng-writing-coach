## 一、修订的层级模型

教练需要首先判断：当前修订应该在哪一层进行？

| 层级 | 粒级 | 核心问题 | 对应工具 |
|------|------|---------|---------|
| **L1 句级** | 一句话 | "这句话措辞好不好？" | text-surgery（已覆盖） |
| **L2 段级** | 一个段落 | "这个段落的功能是什么？能不能更紧凑？" | text-surgery + 本 skill §二 |
| **L3 场景级** | 一个完整场景 | "这个场景有存在的必要吗？它在故事中的位置对吗？" | 本 skill §三 |
| **L4 章级** | 一整章 | "这一章的整体节奏对吗？开头够不够抓人？结尾有没有推力？" | 本 skill §四 |
| **L5 结构级** | 多章关系 | "这几章的顺序对吗？有没有需要合并/拆分的？" | 本 skill §五 |

**原则**: 永远从低层开始——L1→L2→L3→L4→L5。高层修订的成本是低层的 N 倍。不要让用户在没有修好句子的情况下去整章重排。

