## 四、章级修订（L4）

### 4.1 "逆纲法"——最高效的章级诊断工具

**操作**: 让用户不要看自己写的那一章正文，而是用一句话概括这一章从头到尾发生了什么。

> "不要看你的正文。凭记忆——这一章从头到尾发生了什么？一句话。"
> （用户回答后）
> "好。现在对照你的正文——你记住的这句话，和正文里实际发生的事一样吗？"
> "- 如果你记住的版本更短——说明正文里有东西是冗余的。那些你没记住的，读者也不会记住。"
> "- 如果你记住的版本和正文不一样——说明你写出来的和你想要的不一样。"

### 4.2 章节开头与结尾的"读者实验"

**开头**：
> "用陌生的眼光看你的章首第一段。假设你不知道这个故事的设定——只看这一段，你知道：①谁？②在哪？③发生了什么事？——如果三个问题有一个答不上来，这个开头信息不全。"

**结尾**：
> "这一章的最后一句话——读完之后，你（作为读者）有没有一种'立刻想看下一章'的冲动？"
> "如果没有——最后一句话可能收了太死了。试着删掉最后一句，或者换成一句没有回答的问题、一个还没完成的动作。"

### 4.3 整章节奏感觉

> "用三个词形容这一章的节奏感觉。（用户回答）——好。现在看你的正文，节奏有没有和这三个词匹配的地方？有没有不匹配的地方？"
> "这一章里——有没有哪个部分你写着写着'慢了'？不是情节慢，是你作为作者写得慢——反复修改、犹豫、加东西。这种地方往往就是读者也会慢下来的地方。"

---

## 五、结构级修订（L5）

### 5.1 多章关系诊断

**适用**: 用户有 ≥3 章的完整稿。

**"功能链"检查**：
> "把每一章用一句话命名——不是标题，是'这一章的功能'。比如'主角第一次失败''主角发现自己被骗''主角做选择'。"
> "排在一起看——两章之间的功能有没有重复？两章在做完全一样的事？"
> "有没有哪一章的功能在你列出来之后，你看着它觉得'这个功能好像可以合并到前一章'？"

### 5.2 章节顺序的"必要性测试"

> "如果我把你的第 2 章和第 4 章换了位置——故事还能不能讲？"
> 如果能 → 这两章之间没有因果依赖关系。可能不是结构问题——但如果能换，说明"先知道X 和 后知道X"对读者体验没有区别。那你希望读者**先**知道什么？

### 5.3 大删大改的教练策略

最难的教练场景：用户需要删掉一整章或重写一半内容。此时：

> "不用现在就决定删不删。先做一个实验：你假装这一章不存在——从上一章的最后一句，直接跳到下一章的第一句。读一遍。故事有没有断？有没有缺了什么东西？"
> "如果没断——你把这一章的内容里，最重要的那一两句话找出来，看看能不能塞到前一章或后一章里。剩下的，放进去只会增加篇幅。"

**原则**: 永远不要说"删掉"——让用户**假装删掉试试看**。一旦用户自己尝到了"没有这一章也行"的体验，"删不删"就不再是教练的决策，而是用户自己的。

