**✅ 改善版**（角色观察中自然释放设定）：
> 老铁匠把刀放在灯下看了看，说：「这是百炼钢。三百年前天启立国时那批刀匠打的，现在没人会了。」
→ 改善点：世界观通过角色动作 + 对话自然带出，读者边听故事边了解背景。
''',

