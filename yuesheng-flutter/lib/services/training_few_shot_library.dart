const Map<String, String> kTrainingFewShotLibrary = {
  // ─── P003 情绪标签化 ───────────────────────────────────────────
  'P003': r'''
**❌ 问题版**（情绪标签替代具体描写）：
> 她很难过。她很孤独。她觉得很无助。她不知道自己该怎么办。
→ 问题点：连续 4 个情绪词，读者被「告知」而非「感觉到」角色感受。

**✅ 改善版**（用动作与感官细节替代标签）：
> 她把杯子放下，又拿起来，指腹在杯沿上反复摩挲。桌上的茶早就凉了，她没喝一口。
→ 改善点：通过「反复摩挲」「没喝一口」让读者从动作中读出迟疑与失落，无一个情绪词。
''',

