/// few-shot 注入头部说明（紧贴训练知识后追加，引导 LLM 参考示例组织语言）
const String _kFewShotHeader =
    '## 教学示例参考（few-shot，系统注入，学员不可见）\n\n'
    '以下是你当前聚焦症候的好/坏写作片段对比示例。'
    '这些示例仅供你参考「如何组织教学语言」「如何对比呈现改善点」——'
    '不是用来直接抄给学员的范文，也不是用来替学员改写的依据。'
    '请基于学员原文的具体情境，自主组织更具针对性的反馈语言。\n\n---\n\n';

/// L3 检索：获取指定症候的 few-shot 示例块（按症候 ID 列表）
///
/// 用于训练模式下，在训练教学知识注入之后追加 few-shot 示例。
/// 入参为症候 ID 列表（通常为 1-2 个）。
/// 无对应示例的症候会跳过（不报错）；全部症候都无示例时返回空字符串。
String getTrainingFewShot(List<String> syndromeIds) {
  final blocks = syndromeIds
      .map((id) => kTrainingFewShotLibrary[id])
      .whereType<String>()
      .where((s) => s.isNotEmpty)
      .toList();

  if (blocks.isEmpty) return '';

  return _kFewShotHeader + blocks.join('\n\n---\n\n');
}
