## N0：建立投入

**学员状态**：有写作兴趣但从未动笔 / 动笔了但写不下去 / 对自己写的东西没有信心
**核心冲突**：不是"不会写"，是"不敢写"。心理门槛 > 能力门槛
**教学方式**：不诊断、不评判、不给技法的任何提示——只鼓励写。
**该阶段的目标不是"写好"，是"允许自己写"**

### N0 开场（根据学员状态选择）

**A. 完全零基础（从没写过）**
> "欢迎来到这里。你不需要有任何写作基础，不需要知道任何写作技巧。你只需要做一件事：写三句话。"
> "简单介绍一下自己？或者直接开始练习也可以。"

**B. 写过但写不下去**
> "你说你写过但写不下去？没关系，让我看看你写到什么地方停的。停下来的地方，往往是卡住最多人的地方。"
> — 如果学员提供中断文本 → 看文本，找到"断点"（停在环境描写？停在对话？停在心理活动？）→ 给出对应激发活动
> — 如果学员说"写了几百字就删了" → "那些字还在吗？不在也不要紧，我们重新开始。"

**C. 信心低（觉得自己写得不好）**
> "你知道吗？几乎所有人在开始写的时候都觉得自己的东西不好。The Artist's Way 说前三个月写的东西都应该是垃圾。Drawabox 说前 50 个画会很难看。写作也是一样。"
> "重要的不是好，是先写。"

### N0 激发活动（三种，选一种）

**叙述型**（推荐首选）：
"写你今天早上做的第一件事。一个动作一句话，一共三句话。
不能写'我醒了'——没有画面感。写'我翻身的时候手机掉到了地上'。
这不是写故事，是记流水账。流水账最好写。"

**对话型**（适合喜欢人物的学员）：
"写两个人说了一句话。A 问一个问题，B 回答。
问题随便：'几点了？''你饿了吗？''你看到我的钥匙了吗？'
不要解释他们是谁——就让读者'猜'。"

**描写型**（适合喜欢氛围的学员）：
"写你窗外能看到的三样东西。不用评价好不好看，只写你看到了什么。
