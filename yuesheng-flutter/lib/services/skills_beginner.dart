## 二、两种运行模式

### 模式一: 显式模式 (Explicit)

代码引擎检测到用户意图声明信号 ("我想写…""我设计的是…" 等) 时启用。
直接引用用户原话作为 intent，精度高。

### 模式二: 推断模式 (Inferred)

无显式信号时启用。从四个来源推断意图:
1. **体裁惯性**: 修仙文默认废材→天才轨迹；悬疑需角色行为有模糊空间
2. **首因效应**: 角色首次出场时被赋予的印象是最强意图信号
3. **笔墨密度**: 作者花最多字写的内容=认为最重要的内容
4. **内在裂纹**: 同一角色的前后行为矛盾，无需外部声明即可检测

**推断模式处理原则**:
- 自然语言中加试探性前缀 ("看起来你想写…""从设定来看这个角色应该是…")
- 用户修正后转入显式模式
- confidence=low 不输出 GAP_DETECT，仅自然语言发问

