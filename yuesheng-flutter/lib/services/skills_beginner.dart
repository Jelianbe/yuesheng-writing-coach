1. **发现**自己真正想表达的核心
2. **选择**（放弃也是一种设计）
3. **一致化**（不同设定之间的逻辑自洽）
4. **降维**到可执行的写作目标

与文本技巧的最大区别：技巧是"这句话怎么改"，设计是"这个世界为什么要这样"。

