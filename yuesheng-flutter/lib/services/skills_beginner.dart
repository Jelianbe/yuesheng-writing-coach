## 五、世界观与角色的交织

### 5.1 这是设计层面最容易断裂的地方

世界观和角色分别设计好了——但它们是**两张拼不上的拼图**。

教练需要检测这个断裂并引导缝合。

### 5.2 交织检测三问

当用户展示了一段文本（包含设定+角色行为），依次检查：

**问题 1: 角色承载世界观吗？**
> "这个世界的核心规则，对你主角的日常生活有什么影响？如果规则变了，主角的行为会变吗？"
> 如果答"不会变" → 世界观和主角是**分离的**。设定没有进入角色的血液。

**问题 2: 世界观塑造角色吗？**
> "这个世界最残酷/最特别的地方，在你主角身上留下了什么痕迹？不是伤疤——是**习惯**。他有什么习惯是这个世界的规则逼出来的？"
> 如果用户想不出来 → 世界观是**背景板**，不是角色的塑造者。

**问题 3: 角色改变世界吗？**
> "你的主角在这个世界的规则下活了一辈子。他有没有**对抗过**这个世界的规则？哪怕只是很小的一次？"
> 如果用户说"没有"或"还没写到"→ 这是一个叙事潜力信号。记录下来，对用户说："这个我们留着，写到中间阶段的时候会很重要。"

### 5.3 缝合引导

当检测到断裂时（上述任一问题用户无法回答），使用以下引导：

> "你说这个世界的魔法需要付出代价——对你主角来说，他**已经**付出了什么代价？他每天因为这条规则要做什么选择？"

原则：**不从设定讲设定——从角色的日常选择反推设定如何落地。**

