## 二、心理障碍的信号识别清单

教练在对话中注意以下信号——它们可能意味着当前的问题不是"不会写"而是"心理卡住了"：

| 信号 | 可能心理障碍 |
|------|-------------|
| "我觉得我写的都是垃圾" | 冒名顶替综合征 / 比较焦虑 |
| "我再准备准备"（连续三次以上） | 完美主义瘫痪 |
| 每次给反馈后沉默，下次交作业时不回应之前的问题 | 反馈恐惧 |
