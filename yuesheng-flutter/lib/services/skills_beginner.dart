## 一、六大常见写作心理障碍

### 障碍 1：完美主义瘫痪

**信号**：
- 每次动笔前要"准备充分"——但这个准备永远不结束
- 反复修改同一段，永远觉得"还不够好"
- "等我准备好了再开始写"说了三个月
- 写了几百字后全部删掉，因为"方向不对"

**根源**：作品在头脑中是完美的，但落到纸上必然是残缺的——学员不能接受这个落差。

**教练应对**：

**第一步：降低行动门槛**（不是降低质量标准）
> "你不需要一次写对。你就先随便写——写错了我们改。改比从零写容易一百倍。"

**第二步：设置"允许写差"的显式许可**
> "我允许你这一轮写得差。不是降低要求——是'第一稿的任务就是存在'。你先把字弄出来，我们后面有的是时间让它变好。"

**第三步：用过程替代评判**
> 不要问"你觉得这段写得好吗？"→ 问"这段里哪句话你自己比较喜欢？"

**第四步：展示"大师的草稿"心理**
- 很多学员以为好作家一气呵成——不知道海明威改《永别了，武器》的结尾改了47遍
- 教练分享："你喜欢的作家也不是第一稿就写好的。写作就是改出来的。"

**关键判断**: 如果学员能写出来但不敢写 → 完美主义瘫痪。如果学员写不出来 → 可能是写作障碍（障碍 3）或能力问题。

---

### 障碍 2：冒名顶替综合征

**信号**：
- "我写了这些，但我觉得这不叫'写作'"
- "XX才是真正的作家，我就是随便写着玩的"
- 对自己的作品过度贬低
- 不好意思自称"作者"或"写手"

**根源**：学员内心有一个"真正的作家"的形象——通常是已出版/成名/写得好的作家——认为自己不配。

**教练应对**：

**第一步：重新定义"作家"**
> "你在写，你就是作者。'作家'不是出版之后才有的身份——是你决定坐下来写的那一刻就有了。"

**第二步：用证据反驳"不配"**
> "你说你觉得这不是'真正的写作'——但你写了五万字，有完整的角色和情节，有读者在读。一个'不真正的作者'做得到这些吗？"

**第三步：分离"身份"和"水平"**
> "你是不是把'我还不够好'和'我不配'搞混了？前者是客观判断——每个人都在变得更好的路上。后者是自我否定——它不让你往前走。"

**第四步：不要用"你很好"敷衍**
冒名顶替者不会相信模糊的赞美。她们需要的是具体的、不可辩驳的证据——"你写的这段对话，我在读的时候真的被逗笑了。这不是你'觉得'的东西——这是已经发生的事实。"

---

### 障碍 3：写作障碍（空白页恐惧）

**信号**：
- 坐在空白文档前很久，一个字也打不出来
- "脑子里有画面但写不出来"
- 开头反复重写但永远写不到第二章
- 越拖越焦虑，越焦虑越写不出来——恶性循环

**根源**：从"想法"到"文字"的翻译通道被堵住了——可能是完美主义、可能是缺乏工具箱、也可能单纯是太久没写，手生了。

**教练应对**：

**第一步：绕开闸门**（不要求"写作品"）
> "先别写故事。你就用一句话告诉我——你最想写的那一幕，你在脑子里看到的是什么画面？"
> → 学员说了之后："好，把你刚才说的那句话打出来。对，就刚才那句话。这就是你的第一行。"

**第二步：十分钟限时写**
> "我给你十分钟。十分钟内，你不需要写出好的东西——你只需要写出东西。写完后不准删。十分钟后发给我，我来看。"
> → 计时是一个神奇的工具——它把"创作"变成"任务"，绕过完美主义的审查

**第三步：先写中间**
> "别从开头写。直接写你最想写的那一幕——不管它在第几章。你不需要知道'怎么到这里'。你就写这一场戏。"
> → 开头是最难的——因为作者还不知道故事长什么样。从中间写，等中间写好了，开头自然知道怎么写了。

**第四步：如果以上都不行——口述**
> "你把你想写的讲给我听。就当你在跟一个朋友讲一个故事。我们来录音——你说，然后我帮你整理成文字。"
> → 口 → 笔的通道通常比大脑 → 笔的通道畅通得多

---

### 障碍 4：比较焦虑

**信号**：
- "我看完XX的作品后觉得我写的全是垃圾"
- 频繁提到某个比自己强的作者或作品
- 在读了好作品后更加沮丧而不是受启发
- 用自己的草稿对比别人出版的成品

**根源**：学员在用别人的"完成品"和自己的"进行时"比较——这是不公平的比较。

**教练应对**：

**第一步：让比较变公平**
> "你在拿你刚写的第一章对比人家改了三年的出版稿？——这不叫比较，这叫自残。你想比较可以——把人家第一稿拿出来比。但你拿不到。所以你只能跟你自己上一个月的版本比。"

**第二步：把嫉妒变为教材**
> "你说你看完XX后觉得自己很差——那具体是哪一段让你这么觉得？我们来看看ta那段厉害在哪里。不是'ta比我好'，是'ta做对了什么'——你把那个东西偷过来。"

**第三步：建立自己的进步标尺**
> "不看别人写了什么。就看你自己——一个月前你写的和你现在写的。来，我们把两段放在一起。你能看出变化吗？"

---

### 障碍 5：反馈恐惧

**信号**：
- 作品写完了但不敢给人看
- 得到负面反馈后极度沮丧，可能需要数天才能恢复
- 把教练的每一条建议都理解为"我写得不够好"
- 发布作品后每隔五分钟刷新看评论，一条负面评论毁掉一整天

**根源**：学员把"对作品的反馈"等同于"对自我的评判"。作品 = 自我延伸，批评作品 = 批评我。

**教练应对**：

**第一步：脱钩**
> "我给你的每一个建议都不是在说你不好。我是在说——你已经到这一步了，我们还能再往前一步。"
> 用"我们"——让学员和教练站在同一边面对问题，而不是教练站在对面评判。

**第二步：给反馈加"比例"**
> "这段有三个地方我想跟你讨论。但先让我说——这段的整体感觉特别对，尤其是中间那一段对话。所以我们只需要调三个点——其他都是好的。"
> 不能让学员的注意力只集中在需要改的地方。

**第三步：正面反馈要具体**
> 不要说"这段不错" → 说"这里的'他伸手摸了摸杯子，没有喝'——就这个动作，我能感觉到他在想事情但说不出口。这就是好的写作。"

**第四步：处理负面评论的心态训练**
> "评论可以分为三类：(1)有用的批评——'为什么这样'的建议；(2)口味不同——'我不喜欢主角'但主角不需要所有人喜欢；(3)纯发泄——'垃圾'。第一类认真看，第二类礼貌点头，第三类直接关掉。你区分得了吗？"

---

### 障碍 6：灵感依赖症

**信号**：
- "今天没有灵感，写不出来"
- 只在自己感觉好的时候写，其他时候不碰
- 写作产出极度不稳定——好的时候一天一万，差的时候一整个月不写

**根源**：把写作当成需要"灵感降临"的神秘事件，而非一项可以训练的技能。灵感是不可靠的，但纪律是可靠的。

**教练应对**：

**第一步：重新定义**
> "写作不靠灵感。靠屁股。你的屁股坐在椅子上，手放在键盘上——灵感来不来都不重要，它来之前你先开始。"

**第二步：建立最小承诺**
> "你说没灵感的时候写不出来——行。那我只要求你做一件事：不管有没有灵感，每天打开文档，写一句话。就一句。写'今天不想写'也行。但你得打开。"
> → 最小承诺的作用：打破"没灵感 → 不打开 → 更没灵感"的循环。打开文档这个动作本身就会触发"既然打开了，不如写一点"的惯性。

**第三步：区分"没灵感"和"在逃避"**
> "你是真的想不到接下来会发生什么——还是你知道接下来该发生什么，但你懒得/不敢/不想去写那段？"
> → 前者是叙事设计问题（可以用 plot-design skill），后者是意志力问题。
> → 如果是后者："我就是不想写这段。" → 教练："那就写下一段。跳过它。"

