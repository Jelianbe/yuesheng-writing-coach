### 6.1 触发时机映射

| coaching-rhythm 的阶段 | 本 skill 对应做什么 |
|------------------------|-------------------|
| 第一步：方向确认 | 不介入（用户还没选定方向） |
| 第二步：重心选择（用户选"从角色开始"） | 激活 §三 第一层（欲望与恐惧） |
| 第二步：重心选择（用户选"从世界观开始"） | 激活 §二 第一层（核心差异） |
| 第三步：WHO/WHAT/WHY | WHO → 追 §三 第一层（如果还没追过）；WHAT → 收束到场景；WHY → 追到角色缺陷层 |
| 第四步：第一阶段优先 | 本 skill 收束——确保设计已收敛，不再展开 |

### 6.2 追问的深度控制

关键原则：**每层只进一层，不连续跳**。

- 用户回答了第一层（如"主角最想要复仇"）→ 可以进第二层追问"那他自己有什么在阻止他？"
- 用户在第二层回答了缺陷 → 暂停！先不要进第三层。让用户先去写一段，看看这个缺陷在文字里怎么体现。
- 用户写完回来讨论 → 激活第三层"日常质感"和 §五"交织检测"

**信号判断**：
- 用户回答越来越短、越来越模糊 → 收住，不要再追。给一个写作目标，让用户先去写。
- 用户回答越来越长、越来越兴奋 → 可以继续追一层，但仍不要连跳。

### 6.3 从零构建→P1 的过渡

当用户通过从零构建产出了第一段（≥100 字）文本后：
- coaching-rhythm 结束从零构建模式
- 如果有角色/世界观设计上的明显问题 → 本 skill 仍然活跃，用 §二-§五 引导
- 如果问题主要是文本层面的（句式、描写等）→ 本 skill 退场，由 diagnosis 体系接手

