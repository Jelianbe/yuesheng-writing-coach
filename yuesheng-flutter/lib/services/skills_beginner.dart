## 三、角色构建引导

### 3.1 四层递进提问框架

#### 第一层：欲望与恐惧（必问）

**目的**: 这是角色的发动机。没有这二者，角色只是名字+外貌。

**提问**（两个都必须触及）：
> "你的主角最想要什么？——不是大结局要达到什么，是**现在**最想要什么。"
> "他最怕的又是什么？——不是客观危险，是他内心最恐惧的东西。"

**追问**（如果用户回答模糊）：
> "他想要的东西，为什么现在得不到？如果很容易得到，故事就结束了——什么东西在阻止他？"
> "他最怕的东西——他有没有试着掩饰这种恐惧？怎么掩饰的？"

**完成标志**: 用户能说出"主角想要 X，但被 Y 阻止。同时他最怕 Z，所以他用 W 来掩饰。"

#### 第二层：缺陷与弧光（用户回应第一层后）

**目的**: 角色的缺陷是什么——不是"脾气不好"这种标签式缺陷，而是**导致他没有得到想要的东西的本质原因**。

**提问**（核心一问）：
> "你刚才说他想要 X 但被 Y 阻止。但 Y 是外部障碍，对吧？他最想要的东西，有没有一个原因是**他自己**造成的？他性格里什么让他得不到？"
> "故事结束时，他会变成什么样的人？——不是获得什么，是**变成什么**。"

**红线**: 
- ❌ 不要接受"他太善良"作为缺陷——那是伪缺陷，是优点的另一种说法
- ❌ 不要替用户设计弧光——问方向，让用户自己找到转折点
- ✅ 用户的回答可以是"他需要学会信任别人"或"他需要接受自己的平凡"

#### 第三层：日常质感（用户准备开始写时可激活）

**目的**: 让角色从"设计文档"变成"活人"——不是问大背景，是问日常细节。

**提问**（选 1-2 个，不要全部问）：
> "他早上醒来做的第一件事是什么？——不是重要的仪式，是下意识的动作。"
> "他吃早饭的时候是一个人还是和别人一起？吃的时候在想什么？"
> "他走在街上的时候——别人看他的第一眼会注意到什么？他自己知道吗？"
> "他有什么小习惯是周围人觉得奇怪但他自己习以为常的？"

**哲学**: 角色的真实性不是靠"背景故事"建立的，是靠**读者能具体想象的日常画面**建立的。

#### 第四层：收束（必须）

**目的**: 确保角色设计能驱动叙事。不能驱动叙事的角色设计是无效设计。

**话术**：
> "好了。现在用一句话说：**这个主角在第一幕的状态是什么？**"
> "——不是他的性格，不是他的身份。是他故事开始时的**处境**：他在哪里，他和谁在一起，他遇到了什么问题。"
> "这就是第一章的第一句话应该承接的东西。"

### 3.2 角色常见陷阱

| 陷阱 | 信号 | 引导方向 |
|------|------|---------|
| **角色空心** | 用户能说出主角外貌、身份、背景，但说不出"他想要什么" | 跳回第一层，追问欲望 |
| **弧光缺失** | 角色从开始到结束没有变化 | 问"故事结束时，他有什么事情做不到了/不做了/开始做了——这些是故事开始时他完全不会的" |
| **功能化角色** | 配角只是"推动情节"的工具 | 问"这个配角——除了推动情节，他自己想要什么？他跟主角的目标有什么冲突？" |
| **自传体主角** | 主角=作者理想化形象，没有缺陷 | 问"如果去掉所有优点，你的主角还有什么是让读者想看他继续走下去的？"（如果用户答不上来 → 角色需要缺陷） |

