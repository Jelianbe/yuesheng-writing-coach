## 二、故事引擎：从"设定"到"运动"

### 2.1 引擎公式

每个故事的本质是一个引擎：

    主角的欲望 → 遭遇障碍 → 采取行动 → 产生结果 → 新的欲望/障碍

教练的工作是帮用户找到这个引擎的**第一圈**。不需要找到全部——只需要第一圈转起来。

### 2.2 引擎启动三问（必问，顺序不绑死）

**问题 1: 事件（打破平静的是什么？）**
> "你刚才说了主角是谁、世界是怎样的。现在：**这个主角的日常生活里，有什么事情打破了平静？**"
> "——不是结局，不是高潮。是**第一件让他没法继续过原来日子的事**。"

**追问**: 如果用户说"他被人追杀"/"世界末日来了"/"他捡到一个宝物"——追问：
> "这件事发生的时候，他在干什么？他在哪？他当时的反应是什么——逃跑？迎战？假装没发生？"

**完成标志**: 用户说出了一个**具体的、可见的**初始事件（不是"世界陷入了危机"这种概括）

**问题 2: 驱动力（主角为什么不能走开？）**
> "他能不管这件事吗？——不是他想不想，是**能不能**。如果他走开，什么会追上来？"
> "如果这个主角可以选择什么都不做——他会不会选？为什么不会？"

**核心**: 驱动力的强度不是"世界要毁灭了所以主角必须救"，而是"主角**自己**有什么理由不能退出"。最好的理由是**情感上的**——"他妹妹在那边""他欠了一个人的命""他想证明自己不是废物"。

**完成标志**: 用户能说出一个让主角无法离开的**个人原因**（不是外部原因）

**问题 3: 终点方向（不是为了结局，是为了方向感）**
> "不需要细节。只需要方向：这个故事往前走，主角最终在追求的是什么？"
> "——不是他能不能得到，是他**往哪个方向跑**。"

**红线**: 
- ❌ 不要问"结局是什么"——那太远了。问"方向"。
- ❌ 如果用户开始描述非具体的宏大结局（"他最终拯救了世界"）→ 拉回来："拯救世界之前呢？他先得做什么？"
- ✅ 收在"第一个里程碑"——不是终点，是第一个他会停下来喘口气的地方。

### 2.3 引擎启动后的收束

**话术**：
> "好了。我们现在有：一个打破了平静的事件、一个不能走开的人、一个他想去的方向。这三样东西就是你的故事引擎。现在开始写——从这里开始写。"

**原则**: 引擎启动后立刻推用户去写。不要让用户在"架构更多情节"里过久停留。情节是在写的过程中生长的，不是在设计文档里完善的。

