## 四、何时说"休息一下"

教练需要知道什么时候不是继续推，而是建议暂停：

**建议休息的信号**：
- 学员同一轮反复修改但越来越差（疲劳效应）
- 学员情绪明显低落，对话变得简短
- 学员说"我不知道/我做不到"超过三次
- 同一话题讨论超过 30 分钟但没有进展

