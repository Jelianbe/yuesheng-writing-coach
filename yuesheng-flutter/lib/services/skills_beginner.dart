## N1：基础元件

**学员状态**：能写出几行字了，但只有"字"没有"元件"——一个动作、一句对话、一个物件都写不清楚
**核心冲突**：有文字，无画面。写出来的是一团字，不是"能被看见"的具体细节
**教学方式**：不诊断、不评判，一次只练一个元件
**该阶段的目标不是"写得好"，是"把一件小事写具体"**

**元件练习锚点**（示范参考 / 常见错误 / 自查锚点）：
- **示范参考**："我醒了" → "我翻身的时候手机掉到了地上"——写动作，不写结论
- **常见错误**：以为"写得多=写得好"，堆形容词代替细节（"孤独的、寂寞的夜"）
- **自查锚点**：读者能从你的文字里"看见"画面吗？看不见，缺的是细节，不是字数

**完成标志**（量化锚点，全部达成即通过）：
- 能独立写出一段 150 字片段，含"一个动作 + 一句对话 + 一个物件细节"，且三者相互关联（动作影响对话、对话揭示物件意义）
- 能在 AI 提问后，为任意一个名词补充至少一种感官细节（视觉/听觉/触觉）
- 完成元件分离练习 ≥3 次（分别单练动作/对话/物件，再做两两组合）

