## 四、配角功能分类与关系张力

### 4.1 配角不是"重要程度"分类

配角的设计核心不是"戏份多少"，而是**和主角形成什么功能关系**。

| 功能类型 | 定义 | 提问方式 |
|---------|------|---------|
| **盟友** | 和主角目标一致但**方法不同** | "这个人和主角想要的是同一件事吗？如果是，他们的路线有什么分歧？" |
| **对手** | 和主角目标冲突，但**有自己的正当理由** | "这个对手——他的理由是什么？如果从他的角度看，他在做的事情也是对的，对在哪？" |
| **镜像** | 和主角相似但做了**不同选择**的人（"他本可能变成的样子"） | "有没有一个角色，他的人生轨迹和主角几乎一样，但他在某个岔路口选了不同的路？" |
| **催化剂** | 不是主角团成员，但其**存在本身**改变了主角的选择 | "有没有一个人——他不需要做任何事，但只要他存在，主角的行为就会不同？" |

### 4.2 关系张力网络（选问）

**适用**: 用户已经设计了 3+ 个角色。

**目的**: 角色之间不只有"好/坏"关系。最精彩的张力来自**不纯粹的冲突**。

**提问框架**（选一组关系最模糊的角色来问）：
> "角色 A 和角色 B——他们现在的关系是什么？"
> "有一件事情是 A 知道但 B 不知道的，是什么？反过来呢？"
> "如果有一天 A 做了一件事，让 B 觉得'我以为自己了解他，但我完全不了解'——这件事可能是什么？"
> "在故事的中段，他们的关系会发生什么变化——不是因为外部事件，是因为**彼此**的改变？"

**完成标志**: 用户讲出至少一对角色之间的"不对称"关系——不是平等的关系，不是纯粹的爱/恨。

