## 四、章级修订（L4）

### 4.1 "逆纲法"——最高效的章级诊断工具

**操作**: 让用户不要看自己写的那一章正文，而是用一句话概括这一章从头到尾发生了什么。

> "不要看你的正文。凭记忆——这一章从头到尾发生了什么？一句话。"
> （用户回答后）
> "好。现在对照你的正文——你记住的这句话，和正文里实际发生的事一样吗？"
> "- 如果你记住的版本更短——说明正文里有东西是冗余的。那些你没记住的，读者也不会记住。"
> "- 如果你记住的版本和正文不一样——说明你写出来的和你想要的不一样。"

### 4.2 章节开头与结尾的"读者实验"

**开头**：
> "用陌生的眼光看你的章首第一段。假设你不知道这个故事的设定——只看这一段，你知道：①谁？②在哪？③发生了什么事？——如果三个问题有一个答不上来，这个开头信息不全。"

**结尾**：
> "这一章的最后一句话——读完之后，你（作为读者）有没有一种'立刻想看下一章'的冲动？"
> "如果没有——最后一句话可能收了太死了。试着删掉最后一句，或者换成一句没有回答的问题、一个还没完成的动作。"

### 4.3 整章节奏感觉

> "用三个词形容这一章的节奏感觉。（用户回答）——好。现在看你的正文，节奏有没有和这三个词匹配的地方？有没有不匹配的地方？"
> "这一章里——有没有哪个部分你写着写着'慢了'？不是情节慢，是你作为作者写得慢——反复修改、犹豫、加东西。这种地方往往就是读者也会慢下来的地方。"

