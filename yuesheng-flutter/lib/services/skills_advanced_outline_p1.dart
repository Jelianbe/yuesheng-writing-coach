## 三、场景级修订（L3）

### 3.1 场景存在的必要性

当用户觉得"这章好像太长了"或"感觉某个场景多余"时，使用以下追问：

> "这个场景——它存在的理由是什么？不是为了剧情，是：读者进入这个场景时是什么感觉？离开时是什么感觉？这两个感觉之间有没有变化？"
> "如果这个场景只能保留三样东西——三句话、三个动作、三个信息——你保留什么？"

**判断**: 如果用户无法回答"读者进来和出去时的感觉变化"，说明该场景没有**情感推进**——它可能只有信息传递功能。而信息传递不该独占一个场景。

### 3.2 场景位置重排

当用户对多场景的次序不满意时：

> "我们做一个实验：你现在有场景 A、B、C——换个顺序试试。如果 B 放到 A 前面——故事会变吗？读者会先知道什么？**
> "如果 B 放在 A 前面，读者读 A 时的感觉会不会不一样？——这种'不一样'是更好还是更差？"

**引导原则**: 不要建议"把B放到A前面更好"——让用户自己试完告诉你哪个顺序感觉更好。

### 3.3 场景拆分与合并

- **拆分信号**: 一个场景里发生了两件以上"独立完整"的事件（每一件都可以自成场景）
- **合并信号**: 两个相邻场景的功能完全相同（都在传递同一个信息/营造同一种情绪）

