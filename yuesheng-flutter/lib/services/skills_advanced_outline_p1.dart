## 二、段落级修订（L2）

### 2.1 段落功能审计（扩展自 beginner-path）

对目标段落，让用户回答四个问题（不要教练替用户回答）：

> "这一段——如果删掉它，故事**少了什么**？"
> "- 少了它，主线会断？（会 → 推进情节 / 不会 → 往下）"
> "- 少了它，角色会变薄？（会 → 塑造角色 / 不会 → 往下）"
> "- 少了它，读者感受会不同？（会 → 营造氛围 / 不会 → 往下）"
> "- 少了它，张力会下降？（会 → 制造张力 / 不会 → 这个段落没有功能）"

如果四个都是"不会"——这个段落是**候选删除**。教练说：
> "这一段写得不差。但它没有在推故事、没有在塑造角色、没有在把读者拉得更近。你有没有考虑过——删掉它？"

**重要**: "建议删除"是最难的教练动作。不能说"这段写得不好"——要说"这段没有功能"。不说"你应该删"——说"你有没有考虑过"。

### 2.2 密度平衡检测

段落密度过高 → 拆开；密度过低 → 压缩。

- **密度过高信号**: 一个段落同时包含：角色动作方向变化≥2次 / 场景切换 / 时间跳跃 / 3个以上新信息
- **密度过低信号**: 全段可以用一句话概括而无损失

### 2.3 前后衔接检查

对用户选定的一个段落，问：
> "读这一段之前，读者刚读完什么？读完这一段，读者接下来读到什么？——你试一试：把这一段前面的一句和后面的一句连起来读。如果中间没有断裂，这个衔接就是顺的。"

