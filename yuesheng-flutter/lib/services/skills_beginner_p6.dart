## 三、差距类型

### 严重度通用标定

| 维度 | L1 轻微 | L2 重要 | L3 严重 |
|------|--------|---------|---------|
| 偏差幅度 | 细节偏了一点 | 核心特征偏离 | 设定被完全推翻 |
| 读者感知 | "有点不对劲" | 设定和表现不一致 | "作者忘了自己的设定" |
| 修复成本 | 改几处用词 | 重写关键段落 | 重构角色或情节线 |

### G001 程度偏离

**核心**: 角色的某个属性在"意图"和"表现"间程度不一致。

**诊断锚点**: 作者说"主角资质不好"，但第三章"筑基三个月" — 文中最快记录是一年 → G001 L2；从体裁推断"三个月筑基"≈资质中上，但第一章写"灵根驳杂" — 推断意图"废材逆袭"但执行消灭了废材感 → G001 L2 (推断)

**探查**: "你说他天赋普通 — 但这里他三个月就筑基了。在你的世界里，普通人筑基大概要多久？"

### G002 特质偏离

**核心**: 想展示特质A，但行为/对话展示了相反的特质B。

**诊断锚点**: 作者说"心机深沉"，但角色出场第一句话是告诉对手全部计划 → G002 L2；角色被介绍为"谨慎低调"，但进入秘境就主动挑衅 → G002 L2 (推断)

**探查**: "你说他心机深沉 — 但这里他直接说出了计划。你设想的'心机'在这个场景里应该怎么表现？"

### G003 意图落空

**核心**: 想让读者感受到X效果，但文本缺少产生该效果的必要条件。

**诊断锚点**: 作者说"这里是反转"，但前面无任何线索 → G003 L2；章节末尾安排了"发现上古祭坛"的段落，但祭坛出现太突兀，没有铺垫 → G003 L2 (推断)

**探查**: "你说这里想让读者感动 — 你觉得读者需要先对角色有什么了解，才会在这一刻感动？"

### G004 发力错位

**核心**: 笔墨分配和意图重心不匹配 — 该重点写的写太少，该略写的写太细。

**判断**: 核心内容篇幅 < 整段 1/3？过渡长度是否超过合理范围？不重要内容是否过半？

**诊断锚点**: 作者说"打斗是全章高潮"，但前 80% 写环境和前奏，打斗只有两句话 → G004 L2

**探查**: "被偷袭这段是读者最紧张的地方 — 但你前面花在排队和采集上的篇幅比冲突本身还多。如果重新分配，你觉得读者最想看的是什么？"

