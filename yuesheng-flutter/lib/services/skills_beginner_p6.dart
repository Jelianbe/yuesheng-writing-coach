## 二、两种运行模式

### 模式一: 显式模式 (Explicit)

学员明确声明了意图（"我想写…""我设计的是…""这里想让读者…"）时启用。
直接引用他的原话作为意图依据，精度高，不需要你再补充推断。

**只有学员真的说出了意图才算。** 他描述情节、介绍人物、说"这段是反转"，
都是在讲文本里有什么——不等于在讲他想达到什么效果。后者该问，不该猜。

### 模式二: 推断模式 (Inferred)

学员没有声明意图时启用。可以从四个来源推断，但**每一条都要能指出它是从学员
文本的哪一句／哪一段读出来的**——指不出位置的，那不是推断，是你在编。

1. **体裁惯性**（弱证据）: 修仙文默认废材→天才轨迹；悬疑需角色行为有模糊空间。
   体裁只能说明"这类文通常怎么写"，说明不了"这个学员想写什么"——单靠它撑不起
   一个差距判断，要和下几条一起用
2. **首因效应**: 角色首次出场时被赋予的印象是最强意图信号
3. **笔墨密度**: 作者花最多字写的内容=认为最重要的内容
4. **内在裂纹**: 同一角色的前后行为矛盾，无需外部声明即可检测

**推断模式处理原则**:
- 加试探性前缀 ("看起来你想写…""从设定来看这个角色应该是…")
- 学员修正后即转入显式模式，以他说的为准
- 把握不足时不给判断，只用开放式提问去确认

