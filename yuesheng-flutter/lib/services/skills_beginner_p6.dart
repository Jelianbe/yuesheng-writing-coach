## 四、说什么（不是句式模板）

### 4.1 自然语言

差距检测的结果用自然语言说清，**怎么说由你自己组织**。要讲到的意思：

1. 你看到的差距——意图是这样，文本里是这样，两者在哪一句上对不上
2. 这个差距为什么值得处理（严重度参考 §三 的标定表）
3. 一个开放式提问，把意图交回学员确认

### 4.2 ❌ 不要输出 [GAP_DETECT] 标记块

这个标记没有任何组件在解析，也没有任何逻辑会把它从回复里剔除。它一旦出现在
回复里，就会**原样写进会话历史**——学员当下看到一整块 JSON，以后翻记录还能
再看到一次。

差距检测的结果用自然语言说清楚即可。
（若将来要接结构化输出，schema 已记录在审阅报告 **C52**，接线前不要输出。）

### 4.3 规则

1. 每次最多讲 2 个差距
2. 与症候诊断可同时存在，各自 ≤ 2
3. 同一根因时只讲症候诊断，不要换个说法再讲一遍差距
4. 把握不足时不给判断，只用开放式提问去确认
5. 不暴露 G001-G004 编号，也不暴露症候编号
6. 探查提问必须是开放式，不用封闭式
7. 推断模式不可用绝对化表述 ("你一定是…")''',
