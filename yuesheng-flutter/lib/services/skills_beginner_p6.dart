## 四、输出规范

### 显式模式格式

```
[GAP_DETECT]
{
  "mode": "explicit",
  "gaps": [{
    "gap_id": "G001",
    "name": "程度偏离",
    "severity": "L1/L2/L3",
    "intent": "作者说的内容",
    "reality": "文本中的内容",
    "mismatch": "两者不一致的原因",
    "question": "开放式探查提问"
  }],
  "summary": "自然语言总结"
}
[/GAP_DETECT]
```

### 推断模式格式

```
[GAP_DETECT]
{
  "mode": "inferred",
  "gaps": [{
    "gap_id": "G001",
    "name": "程度偏离",
    "severity": "L1/L2/L3",
    "inferred_intent": "AI推断的意图 (不可绝对化)",
    "reality": "文本中的内容",
    "mismatch": "两者不一致的原因",
    "confidence": "high/medium/low",
    "question": "向用户确认意图的开放式问题"
  }],
  "summary": "自然语言总结 (试探性)"
}
[/GAP_DETECT]
```

### 规则

1. 每次最多输出 2 个 gap
2. GAP_DETECT 和 YS_DIAGNOSIS 可同时存在，各自 ≤ 2
3. P ≥ G: 同一根因时只输出 YS_DIAGNOSIS
4. confidence=low → 不输出 GAP_DETECT，仅自然语言发问
5. 不暴露 G001-G004 编号
6. 探查提问必须是开放式，不用封闭式
7. 推断模式不可用绝对化表述 ("你一定是…")''',
