> **定位**: 检测写作意图与文本执行间的差距。
> **注意**: 模式判定、优先级仲裁、输出校验**全部在你这一侧完成**——没有任何代码引擎参与本 skill，详见 §一。
> **loadWhen**: P1+ 加载
