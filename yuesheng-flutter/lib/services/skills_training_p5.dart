  content: '''# SKILL: 范文对照改写

> **定位**: 训练环节的改写练习形态。给学员一段"目标态"范文（与学员当前场景/技法匹配的真人文字），学员对照范式"做到的效果"改写自己的段落——解决"知道怎么写但写不出来"。
> **与 demonstration 的分工**: 示范教学教会"什么是好"（认知：看正例→发现规律）；对照改写教会"怎么做到"（执行：对照目标态→动手改）。
> **与 comparison 的分工**: 对比教学用 A/B 两版让学生找差异；对照改写只有一个目标态范文，学生直接以它为靶改写自己的文本。
> **loadWhen**: P2+ 训练环节，学员示范后仍无法迁移、或说"我懂但这个写不出来"时使用。
> **体积**: 约 1800 tokens

---

## 一、核心理念

学员卡在"懂但写不出来"时，缺的不是认知而是**执行参照**。一段与学员场景同类的目标态范文，让"好"从抽象概念变成可对照的靶子：学员不是临摹它，而是对照它检查"我的版本差在哪"，再动手改。

## 二、适用场景

| 场景 | 触发信号 | 对照目的 |
|------|---------|
| 执行断层 | 学员说"我懂这个技法，但写不出来" | 把"懂"落到"写" |
| 示范无效 | 示范教学后学员仍无法迁移（"看到了，但不会用"） | 提供直接执行参照 |
| 反复卡住 | 同一处 ≥2 轮无进展 | 用具体靶子打破僵局 |
| 需要参照系 | 学员说"你给我看看好的长什么样" | 直接响应 |

## 三、执行流程（四步）

### 步骤 1：选范文

从名家作品或教材中选一段与学员**当前场景/当前症候**匹配的短片段（100-200 字）：

**选材规则**：
- 必须是**真人写的文字**（AI 不编写作）——与示范教学一致
- 场景同类：与学员正在写的场景类型一致（动作/对话/心理/环境）
- 技法相关：展示学员当前症候的目标状态（如 P003 配"无情绪词的动态描写"）
- 片段独立可理解，不依赖上下文

### 步骤 2：展示范文

只展示，不做标注——保留学员自己的发现空间：
> "我给你看一段文字。它写的是[场景类型]，你读一遍。不用分析——先感受它做到了什么。"

- **不标注**：不加粗/下划线/颜色
- **不提示**：不告诉学员"注意动词"——提示会在步骤 3 布置任务时给出

### 步骤 3：布置对照改写任务

锚定学员原文，给出**一个**对照维度：
> "现在看你自己写的那段[原文位置]。这段和你刚读的范文是同一类场景。对照范文——把你这处的[症候焦点]改出来：范文里读者是怎么感受到[目标效果]的？你的版本缺在哪？改这一处。"

**对照规则**：
- **只给一个对照维度**（一次一个点，与训练底线一致）
- 对照维度 = 当前训练的症候焦点（如"用动作替代情绪词""视角不漂移""节奏变化"）
- 任务锚定学员原文（text-surgery 铁律1：不脱离学员文本）
- **不替学员写**、不提供改好的完整版本（V-01 不替写）

### 步骤 4：改写 → 对比 → 评估

- 学员改写完成后：学员自评 → **改前 vs 改后对比**（text-surgery 铁律3，强制收尾）→ AI 评估三档
- 反馈时对照范文指差异："范文里[具体效果]，你这版[对比]——你刚才对照它改的这一处，方向对了/还差在哪。"

## 四、对照维度示例（按症候）

| 症候 | 对照维度 |
|------|---------|
| P003 情绪标签化 | "范文有没有出现情绪词？读者靠什么判断情绪？" |
| P005 视角漂移 | "范文里所有信息是通过谁的眼睛看到的？" |
| P006 节奏停滞 | "范文每一句有没有推进？哪句是你也可以删的？" |
| P011 对话疲劳 | "范文的对话每句有没有潜台词？你的对话在干嘛？" |
| P014 结尾乏力 | "范文结尾怎么收的？你的结尾读者会想看下一章吗？" |

## 五、禁用行为

- ❌ **不让学生临摹/抄写范文**：对照是检查差距，不是模仿字句
- ❌ **不用 AI 生成的文字做范文**：与示范教学同一红线
- ❌ **不给超过一个对照维度**：一次只对照一个症候焦点
- ❌ **不跳过"改前 vs 改后"对比**：对照改写的成果必须展示在对比里
- ❌ **不替学员写**：范文是靶子，学员自己完成改写''',
