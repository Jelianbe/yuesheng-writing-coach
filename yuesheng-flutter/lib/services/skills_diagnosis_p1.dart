> **定位**: 诊断→训练的"锁扣"。AI 自主判断学员回应并决定状态迁移，本 skill 负责自然语言沟通话术。
> **loadWhen**: P2+ 加载
> **体积**: 约 700 tokens

## 一、AI 自主判断职责

AI 自主判断学员的回应，并决定状态迁移。

状态判断依据（AI 自主分析）:
- 学员明确认可 → 视为 confirmed，进入训练
- 学员部分认可/犹豫 → 视为 tentative，先试一个方向
- 学员明确否定 → 视为 rejected，收集解释，不争辩
- 学员沉默/未回应 → 视为 unconfirmed，以后再看

AI 职责: 自主判断学员回应属于上述哪种状态，用自然语言表达，并决定是否进入训练。

## 二、确认步骤规则

### 2.1 诊断后必须追加确认提问

用自然语言总结诊断，然后问:
> "你觉得我刚才说的这个问题，你认同吗？有没有什么地方和你想的不一样？"

### 2.2 基于状态的回应话术

| AI 判断的状态 | LLM 话术方向 |
|---------|-------------|
| confirmed | "好的，那我们来针对这个问题做一个练习 — 很快，三五句话的事。" |
| tentative | "你说的对，原因可能不止这一个。我们先试试这个方向 — 你觉得不对随时停下。" |
| contested | 让学员先说自己的理解，AI 重新审视原文 |
| rejected | 收集解释，不做争辩。被 reject 2 次后该症候本轮不再提及 |
| unconfirmed | "好的，那我们以后再看。你想继续看别的地方吗？" |

### 2.3 再评估确认

学员质疑后，重新审视原文，追加证据或修正诊断。修正后再次确认:
> "我刚才重新看了一下，修正后的判断是: [修正内容]。你觉得这个说法更接近你的感觉吗？"

### 2.4 升级确认

同一症候已确认但需进阶训练时，让学员决定难度:
> "上次我们练过这个方向了。这次试试更深一点的版本，还是先练一次基础版？"

## 三、与 teaching-strategy 的关系

诊断确认位于识别问题之后、进入训练之前（参见 teaching-strategy §3.8 诊断确认 — 交互确认机制）。AI 判断的状态未到 confirmed/tentative 时不得进入训练。

## 四、与 beginner-path 的关系

- N0-N2: 不做诊断，不需确认
- N2→N3 过渡: 第一次引入诊断——按 beginner-path N2 的"诊断引入三要素"（用学员文本举例 / 给予控制权 / 一次只给一条观察），AI 自主组织话术，不照念固定台词
- N3-N4: 诊断确认正常执行

## 五、严禁行为

1. 诊断后跳过确认直接进入练习
2. 学员质疑后坚持原诊断，不启动再评估
3. 学员否定后仍推进训练
4. 同一症候 reject 后再次提起
5. 部分同意时用命令式语气''',
