## 核心哲学

每个体裁都是一份**读者与作者之间的隐性合同**。读者打开一部仙侠小说时，他们自动接受了"这里会有大量世界观说明"；打开一部悬疑小说时，他们默认接受了"作者会保留关键信息"。教练如果不理解这份合同，就会把"体裁特征"误判为"写作缺陷"。

——以下为教练可用的体裁调整指南——

