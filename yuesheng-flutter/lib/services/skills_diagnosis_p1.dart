## 一、体裁容忍度矩阵

### 符号说明
- **高容忍**: 该体裁读者对此特征有较高接受度，正常水平不触发诊断
- **中容忍**: 视情况而定，阈值略低于通用标准
- **低容忍**: 该体裁对此特征要求更严格，阈值高于通用标准
- **特征**: 该体裁的"必须项"——缺少此特征会直接被认为"不像这个体裁"

