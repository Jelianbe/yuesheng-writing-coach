### 言情/都市

**读者合同**: 接受对情感关系的细致描写，接受一定程度的内省和内心独白。核心要求是**情感真实**——角色为什么要爱/不爱/恨/原谅，必须有说服力。

**诊断阈值调整**:

| 症候 | 调整 | 原因 |
|------|------|------|
| P003 情绪标签化 | **降低触发阈值** | 言情以情感为核心——"他很伤心"这种写法直接破坏共情基础 |
| P006 节奏停滞 | **提高触发阈值** | 读者接受情感互动需要"空间"——两人慢慢相处的段落不是停滞 |
| P009 角色空心化 | **降低触发阈值** | 言情的角色动机必须清晰——读者需要理解"ta为什么会爱上ta" |
| P019 情感失真 | **降低触发阈值** | 言情的核心就是情感——情感失真 = 地基塌了 |
| P011 对话疲劳症 | **降低触发阈值** | 言情依赖对话推进关系——无效对话比别的体裁更致命 |

**该体裁特有陷阱**:
- **"工业糖精"陷阱**: 情感进展完全依赖外部事件推动（意外同居/被迫合作/英雄救美），角色之间没有真正的化学反应。检测：如果删掉所有外部事件，这两个人还有理由在一起吗？
- **"工具人恋人"陷阱**: 恋爱对象只有"对主角好"这一个特征，没有独立的欲望、弱点和故事。解决：恋人必须有一章完全是ta自己的视角——ta在没有主角的时候在做什么？
- **"误会驱动"陷阱**: 整篇的情感冲突全靠"不说清楚"来维持——只要角色开口解释一句，故事就结束了。解决：至少有一个冲突不能靠"沟通"解决——那是真正的情感冲突。

---

### 科幻

**读者合同**: 接受技术/科学解释段落，接受一定程度的设定说明。核心要求是**设定自洽**——科幻读者会主动找逻辑漏洞。

**诊断阈值调整**:

| 症候 | 调整 | 原因 |
|------|------|------|
| P004 信息倾泻症 | **提高触发阈值** | 科幻必须解释设定——但解释方式有优劣：融入场景 > 角色对话解释 > 旁白大段说明。只有第三种才触发 |
| P011 对话疲劳症 | **降低触发阈值** | 科幻中的"解释性对话"是最容易崩的地方——两个角色互相告诉对方ta们已经知道的事情，只为向读者解释设定 |
| P018 人设崩塌症 | **标准** | 科技环境下的行为一致性要求更高——一个科学家角色不能做出反科学直觉的事 |
| P016 情节巧合 | **降低触发阈值** | 科幻读者对因果链的要求极严——巧合在科幻中比在其他体裁中更不可接受 |

**该体裁特有陷阱**:
- **"设定展览馆"陷阱**: 花大量篇幅展示"我设计的世界有多酷"，但角色只是走马观花——故事本身没有推进。解决：每一个设定细节的展示都必须服务于当前场景的需要。
- **"技术万能"陷阱**: 关键困境用"新科技"来解决——"他们发明了一个装置克服了重力问题"。解决：技术的引入必须在前面有铺垫，不能凭空出现。
- **"硬科普"陷阱**: 科学解释写得像教科书。解决：解释必须通过角色的体验和反应来呈现——不是"这个引擎的原理是……"，而是"她看着引擎的读数——数值在上升，这意味着什么，她很清楚。"

---

### 武侠/历史

**读者合同**: 接受一定程度的描写密度和"古风"用语，接受较慢的叙事节奏。对"真实感"有较高要求——无论是历史考据的真实还是武侠世界内部逻辑的真实。

**诊断阈值调整**:

| 症候 | 调整 | 原因 |
|------|------|------|
| P003 情绪标签化 | **标准** | 古风表达不等于情感缺失——"肝肠寸断"用对了是古风，用错了是标签化 |
| P006 节奏停滞 | **提高触发阈值** | 读者接受"赶路""住宿""吃饭"等日常段落的描写 |
| P008 语言堆砌 | **提高触发阈值** | 一定程度的铺陈是古风美学的组成部分——但堆砌仍然是堆砌 |
| P007 句式节奏单一 | **降低触发阈值** | 古风文本最容易出现"统一的长句+四字短语"模式——阅读疲劳来得更快 |

**该体裁特有陷阱**:
- **"古风词库"陷阱**: 用一套固定的古风词汇来回替换（眼眸/青丝/朱唇/玉手……），文字像模板填空。解决：同样的东西，不同角色看到应该有不同的描写方式。
- **"考据过载"陷阱**: 历史细节淹没了故事。解决：一个场景最多展示3个历史细节——挑最能建立氛围的。

---

### 恐怖/惊悚

**读者合同**: 接受作者的"操控"——作者需要控制读者的情绪和预期。核心要求是**氛围**——恐怖不在于写了什么，而在于读者"觉得"会发生什么。

**诊断阈值调整**:

| 症候 | 调整 | 原因 |
|------|------|------|
| P003 情绪标签化 | **极大降低触发阈值** | 恐怖的核心是让读者"感受到"不安——"他很害怕"等于什么都没写 |
| P008 语言堆砌 | **降低触发阈值** | 恐怖需要精准——越克制越有效。过度修饰反而消解恐怖 |
| P015 高潮疲软 | **极大降低触发阈值** | 恐怖的"那个时刻"——揭示/遭遇/惊吓——如果疲软，前面积累全部作废 |
| P021 跳跃叙事 | **降低触发阈值** | 恐怖需要让读者"在场"——跳过关键场景直接给结果是恐怖的大忌 |

**该体裁特有陷阱**:
- **"预告式恐怖"陷阱**: 用"他不知道，这将是他最后一次看到她了"这一类预告破坏当下场景的沉浸感。解决：让读者和角色同时发现——而不是提前告诉读者。
- **"惊吓依赖"陷阱**: 全靠 jump scare——突然出现的怪物/声音——推进恐怖感。解决：真正的恐怖在"等待"中——读者看到门慢慢打开的过程，比门突然打开看到怪物更可怕。

