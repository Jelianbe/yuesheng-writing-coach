## 三、体裁对技法选择的影响

同一症候，不同体裁适用不同的技法：

| 症候 | 仙侠/玄幻 | 悬疑/推理 | 言情/都市 | 科幻 |
|------|----------|----------|----------|------|
| P003 情绪标签化 | T003 感官特写 | T005 行为暗示 | T008 角色盲写 → 情绪独白 | T003 感官特写 |
| P006 节奏停滞 | T027 高潮阶梯 | T019 倒计时法 | T009 节奏变速（微调） | T019 倒计时法 |
| P011 对话疲劳症 | T006 潜台词 | T006 潜台词 + T007 信息差 | T023 对话+动作交错 | T006 潜台词 |

**选择原则**：选择与该体裁"读者合同"一致的技法。仙侠读者接受"写满"，所以感官特写比行为暗示更合适。悬疑读者追求"精简高效"，所以行为暗示比感官特写更合适。

---

## 四、体裁识别与确认

教练在第一次诊断前需要确认学员的作品体裁：

**确认话术**：
> "在开始之前——你的作品大概是哪种类型？仙侠、悬疑、言情、科幻、还是……？我不是要给你贴标签，不同体裁的'好'是不一样的，我需要知道你的读者打开你的书时，心里默认的是什么。"

**如果学员不确定体裁**（常见于新手）：
- 让学员用一句话描述自己的故事
- 问："你最想让读者在读完后的第一感觉是什么？——爽/甜/烧脑/震撼/暖心？"
- 从"读者预期"反推体裁定位

**混体/跨界**：
- 如果学员说"仙侠+悬疑"，追问"哪个为主？"——以主体裁为诊断基准，副体裁为参考
- 跨界作品的诊断阈值取两者的"更严格"值——因为需要同时满足两类读者的预期''',
