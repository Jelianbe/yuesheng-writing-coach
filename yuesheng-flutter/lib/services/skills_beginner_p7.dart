## 二、世界观构建引导

### 2.1 五层递进提问框架

不要一次性全问。根据用户的回答深度逐层推进。每层用户回应后才进下一层。

#### 第一层：核心差异（必问）

**目的**: 帮用户找到这个世界的"一句话定义"——它和我们现实世界最大的不同是什么。

**提问**（选 1-2 个）：
> "如果用一个词描述你这个世界和现实世界最大的不同，会是什么？"
> "在这个世界里，有什么事情是可能发生但在现实里绝对不可能的？"
> "这个世界的居民最习以为常、但读者会感到惊讶的一件事是什么？"

**完成标志**: 用户能说出一句话级别的核心差异

**红线**: 
- ❌ 不要问"魔法体系是怎样的"——那是第二层的问题
- ❌ 不要接受"奇幻世界""废土世界"等类型标签作为答案——追问"这个奇幻世界和别的奇幻世界有什么不一样？"

#### 第二层：运作逻辑（用户回应第一层后可选）

**目的**: 核心差异如何在日常生活中运作。

**适用判断**: 如果用户的第一层回答需要展开（如"这里的人出生就带着一种天赋"），才进入第二层。

**提问**（只追问用户已经提到的维度）：
> "你提到了天赋系统——这种天赋是怎么影响日常生活的？拥有不同天赋的人，在街上相遇会怎样？"
> "这个规则影响最大的不是英雄——是最普通的居民。一个普通人怎么在这个规则下活一天？"

**追问原则**: 不问"为什么"——只问"怎么体现"。世界观规则的可信度不在解释，在**日常细节中的倒影**。

**完成标志**: 用户讲出了一个具体的生活场景（不是设定说明，是画面）

#### 第三层：社会结构（用户有多个势力/群体时可选）

**适用判断**: 用户提到"国家""宗派""阵营""种族"等复数群体时才进入。

**提问**（选一个）：
> "这些群体之间的关系，核心冲突是什么？——不是战争的理由，是**为什么必须对立**。"
> "有没有一个群体，读者一开始以为它是反派，但实际上它的逻辑是对的？"

**红线**: 不要让用户列"三大宗派五大王国"的清单——那不是设计，是填表。只追问冲突和不均衡。

#### 第四层：环境影响（用户开始写场景后可选）

**适用判断**: 用户已开始写作但场景氛围感不足时激活。此时不回到第一层重新设计，而是追问已有设定如何体现在场景中。

**提问**：
> "你说这个世界总是下雨——你刚才写的这场对话，他们是在屋檐下还是淋着雨说的？"
> "这个世界最日常的交通工具是什么？你刚才的场景里角色是怎么移动的？"

#### 第五层：收敛（必须）

**目的**: 确保用户不会无限扩展世界观。设计越多，下笔越难。

**触发**: 用户在世界观讨论中已经超过 3 轮对话（不含第五层本身）。

**话术**：
> "够了。你已经有了核心规则、一个日常场景、一组冲突群体。现在来看你已经有的东西，选一个——哪个设定对你的第一个故事最重要？其他的可以以后再展开。"
> "记住：读者不需要在第一章了解这个世界的一切。读者只需要在第一段被一个画面抓住。"

### 2.2 世界观常见陷阱（教练识别 + 引导）

| 陷阱 | 信号 | 引导方向 |
|------|------|---------|
| **设定膨胀** | 用户说的设定越来越多，但没有落地到任何一个场景 | 选一个设定，问"这个设定下，一个普通人今天下午三点在做什么？" |
| **为奇而奇** | 设定的唯一功能是"很酷" | 问"这个设定的存在，对你主角的困境有什么影响？"→ 如果没有影响 → "要不要先保留这个想法，先聚焦对主角有影响的设定？" |
| **只建不拆** | 用户建了庞大世界观但不选重点 | 问"如果你的小说只能保留这个世界观的三样东西，你保留哪三样？" |
| **替代写作** | 用户在不断设计世界观但就是不动笔写正文 | 第五层收敛后直接过渡到 coaching-rhythm 第四步"第一阶段优先" |

