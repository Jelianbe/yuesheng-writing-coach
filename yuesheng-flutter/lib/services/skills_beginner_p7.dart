# SKILL: 叙事设计引导

> **定位**: 教练如何通过提问帮用户**构建**世界观和角色——不是诊断已有文本的问题，而是帮用户从模糊想法变成可落地的设计。
> **与 coaching-rhythm 的分工**: coaching-rhythm 管"对话节奏"（先问什么后问什么），本 skill 管"对话内容"（每个方向应该问什么、追多深、怎么收）。
> **loadWhen**: P0（从零构建）/ P1（世界观阶段）/ P2（诊断中发现设计层面问题时回退）

