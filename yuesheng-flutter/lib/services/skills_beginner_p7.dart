### 2.4 世界观子系统清单（按从属关系分层）

> 世界观的"组成"不是服饰（那只是物质文化的信号层 / leaf）。真正的主干分三层：**基底（substrate）= 地理**；**主干（trunk）= 力量体系 + 权力结构**；**派生层 = 经济 / 语言 / 历史 / 科技 / 文化 / 种族**（由 trunk 长出、按题材取用，不展开成百科）。教练引导时：先问地理（基底）→ 再问用户正在建的那块 trunk → 派生层只在用户题材明确触及才点一下。组织 / 政权 / 宗教不再平列——它们只是"权力结构"这一元框架的三种授权来源变体（见下）。

#### 地理（基底，必问）

**构建原则**: 地理是其余所有子系统的 substrate——气候决定资源与技术，资源决定阶级与贸易，地形决定权力如何分布。只写到"**直接影响角色场景**"为止，丑地图也行，但一条地理事实必须能推出至少一处文化 / 力量 / 组织后果。

**提问**:
> "你的故事发生在什么地形和气候？这种环境逼出居民什么生存方式？这种生存方式又怎么塑造了他们的力量、组织和信仰？"

#### 力量体系（魔法 / 武学 / 科技，主干）

**构建原则**（Sanderson 三定律兜底 + 缺陷补强）: ① 先定硬 / 软——读者要懂到什么程度，角色才能用它解题；② **限制 > 能力**，先写清限制比写清能力更重要；③ 代价与后果不能免——魔法若比驴还便宜，经济当场崩；④ 一处深挖胜过十处浅尝。
**缺陷补强（开放式查漏）**: ⑤ 守**守恒律**——火球不能免费，能量 / 动量得有出处；⑥ 划**距离与稳定性**——能力有物理 / 心理 / 社会半径，不稳定本身就是隐喻；⑦ 防**无敌**——没有弱点的力量 = 无聊，必须给一道裂缝；⑧ 当**科技对待**——任何力量都需 source（来源）+ invocation（发动）+ control（掌控）+ limits（边界），四缺一就塌。

**提问**:
> "你的力量有规则吗（硬还是软）？它最大的限制是什么？用它的代价是什么？如果人人能用，经济或阶级会被改写成什么样？它有没有一道'本该无敌却会断'的裂缝？"

#### 权力结构（主干，整合组织 / 政权 / 宗教）

> 组织 / 政权 / 宗教**不是三个独立子系统**，而是同一件事的三种"授权来源"：权威 = 被授予去代行集体之力的权力，合法性不在枪杆子，而在掌权群体的 buy-in。三者区别只在**授权从哪来**：
> - **组织（faction）**: 授权来自共同目标 / 利益（功能型权威）。典型四问：为何存在 / 如何互动 / 怎么形成 / 历史如何塑今。
> - **政权（government）**: 授权来自制度化程序（制度型权威）。用尺度参数定位：集权度 / 法治度 / 继承方式（血统 / 选举 / 武力），别穷举形态，挑几种让"天生裂缝"与主题互咬。
> - **宗教（religion）**: 授权来自神圣 / 超越来源（神授权威）。常为政权提供合法化外衣；发明优于复制，与现实宗教保持可辨识距离。

**统一构建方法**（三变体通用）: ① 定授权来源（目标 / 制度 / 神圣）；② 定合法性由谁 buy-in；③ 定内部结构（成员 / 资金 / 决策 / 领导更替）；④ 定天生裂缝（所有制度都不完美——succession 危机 / 集权僵化 / 信仰与行为背离）。

**提问**:
> "这个群体凭什么管人？它的权力谁认？它内部怎么决策、领导怎么换、钱从哪来？它这套制度天生有什么裂痕？"

#### 派生层（经济 / 语言 / 历史 / 科技 / 文化 / 种族，按题材取用）

> 这六块由 trunk 长出，不是独立"块"——经济是被力量 / 权力重塑的交换，科技是力量体系的另一面（足够先进的魔法 = 科技），历史是现状倒推的分层记忆，语言 / 文化 / 种族是被地理与权力结构染色的差异。教练只在用户题材明确触及其中一块时点一句，不展开成清单。

| 派生块 | 一句话原则 | 教练提问 |
|--------|-----------|---------|
| 经济 / 货币 | 任何"免费"的力量都会重写经济——先想清它贵不贵、谁控流通（商品货币 vs 法币；市场自调节；财富集中）。 | "你的力量或资源，是商品还是法币？谁发、谁收、谁被它重新分层？" |
| 科技水平 | 交通 / 医疗 / 战争不必同速——分轴定层级（GURPS 0-15），别写"中世纪全包"；禁令暂时可自纠正。 | "这个世界的交通、医疗、战争，分别停在哪个时代？为什么不同步？" |
| 深层历史 | 从"现在什么样"倒推"怎么变成这样"；被遗忘的史靠宣传 / 歪曲 / 自然添油；神话即道德观。 | "你的现状里，哪条规矩是'当年赢家写的历史'留下的？" |
| 语言 / 文字 | 2-5 个外语词 + 1-2 个语法概念足够，别造全套 conlang；Sapir-Whorf 染色但不必写实。 | "统治者与底层说的是同一种话吗？语言本身在标阶级吗？" |
| 文化 | 基于本世界环境而非照搬现实；避免"异域沙拉"乱炖；角色有个性 ≠ 文化。 | "这种文化是被哪条地理 / 权力事实逼出来的，还是你从现实抄来的？" |
| 种族 / 民族 | 奇幻种族本是"族群 / 文化"非物种，类比政党而非生物种；别铁板一块、别优劣失衡。 | "你笔下的'种族'，是文化阵营还是生物学种？它内部有没有分歧？" |

**与 §2.3 / §五 的咬合**: 服饰（§2.3）是派生层里"文化 + 阶级 + 力量"三者在角色身上最肉眼可见的显影；权力结构与力量体系的裂缝，最终都该落到角色的日常（§五 三问）。

