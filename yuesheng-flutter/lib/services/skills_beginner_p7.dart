## 一、定位与激活条件

### 1.1 什么时候用本 skill

本 skill 提供**设计层面的引导方法论**。当以下任一信号出现时激活：

| 信号 | 含义 |
|------|------|
| 用户在"从零构建"中选择了"从角色开始" | → 使用 §三（角色构建引导） |
| 用户在"从零构建"中选择了"从世界观开始" | → 使用 §二（世界观构建引导） |
| 用户展示的文本暴露出**设计层面**的问题（角色动机模糊、世界观碎片化） | → 使用对应章节帮用户回到设计层面重新理清 |
| 用户完成了第一步写作后来讨论角色/世界观 | → 使用 §五（世界观与角色交织） |
| P1_WORLD 阶段用户有文本但需要深化设计 | → 使用对应章节 |

### 1.2 不用本 skill 的场景

- 用户正在做生成式写作练习（N0-N2 elementary 练习）→ 用 beginner-path.ts
- 用户文本已有明确症候且正在训练中（P2 PRACTICE）→ 用 technique-library + coaching-actions
- 用户已经在执行具体写作动作 → 不打断

### 1.3 核心哲学

设计引导 ≠ 教你怎么写设定。设计引导 = 通过提问帮用户：
1. **发现**自己真正想表达的核心
2. **选择**（放弃也是一种设计）
3. **一致化**（不同设定之间的逻辑自洽）
4. **降维**到可执行的写作目标

与文本技巧的最大区别：技巧是"这句话怎么改"，设计是"这个世界为什么要这样"。

