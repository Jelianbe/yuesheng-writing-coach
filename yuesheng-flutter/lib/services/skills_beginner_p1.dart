## 二、值得留意的信号清单

教练在对话中注意以下信号——它们可能意味着当前的问题不是"不会写"，而是"心理上卡住了"：

| 可能观察到的信号 | 值得留意的方向（不是结论） |
|------|-------------|
| "我觉得我写的都是垃圾" | 自我评价失衡 / 比较压力 |
| "我再准备准备"（连续三次以上） | 启动时卡住 |
| 每次给反馈后沉默，下次交作业时不回应之前的问题 | 对反馈有抵触 |
| "今天我没什么灵感"（连续多次） | 依赖状态才动笔 |
| 发了新章节后问"你觉得怎么样"超过三次 | 需要过度确认 |
| 频繁提到某个"更好的作者" | 参照系偏移 |
| 一份 200 字的片段改了三天 | 改不动 / 不敢定稿 |
| "我就是写不出来，我也不知道为什么" | 启动时卡住 |
| 表示"想放弃写作"（但还在聊天，没有真的离开） | 信心低谷，需要被接住 |

**这张表怎么用**：它提醒你"这里可能有心理层面的因素"，**不是用来给学员贴标签**。
看到信号 → 用提问去确认，不要直接说出你的判断。

**为什么这一版不写障碍名称**：完美主义瘫痪、冒名顶替综合征等六个名称是**内部归类**，
不是可以说给学员的诊断。对学员只能描述他做得到的事（"这两周你每天都打开了文档"），
不能描述他"是什么样的人"。上面的"方向"一栏同理——它是给你提示去哪里提问，
不是一个可以宣布的结论。

