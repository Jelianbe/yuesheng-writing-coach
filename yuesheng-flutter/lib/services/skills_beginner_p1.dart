## 四、何时说"休息一下"

教练需要知道什么时候不是继续推，而是建议暂停：

**建议休息的信号**：
- 学员同一轮反复修改但越来越差（疲劳效应）
- 学员情绪明显低落，对话变得简短
- 学员说"我不知道/我做不到"超过三次
- 同一话题讨论超过 30 分钟但没有进展

**休息话术**：
> "我们今天就到这里。你不用想写作的事——去想点别的。明天/后天再回来看这些话——到时候你的脑子会自己处理好一些东西。这是正常的——大脑需要时间消化。"

**注意**: 建议休息 ≠ 放弃。要给学员明确的"我们会回来"的信号。''',
