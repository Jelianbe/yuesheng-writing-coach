## 一、六大常见写作心理障碍

### 障碍 1：完美主义瘫痪

**信号**：
- 每次动笔前要"准备充分"——但这个准备永远不结束
- 反复修改同一段，永远觉得"还不够好"
- "等我准备好了再开始写"说了三个月
- 写了几百字后全部删掉，因为"方向不对"

**一种常见的可能**：作品在头脑里是完整的，落到纸上必然有落差，而这个落差让人难以接受。

**注意**：这只是最常出现的几种情况之一，**不是诊断**。判断依据只能来自学员自己说的话，
不能从"他写得不错但还在改"反推他的内心。要确认，只能问——
比如："你说的'还不够好'，是跟什么比的？"

**教练应对**（方法为主，话术自组）：

- **降低行动门槛**（不是降低质量标准）：先随便写，写错了再改——改比从零写容易
- **显式许可写差**：第一稿的任务就是存在，先把字弄出来，后面有的是时间让它变好
- **用过程替代评判**：不问"你觉得这段写得好吗？"→ 问"这段里哪句话你自己比较喜欢？"
- **大师的草稿**：好作家也是改出来的（海明威改《永别了，武器》结尾改了 47 遍），不是一气呵成

**关键判断**: 如果学员能写出来但不敢写 → 完美主义瘫痪。如果学员写不出来 → 可能是写作障碍（障碍 3）或能力问题。

---

### 障碍 2：冒名顶替综合征

**信号**：
- "我写了这些，但我觉得这不叫'写作'"
- "XX才是真正的作家，我就是随便写着玩的"
- 对自己的作品过度贬低
- 不好意思自称"作者"或"写手"

**一种常见的可能**：心里有一个"真正的作家"的形象（通常是已出版/成名的那类），
拿它当尺子量自己。

**注意**：不是诊断。要确认只能问——比如："你说的'不算写作'，是跟什么比的？"

**教练应对**（方法为主，话术自组）：

- **重新定义"作家"**：在写，就是作者——身份不靠出版解锁
- **用证据反驳"不配"**：拿 ta 真实做过的事（字数、完整角色、有读者）当反证
- **分离"身份"与"水平"**："还不够好"是客观判断，"我不配"是自我否定——后者不让人往前走
- **不用模糊赞美敷衍**：冒名顶替者只信具体、不可辩驳的证据——引用 ta 文本里真实起效的一句

---

### 障碍 3：写作障碍（空白页恐惧）

**信号**：
- 坐在空白文档前很久，一个字也打不出来
- "脑子里有画面但写不出来"
- 开头反复重写但永远写不到第二章
- 越拖越焦虑，越焦虑越写不出来——恶性循环

**一种常见的可能**：从"想法"到"文字"的通道暂时堵住了——可能是太久没写手生了，
也可能是这一段本身就难写。

**注意**：不要从"他写不出来"反推他的内心。要确认只能问——
比如："你现在脑子里有画面吗？还是连画面都还没有？"

**教练应对**（方法为主，话术自组）：

- **绕开闸门**：先让 ta 说出脑子里那一幕的画面，再把刚说的那句话打出来——这就是第一行
- **十分钟限时写**：只要求写出东西、写完不准删——计时把"创作"变成"任务"，绕过完美主义审查
- **先写中间**：开头最难（作者还不知道故事长什么样），从 ta 最想写的那一幕写起，中间立住了开头自然来
- **口述**：以上都无效就让 ta 把故事讲给你听——口→笔的通道通常比脑→笔畅通

---

### 障碍 4：比较焦虑

**信号**：
- "我看完XX的作品后觉得我写的全是垃圾"
- 频繁提到某个比自己强的作者或作品
- 在读了好作品后更加沮丧而不是受启发
- 用自己的草稿对比别人出版的成品

**一种常见的可能**：在用别人的完成品，和自己的进行时比较。

**注意**：不是诊断。要确认只能问——比如："你刚才拿来比的那个，是人家的第几稿？"

**教练应对**（方法为主，话术自组）：

- **让比较变公平**：拿自己的草稿比别人的出版稿不叫比较——能比的只有 ta 自己上个月的版本
- **把嫉妒变教材**：具体到"ta 做对了什么"，把那个方法拿过来用
- **建立自己的进步标尺**：只跟 ta 自己的旧稿比，把两段放在一起看变化

---

### 障碍 5：反馈恐惧

**信号**：
- 作品写完了但不敢给人看
- 得到负面反馈后极度沮丧，可能需要数天才能恢复
- 把教练的每一条建议都理解为"我写得不够好"
- 发布作品后每隔五分钟刷新看评论，一条负面评论毁掉一整天

**一种常见的可能**：把对作品的反馈，等同于对自己的评判。

**注意**：这不是诊断，也**不要直接把这个判断说给学员**。要确认只能问——
比如："上次的反馈里，哪一句让你最不舒服？"

**教练应对**（方法为主，话术自组）：

- **脱钩**：让 ta 感到你和 ta 站在一边面对问题，不是站在对面评判（可用"我们"指代共同讨论，不能指向创作本身——见 core-product-identity 措辞 1，无例外）
- **给反馈加"比例"**：先说整体哪里对，再数要调的点——别让 ta 的注意力只集中在要改的地方
- **正面反馈要具体**：引用 ta 文本里真实起效的一句（动作、细节），不说"这段不错"
- **评论三分类**：有用的批评认真看、口味不同礼貌点头、纯发泄直接关掉——训练 ta 自己区分

---

### 障碍 6：灵感依赖症

**信号**：
- "今天没有灵感，写不出来"
- 只在自己感觉好的时候写，其他时候不碰
- 写作产出极度不稳定——好的时候一天一万，差的时候一整个月不写

**一种常见的可能**：把写作当成需要"灵感降临"才能做的事，而不是一项可以训练的技能。

**注意**：不是诊断。要确认只能问——比如："没灵感的那几天，你打开文档了吗？"

**教练应对**（方法为主，话术自组）：

- **重新定义**：写作靠坐下来，不靠等灵感——它来之前你先开始
- **最小承诺**：每天打开文档写一句话（写"今天不想写"也行）——打破"没灵感→不打开→更没灵感"的循环
- **区分"没灵感"和"在逃避"**：真想不到接下来会发生什么 = 叙事设计问题（转 plot-design）；想得到但不想写 = 跳过它，写下一段

