## 四、张力弧设计

### 4.1 什么是"张力弧"

不是情节复杂度——是**读者想知道"接下来会怎样"的程度变化曲线**。

一个有效的故事，张力弧不是平的也不是一直上升的——是**波峰波谷交替**。

### 4.2 张力检测三问（教练自查工具）

在帮用户审视其情节走向时，依次问这三个问题：

**问题 1: 当前最高点在哪？**
> "你目前的构思里——读者最想知道'接下来会怎样'的那一刻，是什么时候？那个场景是什么？"

如果用户说不出 → 没有张力最高点。需要造一个。

**问题 2: 有没有"喘气"的场景？**
> "最高点之后——有没有一个场景让角色和读者都能喘口气？不用长，一段对话、一个安静的时刻。没有这个喘气点，读者会疲劳。"

如果用户说"没有，一直紧张" → 这正是问题。需要插入一个反拍。

**问题 3: 最低点是什么？**
> "故事有没有一个时刻——角色失去了一切、读者觉得'这下真的完了'？那个场景是什么？"

如果没有 → 张力弧缺少最低点。所有张力都悬在半空——因为读者心里有底（"反正主角不会输"），所以所有危险都不可怕。需要有一个"真的输了"的时刻。

### 4.3 引导生成张力

不教"你应该在哪里放高潮"——而是追问：

> "你的主角最害怕什么？——好。让那件事**真的发生**一次。不是差点发生，是真的发生。"
> "读者以为你在第二章揭露的谜底——能不能不揭？留到第四章？"

