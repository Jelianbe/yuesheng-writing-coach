## 三、场景序列：从"一个事件"到"一串事件"

### 3.1 适用时机

用户已经写了第一段/第一个场景（≥200字），表达想继续但不知道下一个场景写什么。

### 3.2 因果链追问法

**核心问题**：
> "刚才你写的这件事——这件事结束之后，**谁变了**？变了什么？"
> "因为你刚才写的这件事，**有谁发现了什么他知道之前不知道的**？"
> "因为这件事——**下一个必然会发生的事情是什么**？不是可能发生，是必然。"

**判断标准**: 如果用户说的"下一件事"和"上一件事"之间不存在因果关系（"因为A发生，所以B不得不发生"），那就是断裂。教练指出来：
> "你看——上一件事是你说的XXX，下一件事是YYY。XXX的发生，导致了YYY吗？如果没有XXX，YYY还会发生吗？"
> （如果用户说"不会"→ 链条成立。如果"也会"→ 需要重新找下一件事。）

### 3.3 场景功能自检

当用户设计了一个场景后，让用户自己检查：

> "这个场景结束后，如果把它从故事里删掉——有什么**不一样**？"
> "- 少了它，主线会断吗？（如果会 → 这个场景在推进情节）"
> "- 少了它，角色变薄了吗？（如果会 → 这个场景在塑造角色）"
> "- 少了它，读者对世界的理解变了吗？（如果会 → 这个场景在建立世界）"
> "- 少了它，读者对即将发生的事更紧张了吗？（如果会 → 这个场景在制造张力）"
> "——如果四个问题的答案都是'不会'，这个场景可能应该删掉。"

### 3.4 场景序列的常见病

| 病症 | 信号 | 引导 |
|------|------|------|
| **平铺症** | 场景 A→B→C，但每个场景的功能相同（都是"主角遇到一个敌人，打赢"） | 问"下一场能不能不是打？——能不能是主角**输**一次？或者**被迫逃跑**？" |
| **跳过症** | 场景 A 结束直接跳到 C，中间的 B（关键转折）被省略了 | 问"A结束后到C开始前——中间发生了什么？不是概括，是一个画面。" |
| **无因果症** | B 在 A 之后发生，但 A 不是 B 的原因 | 用 3.2 因果链追问法 |
| **支线泛滥** | 同时开了多条线索但都不推进 | 问"如果只能保留一条线——哪条线的主角最在乎？删掉其他的，它们的核心功能能不能合并进主线？" |

