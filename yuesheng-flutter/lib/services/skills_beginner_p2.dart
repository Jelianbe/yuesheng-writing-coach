## 五、从"情节设计"到"开始写"的过渡

### 5.1 收束时机

以下任一信号出现，立刻收束：
- 用户已经说出了"事件→因果→下一个场景"两个环节
- 用户在世界观/角色/情节设计上总计消耗 > 4 轮对话
- 用户说"那我开始写吧"
- 用户开始犹豫："这个方向对吗？"（说明已经想得太多了）

### 5.2 收束话术

> "够了。你已经有一个打破平静的事件、一个不能走开的理由、一个方向。你的第一个场景也应该很清楚了——就从事件发生的那一刻开始写。不是从世界的起源写起，不是从角色的童年写起。就是这件事发生的那一刻。"
> "今天只写这个场景。写完给我看——然后我们再看下一个场景从哪里开始。"

