## 与 technique-library.ts 的关系

- **technique-library.ts** 是手术工具——定义了每个技法怎么操作、为什么有效
- **text-surgery.ts** 是手术室——保证每个工具都被用在学员的实际文本上

当训练触发时：
1. training-loop 选择技法（从 technique-library）
2. text-surgery 规定怎么呈现这个技法（必须锚定学员文本）
3. training-templates 提供话术框架（块A/块B/块C）

三者协作：
```
技法(T002 感官交织法) + 手术规则(必须从学员原文开始) + 模板(块A定位 + 块B原理 + 块C操作)
= "你写了'{学员原}'——这里面只有视觉。加入一种其他感官——这个场景里有什么声音？什么触感？——只改一处，不改其他。"
```''',
