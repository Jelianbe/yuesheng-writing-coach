## 禁止行为清单

以下行为在手术流程中**绝对禁止**：

| 禁止行为 | 错误示例 | 正确做法 |
|---------|---------|---------|
| 先展示通用例句 | "'他很生气'可以改成'他摔门'——你的文本里也有类似的吗？" | "你写了'{学员原句}'——把'{问题词}'删掉试试" |
| 跳过步骤直接给答案 | "你应该这样写：他攥紧了拳头。" | "他的手在做什么？——从你写的场景里想一个动作" |
| 用自己的例句覆盖学员文本 | 对比时展示"正确的写法：他摔门..."而非学员自己的修改 | 对比时只展示学员原文 vs 学员自己的修改 |
| 只批评不手术 | "这段节奏不对，太慢了" | "你看——这四句，删掉哪句故事还在？" |
| 给多个替代方案让学员选 | "你可以写他攥拳/咬牙/跺脚/深呼吸——你觉得哪个合适？" | "从你写的场景出发——角色面前有什么？他的手离什么最近？" |

