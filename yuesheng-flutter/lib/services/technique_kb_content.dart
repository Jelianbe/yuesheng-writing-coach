### T027 高潮阶梯法

**核心原理**：高潮不是"一个事件"，而是"一组事件的阶梯式升级"。读者需要感到冲突在逐级攀升——每一级都比上一级更高，最终在最高点引爆。

**适用症候**：P015 高潮疲软症

**技法描述**：
五级阶梯推进公式：
1. **小冲突**：低强度矛盾，角色能用平常手段应对
2. **冲突升级**：矛盾超出角色预期，角色开始力不从心
3. **不可逆的转折**：某事发生，从此一切都不一样，角色陷入真正的困境
4. **情绪爆发**：角色被逼到极限，说出/做出了一直不敢的事——情感最高点
5. **余韵**：爆发后的寂静，角色和读者一起呼吸，情绪自然回落

**示范对比**：
- ❌ 疲软：铺垫十章→"他走进大殿→两人对决→他赢了→走了"（读者感觉"就这？"）
- ✅ 阶梯：①他接住第一招，退了半步——②血从他袖子里往下淌，他没有看——③剑断了。这是他师父留给他的剑——④他笑了，然后赤手扑了上去——⑤断剑还在地上转着。他弓着身，喘着气，手在发颤

**练习模板**：
> 为你作品的高潮场景画出五级阶梯。确保每一级的"赌注"都比上一级更高——第一级最多丢个面子，第五级必须足以改变主角的命运。

**关联教学动作**：A007 一句话冲突、A009 节奏变速

