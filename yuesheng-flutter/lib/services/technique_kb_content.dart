### T028 反转设计法

**核心原理**：好的反转不是"骗到读者"，而是"让读者在回顾时发现一切都有迹可循"。反转三要素：线索前置（公平机会）、误导方向（引导往另一方向想）、揭示时机（最意想不到的时刻）。

**适用症候**：P016 情节巧合过多症

**技法描述**：
三步反转设计：
1. **线索前置**：在反转揭示前至少安插3个"回顾时合理"的线索
2. **误导方向**：用读者的预期而非谎言来误导——让角色做出"看起来合理"但实际不准确的理解
3. **揭示时机**：在角色和读者最确定的时刻揭示真相——越确定，反转冲击力越大

**示范对比**：
- ❌ 无铺垫："其实他是你父亲。"——前文完全没有任何暗示，读者被耍了
- ✅ 有铺垫：线索①这个陌生人知道主角母亲的名字/②他每次看主角的眼神都很奇怪/③主角遇险时他总是第一个出现。揭示："你为什么知道我妈的名字？""因为我找了她二十年。"

**练习模板**：
> 设计一个反转。先写反转揭晓的那一段——然后倒推：列出至少3个必须前置的线索，每个线索规划好嵌入的场景。

**关联教学动作**：A003 五问法

