### T008 因果动作链

**核心原理**：叙事停滞的标志是"动作在动但因果关系不动"。每个动作必须有前因和后果。

**适用症候**：P006 节奏停滞

**技法描述**：
写出当前段落中角色的动作序列，然后为每个动作补上"因为...所以..."：
```
他喝了口水 → 因为渴了 → 所以放下杯子 → 因为他想起了什么 → 所以站起来 → 因为决定出门
```
如果某一个动作的因果链断裂（"没有原因"或"没有后果"），说明这个动作是无效的。

**示范对比**：
- ❌ 停滞：他坐在窗边。风在吹。咖啡凉了。他看了看表。还有两个小时。
- ✅ 推进：他看了一眼表——还有两个小时。他站起来，决定不再等了。

**练习模板**：
> 写出你当前段落中所有动作的因果链。找到那个"没有原因"或"没有后果"的动作，删掉它或补上因果。

**关联教学动作**：A005 动作链

