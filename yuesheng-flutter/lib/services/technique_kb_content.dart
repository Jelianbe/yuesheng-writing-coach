### T003 核心信息提取（含三稿删减变体）

**核心原理**：好描写的标准不是"多"，是"准"。一段文字的核心信息量是有限的，修饰词每多一个，核心被稀释一分。

**适用症候**：P008 语言堆砌

**技法描述**：
三步提取法：
1. **暴力删除**：删掉段落中所有形容词和副词，只留名词和动词
2. **核心判断**：读剩下来的句子，核心信息还在吗？如果还在，说明原段落冗余严重
3. **选择性恢复**：只恢复那一个非用不可的修饰词

**示范对比**：
- ❌ 堆砌：昏暗的黄昏光线下，他疲惫不堪地坐在那张破旧的木质长椅上
- ✅ 核心提取：他坐在长椅上，黄昏的光线下

**练习模板**：
> 取一段你的描写，先暴力删除所有修饰词。再只恢复一个修饰词——选最不能少的那个。

**关联教学动作**：A011 场景裁剪

