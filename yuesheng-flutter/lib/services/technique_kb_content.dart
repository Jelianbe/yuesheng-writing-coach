### T011 角色中介法

**核心原理**：世界观信息必须通过"角色知道了某事"来传递——读者跟角色同步发现，而不是被作者单方面告知。

**适用症候**：P004 信息倾泻症

**技法描述**：
所有设定信息在输出前加一道"角色过滤器"：
1. **指定接收角色**：这段信息是哪个角色发现的？
2. **发现方式**：这个角色通过什么方式获得的？（看到/听到/猜到/别人告诉ta）
3. **反应**：角色获知后的即时反应是什么？（惊讶/疑惑/恐惧/无所谓）

如果三问中有任何一个答不出来，选择不放这段信息。

**示范对比**：
- ❌ 无中介：天启王朝立国三百余年，三省六部九卿
- ✅ 有中介："天启立国三百年了，"老铁匠把刀放在灯下，"三省六部？早不是当年的三省六部了。"

**练习模板**：
> 找到一段你直接交代的设定，指定一个角色发现它。写这个角色发现时的即时反应。不超过三句话。

**关联教学动作**：A002 回归主角

---

### T012 视角锚定法

**核心原理**：视角漂移的本质是写的时候"忘了谁在看"。建立一个固定的视角锚点，所有信息都经过这个锚点过滤。

**适用症候**：P005 视角漂移

**技法描述**：
开写前确定当前段落的"视角锚点"——正在看故事的人：
1. **锚定标记**：用一个触发器（"他看见""他听见""他注意到"）锁定视角
2. **信息过滤**：只写视角角色能看到、听到、知道、感受到的信息
3. **越界检测**：写完通读一遍，标出所有"视角角色不可能知道"的信息——删掉或改写

**示范对比**：
- ❌ 漂移：林远推开门，屋里坐着三个人。他不知道的是，最左边那个人口袋里有一把刀
- ✅ 锚定：林远推开门，屋里坐着三个人。最左边那个人的手放在口袋里，口袋里鼓起一块

**练习模板**：
> 找出你文本中视角角色不知道的信息。全部改写成"他看见/听见/注意到..."。如果改写后信息不再成立，删掉。

**关联教学动作**：A002 回归主角

---

### T013 潜台词法

**核心原理**：好对话不是"信息交换"，是"意图博弈"。角色说的话和他真正想表达的内容之间有一个"缝隙"，这个缝隙就是潜台词。

**适用症候**：P011 对话疲劳症

**技法描述**：
在写每段对话之前，先问：角色真正的意图是什么？然后让角色说和这个意图相关但**不完全一致**的话。三级递进：
1. **信息层**：角色嘴上说的字面意思
2. **意图层**：角色真正想达成的目的（请求/拒绝/试探/掩饰/攻击）
3. **关系层**：这段对话在改变角色之间的关系（拉近/疏远/确认/挑战）

**示范对比**：
- ❌ 无潜台词："你爱我吗？" "爱。"
- ✅ 有潜台词："你爱我吗？" "今天怎么突然问这个。"（意图层：回避正面回答；关系层：感到不安）

**练习模板**：
> 写一段两个人的对话，要求：A 想借钱、B 不想借。但不允许出现"借钱""没钱""还"这几个词。让读者从潜台词里读出真实意图。

**关联教学动作**：A008 对话瘦身

---

### T014 声线分立法

**核心原理**：如果去掉对话标记（"XX说"），读者还能分清谁在说话吗？不能，说明角色的说话方式没有区分度。

**适用症候**：P011 对话疲劳症

**技法描述**：
为每个角色在三个维度上设定"声线特征"：
1. **词汇**：角色爱用什么词？学术词多还是口语多？喜欢用"但是"还是"不过"？
2. **句长**：角色说话长还是短？紧张时变长还是变短？
3. **语气**：角色爱反问、爱陈述、爱省略还是爱感叹？

三个角色一组对话，每个角色至少有两个维度不同。

**示范对比**：
- ❌ 无区分："你来了。""嗯。""坐。""好。""喝水？""不用。"
- ✅ 有区分："哟，舍得来了？我还以为你忘了我住哪儿。"他靠在门框上，没让路。"堵车。"林远侧身挤进门，熟门熟路地找到了冰箱。

**练习模板**：
> 写三个角色关于"要不要吃火锅"的讨论，每人最多说两句话。去掉引号和人名后，读者必须能分出来谁是谁。

**关联教学动作**：A010 角色盲写

---

### T015 对话节奏法

**核心原理**：对话的节奏就是情绪的节奏。短句→急促/紧张/愤怒；长句→平和/犹豫/掩饰；沉默→情绪的最高潮。

**适用症候**：P011 对话疲劳症

**技法描述**：
三段式节奏控制：
1. **加速**：对话越来越短，回合越来越快——情绪在升温
2. **峰值**：最短的一句或一个词——情绪在顶点
3. **释放**：插入动作/沉默/转移话题——节奏回落

**示范对比**：
- ❌ 平：你去了哪里？我去了超市。买了什么？买了菜。为什么这么久？人多。→ 全程匀速
- ✅ 有节奏："你去了哪里？""超市。""三个小时？""……""看着我。""我去了医院。"（短句加速→沉默峰值→揭示释放）

**练习模板**：
> 写一段对话，用对话节奏表现"从平静到爆发"：前三句每句 10-15 字，中间三句每句 3-5 字，最后一句只有 1-2 个字。

**关联教学动作**：A009 节奏变速

---

### T016 对白动作插入法

**核心原理**：纯对话（Talking heads）让读者看不到"画面"。每段对话之间插入一个动作，读者就有画面了。

**适用症候**：P011 对话疲劳症

**技法描述**：
每 2-3 句对话之间至少插入一个动作描写。动作可代替对话标签、表达情绪、控制节奏、交代环境。

**示范对比**：
- ❌ Talking heads："你确定？""确定。""不后悔？""不后悔。""那好。""走吧。"
- ✅ 动作插入："你确定？"他没有回头。"确定。"林远把钥匙放在桌上，"不后悔？"钥匙在桌面上发出清脆的一声。"不后悔。"

**练习模板**：
> 找一段你只有对话的段落，在每两句话之间插入一个动作描写。不能重复使用"XX说""XX道"。

**关联教学动作**：A008 对话瘦身、A006 感官全开

