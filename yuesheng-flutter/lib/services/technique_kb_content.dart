### T030 人设锚定法

**核心原理**：连载中的角色一致性不是靠"记住角色什么样"，而是靠"为角色设定行为边界"。角色可以成长、可以改变——但不能跳出边界。

**适用症候**：P018 人设崩塌症

**技法描述**：
三步人设锚定：
1. **核心特质清单**：为每个核心角色写下3个不可动摇的行为准则——"在任何情况下都不会做的事"+"在任何情况下都会做的事"
2. **行为边界**：为每个核心特质设定"压力测试"——当角色被逼到极限时，这个特质会怎么表现？
3. **每章自查**：写完一章后用核心特质清单检查每个关键行为——"这个行为在边界内吗？如果不在，有没有足够铺垫来解释？"

**示范对比**：
- ❌ 崩塌：前50章冷静从不伤人→第51章突然打路人。无任何铺垫
- ✅ 有锚定的改变：核心特质①不主动伤人→②在女儿被威胁时打了人→③打完后的反应不是"我变了"，而是对着拳头沉默了很久——"我刚才做了和我最看不起的人一样的事。"

**练习模板**：
> 为你主角写下3个核心特质——每个都是"不可践踏"的。然后写一个场景：这3个特质同时面临考验——角色必须在其中两个之间做出选择。

**关联教学动作**：A003 五问法、A010 角色盲写

