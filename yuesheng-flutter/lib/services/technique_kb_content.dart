### T007 意外测试法

**核心原理**：角色平面化的本质是"可预测"。让角色做一件读者想不到但回溯时又觉得合理的事，角色立刻有立体感。

**适用症候**：P010 OC 平面化

**技法描述**：
为角色设计一个"意外的反应"——在特定场景中，角色做出和读者预期相反的行为，但事后回顾时是合理的：
- **反向反应**：被夸的时候不是开心，而是不安
- **矛盾反应**：嘴里说"没关系"，但手指握紧到发白
- **层级反应**：第一反应是 A，第二反应是 A 的对立面——展示内心的矛盾

**示范对比**：
- ❌ 可预测：她收到礼物，很开心地笑了
- ✅ 意外：她收到礼物，笑了一下，但笑得很犹豫，像是在判断这礼物背后有没有藏着什么

**练习模板**：
> 为你主角设计一个场景：ta 遇到了本应该开心的事，但 ta 的第一反应是"不安"或"怀疑"。写 50 字。

**关联教学动作**：A003 五问法

