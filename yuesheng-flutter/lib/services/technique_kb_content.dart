### T029 过渡桥接法

**核心原理**：场景切换不需要"镜头一转""与此同时"——上一个场景的最后一个画面/情绪/声音可以自然成为下一个场景的第一个画面/情绪/声音。找到这根"线"，两个场景就无缝了。

**适用症候**：P020 过渡生硬症

**技法描述**：
三种桥接方式（选一即可）：
1. **感官桥接**：上一个场景最后的感官体验延续到下一个场景开头——"他关上门，身后的声音还在响。"→"城市的另一边，同样的雨声敲着另一扇窗。"
2. **情绪桥接**：上一个场景结束时的情绪状态自然延续——"他坐在那儿，不知道该去哪。"→"她也在坐着。和他在不一样的窗前，发着一样的呆。"
3. **因果桥接**：上一个场景的结果直接触发下一个场景——"他按下了发送键。"→"手机在黑暗中亮了一下。"

**示范对比**：
- ❌ 机械："他在废墟中找到了那封信。镜头一转。城市的另一端，一个黑衣人正在敲一扇门。"
- ✅ 感官桥接："他把信纸从废墟里抽出来。纸的边角碰到一块碎玻璃，发出一声很轻的叮——城市另一端，一扇门也在响。有人在敲。"

**练习模板**：
> 找一段你用了"镜头一转/与此同时"的过渡。删掉它——然后用三种桥接方式各写一版过渡。选你觉得最自然的那版。

**关联教学动作**：A009 节奏变速、A006 感官全开

