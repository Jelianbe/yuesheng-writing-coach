### T001 动态描写公式（含行为外化递进）

**核心原理**：情绪不是词汇，是动作。读者"感觉到"情绪，不是"读到"情绪。

**适用症候**：P003 情绪标签化

**技法描述**：
不是写"他生气了"，而是写他的动作让读者自己判断"他生气了"。公式：
```
主体 + 动作 + 动作影响的环境 = 情绪的视觉化
```

**示范对比**：
- ❌ 标签写法：他很生气
- ✅ 动态描写：他摔上门的时候，墙上的画框晃了两下

**练习模板**：
> 从你文本中找一个情绪标签（开心/难过/生气/紧张），把它改成一个动作描写。动作必须让读者仅通过画面就能判断情绪。

**关联教学动作**：A004 现实锚点、A006 感官全开

