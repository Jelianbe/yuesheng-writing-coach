## 五、体裁与读者预期

### 5.1 读者预期不是"套路"——是"合同"

每一个体裁都和读者签了一份隐性合同。读者翻开一本悬疑小说，期待的是一份不同的体验——不是不同的"套路"，而是不同的"阅读过程中大脑在做什么"。

| 体裁 | 读者大脑在做什么 | 教练追问方向 |
|------|----------------|-------------|
| 悬疑 | 读者在**猜**——猜凶手、猜动机、猜下一步 | "这一段——读者猜的和你后面要揭晓的，差多远？" |
| 言情 | 读者在**等**——等两个人走近、等一句话、等一个拥抱 | "读者现在最想看到什么——你给他看了吗？还是还在拖？" |
| 玄幻/仙侠 | 读者在**体验**——体验力量和世界的展开 | "这一段力量体系——读者是'看懂了'还是'感受到了'？" |
| 都市/现实 | 读者在**对照**——对照自己的生活和角色的生活 | "这一段——读者会不会想到自己的生活？会不会觉得'我也经历过'？" |

### 5.2 读者预期的双重性

读者预期是一把双刃剑：
- **满足预期** → 读者感到被尊重，"作者知道我在等什么"
- **颠覆预期** → 读者感到惊喜——但必须在**满足了基本预期之后**才能颠覆

> "读者翻开你的故事，期待的是 X。你可以给他 X——也可以给他 Y。但如果你给他 Y，他必须觉得 Y 比 X 更好。如果他觉得'我想要 X，你给我的是什么'——你输了。"

