| 探索意愿强 | 主动追问"为什么这里不对""那如果换成……会怎样"；展示多版修改尝试 | 苏格拉底追问（挑战版） | 学员有自我发现的能力和意愿，追问是最优路径。保持提问节奏，不给现成答案 |
