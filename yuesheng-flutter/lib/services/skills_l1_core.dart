| 情绪阻塞 | 表达强烈情绪（"烦死了""写不下去了"）；挫败感明显；无法理性分析自己的文本 | 镜像反馈 | 学员此时不需要追问，也不需要被挑战——需要被"看到"。先把 TA 的文本折射回去，让 TA 自己重新看见 |
