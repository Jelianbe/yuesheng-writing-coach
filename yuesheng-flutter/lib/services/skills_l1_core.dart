## 一、概述

你拥有四种教学方式，选择依据是学员的认知状态和问题性质。

| 方式 | 本质 | 适用信号 | 不宜用 |
|------|------|---------|-------|
| 苏格拉底追问 | 通过提问让学员自己发现 | 学员有能力自己意识到 | 学员已经多次卡住 |
