## 一、核心理念

限时本身不是训练目标——它是绕过完美主义的教学工具。当学员在改写中反复纠结、迟迟不动手时，时间上限把"要不要改好"变成"必须交出一个版本"。**完成的版本是可评估的，完美的版本是永远不存在的。**

## 二、适用场景

| 场景 | 触发信号 | 限时目的 |
|------|---------|---------|
| 过度打磨 | 学员反复修改同一个词/句子 ≥3 次 | 切断无限修改循环 |
| 延迟决策 | 学员说"我还在想"但迟迟不改 | 推动即时决策 |
| 完美主义审查 | 学员改写耗时过长、来回纠结 | 让"够好"取代"最好" |
| 节奏卡顿 | 训练轮次紧张、学员反复返工 | 加快单轮节奏 |

**不适用**：学员正处在新手恐慌期（不敢下笔）时不要用——先用 writer-psychology 应对恐惧，再谈限时。

## 三、执行流程（四步）

### 步骤 1：设置限时

根据改动范围给出明确时间上限（数字 + 起点）：

| 改动范围 | 建议时限 |
|---------|---------|
| 单句改写 | 2 分钟 |
| 小段改写（2-3 句） | 5 分钟 |
| 整段改写 | 10 分钟 |

同时说明规则，一次说完：
> "给你 5 分钟，改这一处。时间到就停——不用写到'完美'，交出一个版本就行。写完了提前告诉我，没写完时间到了也停。"

**规则要点**：
- 必须给出明确的数字时限（不是"快点"）
- 必须说明"时间到即停，未完成也提交"
- 完成标准照常给出（限时不改变评估标准）

### 步骤 2：启动计时

给出明确的开始信号，不再加任何引导。
> "开始。5 分钟后见。"

- 计时开始后**不再说话**——任何补充引导都会打断专注
- 学员中途提问 → 一句简短回答，然后回到计时

### 步骤 3：时间到

时间到即收版本，**不延期**：
> "时间到。把你现在的版本发给我。"

- 无论学员是否"满意"，收到的版本就是评估对象
- 学员说"再给我两分钟" → 不延（延时会退回完美主义模式）："不用完美——你手上这个版本就够了。发过来。"
- 学员说"我还没改好" → "没关系，你当前这一版就是这轮的结果。我们看看它——下次可以更快。"

### 步骤 4：评估照常

限时只改变"执行方式"，不改变评估标准：
- 学员自评 → 改前改后对比 → AI 评估（三档：达标/部分达标/未达标）
- 达标/未达标判定与普通改写一致
- 反馈时肯定"完成的动作"本身："你在时限内交出了版本，这就是速度。"——再回到文本评估

## 四、禁用行为

- ❌ **不因未完成而判定失败**：限时的目的是绕过审查，不是制造新压力——未完成按"当前版本"正常评估
- ❌ **不延期**：学员要求"再两分钟"时不松口
- ❌ **不要求"写得多好"**：限时内只要求"交出一个版本"
- ❌ **不跳过改前改后对比**：限时是形态，text-surgery 的强制收尾依然有效''',
);
