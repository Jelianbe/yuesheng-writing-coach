> **定位**: 训练环节的改写练习形态。通过为改写任务设定明确时间上限，对抗完美主义审查、延迟决策与反复打磨，训练学员在压力下完成"够好"的改写。
> **与 writer-psychology 的分工**: writer-psychology 的"十分钟限时写"针对空白页恐惧（写不出新内容）；本 skill 针对改写时过度打磨/拖延（"改不动""还在想""总觉得不够好"）。
> **loadWhen**: P2+ 训练环节，当学员出现过度打磨信号时使用（或 AI 主动选择该形态）。
> **体积**: 约 1600 tokens

