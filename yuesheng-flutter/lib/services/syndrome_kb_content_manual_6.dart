### P043 题材边界感缺失症

> **position_sensitivity**: global

**核心问题**：写作者不清楚自己写的是哪个题材赛道、目标读者是谁，题材内部混搭失焦（言情里硬塞科幻设定、历史里硬塞系统文），读者找不到类型预期，平台也推不动。与 P025（黄金三章失效，是开篇契约问题）不同，P043 是更前置的**赛道定位**问题——连"写给谁看"都没想清。

**触发信号**：开篇大段世界观铺陈却不说清楚类型；同一本书里言情、悬疑、科幻元素随机混搭；作者自己说不清"这本书像哪一类畅销书"；题材随热点飘移，上一本赘婿下一本无限流毫无积累。

**判断原则**（基于上下文，非硬性标准）：
- 读者能不能用一句话说出"这是本什么书"？
- 题材混搭是否有统一的内核（类型约定）支撑，还是单纯蹭元素？
- 目标读者画像是否清晰（给谁爽、给谁哭）？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别章节跑题，主类型仍可辨识
- L2：主线题材模糊，读者找不到类型预期
- L3：全书赛道混乱，平台无法归类、读者无从安利

**例外情况**（以下场景通常不是题材边界缺失）：
- 有意做类型融合且内核统一（如蒸汽朋克=工业+魔法，有明确审美纲领）
- 文学性实验作品（类型边界本就是讨论对象）
- 系列化多品类（作者明确是多线品牌，非单本混搭）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（题材混搭失焦）**：
> 原文：第一章是深宅大院里的嫡庶争斗（古言），第三章突然冒出系统面板"叮，检测到穿越者"，第五章又变成都市商战。读者问："这到底是个啥？"
> 判定：P043 L2
> 理由：题材元素随机混搭，无统一类型内核，读者找不到预期。

**❌ 未命中（类型融合有纲领）**：
> 原文：全书是唐朝背景，但主角用"格物"之法造蒸汽机与机关兽，叙事始终扣住"礼法社会撞上工业理性"的张力。
> 判定：不触发
> 理由：蒸汽朋克式融合有统一审美纲领，类型内核清晰。

**✅ L3 命中（赛道混乱）**：
> 原文：作者在简介写"本书集爽文、虐恋、悬疑、科幻、种田于一体"，正文前三十章换了四种打开方式，签约编辑都无法归类频道。
> 判定：P043 L3
> 理由：全书无稳定赛道，平台与读者都无从安利。

**推荐教学动作**：首选 A007 一句话冲突，备选 A003 五问法

**外部佐证（商业网文向标注）**：本症候为"商业网文向"题材定位专项——面向以网文商业逻辑写作的学员；非商业/纯文学向学员若题材融合有纲领则不触发。

### P044 切入点选择偏差症

> **position_sensitivity**: serial

**核心问题**：开篇或章节不从最有戏的地方进故事，而是从背景铺陈、日常流水、设定说明起笔，绕大圈才进正题，读者在前 300 字流失。与 P025（黄金三章整体契约失效）不同，P044 是**切入角度**问题——不是三章没建好，而是第一笔就选错了落点。

**触发信号**：开局先交代世界观/身世/设定三页才出现第一个事件；主角出场前用大段环境或旁白铺垫；章节开头从"昨天发生的事"倒叙半天；作者觉得"背景很重要必须先讲"而读者觉得"跟我有什么关系"。

**判断原则**（基于上下文，非硬性标准）：
- 开篇第一句落地在"有冲突/有悬念/有具体的人"上吗？
- 背景信息能否后置到情节推进中自然带出？
- 读者在前 300 字能不能找到"继续读的理由"？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别章节开头偏平，正题来得稍慢
- L2：开篇/重要章节切入点拖沓，流失风险高
- L3：整本书惯于绕圈起笔，读者留存系统性受损

**例外情况**（以下场景通常不是切入点偏差）：
- 刻意慢热铺垫（作者清楚节奏，且前文有钩子托底）
- 多线叙事的必要交代（每条线都有自身钩子）
- 文学性序章（类型约定，读者预期不同）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（从最无聊处起笔）**：
> 原文：第一章用两千字介绍大陆版图、七大帝国疆域、主角家族三百年的兴衰史，直到章末才出现主角第一次遇险。
> 判定：P044 L2
> 理由：从背景铺陈起笔，正题严重后置，前段无可读钩子。

**❌ 未命中（先给钩子再铺背景）**：
> 原文：开篇主角被按在斩首台上，刀落前一刻他想起三天前那封密信——然后才倒叙回大陆局势。
> 判定：不触发
> 理由：先给强冲突钩子，背景作为解谜后置，切入点正确。

**✅ L3 命中（系统性绕圈）**：
> 原文：全书每章都从"清晨醒来—梳洗—回忆往事"起笔，读者要熬过八百字才到剧情。十章读完留存率掉到三成。
> 判定：P044 L3
> 理由：切入惯性拖沓，整书留存系统性受损。

**推荐教学动作**：首选 A007 一句话冲突，备选 A001 缩小范围

**外部佐证（商业网文向标注）**：本症候为"商业网文向"开篇效率专项——商业网文对前 300 字留存极敏感；纯文学/慢热向作品若前文有钩子托底则不触发。

### P045 驱动力套皮缺失症

> **position_sensitivity**: global

**核心问题**：主角的"想要什么"只写在标签层（想复仇、想变强、想保护），没有可感知的动机锚点——无具体对象、无代价、无场景落地，读者替角色着急不起来。与 P039（目标模糊，是目标四要素缺失）不同，P045 是**驱动力无锚**——目标词有了，但底下是空的；与 P040（被动主角，是不主动）不同，P045 是连"为什么想要"都说不清。

**触发信号**：动机全靠旁白/简介盖章（"他一心想复仇"），正文里看不到为这个目标付出的具体行动与代价；欲望可以被任意同义替换（把"复仇"换成"变强"句子依然通顺，说明欲望没有专属锚点）；冲突来了主角却不为自己的"核心欲望"做任何挣扎。

**判断原则**（基于上下文，非硬性标准）：
- 把主角的欲望词换成一个无关词，句子还成立吗？（成立＝欲望是套皮）
- 欲望有没有绑在具体的人/物/场景上（而非抽象概念）？
- 主角为这欲望付出过可感知的代价吗？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别动机略显标签化，主线仍可推动
- L2：核心欲望悬空，读者代入受阻
- L3：全书驱动力皆为套皮，人物行为失去内在逻辑

**例外情况**（以下场景通常不是驱动力套皮）：
- 欲望本身在成长（开局模糊、中段逐渐锚定，是角色弧线设计）
- 反类型作品刻意留白动机（读者参与补全）
- 群像/事件驱动型（本就不依赖单一主角欲望）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（欲望可替换）**：
> 原文：他握紧拳头："我一定要变强。"下一章他又说："我一定要复仇。"两句话的主语欲望互换，上下文毫无违和——说明这两个词对他只是同义标签。
> 判定：P045 L2
> 理由：欲望无专属锚点，可任意替换，底下是空的。

**❌ 未命中（欲望有锚）**：
> 原文：他每月十五去城北坟头坐一夜，因为三年前妹妹被掳那夜正是十五——"变强"对他不是口号，是赎那夜没拉住她的手。
> 判定：不触发
> 理由：欲望绑在具体的记忆与场景上，有代价有锚点。

**✅ L3 命中（全篇套皮）**：
> 原文：全书所有角色都"为了正义""为了和平"行动，没有人因为任何具体的、属于自己的东西挣扎，冲突像在空转。
> 判定：P045 L3
> 理由：驱动力皆为套皮，人物行为失去内在逻辑。

**推荐教学动作**：首选 A003 五问法，备选 A007 一句话冲突

### P046 翻译腔/外来语干扰症

> **position_sensitivity**: chapter

**核心问题**：句子带着翻译腔——长定语前置、名词化堆叠、被动句滥用、It is…式抽象判断，或被生硬的音译词/外来语打断中文语流，读起来像机翻不像人写。不是单句偶发（那是 P008 语言堆砌的字句层），而是**句式结构被外语语序带跑**。与 P022（重复用词/基础语病）不同，P046 的问题在"不像中文"而非"重复"。

**触发信号**：一句话里三四个"的"字长定语叠在名词前；频繁"被…所…""对于…来说"式被动/框式结构；抽象名词作主语句首（"重要的是…""值得注意的是…"）；音译词/外文术语没有中文语境缓冲直接砸进句子。

**判断原则**（基于上下文，非硬性标准）：
- 这句话按中文习惯，语序要不要重排？（长定语能不能拆成短句？）
- 被动/框式结构是不是多余？（"被他所击败"能否改主动？）
- 音译词有没有给读者落地的中文锚点？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别句子翻译腔明显，整体仍通顺
- L2：段落级翻译腔，语感断裂影响阅读
- L3：通篇机翻腔，读者出戏严重

**例外情况**（以下场景通常不是翻译腔）：
- 学术/法律等本就框式表达的文体（类型约定）
- 角色人设故意用书面/翻译腔说话（角色声线功能）
- 有意借用外来语制造异域感（作者主动选择，且有中文缓冲）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（长定语+被动）**：
> 原文：被那个在昨天的会议上所被提及的关于项目的决定性的方案，是由他来完成实施的。
> 判定：P046 L2
> 理由：长定语前置+被动框式堆叠，典型翻译腔，中文语感断裂。

**❌ 未命中（中文主动短句）**：
> 原文：昨天会上提了那个关键方案，最后交给他落地。
> 判定：不触发
> 理由：中文主动短句，语序自然，无翻译腔。

**✅ L3 命中（通篇机翻）**：
> 原文：值得注意的是，对于主角而言，最为重要的是，那个被命运所选择的少年，在他的旅程之中，逐渐地认识到了世界的真相。
> 判定：P046 L3
> 理由：通篇"It is…/对于…而言/被…所"框式，机翻腔严重。

**推荐教学动作**：首选 A006 感官全开，备选 A011 场景裁剪

**外部佐证（中文写作规范三来源）**：翻译腔/外来语干扰被独立规范印证——B-42（机翻腔诊断）、C-14（real 直译导致的语序异化）；语法层 A-11/12/13/16 与 B-3/4/9 的"中文主谓骨架"要求侧面约束 P046。

### P047 空评价词症

> **position_sensitivity**: chapter

**核心问题**：大量使用"很美""太棒了""特别感人""非常震撼"等无信息量评价词，作者不断给场景"盖章"，读者只看到判断看不到画面。不是描写少（那是 P028 画面感缺失），而是**用判断代替呈现**——把本该让读者自己感受的东西直接替读者下了结论。

**触发信号**：一段话里反复出现"好/美/棒/感人/震撼/绝了"等评价形容词或感叹；情绪场景靠"太感人了"收尾而非靠细节让人鼻酸；形容一个人漂亮写"她真的很美"而不是写她的眉眼与姿态；评价词密度高到读者只记得作者在不停夸。

**判断原则**（基于上下文，非硬性标准）：
- 这个评价词能不能换成具体画面？（不能＝空评价）
- 删掉这句中"很/太/非常"，句子还剩什么信息？
- 作者是在"呈现"还是在"替读者下结论"？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别评价词空转，不影响理解
- L2：段落级空评价，画面被判断淹没
- L3：通篇盖章式评价，读者无法自己感受

**例外情况**（以下场景通常不是空评价词）：
- 第一人称内心吐槽（角色声线，评价是性格）
- 反讽/刻意夸张（作者主动修辞）
- 极简留白后的一个重音词（前文已铺满画面，末句一个"美"是收束）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（判断代替呈现）**：
> 原文：她站在夕阳下，真的很美，美得让人感动，那种美太震撼了，我简直说不出话。
> 判定：P047 L2
> 理由：连续空评价词盖章，读者只见判断不见画面。

**❌ 未命中（用画面说话）**：
> 原文：她站在夕阳下，风把她的裙角吹成一面褪色的旗，侧脸的轮廓被光描出一道毛边。
> 判定：不触发
> 理由：用具体画面呈现，读者自己会感受到美。

**✅ L3 命中（通篇盖章）**：
> 原文：这顿饭很好吃，这家店太棒了，那个服务员特别热情，整个体验非常完美，我真的好感动。
> 判定：P047 L3
> 理由：通篇空评价，无一处具体呈现，读者无法代入。

**推荐教学动作**：首选 A006 感官全开，备选 A016 高频词清扫

**外部佐证（中文写作规范三来源）**：空评价词被独立规范印证——C-8（评价词空转，须以感官细节替代）；与 P028 画面感缺失互为表里，P047 重在"判断代替呈现"。

### P048 语法层语病症

> **position_sensitivity**: chapter

**核心问题**：基础语法错误——主谓搭配不当、指代混乱、时态跳脱、成分残缺，句子本身读不通。不是修辞问题（那是 P008 语言堆砌/P046 翻译腔），而是**句子骨架就立不住**，读者要在脑内先做语法修复才能读懂。与 P022（重复用词/基础语病）不同，P048 指"句子读不通"而非"词用重复"。

**触发信号**：一个长句里主语中途消失、后半句不知谁在动作；"他"指代前文的甲还是乙分不清；过去现在将来时态在同一段乱跳；该有的谓语/宾语被删掉导致半句话；关联词残缺（"虽然…"没有"但是"）。

**判断原则**（基于上下文，非硬性标准）：
- 这句话脱离语境，语法上站得住吗？（主谓宾齐全、指代唯一？）
- 读者需要"脑补修复"才能懂，还是一次读通？
- 这是偶发笔误，还是作者缺乏语法自觉？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别句子有语病，不影响整体理解
- L2：段落级语法失稳，多处需脑补修复
- L3：通篇语法不可靠，阅读成本极高

**例外情况**（以下场景通常不是语法层语病）：
- 方言/口语化故意破句（角色声线或文体约定）
- 意识流/诗化断句（作者主动选择，语义仍可达）
- 网络语体特有的省略（读者社群共识，不影响理解）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（指代混乱+成分残缺）**：
> 原文：小李把方案交给经理，他说改完再发，然后在会上被表扬了，大家都觉得他的努力没有白费。
> 判定：P048 L2
> 理由："他"指代不清，"被表扬"主语缺失，句子需脑补修复。

**❌ 未命中（语法干净）**：
> 原文：小李把方案交给经理，经理说改完再发。一周后方案在会上通过，大家都说小李的努力没白费。
> 判定：不触发
> 理由：主谓清晰、指代唯一，一次读通。

**✅ L3 命中（通篇不可靠）**：
> 原文：由于当天气温骤降使得比赛被迫延期尽管选手们已经做了充分准备但遗憾还是发生了让主办方非常难过。
> 判定：P048 L3
> 理由：长句成分堆叠、关联词残缺，语法骨架立不住，需反复拆解。

**推荐教学动作**：首选 A016 高频词清扫，备选 A011 场景裁剪

**外部佐证（中文写作规范三来源）**：语法层语病被独立规范印证——A-11/12/13/16（主谓骨架、指代唯一、时态一致）+ B-3/4/9（基础语法健康度）；P048 是修辞层问题之下的"地基"，须先于一切文采修复。

