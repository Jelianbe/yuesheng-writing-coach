### P038 支线涣散症

> **position_sensitivity**: serial

**核心问题**：支线剧情不服务主线/人设/爽点，写着写着被带跑，主线被搁置。与 P034（配角无性格，人物维度）不同，P038 是**剧情线维度**——支线本身有事件，但删掉不影响主线；与 P027（追读动力不足，是结果）不同，P038 是导致弃书的原因之一；与 P006（局部停滞）不同，P038 是长线结构问题。

**触发信号**：支线连着写数章与主线无关的日常；主线危机在即，作者去写支线；读者问"这条线跟主线什么关系"；多个支线并行但互不相干。

**判断原则**（基于上下文，非硬性标准）：
- 支线是否有存在意义？（推动主线 / 丰富人设 / 提供爽点，三者至少其一？）
- 这条支线删掉，主线/人设/阅读体验是否有损失？
- 主线是否因支线而搁置？（支线挤占主线篇幅？）

**严重度判断**（结合三维标定表综合评估）：
- L1：单条支线略显游离，不影响主线
- L2：支线喧宾夺主，主线推进被明显拖慢
- L3：主线长期搁置，读者对"这本书要讲什么"失去把握

**例外情况**（以下场景通常不是支线涣散）：
- 支线埋了主线伏笔（看似无关，实际在给主线铺路）
- 支线丰富核心角色人设（从侧面立人物，服务于人设）
- 支线本身就是爽点单元（单元剧结构，支线即卖点）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（支线游离主线）**：
> 原文：主线危机是三天后的大比，主角却用了整整三章写他在城里帮邻居修屋顶、陪小贩讨价还价、跟路人闲聊家常的日常支线，每章结尾都没回到主线。
> 判定：P038 L2
> 理由：支线连写数章与主线无关，主线推进被明显拖慢。

**❌ 未命中（支线有主线意义）**：
> 原文：主角帮邻居修屋顶时，从邻居口中听到了一条线索——三年前那场火灾的幸存者还活着。他修完屋顶，径直朝城西走去。
> 判定：不触发
> 理由：支线埋了主线伏笔（火灾真相），事件有主线意义，不算涣散。

**✅ L3 命中（主线被搁置）**：
> 原文：大比在即，主角却陷入一场三角恋爱支线，连写十章，读者都快忘了这本书的主线是夺回王位。
> 判定：P038 L3
> 理由：主线长期搁置，读者对故事核心失去把握。

**推荐教学动作**：首选 A013 情节复盘，备选 A002 回归主角

