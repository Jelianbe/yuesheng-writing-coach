### P031 题材边界感缺失症

> **position_sensitivity**: global

**核心问题**：写作者不清楚自己写的是哪个题材赛道、目标读者是谁，题材内部混搭失焦（言情里硬塞科幻设定、历史里硬塞系统文），读者找不到类型预期，平台也推不动。与 P011（黄金三章失效，是开篇契约问题）不同，P031 是更前置的**赛道定位**问题——连"写给谁看"都没想清。

**触发信号**：开篇大段世界观铺陈却不说清楚类型；同一本书里言情、悬疑、科幻元素随机混搭；作者自己说不清"这本书像哪一类畅销书"；题材随热点飘移，上一本赘婿下一本无限流毫无积累。

**判断原则**（基于上下文，非硬性标准）：
- 读者能不能用一句话说出"这是本什么书"？
- 题材混搭是否有统一的内核（类型约定）支撑，还是单纯蹭元素？
- 目标读者画像是否清晰（给谁爽、给谁哭）？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别章节跑题，主类型仍可辨识
- L2：主线题材模糊，读者找不到类型预期
- L3：全书赛道混乱，平台无法归类、读者无从安利

**例外情况**（以下场景通常不是题材边界缺失）：
- 有意做类型融合且内核统一（如蒸汽朋克=工业+魔法，有明确审美纲领）
- 文学性实验作品（类型边界本就是讨论对象）
- 系列化多品类（作者明确是多线品牌，非单本混搭）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（题材混搭失焦）**：
> 原文：第一章是深宅大院里的嫡庶争斗（古言），第三章突然冒出系统面板"叮，检测到穿越者"，第五章又变成都市商战。读者问："这到底是个啥？"
> 判定：P031 L2
> 理由：题材元素随机混搭，无统一类型内核，读者找不到预期。

**❌ 未命中（类型融合有纲领）**：
> 原文：全书是唐朝背景，但主角用"格物"之法造蒸汽机与机关兽，叙事始终扣住"礼法社会撞上工业理性"的张力。
> 判定：不触发
> 理由：蒸汽朋克式融合有统一审美纲领，类型内核清晰。

**✅ L3 命中（赛道混乱）**：
> 原文：作者在简介写"本书集爽文、虐恋、悬疑、科幻、种田于一体"，正文前三十章换了四种打开方式，签约编辑都无法归类频道。
> 判定：P031 L3
> 理由：全书无稳定赛道，平台与读者都无从安利。

**推荐教学动作**：首选 A007 一句话冲突，备选 A003 五问法

**外部佐证（商业网文向标注）**：本症候为"商业网文向"题材定位专项——面向以网文商业逻辑写作的学员；非商业/纯文学向学员若题材融合有纲领则不触发。

### P032 翻译腔/外来语干扰症

> **position_sensitivity**: chapter

**核心问题**：句子带着翻译腔——长定语前置、名词化堆叠、被动句滥用、It is…式抽象判断，或被生硬的音译词/外来语打断中文语流，读起来像机翻不像人写。不是单句偶发（那是 P006 语言堆砌的字句层），而是**句式结构被外语语序带跑**。与 P018（重复用词/基础语病）不同，P032 的问题在"不像中文"而非"重复"。

**触发信号**：一句话里三四个"的"字长定语叠在名词前；频繁"被…所…""对于…来说"式被动/框式结构；抽象名词作主语句首（"重要的是…""值得注意的是…"）；音译词/外文术语没有中文语境缓冲直接砸进句子。

**判断原则**（基于上下文，非硬性标准）：
- 这句话按中文习惯，语序要不要重排？（长定语能不能拆成短句？）
- 被动/框式结构是不是多余？（"被他所击败"能否改主动？）
- 音译词有没有给读者落地的中文锚点？

**边界纪律**：
- 禁止把句末"吧"一律当"建议/商量"、"呢"一律当"疑问/持续"——句末语气词功能在句法层级下高度依赖上下文（FDG 框架四层层级约束；功能"elusive and notoriously controversial"），不得贴固定功能标签。
- 诊断对白口语度时：先排除同形词（"的/了"），再看语气词共现与层级约束（最多三词共现）。
- 触发：诊断对白口语度时。
- 禁止凭"读着别扭"就扣翻译腔/欧化帽子并套固定改法——先看语境可及性（已知信息是否前置、新信息是否后置），可及性合理即不是病。
- 触发：学员问"这句语序是不是有问题"时。
- 禁止看到句末"的/了/呢"就当语气词——先排除结构助词/体标记等同形用法。
- 触发：对白/内心独白句末标注时。
- 禁止把英语进行体=正在进行/未完成、完成体=已完成的直接假设套到中文"在/了/过"——中文体标记功能不同。
- 触发：中文时态诊断时。

**严重度判断**（结合三维标定表综合评估）：
- L1：个别句子翻译腔明显，整体仍通顺
- L2：段落级翻译腔，语感断裂影响阅读
- L3：通篇机翻腔，读者出戏严重

**例外情况**（以下场景通常不是翻译腔）：
- 学术/法律等本就框式表达的文体（类型约定）
- 角色人设故意用书面/翻译腔说话（角色声线功能）
- 有意借用外来语制造异域感（作者主动选择，且有中文缓冲）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（长定语+被动）**：
> 原文：被那个在昨天的会议上所被提及的关于项目的决定性的方案，是由他来完成实施的。
> 判定：P032 L2
> 理由：长定语前置+被动框式堆叠，典型翻译腔，中文语感断裂。

**❌ 未命中（中文主动短句）**：
> 原文：昨天会上提了那个关键方案，最后交给他落地。
> 判定：不触发
> 理由：中文主动短句，语序自然，无翻译腔。

**✅ L3 命中（通篇机翻）**：
> 原文：值得注意的是，对于主角而言，最为重要的是，那个被命运所选择的少年，在他的旅程之中，逐渐地认识到了世界的真相。
> 判定：P032 L3
> 理由：通篇"It is…/对于…而言/被…所"框式，机翻腔严重。

**推荐教学动作**：首选 A006 感官全开，备选 A011 场景裁剪

**外部佐证（中文写作规范三来源）**：翻译腔/外来语干扰被独立规范印证——B-42（机翻腔诊断）、C-14（real 直译导致的语序异化）；语法层 A-11/12/13/16 与 B-3/4/9 的"中文主谓骨架"要求侧面约束 P032。

### P033 冲突未升级/模式重复症

> **position_sensitivity**: serial

**核心问题**：同一冲突模式被重复使用多次，但威胁程度、信息量、情绪强度没有逐级递增。读者第二次就摸清了套路，之后再遇到只是"把音量调大"——同样的结构、同样的起承转合，只是更吵。不是冲突本身不好（那是 P010 张力不足），而是**重复的冲突没有进化**：模式可识别、强度不爬坡，读者预判了下一步，追读快感耗尽。

**触发信号**：连续几场戏都是同一套结构（如"出现异常→主角紧张→虚惊一场"）；每次危机的解法和代价差不多；新冲突和旧冲突在量级上无法区分；紧张感靠"写得更急""感叹号更多"维持而非靠局势真的恶化；读者能提前猜到"这关最后肯定虚惊"。

**判断原则**（基于上下文，非硬性标准）：
- 把第二场和第一场并列，威胁/信息量/情绪上了一个台阶吗？（原地踏步＝未升级）
- 读者第二次看到这个模式，还需要猜结局吗？（已经能背＝模式重复）
- 强度是靠"局势真的变难"推上去的，还是靠"形容词更猛"堆出来的？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别段落结构近似，强度略有差异
- L2：连续多场冲突同构，威胁不递增，读者开始疲
- L3：全篇同一套路反复，模式可预测，追读动力枯竭

**例外情况**（以下场景通常不是冲突未升级/模式重复）：
- 刻意的循环/复沓结构（主题需要"轮回感"，且作者有自觉的变奏设计）
- 日常流/治愈系本就低冲突（类型约定，不靠升级驱动）
- 看似重复实则每轮换了维度（此轮外部危机、下轮内部信任崩塌＝升级而非重复）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（同构虚惊，强度不涨）**：
> 原文：第一次：深夜异响，他握紧手电，推开门——是风吹动了窗帘。第二次：又是异响，他冲到门口，心跳如鼓——是野猫碰倒了花盆。第三次：异响再起，他额头冒汗地拉开门——又是风。
> 判定：P033 L2
> 理由：三轮"异响→紧张→虚惊"结构完全同构，威胁与信息量零递增，第三次读者早已预判。

**❌ 未命中（重复但在升级）**：
> 原文：第一次异响查出是风；第二次异响，窗台上多了一枚不属于这里的脚印；第三次异响，门是从里面被反锁的。
> 判定：不触发
> 理由：同样"异响"母题，但每轮信息量与威胁递增，模式在进化。

**✅ L3 命中（全篇套路可预测）**：
> 原文：每三章一次危机：主角被质疑→嘴硬→反转打脸→众人惊叹。七章里四次同一套流程，只是对手一次比一次喊得更大声。
> 判定：P033 L3
> 理由：冲突结构反复复用、强度只靠音量堆叠，读者完全可预测，追读快感耗尽。

**推荐教学动作**：首选 A007 一句话冲突，备选 A003 五问法 或 A009 节奏变速

**外部佐证（中文写作规范三来源）**：冲突递进/模式去重与叙事节奏规范相互印证——张力需随阶段递增而非重复同强度刺激；与 P010（张力不足，是"单次冲突没分量"）、P004（节奏停滞，是"段落无推进"）区分，P033 重在"重复的冲突没有逐级升级"。

