### P028 被动主角症

> **position_sensitivity**: global

**核心问题**：剧情需要主角去哪主角就去哪——无理由、无顾虑、无权衡，角色被作者硬拖着走，读者一眼出戏。与 P007（目标不具体）不同，P028 主角目标可能清楚，但**不主动决策**；与 P014（情节靠巧合推进）不同，P028 是**主角的主动性**问题，巧合是被动的一种表现。

**触发信号**：主角全程「被安排」——被推着进入事件、被动挨打等待反转；面临选择时无自己的考量与代价评估；剧情需要主角冲就冲，没有内心渴望或外部逼迫的支撑；配角比主角更有主意（主角变配角）。

**判断原则**（基于上下文，非硬性标准）：
- 角色的每个动作是否有动机？（要么内心渴望，要么外部逼迫）
- 面临选择时，主角是否有自己的权衡与代价评估？
- 主线推进是靠主角的决策，还是靠事件本身往前撞？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别段落主角略显被动，整体仍有主动性
- L2：主角长期被剧情推着走，读者开始出戏
- L3：主角完全木偶化，爽点偏移，配角反成主角

**例外情况**（以下场景通常不是被动主角）：
- 侦探/悬疑题材主角以「观察者」身份展开（被动是类型功能）
- 主角故意隐忍/蛰伏（等待时机是主动选择）
- 群像剧刻意弱化单一主角（类型约定）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（被推着走）**：
> 原文：反派设了个局，主角果然被引入陷阱；剧情需要他逃，他就慌慌张张地逃；需要他遇到贵人，贵人就刚好出现。从头到尾，主角没有做过一个自己的决定。
> 判定：P028 L2
> 理由：主角全程被安排，无主动决策与权衡。

**❌ 未命中（主动决策）**：
> 原文：他权衡了半炷香——进城是死路，但城外的迷雾中藏着妹妹的解药。他咬牙转身，朝迷雾走去。
> 判定：不触发
> 理由：主角有考量、有代价评估、有主动选择。

**✅ L3 命中（木偶化）**：
> 原文：十章过去了，主角每一次行动都是别人推的：师父让他去、仇家引他去、系统逼他去。读者比主角更早知道他要干什么。
> 判定：P028 L3
> 理由：主角完全木偶化，爽点与读者预期全部偏移。

**推荐教学动作**：首选 A002 回归主角，备选 A007 一句话冲突

