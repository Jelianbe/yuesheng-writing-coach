### P037 心理内耗症

> **position_sensitivity**: chapter

**核心问题**：角色内心反复纠结、自我怀疑、复盘过往，大段独白无进展。与 P003（情绪词直接告知）不同，P037 是**内心戏篇幅失控**——情绪真实但反复拉扯；与 P008（词藻堆砌）同构但载体是心理独白而非修饰词；与 P019（情感失真：反应与情境不匹配）不同，P037 的纠结本身合理，只是**没有收敛与推进**。

**触发信号**：冲突结束后大段内心复盘（"我是不是不该…万一…可是…"）；同一犹豫反复出现多段；内心独白占段落大半且无动作/决策推进；读者看独白时"进度条不动"。

**判断原则**（基于上下文，非硬性标准）：
- 内心独白是否有进展？（从纠结到决策，哪怕一步？）
- 独白是否可转为动作/对话？（卡在原地反复想，还是转化为行动？）
- 独白篇幅是否超过叙事需要？（一段纠结两三句可表达，却写了三页？）

**严重度判断**（结合三维标定表综合评估）：
- L1：个别段落内心拉扯偏长，不影响理解
- L2：每章固定大段无进展独白，节奏被稀释
- L3：冲突/行动被内心戏淹没，读者跳过独白才能读到剧情

**例外情况**（以下场景通常不是心理内耗）：
- 独白在推进决策（纠结后给出选择/行动，有收敛）
- 内心戏本身是看点（心理悬疑/权谋博弈中，内心推算即剧情）
- 少量内心留白服务于人物厚度（一段点睛独白不算内耗）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（反复纠结无进展）**：
> 原文：他躺在床上翻来覆去："我是不是不该接下这个任务？万一失败了怎么办？可是不接的话……接了又怕连累他们。要是当初没答应就好了。可现在已经答应了，现在反悔还来得及吗？"这一想，就到了天亮。
> 判定：P037 L2
> 理由：内心反复纠结、复盘过往，多段独白无决策进展，节奏被稀释。

**❌ 未命中（纠结后决策推进）**：
> 原文：他翻了个身："不接了。"这三个字一出口，胸口那团乱麻忽然松了。他爬起来，摸黑给自己倒了杯水，开始想明天怎么跟队长开口。
> 判定：不触发
> 理由：纠结后给出决策并转化为行动，有收敛有进展，不算内耗。

**✅ L3 命中（行动被内心戏淹没）**：
> 原文：反派已经杀到门口，主角却在屋内三段独白里反复复盘自己半生的选择，直到门被撞开。
