### P026 心理内耗症

> **position_sensitivity**: chapter

**核心问题**：角色内心反复纠结、自我怀疑、复盘过往，大段独白无进展。与 P001（情绪词直接告知）不同，P026 是**内心戏篇幅失控**——情绪真实但反复拉扯；与 P006（词藻堆砌）同构但载体是心理独白而非修饰词；与 P001（情感失真：反应与情境不匹配）不同，P026 的纠结本身合理，只是**没有收敛与推进**。

