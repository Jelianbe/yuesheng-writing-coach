### P039 目标模糊症

> **position_sensitivity**: global

**核心问题**：主角目标抽象模糊（想变强/要复仇），无数量/期限/代价，读者找不到可「替他着急」的点。与 P009（行为整体无动机，换角色剧情依然成立）不同，P039 角色**有动机方向**，但目标不具体不可追踪；与 P040 被动主角症（目标清楚但角色不主动行动）不同，P039 是**欲望本身不清**。

**触发信号**：开篇只写"想变强/要复仇"没有具体所指；主角被动等待事件，读者无法预期下一步；"他为什么做这件事"说不出一句话；阶段目标断档——开篇立了目标，中段被遗忘或换了个不相干的目标（serial 表现）。

**判断原则**（基于上下文，非硬性标准）：
- 目标四要素是否齐全？（具体目标 + 明确数量 + 截止时间 + 失败代价）
- 读者能不能用一句话说出"主角现在最想要什么"？
- 阶段目标是否承接长期目标？（上一目标未成型就开新目标，会让读者觉得换了一本书）

**严重度判断**（结合三维标定表综合评估）：
- L1：目标稍显空泛，但读者仍能感知主角方向
- L2：目标模糊导致读者无法为主角担心，代入感下降
- L3：全书无主心骨，读者对"这个故事要讲什么"失去把握

**例外情况**（以下场景通常不是目标模糊）：
- 角色刻意隐藏目标（悬念设计，后期揭示）
- 反类型/文艺向作品有意识地模糊欲望（类型约定）
- 新手在探索期暂时没有方向（属于设计阶段问题，非文本症候）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（目标空泛）**：
> 原文：他想变强，想在这个世界闯出一片天。至于强到什么程度、什么时候做到、做不到会怎样，他从来没有想过。
> 判定：P039 L2
> 理由：目标只有方向没有四要素，读者无可期待。

**❌ 未命中（目标具体）**：
> 原文：他需要三十八万，下周三前到账，否则妹妹的肾移植手术就要从名单上划掉。
> 判定：不触发
> 理由：具体目标 + 数量 + 期限 + 代价齐全。

**✅ L3 命中（阶段目标断档）**：
> 原文：第一卷的主角目标是夺回城主之位，第二卷开场却毫无交代地变成在学院里追女孩，两卷之间没有任何过渡和承接。
> 判定：P039 L3
> 理由：阶段目标断档，读者感觉换了本书。

**推荐教学动作**：首选 A003 五问法，备选 A007 一句话冲突

