### P042 声线漂移症

> **position_sensitivity**: global

**核心问题**：文风随段落漂移、前后声线不统一，读者辨不出"这是谁写的"。不是单段写得差（那是 P007/P008 的字句层问题），而是**风格不稳定**——情绪一上来文风突变、模仿腔与本色腔混用、对话与叙述声线打架，整本书没有一条连贯的"作者的声音"。

**触发信号**：同一部作品里一段冷峻一段煽情，切换没有过渡；写爽文时一套腔调、写日常时换一套腔调，声线跟着题材走；叙述部分像教科书、对话部分却活泼跳脱（声线分层但不在同一节奏上）；读者评价"风格不统一""不像一个人写的"。

**判断原则**（基于上下文，非硬性标准）：
- 同一场景内，叙述声线是否稳定？（句式节奏、用词浓度、视角距离）
- 情绪升级时文风是渐变还是突变？（声线漂移常在情绪高点爆发）
- 对话与叙述的声线是否属于同一个"叙述者"？（对话活泼≠叙述必须活泼）

**严重度判断**（结合三维标定表综合评估）：
- L1：个别段落文风起伏，整体声线仍可辨识
- L2：章节间声线明显漂移，读者开始出戏
- L3：整部作品声线分裂，读者辨不出"这是谁写的"

**例外情况**（以下场景通常不是声线漂移）：
- 多视角叙述刻意切换叙述者声线（类型功能）
- 角色内心独白故意用角色腔（对话功能，与叙述声线分开看待）
- 风格实验/跨题材尝试（作者主动选择，声线作为变量而非失误）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（情绪带动突变）**：
> 原文：前一刻还是克制的白描——"他关上门，把钥匙放进抽屉"；主角情绪爆发后，叙述突然变成密集的比喻和感叹——"怒火像岩浆在他胸腔炸裂！整个世界都在燃烧！！"。同一场景，声线从冷静叙述骤然切到情绪宣泄腔。
> 判定：P042 L2
> 理由：情绪高点文风突变，句式节奏与用词浓度整体切换，无过渡。

**❌ 未命中（声线分层）**：
> 原文：叙述保持白描——"她数着硬币，一枚、两枚"；对话活泼——"老板，这钱能再算便宜点不？"。
> 判定：不触发
> 理由：对话用角色腔、叙述保持叙述者腔，是声线分层而非漂移，两套声线各有稳定的句式节奏。

**✅ L3 命中（整书分裂）**：
> 原文：第一卷是冷峻的第三人称白描，第二卷变成轻快的第二人称吐槽，第三卷又切回第三人称但带着播音腔。三卷三个"作者"。
> 判定：P042 L3
> 理由：整部作品声线分裂，个人风格不统一。

**推荐教学动作**：首选 A009 节奏变速，备选 A016 高频词清扫

**外部佐证（中文写作规范三来源）**：词系/专名不统一被独立规范印证——C-6（指标名/动作词须属同一语义系统）、C-5（专名写法全文统一）；C-7（过场句/主持句/播音腔）的「腔调不统一」侧面被 P042 覆盖。详见报告 ④ 4.1。

