### P041 降智反派症

> **position_sensitivity**: global

**核心问题**：反派为坏而坏、降智送人头，无利益动机，冲突失真张力崩坏。不是冲突无分量（那是 P012 的结果），不是核心角色动机缺失（那是 P009），而是**对手角色被工具化**——放着资源不用非要无脑死磕，读者一眼看出"这是为剧情需要造的反派"。

**触发信号**：反派被主角怼两句就无脑死磕；身居高位却心思单纯得可笑；反派的行为无利益支撑（不为利、不为命、不为仇）；全篇反派都"为坏而坏"，没有一个立场站得住；读者吐槽"反派智商不在线"。

**判断原则**（基于上下文，非硬性标准）：
- 反派的每个行为是否有利益动机？（资源、活路、欲望，至少其一）
- 反派与主角的冲突是否建立在真实利益冲突上？
- 高手博弈只为两样东西——利益和活路；反派会不会做"聪明人该做的选择"？

**严重度判断**（结合三维标定表综合评估）：
- L1：个别反派略显单薄，主要对手仍有动机
- L2：核心反派降智，冲突失真，读者出戏
- L3：所有对手都工具化，主角赢得毫无说服力

**例外情况**（以下场景通常不是降智反派）：
- 反派身患执念/偏执（动机极端但不失内在逻辑）
- 喜剧/荒诞向作品刻意用降智制造笑点（类型约定）
- 反派的"愚蠢"其实是局（表面降智、暗中算计）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（为坏而坏）**：
> 原文：作为一城之主，反派放着千军万马不用，非要跟主角单挑，被主角三言两语激怒后亲自下场送人头。事后读者追问："他图什么？"
> 判定：P041 L2
> 理由：反派行为无利益动机支撑，冲突失真。

**❌ 未命中（利益动机）**：
> 原文：墨大夫悉心栽培韩立，传道授业，实则步步算计——他的目标是夺舍延续自身性命。温柔是铺垫，付出皆为目的。
> 判定：不触发
> 理由：反派行为有明确利益动机（夺舍续命），算计有铺垫。

**✅ L3 命中（全篇工具化）**：
> 原文：全书七个反派，全部是"被主角打脸后恼羞成怒送人头"的模板，没有一个有自己的利益诉求。主角赢得毫无说服力。
> 判定：P041 L3
> 理由：所有对手都工具化，冲突真实性整体崩坏。

**推荐教学动作**：首选 A003 五问法，备选 A007 一句话冲突

