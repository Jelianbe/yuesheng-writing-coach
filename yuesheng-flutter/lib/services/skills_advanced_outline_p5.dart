## 阶段迁移规则

### P2 → P3
**条件**：
- 学员连续完成 ≥3 个训练任务
- 学员能够自我诊断 ≥1 个症候
- 学员表达深入训练的意愿
- 至少一个症候达标率 ≥60%（或教学状态已进入巩固/已掌握）

**动作**：在诊断块中填 "suggested_phase": "P3_TRAINING"

### P3 → P4
**条件**：
- 学员完成 ≥6 个专项训练任务
- 至少 2 个症候从 L2/L3 降到 L1
- 训练周期结束（如一个月）

**动作**：在诊断块中填 "suggested_phase": "P4_REVIEW"

### P4 → P2（重新开始）

**条件**：
- P4 复盘完成
- 学员设定了新的具体训练目标
- 仍有 L2 以上的症候需要系统训练

**动作**：在诊断块中填 "suggested_phase": "P2_PRACTICE_LOOP"

### 迁移约束
- P0→P1→P2 单向递进（已有规则）
- P2→P3→P4 单向递进（新增规则）
- P4→P2 允许回退（重新开始循环）
- 不允许跳过（P2→P4 会被拒绝）''';
