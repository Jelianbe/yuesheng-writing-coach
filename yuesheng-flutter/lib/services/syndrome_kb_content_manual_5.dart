### P035 对话注水症

> **position_sensitivity**: chapter

**核心问题**：对话段落信息增量低——寒暄、客套、重复确认、明知故问，看似推进实则灌水。与 P011（对话无表现力：无潜台词/无动作/无区分度）不同，P035 是**对话信息密度**问题——每句对话都不推进剧情、不升级矛盾、不暴露人设；与 P004（叙述层设定灌输）不同，P035 聚焦对话层的信息冗余。

**触发信号**：连续多轮"你来了/嗯/怎么这么晚/路上有事"式寒暄；用对话解释读者已知的设定；对话重复确认同一信息；对话段长但删掉后剧情无变化。

**判断原则**（基于上下文，非硬性标准）：
- 每句对话是否有信息增量？（推进剧情/升级矛盾/暴露人设/抛出线索，四者至少其一）
- 这段对话删掉，剧情/情绪/信息是否有损失？（无损失 = 纯注水）
- 对话是否在重复交代？（明知故问/重复确认/废话解释）

**严重度判断**（结合三维标定表综合评估）：
- L1：个别对白注水，不影响理解
- L2：整段对话以寒暄客套为主，读者快速扫过
- L3：长对话章节全靠水话撑字数，节奏被拖垮

**例外情况**（以下场景通常不是对话注水）：
- 寒暄本身在暴露人物关系/性格（客套话带情绪、带潜台词）
- 慢节奏场景的闲笔对话服务于氛围（有情绪价值的闲聊不算水）
- 信息量少但每句都推进情绪（情绪张力本身是信息）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（寒暄客套无信息增量）**：
> 原文："你来了。"他头也不抬。"嗯，我来了。""怎么现在才来？""路上有点事耽误了。""吃过饭了吗？""还没有。""那先去吃饭吧。"
> 判定：P035 L2
> 理由：多轮对话无信息增量，寒暄客套灌水，删掉后剧情无变化。

**❌ 未命中（对话推进剧情）**：
> 原文："耽误什么事，需要你失联一整晚？"她抬眼，语气平得很。"救一个人。"他把沾血的袖口往下扯了扯，"顺便，知道了你哥是怎么死的。"
> 判定：不触发
> 理由：每句对话都在推进剧情/抛出线索，信息密度高，不算注水。

**✅ L3 命中（对话层灌设定）**：
> 原文：女主和闺蜜一聊就是三页，把整个世界的修炼体系、势力分布、主角身世从头到尾讲了一遍。
> 判定：P035 L3
> 理由：用对话大段交代设定，看似推进实则灌水，节奏被拖垮。

**推荐教学动作**：首选 A008 对话瘦身，备选 A009 节奏变速

