### P023 设定矛盾症

> **position_sensitivity**: global

**核心问题**：世界观设定前后冲突——能力体系规则、等级上限、地理距离、时间线、历史事件、魔法/科技规则在连载中自相矛盾（"筑基能御剑"与"筑基不能飞行"并存）。与 P015（角色行为模式断裂）不同，P023 是**设定事实层**矛盾；与 P002（设定以旁白硬塞）不同，P023 是设定**本身不自洽**，不是呈现方式问题。

**触发信号**：读者在评论区指出"前后设定对不上"；同一规则在前后文有不同描述；角色能力/世界规则随剧情需要临时变动。

**判断原则**（基于上下文，非硬性标准）：
- 同一设定要素在前文与后文描述是否一致？
- 能力/规则是否只服务于当期剧情，违背既有约束？
- 时间线（季节/人物年龄/事件间隔）是否自洽？
- 设定矛盾先分层：局部接缝矛盾（这一章前后说法不一）vs 全局历史矛盾（跨卷与已确立世界史冲突）；时间边关系须显式标注，不隐式默认，附五类边状态账本 before/after/overlap/contains/equal。
- 判"时间线矛盾"前四分：(1) 显式冲突（两处明说且互斥）；(2) 闭包矛盾（由已陈述推出互斥）；(3) 领域知识冲突；(4) 欠指明（文本根本没给足够信息）。第 (4) 类不得判为矛盾，只能记"时间未定"。

**边界纪律**：
- 禁止把“同一章/同一场”自动当成同一时间容器；禁止把相邻叙述事件默认设为 BEFORE（先后）关系。
- 触发：时间关系标注。
- 禁止在文本未给足时间信息时，由教练/模型"补全"一个唯一时间点。
- 触发：梳理时间线/排查时间矛盾——证据不足记"时间未定"，与"欠指明不判矛盾"一致。
- 禁止因为一个指代能在原文找到所指，就判定该处语义正确或与前文长程自洽。
- 触发：回指/指称核对。
- 禁止把人物的愿望/信念/谎言/回忆/假设并入故事事实时间线。
- 触发：视角漂移/情感失真/设定矛盾诊断。
- 禁止把页码/章节位置当故事时间真值；禁止把两段已叙述跨度之间的省略空隙（ellipsis）由模型记忆补写。
- 触发：梳理跨章时间关系——空隙内事件记"未叙述"，不得自行补全。
- 禁止在作品含时间循环/穿越/多世界/嵌套时把所有事件排进单条 fabula 轴。
- 触发：此类设定作品——须报 single_fabula_axis_inapplicable 并按分支/时间旅行体制处理，不得强行压单轴。
- 禁止单本网文诊断时引入跨作品实体键账本；禁止自动修正学员后作/附录与正文的设定矛盾。
- 触发：仅当用户声明跨作品共享世界（系列/同宇宙）时才激活账本。
- 禁止把传统线性小说里的人物愿望/未发生的可能/假设/倒叙自动标注为"互动分支/多结局/平行世界"。
- 触发：仅当作品真给离散选择点/存档重载规则时才启用分支真值审计。
- 禁止在未声明一致性体制时混用"过去不可改/平行世界/覆盖时间线"；L4 不得自行"修复"时间线矛盾。
- 触发：时间旅行/循环/多世界作品——先在四种体制中显式声明其一，再诊断。
- 禁止把某章"代表日期"写成完整起止；禁止把两章同日/同季写成严格同时。
- 触发：长篇跨卷设定审计——跨卷日期重叠只能建 synchronization_candidate，不得写 synchronized。

**严重度判断**（结合三维标定表综合评估）：
- L1：单处细节矛盾（如地名前后不一致），不影响主线理解
- L2：关键设定矛盾（能力体系/世界规则），读者可感知到"作者忘了"
- L3：核心设定崩塌（主角能力来源/世界根基矛盾），读者对故事可信度整体怀疑

**例外情况**（以下场景通常不是设定矛盾）：
- 视角限制下的信息差（角色不知道 ≠ 设定矛盾，P003 场景）
- 角色成长导致的合理能力变化（有铺垫的升级不算矛盾）
- 留白设定（未明确过的规则不构成"前后不一致"）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（规则冲突）**：
> 原文：第三章主角使用"瞬移符"跨越千里。第十五章同一张符纸被描述为"只能移动十步"。两处对瞬移符的规则描述冲突，且无任何解释。
> 判定：P023 L2
> 理由：同一设定要素规则矛盾，读者可感知到"作者忘了"。

**❌ 未命中（信息差）**：
> 原文：第三章主角对女配隐瞒了自己会御剑。第十五章暴露时女配震惊。
> 判定：不触发
> 理由：是信息差/角色选择，非设定矛盾。

**推荐教学动作**：首选 A013 情节复盘，备选 A012 伏笔追踪

### P024 金手指失衡症

> **position_sensitivity**: serial

**核心问题**：金手指（主角核心超出常态的专属能力/系统/外挂）设定或使用失衡——三种典型：①迟迟不亮相（错过黄金三章）②过强消灭冲突（读者知道主角必胜，冲突失效）③规则前后崩坏（金手指规则随剧情需要临时变动）。与 P010（冲突整体无代价）不同，P024 是**机制压过叙事**——金手指机制本身碾平了冲突；与 P023（世界观整体规则矛盾）不同，P024 仅聚焦金手指专项规则。

**触发信号**：金手指到 N 章才首次亮相/使用；主角获得金手指后冲突立即失效；金手指规则随剧情需要临时变动。

**判断原则**（基于上下文，非硬性标准）：
- 金手指是否在黄金三章内亮相？（迟到即错过期待窗口）
- 金手指是否留有代价/限制/成长空间？（无代价则冲突无悬念）
- 金手指规则前后是否一致？（能力边界是否随剧情临时放宽/收紧）
- **金手指定量参考**（外部资料佐证）：可按"事件概率倒数的 log10"估算金手指等级，合理总量区间为 6-9（等级 6≈百万分之一运气，等级 9≈十亿分之一；超过 10 超出地球人口总数，读者潜意识会觉得不现实；低于 5 无法满足读者的不劳而获心理）。常见基准：跳崖得宝=6 级、穿越贵族=3 级、相貌英俊=2 级、智商 160=4.2 级。多个独立金手指等级可相加；有依赖关系的需按条件概率另算。
- **穿越流背景豁免**：在穿越流派中，"穿越"本身是既定背景设定，不计入金手指等级（如同急诊室小说里全是病人不叫不真实）。早期穿越作品（穿越尚属新鲜事物）可视为 8 级金手指（亿中挑一）。

**严重度判断**（结合三维标定表综合评估）：
- L1：亮相偏晚/单处规则瑕疵，不影响主线张力
- L2：金手指过强导致局部冲突失效，或规则矛盾读者可感知
- L3：金手指完全消灭冲突张力，或核心规则崩塌使读者对故事失去信任

**例外情况**（以下场景通常不是金手指失衡）：
- 金手指有代价/限制且冲突仍在（受限金手指是合理设定）
- 高阶世界金手指只是常规能力的铺垫（后续揭示世界层次）
- 信息差下的能力隐藏（角色不知道 ≠ 金手指失衡，P003 场景）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（过强消灭冲突）**：
> 原文：主角获得"一键满级"系统后，第三章开始无敌碾压，所有对手瞬间秒杀，后续十章冲突全部消失。
> 判定：P024 L2
> 理由：金手指过强导致冲突失效，读者知道主角必胜，悬念消失。

**✅ L2 命中（迟到亮相跳过黄金三章）**：
> 原文：金手指设定到第三十章才首次亮相，前三十章主角以普通身份平铺直叙。
> 判定：P024 L2
> 理由：金手指亮相太晚，错过黄金三章的期待窗口，读者已经失去代入。

**❌ 未命中（有代价限制）**：
> 原文：主角的"读心术"每月只能使用一次，且每次使用后虚弱三天。冲突仍然成立。
> 判定：不触发
> 理由：金手指有明确代价与限制，冲突仍在，不算失衡。

**推荐教学动作**：首选 A013 情节复盘，备选 A009 节奏变速

### P025 配角工具人症

> **position_sensitivity**: global

**核心问题**：配角群像工具化——无独立性格/动机/记忆点，仅承担传话、推剧情、喊口号的功能。与 P007（核心角色无动机）不同，P025 是**配角群像**功能性过强；与 P008（核心角色无辨识度）不同，P025 聚焦配角辨识度。

**触发信号**：配角台词只有"大哥英明/遵命/是"；配角出场仅为了推进剧情或给主角送情报；读者记不住配角的名字与特征。

**判断原则**（基于上下文，非硬性标准）：
- 配角是否有独立动机？（换掉这个配角剧情是否依然成立？）
- 配角是否有辨识行为/台词？（不看名字能否认出这个角色？）
- 配角是否只是功能？（传话/送宝/喊口号，用完即弃？）
- 配角是否"工具人"看三证据：(a) 是否记得主角之前的事；(b) 是否有独立于主角的目标；(c) 是否对主角有自己的模型（猜主角会怎么想）。三者皆无 → 工具人；有 → 即便戏份少也不是工具人。

**严重度判断**（结合三维标定表综合评估）：
- L1：个别配角平面化，不影响主线
- L2：多个配角工具化，读者对配角群像失去兴趣
- L3：全员配角工具人，世界显得虚假，主角互动失去重量

**例外情况**（以下场景通常不是配角工具人）：
- 配角的日常行为与主线无关但展现性格（独立于剧情服务的塑造是合理的）
- 一次性功能性角色（跑腿/报信）本就短暂出场——关键是重要配角要有辨识度
- 群像场景中配角群有集体辨识度（群像本身成立，不要求每个单点立体）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（工具人配角）**：
> 原文：反派身边的跟班从头到尾只有一句台词："大哥英明！"每次出场都是递情报、被主角顺手解决。
> 判定：P025 L2
> 理由：配角无独立性格/动机/记忆点，仅承担喊口号+送情报功能。

**❌ 未命中（独立于剧情服务）**：
> 原文：酒馆老板的日常与主线无关——闲时数着铜钱跟熟客逗乐，说今日雨大怕路人受凉，顺手给主角多烫了一壶酒。
> 判定：不触发
> 理由：配角行为虽与主线无关但展现性格，独立于剧情服务，不算工具化。

**推荐教学动作**：首选 A010 角色盲写，备选 A003 五问法

