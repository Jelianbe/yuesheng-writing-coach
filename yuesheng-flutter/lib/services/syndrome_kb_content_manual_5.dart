### P031 设定矛盾症

> **position_sensitivity**: global

**核心问题**：世界观设定前后冲突——能力体系规则、等级上限、地理距离、时间线、历史事件、魔法/科技规则在连载中自相矛盾（"筑基能御剑"与"筑基不能飞行"并存）。与 P018（角色行为模式断裂）不同，P031 是**设定事实层**矛盾；与 P004（设定以旁白硬塞）不同，P031 是设定**本身不自洽**，不是呈现方式问题。

**触发信号**：读者在评论区指出"前后设定对不上"；同一规则在前后文有不同描述；角色能力/世界规则随剧情需要临时变动。

**判断原则**（基于上下文，非硬性标准）：
- 同一设定要素在前文与后文描述是否一致？
- 能力/规则是否只服务于当期剧情，违背既有约束？
- 时间线（季节/人物年龄/事件间隔）是否自洽？

**严重度判断**（结合三维标定表综合评估）：
- L1：单处细节矛盾（如地名前后不一致），不影响主线理解
- L2：关键设定矛盾（能力体系/世界规则），读者可感知到"作者忘了"
- L3：核心设定崩塌（主角能力来源/世界根基矛盾），读者对故事可信度整体怀疑

**例外情况**（以下场景通常不是设定矛盾）：
- 视角限制下的信息差（角色不知道 ≠ 设定矛盾，P005 场景）
- 角色成长导致的合理能力变化（有铺垫的升级不算矛盾）
- 留白设定（未明确过的规则不构成"前后不一致"）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（规则冲突）**：
> 原文：第三章主角使用"瞬移符"跨越千里。第十五章同一张符纸被描述为"只能移动十步"。两处对瞬移符的规则描述冲突，且无任何解释。
> 判定：P031 L2
> 理由：同一设定要素规则矛盾，读者可感知到"作者忘了"。

**❌ 未命中（信息差）**：
> 原文：第三章主角对女配隐瞒了自己会御剑。第十五章暴露时女配震惊。
> 判定：不触发
> 理由：是信息差/角色选择，非设定矛盾。

**推荐教学动作**：首选 A013 情节复盘，备选 A012 伏笔追踪

### P032 金手指失衡症

> **position_sensitivity**: serial

**核心问题**：金手指（主角核心超出常态的专属能力/系统/外挂）设定或使用失衡——三种典型：①迟迟不亮相（错过黄金三章）②过强消灭冲突（读者知道主角必胜，冲突失效）③规则前后崩坏（金手指规则随剧情需要临时变动）。与 P012（冲突整体无代价）不同，P032 是**机制压过叙事**——金手指机制本身碾平了冲突；与 P031（世界观整体规则矛盾）不同，P032 仅聚焦金手指专项规则。

**触发信号**：金手指到 N 章才首次亮相/使用；主角获得金手指后冲突立即失效；金手指规则随剧情需要临时变动。

**判断原则**（基于上下文，非硬性标准）：
- 金手指是否在黄金三章内亮相？（迟到即错过期待窗口）
- 金手指是否留有代价/限制/成长空间？（无代价则冲突无悬念）
- 金手指规则前后是否一致？（能力边界是否随剧情临时放宽/收紧）

**严重度判断**（结合三维标定表综合评估）：
- L1：亮相偏晚/单处规则瑕疵，不影响主线张力
- L2：金手指过强导致局部冲突失效，或规则矛盾读者可感知
- L3：金手指完全消灭冲突张力，或核心规则崩塌使读者对故事失去信任

**例外情况**（以下场景通常不是金手指失衡）：
- 金手指有代价/限制且冲突仍在（受限金手指是合理设定）
- 高阶世界金手指只是常规能力的铺垫（后续揭示世界层次）
- 信息差下的能力隐藏（角色不知道 ≠ 金手指失衡，P005 场景）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（过强消灭冲突）**：
> 原文：主角获得"一键满级"系统后，第三章开始无敌碾压，所有对手瞬间秒杀，后续十章冲突全部消失。
> 判定：P032 L2
> 理由：金手指过强导致冲突失效，读者知道主角必胜，悬念消失。

**✅ L2 命中（迟到亮相跳过黄金三章）**：
> 原文：金手指设定到第三十章才首次亮相，前三十章主角以普通身份平铺直叙。
> 判定：P032 L2
> 理由：金手指亮相太晚，错过黄金三章的期待窗口，读者已经失去代入。

**❌ 未命中（有代价限制）**：
> 原文：主角的"读心术"每月只能使用一次，且每次使用后虚弱三天。冲突仍然成立。
> 判定：不触发
> 理由：金手指有明确代价与限制，冲突仍在，不算失衡。

**推荐教学动作**：首选 A013 情节复盘，备选 A009 节奏变速

### P033 升级节奏失衡症

> **position_sensitivity**: serial

**核心问题**：升级/成长节奏失衡——升级过快导致力量通货膨胀（数值爆炸，读者对成长失去感知），或升级过慢导致读者期待流失（成长弧线拖沓）。与 P030（铺垫/高潮/收束段落比例）不同，P033 是**升级节奏本身**；与 P032（金手指机制过强）不同，P033 聚焦成长弧线的推进速度。

**触发信号**：主角每章都在升级/数值飙升；升级不再带来新鲜冲突；读者反馈"主角已经无敌了没看头"；或长期无实质成长，读者失去期待。

**判断原则**（基于上下文，非硬性标准）：
- 升级是否伴随新冲突/新代价？（无代价的升级是数据膨胀）
- 升级间隔是否让读者保持期待？（太快无积累感，太慢无期待感）
- 成长弧线是否服务主线？（升级是否只是为了爽，不推动叙事）

**严重度判断**（结合三维标定表综合评估）：
- L1：单处升级过快/过慢，不影响主线张力
- L2：力量通货膨胀或成长停滞读者可感知，期待感明显下降
- L3：升级体系整体崩塌（数值毫无意义，或读者对成长彻底失去兴趣）

**例外情况**（以下场景通常不是升级节奏失衡）：
- 升级伴随新冲突/新代价（有节奏的成长是合理设定）
- 特定阶段无升级是蓄力（大战前的铺垫，后续集中兑现）
- 主角刻意压制实力（信息差/扮猪吃虎场景）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（力量通货膨胀）**：
> 原文：主角每章获得一次升级，第三章从凡境跳到圣境，第七章已无敌于天下，后续战斗全是秒杀。
> 判定：P033 L2
> 理由：升级过快导致力量通货膨胀，读者对数值失去感知，期待感流失。

**✅ L2 命中（期待流失）**：
> 原文：主角十章没有一次实质成长，境界纹丝不动，读者等待的突破迟迟不来。
> 判定：P033 L2
> 理由：成长过慢导致读者失去期待，升级弧线拖沓。

**❌ 未命中（升级伴随代价）**：
> 原文：主角突破大境界后引来天劫与旧敌追杀，每次升级都带来新的危机。
> 判定：不触发
> 理由：升级伴随新冲突/新代价，成长有节奏，不算失衡。

**推荐教学动作**：首选 A009 节奏变速，备选 A013 情节复盘

### P034 配角工具人症

> **position_sensitivity**: global

**核心问题**：配角群像工具化——无独立性格/动机/记忆点，仅承担传话、推剧情、喊口号的功能。与 P009（核心角色无动机）不同，P034 是**配角群像**功能性过强；与 P010（核心角色无辨识度）不同，P034 聚焦配角辨识度。

**触发信号**：配角台词只有"大哥英明/遵命/是"；配角出场仅为了推进剧情或给主角送情报；读者记不住配角的名字与特征。

**判断原则**（基于上下文，非硬性标准）：
- 配角是否有独立动机？（换掉这个配角剧情是否依然成立？）
- 配角是否有辨识行为/台词？（不看名字能否认出这个角色？）
- 配角是否只是功能？（传话/送宝/喊口号，用完即弃？）

**严重度判断**（结合三维标定表综合评估）：
- L1：个别配角平面化，不影响主线
- L2：多个配角工具化，读者对配角群像失去兴趣
- L3：全员配角工具人，世界显得虚假，主角互动失去重量

**例外情况**（以下场景通常不是配角工具人）：
- 配角的日常行为与主线无关但展现性格（独立于剧情服务的塑造是合理的）
- 一次性功能性角色（跑腿/报信）本就短暂出场——关键是重要配角要有辨识度
- 群像场景中配角群有集体辨识度（群像本身成立，不要求每个单点立体）

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（工具人配角）**：
> 原文：反派身边的跟班从头到尾只有一句台词："大哥英明！"每次出场都是递情报、被主角顺手解决。
> 判定：P034 L2
> 理由：配角无独立性格/动机/记忆点，仅承担喊口号+送情报功能。

**❌ 未命中（独立于剧情服务）**：
> 原文：酒馆老板的日常与主线无关——闲时数着铜钱跟熟客逗乐，说今日雨大怕路人受凉，顺手给主角多烫了一壶酒。
> 判定：不触发
> 理由：配角行为虽与主线无关但展现性格，独立于剧情服务，不算工具化。

**推荐教学动作**：首选 A010 角色盲写，备选 A003 五问法

