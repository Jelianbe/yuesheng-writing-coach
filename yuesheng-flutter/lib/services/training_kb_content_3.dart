## P031 设定矛盾症

**核心本质**：世界观设定前后冲突——能力体系规则、等级上限、地理距离、时间线、历史事件、魔法/科技规则在连载中自相矛盾（"筑基能御剑"与"筑基不能飞行"并存）。不是呈现方式问题（那是 P004），不是角色行为断裂（那是 P018），而是**设定事实层不自洽**：同一规则随剧情需要临时变动。

**教学要点**：
- 设定台账：让学员建立世界设定清单（能力规则/等级上限/地理/时间线），写前核对
- 前文检索：改设定前先搜前文是否已出现过该规则，避免"作者忘了"
- 规则承诺观：每条设定都是向读者的承诺——修改要显式处理（伏笔或明确修订），不静默推翻
- 时间线核查：季节/年龄/事件间隔用时间轴拉一遍，找隐性矛盾

**常见误区**：
- 以为信息差就是设定矛盾——角色不知道不等于规则矛盾（那是视角/叙事问题）
- 以为角色能力变化都是矛盾——有铺垫的成长/升级不算，矛盾是"无解释的冲突"
- 过度补丁：发现矛盾后绕开而不是正面修订，越补越乱（滑向 P016 巧合过多）

**严重度判断参考**：
- L1：单处细节矛盾 → 设定台账标红，前后文统一（如地名/年龄）
- L2：关键设定矛盾 → 补修订段落或加伏笔解释，读者可感知时需正面回应
- L3：核心设定崩塌 → 重审世界根基，安排专门的设定重述/修订章节

**教学素材库**：
- 设定台账模板：规则名 / 首次出现章节 / 当前描述 / 备注（修订历史）
- 时间线核查表：季节 / 人物年龄 / 事件间隔逐项核对
