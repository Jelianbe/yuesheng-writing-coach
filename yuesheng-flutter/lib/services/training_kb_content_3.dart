## P019 章节钩子缺失症

**核心本质**：章末缺乏悬念/反转/情绪冲击——信息在章内交代完毕、情绪落地即收束，读者没有翻页动力。网文以章为消费单位，章末钩子是连载节拍器：每章结束都应留一个"未闭合"的引子。

**教学要点**：
- 章末留问：至少留一个未解问题（谁/为什么/然后呢），读者会为答案翻页
- 情绪余波：章末停在情绪高点之后的"余韵"或"陡转"，而非平淡收束
- 反转收尾：信息在章末被"扭转"（新发现/身份揭晓/局势反转），制造继续阅读的冲动
- 承诺衔接：章末钩子与下一章开头呼应，兑现越及时翻页动力越稳

**常见误区**：
- 收束式结尾——"解决完，大家休息了"，一切闭合，读者随时可停
- 钩子悬空——章末抛悬念却五章不接，承诺失信（见 P019）
- 为钩而钩——生硬的反转/悬念与主线无关，读者觉得被戏弄

**严重度判断参考**：
- L1：单章结尾平淡 → 给该章补一个"引子句"（未解之问/情绪余波）
- L2：多章无钩子 → 建立"章末钩子"习惯，每章结尾自检是否有翻页理由
- L3：每章都无钩子 → 重读全书章末，逐章设计钩子并规划兑现点

**教学素材库**：
- 翻页测试：每章结尾问一句"读者为什么还想看下一章"——答不出即为无钩子章
- 钩子句式练习：三种钩子模板（悬念问句/情绪陡转/信息反转），给无钩子章补结尾
- 兑现衔接：把上一章钩子与本章开头连线，练习"抛-接"节奏

