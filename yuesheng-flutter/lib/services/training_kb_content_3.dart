## P032 金手指失衡症

**核心本质**：金手指（主角核心超出常态的专属能力/系统/外挂）设定或使用失衡——亮相时机偏晚（错过黄金三章）、强度过强（碾压冲突，读者知道主角必胜）、规则前后崩坏（能力边界随剧情临时变动）。不是冲突整体无代价（那是 P012），不是世界观整体矛盾（那是 P031），而是**金手指机制本身失衡**：机制压过叙事，读者失去代入与期待。

**教学要点**：
- 亮相时机校准：黄金三章内必须让读者感知金手指存在（不一定要完全展露，但要给"主角不普通"的信号）
- 设限设计：给金手指代价/限制/成长空间——消耗资源、冷却时间、等级解锁，冲突才留有悬念
- 规则承诺观：金手指能力边界写进设定台账，后续每处使用对照核查，修改要显式处理不静默推翻
- 冲突保留检查：每个金手指使用场景自问"主角这次还有失败的可能吗？"——若没有，收强度

**常见误区**：
- 以为金手指越强越爽——无代价金手指消灭冲突，读者从"期待"滑向"无聊"
- 以为亮相越晚越有神秘感——错过黄金三章，读者还没等到金手指就弃书了
- 以为规则可以随剧情临时放宽——每次放宽都是对读者承诺的背弃（滑向 P031 设定矛盾）

