## P020 追读动力不足症

**核心本质**：长线追读设计缺失——更新期待、长线悬念、情感绑定与主线牵引弱，爽点分散无主轴，读者在连载中逐渐弃书。留存靠"读者与故事建立了持续关系"：有要追的目标、有在意的角色、有成长弧光。

**教学要点**：
- 主线牵引：一条跨多卷的主线目标，每章都推进它（哪怕一小步），支线服务主线
- 长线悬念充值：每几章推进/加深一次主线悬念，保持"读者心里悬着一件事"
- 情感绑定：经营读者与角色的关系（羁绊/遗憾/承诺），让读者"舍不得"角色
- 成长弧光：主角的成长要有阶段感（每卷有明确跃升），而非原地打转

**常见误区**：
- 主线被支线淹没——支线写得爽但主线三个月不推进，读者找不到"要追的东西"
- 爽点无累积——每个副本独立结算，主角能力不沉淀，读者感觉"白看"
- 无情感钩子——角色关系无变化/无推进，读者对角色无牵挂

**严重度判断参考**：
- L1：局部章节游离主线 → 给游离章节接回主线的"线头"
- L2：主线淡化、支线喧宾夺主 → 重排连载大纲，主线推进点前移加密
- L3：主线消失、无情感绑定、无成长弧光 → 设计"下一卷主线"并重铺长线悬念

**教学素材库**：
- 主线一句话：让学员用一句话说清"整本书读者在追什么"——说不清即为无主线
- 悬念充值日历：规划未来 10 章中主线悬念的"推进/加深"时点
- 情感绑定盘点：列出读者可能"舍不得"的角色关系/遗憾/承诺，缺位则设计补位

