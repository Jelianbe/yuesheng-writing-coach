## P024 期待感断裂症

**核心本质**：悬念与承诺管理失衡——章末钩子不兑现、信息提前剧透、吊胃口过度悬而不决，读者期待一次次落空后情绪耗散。期待感的本质是"承诺-兑现"循环：承诺给读者一个值得等的答案，并在合理时点兑现或推进。

**教学要点**：
- 承诺要记账：抛出的悬念记下来，规划"何时推进/何时兑现"，避免忘记
- 兑现要准时：读者最想要的答案，在期待最盛时兑现，不要在冷却后补
- 信息释放配比：保持"已知略多于未知"——读者知道得太多没期待，知道得太少没代入
- 延迟要有效：吊胃口必须伴随"新的信息增量"推进，纯拖延会消磨信任

**常见误区**：
- 把"悬念"当"拖延"——重复拉长同一悬念而无推进，读者看穿后弃书
- 提前剧透毁期待——对话/旁白提前说破结果，悬念失去张力
- 承诺失信——设了不兑现的钩子（如"下一章揭晓"却迟迟不揭）

**严重度判断参考**：
- L1：单处悬念拖沓 → 提醒该处需在 1-2 章内推进
- L2：多次悬而不决/提前剧透 → 建立"悬念记账本"，逐个安排兑现点
- L3：全书承诺失信 → 复盘所有未兑现钩子，设计回收/转写方案

**教学素材库**：
- 悬念记账本：让学员列出当前所有未收的悬念，标注"已抛章数/读者期待度/计划兑现章"，找出拖沓项
- 兑现代练：选一个悬置最久的钩子，写一段"兑现"场景——感受承诺兑现带来的信任
- 剧透扫描：通读最近 5 章，标出所有"提前说破"的位置，练习把信息压后

