## P028 画面感缺失症

**核心本质**：通篇停留在抽象概述层——"他很悲伤地走了""场面十分混乱"，全程无场景化、无感官细节，读者无法脑内成像。作者习惯用"总结"代替"呈现"：不是词句问题（那是 P003），不是特定情节点被带过（那是 P021），而是整体表达方式的抽象化。
**写作认知锚点**："读者不是读到情绪，而是读到画面后自己产生情绪。"叙述的任务是把事件"演"出来，而非"报"出来。

**教学要点**：
- 场景三要素：让学员把一段概述改写成"人物 + 动作 + 环境"三要素齐全的场景
- 感官锚点：每个场景至少一处具体感官（视觉/听觉/触觉/气味），先练视觉
- 结果反推过程：把"她很难过地走了"反推成"她做了哪些动作、经过哪些地方、最后如何离开"
- 一句话画面测试：概述改写后，让学员说"这一段读者能看见什么"——说不出来即仍抽象

**常见误区**：
- 以为加形容词就算具象——"非常难过地、十分悲伤地"仍是抽象，具象靠名词与动作
- 以为加环境描写就算画面——堆砌景物但与人物动作无关，会滑向 P008
- 对话多就算有画面——对话无法代替叙述的画面感

**严重度判断参考**：
- L1：个别段落抽象概述 → 挑 1-2 段做"场景化改写"
- L2：整章以概述推进 → 选关键场景整段改写（优先开场/转折/高潮场景）
- L3：全文几乎无场景 → 拆章逐场景重建，从大纲式叙述改为场景式叙述

**教学素材库**：
- 概述→场景对照练习：给 3 句抽象概述（难过/愤怒/紧张），让学员补出场景
- 感官锚点清单：视觉/听觉/触觉/嗅觉/味觉各 3 个可写选项，写作时随手挑
- 画面测试卡：改写后自问"这句话读者能在脑中成像吗"，不能则继续拆

