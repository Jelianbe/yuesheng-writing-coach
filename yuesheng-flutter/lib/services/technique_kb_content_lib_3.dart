### T023 句速控制法

**核心原理**：句子长短直接控制阅读速度。短句加速，长句减速。什么时候加速、什么时候减速，是由文本的情绪密度决定的。

**适用症候**：P007 句式节奏单一

**技法描述**：
三种句速模式：
1. **冲刺模式**（紧张/兴奋/愤怒）：连续短句，每句不超过 6 个字
2. **沉缓模式**（思考/犹豫/悲伤）：长句，用逗号分隔节奏，让读者慢下来
3. **切换模式**（情绪变化）：从长句突然变到短句，或从短句突然拉长——切换本身就是效果

**示范对比**：
- ❌ 均速：他慢慢地推开门，小心翼翼地看了一圈，确定没有人之后才走了进去
- ✅ 变速：他推开门。（中速）没有人。（短句加速）空的。全空了。桌椅。书柜。墙上的挂钟。什么都没留下。（冲刺式短句→紧张感）

**练习模板**：
> 写一段 100 字"紧张"场景。前 50 字用沉缓长句，后 50 字用冲刺短句。中间有一个 1 字句作为切换点。

**关联教学动作**：A009 节奏变速

