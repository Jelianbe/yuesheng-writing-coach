### T026 伏笔回收法

**核心原理**：伏笔的质量 = 埋设的隐蔽度 × 中途的强化度 × 回收的满足度。一个好伏笔在回收时，读者会感觉"原来如此——我本应该猜到的"。

**适用症候**：P017 伏笔失效症

**技法描述**：
伏笔的三段式生命周期：
1. **前期埋设**：安插一个不合常理的细节/一句没说完的话/一个不该出现的东西——让它**自然地**出现在场景中，不给特写
2. **中期强化**：在后续章节中用不同角度、不同角色的反应**轻触**这个伏笔——不解释，只让读者模糊地感觉"这东西有戏"
3. **后期兑现**：在关键转折点揭示真相——不是"说出来"而是"让角色展现出这个真相的后果"。读者获得"原来如此"的满足感，同时这个兑现**改变了故事的走向**

**示范对比**：
- ❌ 裸露：旁白"他看了一眼窗台上的花盆。那是一盆兰花。他没有多想。"（旁白给了不该给的注意力）
- ✅ 自然埋设：他在窗台上摸钥匙的时候，手指碰到了一片兰花叶子。他顿了顿——这盆花不该在这里——然后门铃响了

**练习模板**：
> 在场景中安插一个"异常细节"——必须自然融入场景（不给特写）。然后列出这个细节会在后续哪三个场景中再次出现，最后设计一个回收场景——回收必须带来情节转折。

**关联教学动作**：A003 五问法

