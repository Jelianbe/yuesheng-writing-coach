### T024 钩子开篇法

**核心原理**：读者在开篇前 3 秒决定是否继续读。前 3 秒必须给读者一个"必须看下去"的理由——不是信息，是疑问。

**适用症候**：P013 开篇平庸症

**技法描述**：
四种钩子类型（选一即可）：
1. **反常钩**：第一句就是反常事件——"你被开除了""他死了""她不见了"
2. **疑问钩**：第一句制造一个"为什么"——"他不记得自己是怎么到这里的"
3. **冲突钩**：第一句就扔冲突——"你选一个，他和你妹妹只能留一个"
4. **情绪钩**：第一句用强烈的氛围抓住读者——"那是他最后一次见到她"

**示范对比**：
- ❌ 平淡：李明是一个普通的上班族，每天早上九点准时到公司
- ✅ 钩子：李明到公司的时候，他的工位已经空了。所有的东西都被清走了，桌上只剩一张纸，上面写着两个字：别找。

**练习模板**：
> 为你作品写一个开头——第一句话必须让读者产生一个"为什么？"。看这一句能不能撑住前三段。

**关联教学动作**：A007 一句话冲突

