### T031 氛围构建法

**核心原理**：场景氛围不是靠形容词维系的，是靠"锚定物+感官统一+节奏配合"三条暗线共同编织的。好的氛围让读者进入特定的"色调"，一直维持到场景结束。

**适用症候**：P003 情绪标签化、P008 语言堆砌

**技法描述**：
三步构建氛围：
1. **选锚定物**：为场景选一个核心锚定物——反复出现的物件/声音/光线/气味，它在场景每个阶段有不同的状态
2. **感官统一**：所有感官描写都围绕核心情绪色调——压抑的场景所有感官都"压抑"：光只会"昏暗"，声音只会"闷"/"钝"/"远"
3. **节奏配合**：氛围描写的"密度"与情节的"紧张度"同步——紧张度上升，描写变密集；紧张度下降，描写变稀疏

**示范对比**：
- ❌ 无氛围："房间里有一张桌子。他坐在椅子上。外面在下雨。"
- ✅ 有氛围（锚定物=雨）："桌沿上有一道水痕——不是他弄的，是天花板在漏。他坐在那儿看那道水痕慢慢往下爬。雨打在窗上的声音一收一紧，像有人在喘。他就听这个声音，听了很久。"

**练习模板**：
> 选一个200字场景。①确定核心情绪色调；②选一个锚定物；③重写——锚定物至少出现2次（状态不同），所有感官描写统一在同一个色调。

**关联教学动作**：A006 感官全开

