### T025 余韵收束法

**核心原理**：结尾不是"故事结束"，是"情绪停留"。好的结尾让读者读完最后一句话后，还留在那个氛围里几秒钟。

**适用症候**：P007 句式节奏单一

**技法描述**：
四种收束方式：
1. **景物收束**：不写情绪，写一个静的景物——情绪留在景物里
2. **回声收束**：重复前文出现过的一句话/一个细节——首尾呼应
3. **开放式收束**：结束在一个未完成的动作上——读者自己脑补
4. **颠覆式收束**：最后一句颠覆读者对前文的理解——重新解读

**示范对比**：
- ❌ 总结：这件事让他明白了，人不能太天真
- ✅ 景物收束：他关上门。走廊里很安静，只有自己的脚步声，一下一下，消失在尽头。

**练习模板**：
> 重写你作品的结尾。不用总结、不用感悟、不用"明白了什么"。只写一个景物——让情绪留在景物里。

**关联教学动作**：A009 节奏变速

