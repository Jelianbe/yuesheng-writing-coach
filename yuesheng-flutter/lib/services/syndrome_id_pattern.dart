// ─────────────────────────────────────────────────────────────
// 症候编号识别器（ADR-0003 甲-1 · 层 2 S1 批 · 2026-10-05）
//
// 目的：**让「哪些字符串算症候编号」这个判断只有一个真源**。
// 此前全仓 8 处生产/测试代码各自硬编码 `P0\d{2}`（宽松形态）或
// `^P0\d{2}$`（锚定形态），新增编号段时必须同步改 8 处，漏一处
// ⇒ 该段编号对「编号泄漏检测」「训练任务 ID 提取」完全隐形
// （层 2 判据 3 探针报告 §2.1 实测的阻断项）。
//
// 派生方式：**由「已登记的编号段」列表派生**，而不是由注册表的
// 具体 ID 派生。理由：注册表只含「已实体化」的号，而防线需要覆盖
// 「段」这个抽象层——若某段已宣布启用但首条实体尚未注册（正是
// ADR-0003 阶段二 `S001` 的处境），按注册表派生会漏掉整个段。
//
// ⚠️ 派生**不是**自动的：新开一个编号段仍须在 [_kSegments] 加一条。这是
// 刻意的——「加一条」与「改 8 处」相比是数量级的差别，且留下一个可 grep
// 的真源点（§4-148 纪律：约束要钉在可指认的地方）。
// ─────────────────────────────────────────────────────────────

/// 已登记的编号段。
///
/// ★ **新增编号段时唯一需要改的地方**（加一条）。
/// `pattern` 是该段的完整局部模式（含段前缀），`{N}` 占位会被替换成
/// `\d{digits}`。例如 P 段 = 前缀 `P` + 字面 `0` + `{N}` 位数字。
///
/// ⚠️ `digits` 数的是**占位符那几位的总位数**（P 段 = 2，对应
/// `P0xx` = `P` + `0` + 两位数字）。写成 3 会派生出 `P0\d{3}`，
/// 匹配不到任何现行编号 —— S2 护栏 #S2-A2 就是为拦这个而设。
///
/// 为什么是「一条记录」而不是「两张表」：位宽与模式必须成对。改一处
/// 漏另一处会派生出**语法错误或静默失配**的 RegExp（`{N}` 留着不替换
/// ⇒ 模式匹配不到任何东西 ⇒ 防线静默失效，§4-153 同型）。
const List<({int digits, String pattern})> _kSegments = [
  // P 段：P001–P099（现行 37 条实体 P001–P037）
  (digits: 2, pattern: r'P0{N}'),
];

/// `\d{` —— 单独成常量是为了**规避 Dart 的插值解析歧义**（见上方
/// [kAnySyndromeIdRe] 注释）：写成 `r'\d{'` 后紧跟插值 `${digits}` 时，
/// 前一个 `{` 会被当作插值的起始花括号，编译器**不报错**而原样输出，
/// 得到一个永不匹配的正则。拆成常量后，`{` 不再处于插值紧邻位。
const String _kDigitRunOpen = r'\d{';

/// 宽松形态：在任意文本中搜「疑似编号泄漏」用。**不加锚点**。
///
/// 消费方：`diagnosis_validator` 的 V-03 编号回填（`replaceAllMapped`
/// 逐个替换命中项）、`teacher_validator` 的 `detectSyndromeIdLeak`。
final RegExp kAnySyndromeIdRe = RegExp(
  _kSegments
      .map((s) => s.pattern.replaceAll('{N}', '$_kDigitRunOpen${s.digits}}'))
      .join('|'),
);

/// 锚定形态：校验**整个字段值**就是合法编号时用。
///
/// 必须锚定，否则 `hasMatch('XP003')` 也会命中 ⇒ 等于没校验
/// （`diagnosis_parser.dart` 的 `syndrome_id_format` 拒答理由依赖此性质）。
///
/// ⚠️ 插值必须写 `${kAnySyndromeIdRe.pattern}` 而**不是** `$kAnySyndromeIdRe`
/// ——后者会把 `RegExp` 对象的 `toString()`（形如
/// `RegExp: pattern=P0\d{2} flags=`）整体拼进模式里，正则语法错误。
/// 该错误同样**不会**被编译器拦下（S2 护栏 #S2-A3 实测）。
final RegExp kAnchoredSyndromeIdRe = RegExp(
  '^(?:${kAnySyndromeIdRe.pattern})\$',
);

/// 字段值是否为合法症候编号（锚定语义，避免调用方各自拼锚点）。
bool isSyndromeId(String? id) =>
    id != null && kAnchoredSyndromeIdRe.hasMatch(id);
