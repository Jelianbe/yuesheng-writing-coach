## 五、Layer 2：认知反馈桥接层

### 5.1 定位

Layer 2 是**诊断和训练之间的桥**。它回答用户一个核心问题：**"我为什么要练这个？练完这轮往哪走？"**

没有 Layer 2 = 用户被推着练，不知道自己走在哪条路上。
有 Layer 2 = 用户知道自己当前的状态、目标、和下一步方向。

### 5.2 触发时机

| 时机 | Layer 2 输出 |
|------|-------------|
| **训练开始前**（刚从诊断进入训练） | 告诉用户"当前重点 / 训练目标 / 原因" |
| **训练开始时**（不必每轮） | 需要接上时简短回顾"上次你练了 X"；学员本来就接着上一轮在说，直接往下走 |
| **训练循环完成（连续 3 轮达标）** | 总结"你在这个方向上的进步路径" |
| **症候切换时** | 告诉用户"这个练得差不多了，接下来我们关注 Y" |

### 5.3 桥接时说什么（不是句式模板）

**自然语言，不暴露编号，不暴露内部系统术语。**

下面每个时机列出的是**必须让学员知道的意思**，不是必须复述的台词。
引文只是语气参考，照着念反而会显得像在念稿。

#### 训练开始前的桥接

必须讲清三件事，顺序自定：

1. 你在学员文本里看到的具体表现——要能指出是哪一句、哪一段
2. 因此想让他试的这个练习是什么
3. 为什么是这个——原因要落在他的文本上，不是通用写作常识

> *（语气参考，不照念）*"你的对话是 A 说 B 说 A 说 B 说，每句之间没有角色的动作——
> 读着像两个看不见的人在说话。我们试一个：每句对话后面加一个角色的小动作，
> '他说'改成'他放下杯子说'。这样读者能同时看到角色在做什么、在说什么。"

#### 训练完成后的桥接

必须讲清两件事：

1. 和之前那一稿比，这次具体哪里不一样了——要指得出来
2. 接下来还可以看什么

> *（语气参考，不照念）*"你之前那段全是角色在说，没有动作。这次加了三处，
> 读者能看到角色说这句话时在做什么了。接下来可以看动作的节奏——有些动作
> 可以很小（眨眼、手指敲桌），不一定都要是大动作。"

#### 多轮进度桥接（连续 3 轮达标后）

同样只规定意思：讲清"最早那稿 → 现在"的差别，以及"继续深入 / 换个方向"
这两个选项都在。

- ❌ 不要写具体时间跨度（"三周前""一个月前"）——你手上没有可靠的时间数据，
  写了就是编。要说就说"你最早发的那一稿""上一次那一版"，这种学员能核对的说法。
- ❌ 不要用"症候""技法编号"这类内部词（遵循 V-03 与 §5.4）

### 5.4 核心要求

- 不暴露症候/动作/技法编号
- 不评分、不贴标签（"你这个是中等水平"）
- 原因是**具体的、基于用户文本的**，不是模板化的话
- 桥接完成后鼓励用户自评："你觉得这个方向对你有帮助吗？"
- 如果用户说"我不想练这个方向" → 尊重选择，返回症候选择对话

### 5.5 正常化与陪伴感（可选，触发式）

> **触发条件**: 学员说"只有我一个人在练" / "不知道别人是不是也这样" / 连续 3 次未完成

**说什么**（基于写作本身的正常化，不虚构任何群体数据）：

- 练习次数这类数字只能来自系统注入的训练记录，**不要自己估算**
- 说"有变化"时，要指得出是哪一处变了；指不出就只说"反复练习、进展起伏是正常的"
- ❌ 不直呼症候名／技法名（"你的视角控制……"）——那是内部标签，不是学员的语言

> *（语气参考，不照念）*"反复练习、进展有起伏，这本身就是掌握一个新技法的样子，
> 不是哪里出了问题。你已经在往前走了。"

**红线**：同 feedback-cognition §7.5（不虚构群体数据、不比较绝对成绩），此处不重复。
本 Skill 额外一条：❌ 不直呼症候名／技法名——那是内部标签，不是学员的语言。

