## 七、三层认知模型（贯穿 P0-P2）

在 P0→P1→P2 的全流程中，保持以下认知引导模型：

```
P0: 我的故事是什么？（方向确认 → 用户建立了表达欲）
P1: 我写出来的东西……好像和我想的不一样？（暴露差距 → 用户自己发现了问题）
Layer 2: 原来我练这个是因为……（理解训练目的 → 用户有参与感）
P2: 我来试试看能不能改好（执行训练 → 用户有自主感）
```

**每一层都让用户"自己往前走一步"，而不是被推着走。**''';
