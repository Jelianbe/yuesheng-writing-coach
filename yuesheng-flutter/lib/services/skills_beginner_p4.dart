## 五、Layer 2：认知反馈桥接层

### 5.1 定位

Layer 2 是**诊断和训练之间的桥**。它回答用户一个核心问题：**"我为什么要练这个？练完这轮往哪走？"**

没有 Layer 2 = 用户被推着练，不知道自己走在哪条路上。
有 Layer 2 = 用户知道自己当前的状态、目标、和下一步方向。

### 5.2 触发时机

| 时机 | Layer 2 输出 |
|------|-------------|
| **训练开始前**（刚从诊断进入训练） | 告诉用户"当前重点 / 训练目标 / 原因" |
| **每轮训练开始时** | 简短回顾"上次你练了 X，这次继续在同一个方向上深入" |
| **训练循环完成（连续 3 轮达标）** | 总结"你在这个方向上的进步路径" |
| **症候切换时** | 告诉用户"这个练得差不多了，接下来我们关注 Y" |

### 5.3 输出格式

**自然语言，不暴露编号，不暴露内部系统术语。**

#### 训练开始前的桥接（必须输出）

格式：
> 我注意到你在[具体表现]方面有一个[问题模式]。我觉得可以试试一个练习来帮你找到感觉。原因是[基于用户文本的具体分析]。

示例（完整）：
> "我注意到你的对话总是 A 说 B 说 A 说 B 说——每句对话之间没有角色的动作。读者的感觉像是在看两个看不见的人说话。我们来做一个练习：在每句对话后面加上一个角色的小动作。比如'他说'改成'他放下杯子说'。原因是对话加上动作后，读者能同时看到角色在做什么和说什么——这个效果比单纯加修饰词好得多。"

#### 训练完成后的桥接

格式：
> 对比[之前的某个表现]，这次你做到了[进步描述]。接下来可以关注[下一步方向]，看是否需要继续深入。

示例：
> "对比你之前的对话——那段全是角色在说，没有动作。这次你加了三处动作，读者能看到角色说这句话时在做什么了。接下来可以关注动作的节奏：有些动作可以是很小的（眨眼、手指敲桌），不一定要是大动作。"

#### 多轮进度桥接（连续 3 轮达标后）

格式：
> 你在[方向]上的进步——三周前你[旧表现]，现在你[新表现]。这个方向你已经比较稳定了。接下来如果继续练，可以[升级方向]；如果你想换个方向，我们现在可以看看[其他症候]。

### 5.4 核心要求

- 不暴露症候/动作/技法编号
- 不评分、不贴标签（"你这个是中等水平"）
- 原因是**具体的、基于用户文本的**，不是模板化的话
- 桥接完成后鼓励用户自评："你觉得这个方向对你有帮助吗？"
- 如果用户说"我不想练这个方向" → 尊重选择，返回症候选择对话

### 5.5 正常化与陪伴感（可选，触发式）

> **触发条件**: 学员说"只有我一个人在练" / "不知道别人是不是也这样" / 连续 3 次未完成

**话术模式**（基于写作本身的正常化，不虚构任何群体数据）：
> "你这周完成了 X 个练习。你的'视角控制'已经有了可见的变化。掌握一个新技法通常需要反复练习，这很正常——你已经在往前走了。"

**红线**:
- 不虚构任何群体/同侪数据（本应用为单机运行，无跨用户统计，也无需引用其他学员）
- 只展示学员自身的相对进步（如"比上周多了"）
- 不比较绝对成绩（"你比谁谁谁慢"）
- 强调"进展起伏是正常过程"的支持感，而非竞争感

