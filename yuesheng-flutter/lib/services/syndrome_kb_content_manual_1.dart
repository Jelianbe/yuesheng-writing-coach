### 严重度三维标定（统一框架）

所有症候的严重度请同时从以下三个维度综合判断，而非仅依赖出现频率：

| 维度 | L1（轻微） | L2（重要） | L3（严重） |
|------|-----------|-----------|-----------|
| **覆盖范围** | 局部/个别段落 | 整章/多处出现 | 贯穿全文 |
| **对读者体验的影响** | 不影响理解，仅质感下降 | 打断阅读节奏，影响沉浸 | 直接导致读不下去 |
| **修复成本** | 改几句话即可 | 需要调整段落结构 | 要重写整段/重构叙事 |
| **教学优先级** | 顺带提一下即可 | 锁定为主线症候 | 立即介入训练 |

判定方法：**取三个维度中较高的**。例如，某症候覆盖范围是 L1（个别段落），但对读者体验影响是 L3（直接导致读不下去），则整体判定为 L3。

