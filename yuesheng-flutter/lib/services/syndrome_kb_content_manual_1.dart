### P001 情绪标签化

> **position_sensitivity**: global

**核心问题**：使用直接的情绪词汇替代了具体的感官描写，读者被"告知"角色感受而非"感觉到"角色感受。

**触发信号**：直接用情绪词概括，无具体描写

**判断原则**（基于上下文，非硬性标准）：
- 删掉情绪词后，是否还能通过动作/对话/环境感受到角色的情绪？
- 读者是通过读到角色的肢体语言来理解情绪的，还是通过读到"他很生气"这样的标签来理解的？
- 这段文本中，情绪标签和具体描写的比例是否合理？
- **描写四忌校验**（外部资料佐证）：是否用情绪标签替代了具体的感官/动作描写？——"他很生气" vs "他捏碎了手里的杯子"。描写应通过主角的眼睛来展现，并推动叙述向前发展（不中断故事）。

**严重度判断**（结合三维标定表综合评估）：
- L1：偶尔使用情绪标签，但有足够的具体描写支撑，读者仍能感受到情绪，改几句即可
- L2：情绪标签成为主要表达手段，具体描写被挤压，读者感到"被告知"而非"感受到"，修饰成本中等
- L3：几乎完全依赖标签，没有任何可供读者"感受"的细节，全文叙述体验如简历而非小说

**例外情况**（以下场景通常不是情绪标签化）：
- 简洁叙事中的快速过渡（"他很失望，但没说什么"——紧凑叙事的必要压缩）
- 第一人称内心独白中的真实自我感受表达（"我很害怕"是真实的内心声音）
- 刻意营造的"抽离感"叙事风格——情绪标签反而是风格的一部分
- 轻微隐喻表达——"冰冷的眼神""心头一热""心头一沉"等已成为中文文学中约定俗成的感性表达，单个出现时不视为情绪标签
- 上下文已用具体描写支撑——情绪词只是"引导读者注意"的提示，而非唯一的表达手段

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（典型）**：
> 原文："她很难过。她很孤独。她觉得很无助。她不知道自己该怎么办。她想要有人陪她。"
> 判定：P001 L2
> 理由：连续 5 句都是情绪标签，无任何具体描写。读者被"告知"感受而非"感觉到"感受。

**❌ 未命中（有具体描写）**：
> 原文："她很难过。但这难过里有一点说不清的释然——就像在机场送走了一个不该送的人。"
> 判定：不触发
> 理由：虽然以标签开头，但后面跟着具体感受描写，"释然"以比喻呈现，读者能"感觉到"。

**推荐教学动作**：首选 A004 现实锚点，备选 A006 感官全开

