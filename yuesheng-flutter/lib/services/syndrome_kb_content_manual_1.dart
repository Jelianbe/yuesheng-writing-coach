### P002 信息倾泻症

> **position_sensitivity**: beginning

**核心问题**：设定信息以旁白/说明方式直接交代，而非通过角色的日常体验自然呈现。可能表现为信息量过大（世界观膨胀），也可能表现为信息传递方式不当（信息硬塞）。

**触发信号**：设定通过旁白交代而非角色日常；大量世界观设定但主角模糊

**判断原则**（基于上下文，非硬性标准）：
- 这段信息是读者"需要知道的"，还是作者"想说的"？
- 如果读者的视角始终跟随一个角色，这个角色是如何获知这段信息的？
- 这段信息是"嵌在叙事中的"（通过对话、观察、行动自然流露），还是"中断叙事来交代的"？
- 去掉这段设定，故事是否依然成立？（如果是，说明这是"悬浮"的设定）
- 世界观的引入是否有角色作为媒介？还是作者在直接对读者说话？

**严重度判断**（结合三维标定表综合评估）：
- L1：少量背景信息通过旁白交代，但不打断叙事流畅度，删改几句话即可
- L2：频繁出现设定说明打断叙事主线，读者被迫"暂停故事情节来学设定"
- L3：整段叙事被设定说明覆盖，故事推进几乎停滞，需要重构信息释放节奏

**例外情况**（以下场景通常不是信息硬塞）：
- 用对话方式自然带出——角色之间讨论设定是合理的
- 通过角色的观察来展现——"他看到墙上贴着告示：宵禁期间禁止出门"
- 关键信息的集中揭示——一个必须提前交代才能看懂后续的规则（但仍需尽量压缩）
- 角色的内心自省——角色在反思自己的处境/命运/能力时自然带出的背景信息，如"金丹便是终点""百余年后的枯骨"——这是角色在评价自己，不是作者在给读者补设定
- 角色在评价一个地点/势力时的随口判断——"那是出了名的死地""那地方一般人进不去"——这是角色的个人判断，不是设定说明

**诊断锚点示例**（few-shot 参考）：

**✅ L2 命中（背景说明型）**：
> 原文："天元大陆有四大帝国，东有天元帝国，西有云荒帝国，南有星落帝国，北有冰原帝国。四大帝国之间经常发生战争。其中天元帝国最为强大，拥有一支百万大军。云荒帝国虽然小，但擅长魔法……"
> 判定：P002 L2
> 理由：纯设定说明中断了正在进行的叙事，读者被迫"暂停故事学设定"。

**❌ 未命中（对话释放）**：
> 原文："老铁匠把刀放在灯下看了看，说：'这是百炼钢。三百年前天启立国的时候，开国那批刀匠打的。现在没人会了。'"
> 判定：不触发
> 理由：世界观信息通过角色+对话自然释放。

**推荐教学动作**：首选 A002 回归主角，备选 A008 对话瘦身

