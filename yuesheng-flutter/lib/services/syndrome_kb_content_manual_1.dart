### P004 节奏停滞

> **position_sensitivity**: middle

**核心问题**：事件推进密度低，叙事陷入静止状态，缺乏冲突或悬念驱动读者前进。

**触发信号**：叙事推进停滞，连续多段缺乏事件进展或冲突升级，场景处于静止状态

**判断原则**（基于上下文，非硬性标准）：
- 去掉这一段，故事是否少了一件事？（如果是，说明这段是有推进的）
- 读者在读到这一段的时候，是否有一个"想知道接下来会发生什么"的驱动力？
- 这段文字是在累积情绪/铺垫，还是在原地打转？打转的标志是"没有新信息、没有新冲突、没有新悬念"。
- **互斥校验**：先排除 P017 场景（关键情节点被概括句跳过）——若停滞段落本身包含"该展开却被一笔带过"的情节点，优先归入 P017；排除后的剩余文本仍显静止，才归入 P004

**严重度判断**（结合三维标定表综合评估）：
- L1：个别段落节奏偏慢，但整体推进感完整，压缩几段即可
- L2：整段/整章节奏停滞，读者容易走神，需要调整段落的紧凑度
- L3：连续多章没有有效事件推进，读者失去阅读动力，需要重做章节结构

**例外情况**（以下场景通常不是节奏停滞）：
- 情绪沉淀段落——高强度冲突后必要的节奏回落，为下一轮积累势能
- 氛围描写的节奏变化——故意放慢节奏制造压抑感（但需有节制）
- 关键揭示前的"屏息时刻"——缓慢的细节铺垫服务于即将到来的爆发

**诊断锚点示例**（few-shot 参考）：
- **L2 命中**："他坐在窗边。窗外的风在吹。桌上的咖啡已经凉了。一只猫在墙角睡觉。远处传来汽车的声音。他又坐了一会儿。然后看了看表。离约定的时间还有两个小时。" → 连续 8 句没有任何事件推进，没有冲突累积，没有新信息。P004 L2
- **❌ 未命中（蓄力而非停滞）**："他握着门把手，没有推开。走廊里的灯忽明忽暗。他听见自己的心跳。门后传来一声极轻的咳嗽。他深吸一口气，推门而入。" → 判定：不触发。理由：缓慢细节全部服务于即将到来的揭示——这是爆发前的屏息时刻，不是无意义的空转。

**推荐教学动作**：首选 A003 五问法，备选 A005 动作链 或 A009 节奏变速

