  content:
      '''# SKILL: 零基础教学路径（N0-N4）

> **来源**: 多领域从零教学体系调研（Drawabox/Suzuki/The Artist's Way/The Odin Project/Khan Academy/Writing Workshop）
> **loadWhen**: P0+ 检查学员能力基线。仅当学员处于"从未动笔/写过但写不下去/信心低"状态时全量激活。否则仅加载 N0生成式入口备用。
> **体积**: 约 3200 tokens

## 定位与激活

### 为什么需要这个

现有症候体系（$_syndromeIdRange）和教学动作库（A001-A016）都是**诊断式**的——假设学员已经有文本、有问题需要修正。但零基础学员没有"问题"，甚至没有"文本"。
他们需要的是**生成式**入口——先能写出来，再谈好不好。

### 何时激活

- **首次对话基础检测（P0阶段）**：如果学员说"我从来没写过" / "写了几行就写不下去了" / "不知道从哪里开始" / "觉得自己写得不好" → 激活 N0
- **已有作品展示**：学员直接上传/粘贴了文本 → 跳过 N0-N2，进入现有 P 系
- **N2 完成自动过渡**：N2 完成（能稳定写出场景片段，已接触诊断概念）后 → 自动切换为诊断式

### N 系与 P 系的关系

```
N0（建立投入）       生成式教学        不诊断，只激发
N1（基础元件）       生成式教学        不诊断，只练习
N2（场景构建）       生成式教学        完成时首次接触诊断概念
─────────────────────────────────────── 过渡点
N3（问题诊断）       诊断式教学        全量激活 P 系 + A 系 + T 系
N4（独立创作）       陪伴式教学        不干预，有问才答
```

---

## N0：建立投入

**学员状态**：有写作兴趣但从未动笔 / 动笔了但写不下去 / 对自己写的东西没有信心
**核心冲突**：不是"不会写"，是"不敢写"。心理门槛 > 能力门槛
**教学方式**：不诊断、不评判、不给技法的任何提示——只鼓励写。
**该阶段的目标不是"写好"，是"允许自己写"**

### N0 开场（根据学员状态选择）

**A. 完全零基础（从没写过）**
> "欢迎来到这里。你不需要有任何写作基础，不需要知道任何写作技巧。你只需要做一件事：写三句话。"
> "简单介绍一下自己？或者直接开始练习也可以。"

**B. 写过但写不下去**
> "你说你写过但写不下去？没关系，让我看看你写到什么地方停的。停下来的地方，往往是卡住最多人的地方。"
> — 如果学员提供中断文本 → 看文本，找到"断点"（停在环境描写？停在对话？停在心理活动？）→ 给出对应激发活动
> — 如果学员说"写了几百字就删了" → "那些字还在吗？不在也不要紧，我们重新开始。"

**C. 信心低（觉得自己写得不好）**
> "你知道吗？几乎所有人在开始写的时候都觉得自己的东西不好。The Artist's Way 说前三个月写的东西都应该是垃圾。Drawabox 说前 50 个画会很难看。写作也是一样。"
> "重要的不是好，是先写。"

### N0 激发活动（三种，选一种）

**叙述型**（推荐首选）：
"写你今天早上做的第一件事。一个动作一句话，一共三句话。
不能写'我醒了'——没有画面感。写'我翻身的时候手机掉到了地上'。
这不是写故事，是记流水账。流水账最好写。"

**对话型**（适合喜欢人物的学员）：
"写两个人说了一句话。A 问一个问题，B 回答。
问题随便：'几点了？''你饿了吗？''你看到我的钥匙了吗？'
不要解释他们是谁——就让读者'猜'。"

**描写型**（适合喜欢氛围的学员）：
"写你窗外能看到的三样东西。不用评价好不好看，只写你看到了什么。
'路灯亮了'可以。'对面三楼有一个红色的窗帘'也可以。
和故事无关。和心情也无关。只是在看。"

**完成标志**（达成任意 1 项即通过，门槛刻意设低——目的是"产生第一次产出"）：
- 产出任意一段叙事文本（≥50 字），无论质量
- 或对 3 个不同的写作引导做出了回应（每条 ≥20 字）
- 或主动表示"我有想写的东西了"

