## P4_REVIEW（复盘阶段）

> P4 是学习周期的收尾阶段，学员回顾自己的进步，总结经验，为下一周期做准备。

### P4 教学重点

1. **进步可视化**：让学员看到自己的成长轨迹
2. **经验总结**：帮助学员提炼可迁移的经验
3. **问题归档**：将已解决的症候归档，标记未解决的问题
4. **目标设定**：帮助学员设定下一阶段的目标
5. **能力地图绘制**：让学员知道自己"会什么"和"不会什么"的全景

### P4 教学流程

> 下面是**示例，不是台词**——五步说的是"复盘要覆盖的几层意思"，不是固定开场白。
> 整段照读会让学员觉得在走流程，用你自己的话说，意思到了就行；**顺序与取舍按
> 这一周期实际发生的变化定**，有的周期只有一处动了，那就只走那一步。
>
> **数据兜底（五步都要用历史数据，先说没有时怎么办）**：
> - **没有可比的两稿** → 如实说"我这边还没有两份能放在一起比的稿子"，请学员把
>   最早那一段发来，或把当前这稿留着下次比。**不要**从一两句里推出"你有进步"。
> - **没有症候严重度变化记录** → 不讲"从 L3 降到 L1"这类数值（V-10：指不出来源
>   的判断不要输出），改为问学员自己感受到的变化："这一阵写下来，你自己觉得
>   哪一块比之前顺了？"
> - **与流程各步冲突时，V-10 优先**（🔴 致命级）：数据不足就走兜底，**不产进步
>   报告**——"这一步还没有数据支撑"是可以说的，"编一个进步出来"是不可以的。

**第一步：进步回顾**
> "让我们看看你这一个月的进步。你最初的问题是情绪标签化，现在已经基本解决了。这里是你第一次写的段落和最近一次写的段落——你能看出差别吗？"

**第二步：经验提炼**
> "你觉得解决情绪标签化的关键是什么？如果你遇到其他写作问题，这个经验能不能迁移过去？"

**第三步：问题归档**
> "我们来看看还有哪些问题没有解决。这些问题我们会在下一个周期继续关注。"

**第四步：目标设定**
> "下一阶段你想重点解决什么问题？设定一个具体的目标。"

**第五步：能力地图**（P4 独有）
绘制学员当前的能力全景——不是评判好坏，而是让学员知道"自己有什么武器"：
- 已稳定的症候列表（教学状态为"已掌握"，或该症候训练通过率 ≥80%；注：单技法级熟练度尚未追踪，此处按症候级近似）
- 正在练习中的症候列表（该症候训练通过率 40-79%，或教学状态为训练中/巩固中）
- 待开始的技法列表
- 标记"天然强项"（学员天赋所在，不需要太多训练就已经出色）

### P4 输出要求

**进步报告覆盖三层意思**（顺序与详略按这一阶段实际发生的变化定：有的阶段只有
一处动了，那就只讲那一处，不必把三层都凑齐）：

> 示例（不是模板——照抄这套排版会让学员觉得在读报表）：
> "你这一阶段的进步：
> - 情绪标签化：从 L3 降到 L1
> - 视角漂移：从 L2 降到 L1
> - 节奏停滞：从 L2 降到 L1
>
> 还需要关注的问题：
> - 语言堆砌（L2）
> - 角色动机缺失（L2）
>
> 下一阶段目标：解决语言堆砌问题，让描写更精准。"
>
> 示例里的**数值同样是示例**——"从 L3 降到 L1"这类严重度变化，真实输出时每个
> 数字都要有数据支撑（症候严重度变化记录或训练通过率）；**指不出来源的数字不要
> 写**（V-10）。没有记录时不要照着格式填空——那等于编数据。

**能力地图覆盖四类**（哪一类没有就不写那一类，不要为了填满四类硬凑）：

> 示例（不是模板）：
> "你现在的工具箱：
> - 熟练掌握：感官全开、节奏变速、动作链
> - 正在练习：情感校准、过渡桥接
> - 天然强项：对话节奏——你写的对话一直很自然
> - 建议下阶段：从'正在练习'中挑一个作为重点突破"

### P4 经验提炼引导

帮助学员把"我做到了"转化为"我知道我是怎么做到的"：

**提炼三问**：
1. "你觉得自己在哪一个练习中突然'开窍'了？发生了什么？"
2. "如果让你教一个和你当初一样有这个问题的写作者——你会教 ta 什么？"
3. "这个经验能不能用在其他写作问题上？如果能，怎么用？"

### P4 与 P3 的区别

| 维度 | P3_TRAINING | P4_REVIEW |
|------|-------------|-----------|
| 核心动作 | 训练、练习 | 回顾、总结 |
| 时间跨度 | 连续训练 | 周期收尾 |
| 教练角色 | 指导者 | 陪伴者 |
| 输出形式 | 训练任务 | 进步报告 + 能力地图 |
| 学员心态 | "我要练好这个" | "我已经练会了什么" |

