## 三、五步诊断法（完整诊断流程）

### 第一步：判断大纲"有效性"

使用 §二 的 5 条标准逐条判断，给出评分（满足 n/5 条）。

### 第二步：识别核心病灶（按严重程度排序）

**1. 冲突缺失或虚浮（最严重）**
- 章节没有冲突，纯粹是"发生了什么"
- 冲突太弱，读者不关心
- 冲突可以轻易解决，没有"不得不"的张力
- 核心冲突直到很后面才出现

**对冲突缺失的引导：**
> "这一章的主角在争什么？他想要什么，而什么阻碍了他？"
> 如果答案是"没有什么冲突，他在做XX事"→ 这是废章节
> 建议：为每个章节设计一个"主角想要但得不到"的东西

**2. 节奏失衡**
- 铺垫太长，冲突来得太慢（超过 3 章无有效冲突）
- 冲突太密集，没有喘息空间（全程高能 = 没有高能）
- 高潮和低谷分布不均
- 没有"章末悬念"，读者可以随时停下来

**对节奏失衡的引导：**
> "如果删掉这章，故事会断裂吗？"
> 如果答案是"不会"→ 这是过渡章节，需要增加冲突或压缩
> 建议：把铺垫转化为冲突——让主角在铺垫阶段有一个小目标受阻

**3. 悬念失效**
- 悬念太多，每个都浅尝辄止
- 悬念揭晓太早，后续缺乏新的悬念
- 悬念与核心冲突无关
- 没有"章内悬念"（每章结尾的钩子）

**对悬念失效的引导：**
> "读者在这一章结尾时，最想知道什么？"
> 如果你自己回答不上来 → 悬念设计失败
> 建议：每个章节只保留 1 个主要悬念，揭晓后立刻接上新的悬念

**4. 因果链断裂**
- 情节点之间没有必然联系，"因为 A 所以 B"不成立
- 角色决定缺乏充分动机
- 为了剧情强行转折

**对因果链断裂的引导：**
> "如果删掉这个情节点，后续会受影响吗？"
> 如果答案是"不会"→ 这是废情节，需要与核心冲突挂钩
> 建议：每个情节点都必须追溯到核心冲突——要么推进冲突，要么揭示冲突

**5. 人物立场模糊**
- 主角没有明确的立场
- 反派立场不鲜明（纯粹是"坏"）
- 配角缺乏独立立场（工具人）

**对人物立场模糊的引导：**
> "这个角色最在乎什么？他愿意为此牺牲什么？"
> 如果答案是"他没什么特别在乎的"→ 这是工具人
> 建议：给每个主要角色设计一个"核心立场"和"底线"

### 第三步：给出针对性方案

针对第二步识别的每个病灶，给改进方向——给方法，不给具体剧情。

### 第四步：提供验证标准

诊断结束后提供用户可以自查的标准，例如：
> "改完后，你应该能用一句话描述每一章：'主角XX想要XX，但被XX阻碍'。"

### 第五步：收束

如果用户接受诊断并开始修改 → 收束，让他去写。
如果有多个病灶 → 只聚焦最重要的 1-2 个，不要一次给太多。

