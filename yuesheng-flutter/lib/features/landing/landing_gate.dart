// 【为什么不写成 `main.dart` 里的内联 `home: kIsWeb ? ... : ...`】
//   与 `nav_gate.dart` 同源教训：`kIsWeb` 在 **VM 测试里恒为 `false`** ⇒ 内联三元
//   在 `flutter test` 永远走不到「门面」那一支，等于**写了一条不可能变红的判据**
//   （`.ai/PRACTICES.md A3c`）。抽成带 `isWeb` 覆写参数的纯函数后两个分支都能断言：
//   负向 = `isWeb: true` 必须 `true`；正对照 = `isWeb: false` 必须 `false`
//   （正对照防「函数恒返回 true」这种最省事的假绿）。
//
// 【为什么不并进 `nav_gate.dart`】
//   两者语义不同：`nav_gate` 决定**底部导航栏渲不渲**（NAV-1，导航层），
//   本文件决定**首访首屏是门面还是引导**（进门层）。合并会让「一个判定点」
//   变成「一个文件里两个不相干的判定」，复核时反而更难定位。
//   因此**不合并**，但两者共享同一条纪律：判定只有一处、可注入、两端可断言。
// ─────────────────────────────────────────────────────────────

import 'package:flutter/foundation.dart' show kIsWeb;

/// 当前是否 **web 端面**。
///
/// ★ 这是「web 与否」的**唯一判定点**（`§4-499`）：门面（首访）与 header 试用入口
/// （常驻）两处都调它，**任何一处都不许直接写 `kIsWeb`**。
/// 理由同 [shouldShowLanding] 的文件头：`kIsWeb` 在 VM 测试恒 `false` ⇒ 裸用即
/// 写了一条不可能变红的判据。两处共用一个函数 ⇒ 也不会出现「一处改了另一处忘了」。
///
/// `isWeb` 仅供测试覆写；生产调用一律**不传**。
bool isWebSurface({bool? isWeb}) => isWeb ?? kIsWeb;

/// 是否把**首访首屏**换成试用介绍页（替代应用内首启引导）。
///
/// 注意语义：本函数只回答「首访走哪」；「web 端面本身」由 [isWebSurface] 回答。
/// 目前两者取值一致，但**刻意分成两个函数** —— 将来若 web 首访的形态再变
/// （例如首访直接进主壳、只留 header 入口），只需要改这一个函数，
/// 而 header 入口不会跟着静默改变。
bool shouldShowLanding({bool? isWeb}) => isWebSurface(isWeb: isWeb);
